/**
 * 七元权重排队系统
 *  权重高的放在前面·权重低的放在后面·
 *  U先读方向·从尾当头/从头先读/任意方向
 *  优先级可以动态给与流动权·入口的流动权
 */
class SeptenaryPriorityQueue {
  constructor() {
    this.items = [];
    this.direction = 'priorityBased'; // 默认按权重
  }

  /**
   * 入队·标记权重及位置
   */
  enqueue(value, weight = 0, label = '') {
    this.items.push({ value, weight, label, at: Date.now() });
    this.items.sort((a, b) => b.weight - a.weight);
    return this;
  }

  /**
   * 设定/切换读取方向
   */
  setReadDirection(dir) {
    const valid = ['tailFirst', 'headFirst', 'anyFirst', 'priorityBased'];
    if (valid.includes(dir)) this.direction = dir;
    return this;
  }

  /**
   * 读取队列
   */
  read() {
    let arr = this.items.slice();
    switch (this.direction) {
      case 'tailFirst':    arr.reverse(); break;          // 以尾当头
      case 'headFirst':    /* forward */ break;
      case 'anyFirst':     arr.sort(() => Math.random() - 0.5); break;
      case 'priorityBased':/* already sorted */ break;
    }
    return arr;
  }
}

