/* 填充一条链 */
static void 填充链(chain_t* chain, const char* symbols[], int count) {
    for (int i = 0; i < count; i++) {
        /* 层级按位置循环: 元→阶→层→代→世→界→域→场 */
        uint8_t level = (uint8_t)(i % 8);
        char obs[64];
        snprintf(obs, sizeof(obs), "第%d个%s，%s层", i + 1, chain->name, 
                 level == 0 ? "元" : level == 1 ? "阶" : level == 2 ? "层" :
                 level == 3 ? "代" : level == 4 ? "世" : level == 5 ? "界" :
                 level == 6 ? "域" : "场");
        
        链_追加(chain, level, symbols[i], "创世", obs);
    }
}

