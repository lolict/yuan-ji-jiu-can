static inline const radical_entry_t *radical_get(uint8_t index) {
    if (index < 1 || index > RADICAL_COUNT) return 0;
    return &RADICAL_TABLE[index - 1];
}

static inline uint16_t radical_get_ucs2(uint8_t index) {
    const radical_entry_t *r = radical_get(index);
    return r ? r->ucs2 : 0xFFFF;
}

static inline uint8_t radical_get_strokes(uint8_t index) {
    const radical_entry_t *r = radical_get(index);
    return r ? r->strokes : 0;
}

static inline uint8_t radical_find_by_char(uint16_t ucs2) {
    for (uint8_t i = 0; i < RADICAL_COUNT; i++) {
        if (RADICAL_TABLE[i].ucs2 == ucs2) return i + 1;
    }
    return 0;
}

