static void 填充链(chain_t* chain, const char* symbols[], int count, 
                   memory_chain_t* mem, const char* actor) {
    char tag[128];
    for (int i = 0; i < count; i++) {
        uint8_t level = (uint8_t)(i % 8);
        链_追加(chain, level, symbols[i], actor, "符号加载");
        
        /* 记录到记忆链 */
        if (mem) {
            snprintf(tag, sizeof(tag), "%s 加载链[%s]符号[%s]",
                     actor, chain->name, symbols[i]);
            记忆链_记录(mem, MEM_CHAIN_APPEND, MEM_DEPTH_OPERATION, tag, actor);
        }
    }
}

