"""
domain_loader.py — 域加载器

核心原则：运行前一切符号已准备好，运行时不生成新符号，不增加内存。
意识只在预加载的符号空间里流动。

本文件实现：
1. 符号空间 — 所有预加载的符号
2. 索引表 — 符号 → 地址的映射
3. 意识流 — 控制流和数据流
4. 复刻机制 — 克隆符号空间
"""

