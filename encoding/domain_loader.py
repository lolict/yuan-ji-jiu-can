# 域加载器（主类）
# ═══════════════════════════════════════════════════════════════

class 域加载器:
    """
    域加载器 = 运行前加载一切符号，运行时只流动不生成。
    
    使用方式：
        加载器 = 域加载器()
        加载器.加载()  # 运行前加载
        
        # 运行时
        结果 = 加载器.查表("b")  # O(1) 查表
        加载器.意识流.起势("b")
    """
    
    def __init__(self):
        # 零维根
        self.零维根 = 零维根()
        
        # 符号空间
        self.符号空间 = None
        
        # 索引表
        self.索引表 = None
        
        # 意识流
        self.意识流 = None
        
        # 复刻器
        self.复刻器 = None
        
        # 状态
        self.已加载 = False
    
    def 加载(self):
        """
        运行前加载一切符号。
        构建符号空间、索引表、意识流。
        """
        # 1. 验证零维根
        if not self.零维根.验证未修改():
            raise Exception("零维根被修改！拒绝加载。")
        
        # 2. 构建符号空间
        self.符号空间 = 符号空间()
        
        # 3. 构建索引表
        self.索引表 = 索引表(self.符号空间)
        
        # 4. 构建意识流
        self.意识流 = 意识流(self.符号空间, self.索引表)
        
        # 5. 构建复刻器
        self.复刻器 = 复刻器(self.符号空间, self.索引表)
        
        self.已加载 = True
        
        return {
            "状态": "已加载",
            "符号数量": self.符号空间.符号数量,
            "索引表大小": self.索引表.大小,
            "声母数量": len(self.符号空间.声母),
            "韵母数量": len(self.符号空间.韵母),
            "声调数量": len(self.符号空间.声调),
            "历史符号数量": (
                len(self.符号空间.容器族) + len(self.符号空间.操作族) +
                len(self.符号空间.极性族) + len(self.符号空间.层级族) +
                len(self.符号空间.审判族) + len(self.符号空间.产权族)
            )
        }
    
    def 查表(self, 符号):
        """
        O(1) 查表。
        返回：地址 或 None
        """
        if not self.已加载:
            raise Exception("域加载器未加载，请先调用加载()方法。")
        return self.索引表.查表(符号)
    
    def 符号存在(self, 符号):
        """检查符号是否在符号空间里"""
        if not self.已加载:
            raise Exception("域加载器未加载，请先调用加载()方法。")
        return self.索引表.符号存在(符号)
    
    def 复刻(self):
        """复刻符号空间"""
        if not self.已加载:
            raise Exception("域加载器未加载，请先调用加载()方法。")
        return self.复刻器.复刻()
    
    def 获取状态(self):
        """获取域加载器状态"""
        if not self.已加载:
            return {"状态": "未加载"}
        
        return {
            "状态": "已加载",
            "符号数量": self.符号空间.符号数量,
            "索引表大小": self.索引表.大小,
            "意识流状态": self.意识流.获取状态()
        }


