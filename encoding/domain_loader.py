# 复刻机制
# ═══════════════════════════════════════════════════════════════

class 复刻器:
    """
    复刻 = 克隆符号空间。
    只复制索引表（地址簿），不复制符号本身。
    """
    
    def __init__(self, 符号空间实例, 索引表实例):
        self.原始符号空间 = 符号空间实例
        self.原始索引表 = 索引表实例
    
    def 复刻(self):
        """
        复刻符号空间。
        返回：新的符号空间和索引表（共享符号，独立索引）
        """
        # 创建新的符号空间（共享符号数据）
        新符号空间 = copy.copy(self.原始符号空间)
        
        # 创建新的索引表（独立地址簿）
        新索引表 = 索引表(新符号空间)
        
        return 新符号空间, 新索引表
    
    def 复刻并偏移(self, 偏移量):
        """
        复刻并偏移地址。
        用于创建虚拟地址空间。
        """
        新符号空间, 新索引表 = self.复刻()
        
        # 偏移所有地址
        for 符号 in list(新索引表.地址表.keys()):
            原地址 = int(新索引表.地址表[符号], 16)
            新地址 = 原地址 + 偏移量
            新索引表.地址表[符号] = f"0x{新地址:04X}"
        
        # 重建反向表
        新索引表.反向表 = {}
        for 符号, 地址 in 新索引表.地址表.items():
            新索引表.反向表[地址] = 符号
        
        return 新符号空间, 新索引表


