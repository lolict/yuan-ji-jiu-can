# 意识流
# ═══════════════════════════════════════════════════════════════

class 意识流:
    """
    意识流 = 在符号空间中的移动。
    
    控制流：意识的先后顺序（声母调入的顺序）
    数据流：符号在容器间的流动（产权流、容器流）
    """
    
    def __init__(self, 符号空间实例, 索引表实例):
        self.符号空间 = 符号空间实例
        self.索引表 = 索引表实例
        
        # 当前位置
        self.当前声母 = None
        self.当前韵母 = None
        self.当前声调 = None
        
        # 遍历状态
        self.声母索引 = 0
        self.韵母索引 = 0
        
        # 折叠层数
        self.折叠层数 = 0
        
        # 流动历史
        self.历史 = []
    
    def 起势(self, 声母):
        """意识从声母容器起势"""
        if not self.索引表.符号存在(声母):
            return False, f"符号 '{声母}' 不在符号空间里"
        
        self.当前声母 = 声母
        self.当前韵母 = None
        self.当前声调 = None
        self.韵母索引 = 0
        
        self.历史.append({
            "动作": "起势",
            "声母": 声母,
            "地址": self.索引表.查表(声母)
        })
        
        return True, f"意识从声母 '{声母}' 起势"
    
    def 流入韵母(self, 韵母):
        """意识流入韵母容器"""
        if not self.索引表.符号存在(韵母):
            return False, f"符号 '{韵母}' 不在符号空间里"
        
        self.当前韵母 = 韵母
        
        self.历史.append({
            "动作": "流入韵母",
            "韵母": 韵母,
            "地址": self.索引表.查表(韵母)
        })
        
        return True, f"意识流入韵母 '{韵母}'"
    
    def 加上声调(self, 声调):
        """意识加上声调"""
        if not self.索引表.符号存在(声调):
            return False, f"符号 '{声调}' 不在符号空间里"
        
        self.当前声调 = 声调
        
        self.历史.append({
            "动作": "加上声调",
            "声调": 声调,
            "地址": self.索引表.查表(声调)
        })
        
        return True, f"意识加上声调 '{声调}'"
    
    def 获取当前发音地址(self):
        """获取当前发音地址 = 声母地址 + 韵母地址 + 声调地址"""
        if not self.当前声母:
            return None
        
        声母地址 = self.索引表.查表(self.当前声母)
        韵母地址 = self.索引表.查表(self.当前韵母) if self.当前韵母 else "0x0000"
        声调地址 = self.索引表.查表(self.当前声调) if self.当前声调 else "0x0000"
        
        return {
            "声母地址": 声母地址,
            "韵母地址": 韵母地址,
            "声调地址": 声调地址,
            "完整发音": f"{self.当前声母}{self.当前韵母 or ''}{self.当前声调 or ''}"
        }
    
    def 下一个声母(self):
        """切换到下一个声母"""
        self.声母索引 += 1
        if self.声母索引 >= len(self.符号空间.声母):
            # 边界到达 → 折叠
            self.折叠层数 += 1
            self.声母索引 = 0
            self.历史.append({"动作": "折叠", "层数": self.折叠层数})
        
        self.当前声母 = self.符号空间.声母[self.声母索引]
        self.当前韵母 = None
        self.当前声调 = None
        
        self.历史.append({
            "动作": "下一个声母",
            "声母": self.当前声母,
            "地址": self.索引表.查表(self.当前声母)
        })
        
        return True, f"切换到声母 '{self.当前声母}'"
    
    def 边界到达(self):
        """边界到达 → 从另一个容器拿新符号"""
        self.历史.append({"动作": "边界到达"})
        return self.下一个声母()
    
    def 获取状态(self):
        """获取当前状态（强制5项输出格式）"""
        return {
            "当前层号": self.折叠层数,
            "当前声母": self.当前声母,
            "当前韵母组合": self.当前韵母,
            "折叠状态": f"已折叠{self.折叠层数}层",
            "下一步操作": "继续" if self.声母索引 < len(self.符号空间.声母) else "折叠"
        }


