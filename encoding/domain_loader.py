# 索引表
# ═══════════════════════════════════════════════════════════════

class 索引表:
    """
    索引表 = 符号 → 地址的映射。
    运行前构建，运行时只读。
    查表 = O(1) 直接定位，不是搜索。
    """
    
    def __init__(self, 符号空间实例):
        self.符号空间 = 符号空间实例
        self.地址表 = {}  # 符号 → 地址
        self.反向表 = {}  # 地址 → 符号
        self._构建索引()
    
    def _构建索引(self):
        """构建索引表"""
        地址计数器 = 0
        
        # 声母 → 地址 0x0000 ~ 0x0017
        for 声母 in self.符号空间.声母:
            self.地址表[声母] = f"0x{地址计数器:04X}"
            反向地址 = f"0x{地址计数器:04X}"
            self.反向表[反向地址] = 声母
            地址计数器 += 1
        
        # 韵母 → 地址 0x0018 ~ 0x00FF
        for 韵母 in self.符号空间.韵母:
            self.地址表[韵母] = f"0x{地址计数器:04X}"
            反向地址 = f"0x{地址计数器:04X}"
            self.反向表[反向地址] = 韵母
            地址计数器 += 1
        
        # 声调 → 地址 0x0100 ~ 0x0103
        for 声调 in self.符号空间.声调:
            self.地址表[声调] = f"0x{地址计数器:04X}"
            反向地址 = f"0x{地址计数器:04X}"
            self.反向表[反向地址] = 声调
            地址计数器 += 1
        
        # 历史符号 → 地址 0x0100+
        for 符号 in (self.符号空间.容器族 + self.符号空间.操作族 + 
                     self.符号空间.极性族 + self.符号空间.层级族 + 
                     self.符号空间.审判族 + self.符号空间.产权族):
            if 符号 not in self.地址表:  # 避免重复
                self.地址表[符号] = f"0x{地址计数器:04X}"
                反向地址 = f"0x{地址计数器:04X}"
                self.反向表[反向地址] = 符号
                地址计数器 += 1
    
    def 查表(self, 符号):
        """
        查表 = O(1) 直接定位。
        返回：地址 或 None（符号不在空间里）
        """
        return self.地址表.get(符号)
    
    def 反向查表(self, 地址):
        """地址 → 符号"""
        return self.反向表.get(地址)
    
    def 符号存在(self, 符号):
        """检查符号是否在索引表里"""
        return 符号 in self.地址表
    
    @property
    def 大小(self):
        return len(self.地址表)
    
    def 导出(self):
        """导出索引表为字典"""
        return dict(self.地址表)


