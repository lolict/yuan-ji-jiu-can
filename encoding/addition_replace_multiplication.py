"""
加法替代乘法 —— 成本降维打击系统

核心哲学：
- 乘法/除法：快速均匀分层，高成本，占领所有维度
- 加法/减法：慢速分层，低成本，线性不对称
- 公约数：静态绝对参考系（庄家）
- 公倍数：动态可修改匹配（赌徒）

目标：
用低成本的加法/减法，替代高成本的乘法/除法
成为庄家（绝对参考系），不再当赌徒
"""


class 运算成本:
    """四种运算的成本对比"""
    
    @staticmethod
    def 乘法(输入):
        """
        乘法：快速均匀分层
        - 平面的对称
        - 同时占领一维、二维、零维
        - 成本高：需要遍历所有维度
        """
        结果 = []
        for i in range(输入):
            for j in range(输入):
                结果.append((i, j))
        return {
            "运算": "乘法",
            "结果": 结果,
            "成本": len(结果),
            "维度": "平面",
            "特点": "均匀快速分层"
        }
    
    @staticmethod
    def 除法(输入, 份数):
        """
        除法：均匀分割
        - 把一个东西分成N份
        - 成本高：需要精确分配
        """
        每份 = 输入 // 份数
        余数 = 输入 % 份数
        return {
            "运算": "除法",
            "每份": 每份,
            "余数": 余数,
            "成本": 份数,
            "维度": "均匀分割",
            "特点": "快速分层"
        }
    
    @staticmethod
    def 加法(输入, 目标):
        """
        加法：慢速分层，线性不对称
        - 从外部寻找匹配对象
        - 成本最低：只需要找到缺少的那块
        - 线性：按步骤进行，不对齐也可以
        """
        当前 = 输入
        步骤 = []
        while 当前 < 目标:
            缺少 = 目标 - 当前
            当前 += 缺少
            步骤.append(缺少)
        return {
            "运算": "加法",
            "步骤": 步骤,
            "成本": len(步骤),
            "维度": "线性",
            "特点": "慢速分层，不对称"
        }
    
    @staticmethod
    def 减法(输入, 要移除的):
        """
        减法：过滤、分类、弱化
        - 不需要的东西，用减法移除
        - 成本最低：直接丢掉
        - 可以不对称移除
        """
        结果 = []
        for 项 in 输入:
            if 项 not in 要移除的:
                结果.append(项)
        return {
            "运算": "减法",
            "结果": 结果,
            "成本": len(要移除的),
            "维度": "过滤",
            "特点": "慢速分类，弱化"
        }


class 降维打击:
    """
    从高维降维到低维到零维
    成本替代：用低维成本替代高维成本
    """
    
    @staticmethod
    def 高维转低维(高维符号):
        """
        高维：4个字母的单词
        低维：1个字母的符号
        成本：高维需要4份，低维只需要1份
        """
        if len(高维符号) <= 1:
            return {
                "高维": 高维符号,
                "低维": 高维符号,
                "降维比": "1:1",
                "成本节省": "0%",
                "说明": "已经是低维"
            }
        
        低维 = 高维符号[0]  # 取第一个字母
        return {
            "高维": 高维符号,
            "低维": 低维,
            "降维比": f"{len(高维符号)}:1",
            "成本节省": f"{(1-1/len(高维符号))*100:.0f}%",
            "说明": "锚定第一个发音"
        }
    
    @staticmethod
    def 成本对比(高维符号, 低维符号):
        """
        对比高维成本和低维成本
        谁的成本低，谁存活
        """
        高维成本 = len(高维符号)
        低维成本 = len(低维符号)
        
        if 低维成本 < 高维成本:
            return {
                "赢家": "低维",
                "输家": "高维",
                "原因": f"低维成本({低维成本}) < 高维成本({高维成本})",
                "策略": "用低维替代高维"
            }
        else:
            return {
                "赢家": "高维",
                "输家": "低维",
                "原因": f"高维成本({高维成本}) <= 低维成本({低维成本})",
                "策略": "保持高维"
            }


class 公倍数照镜子:
    """
    公倍数照公约数的镜子
    动态匹配静态
    """
    
    def __init__(self):
        self.公约数库 = {}  # 静态参考系
        self.公倍数库 = {}  # 动态匹配
    
    def 注册公约数(self, 名称, 特征):
        """注册一个静态公约数（别人的绝对参考系）"""
        self.公约数库[名称] = {
            "特征": 特征,
            "状态": "静态",
            "角色": "庄家"
        }
    
    def 照镜子(self, 公倍数名称, 目标公约数名称):
        """
        公倍数照公约数的镜子
        看能不能匹配上
        """
        if 目标公约数名称 not in self.公约数库:
            return None
        
        目标 = self.公约数库[目标公约数名称]
        
        # 检查特征是否匹配
        匹配结果 = {
            "公倍数": 公倍数名称,
            "公约数": 目标公约数名称,
            "目标特征": 目标["特征"],
            "匹配": False,
            "策略": ""
        }
        
        # 如果公倍数的特征覆盖了公约数的特征
        if 公倍数名称 in self.公倍数库:
            公倍数特征 = self.公倍数库[公倍数名称]["特征"]
            if 公倍数特征 == 目标["特征"]:
                匹配结果["匹配"] = True
                匹配结果["策略"] = "用公倍数替代公约数"
            else:
                匹配结果["策略"] = "调整公倍数特征以匹配公约数"
        
        return 匹配结果
    
    def 创建公倍数(self, 名称, 特征, 可修改=True):
        """创建一个新的公倍数（动态）"""
        self.公倍数库[名称] = {
            "特征": 特征,
            "状态": "动态",
            "角色": "赌徒→庄家",
            "可修改": 可修改
        }


class 替换策略:
    """
    替代策略：用加法/减法替代乘法/除法
    """
    
    @staticmethod
    def 用加法替代乘法(目标):
        """
        乘法：快速占领所有维度（高成本）
        加法：慢速匹配，从外部寻找（低成本）
        
        替代逻辑：
        - 乘法需要遍历所有可能的组合
        - 加法只需要找到缺少的那个匹配
        """
        return {
            "原运算": "乘法",
            "替代运算": "加法",
            "原成本": "高（遍历所有维度）",
            "替代成本": "低（只找缺少的）",
            "策略": "从外部寻找匹配对象，照镜子替代"
        }
    
    @staticmethod
    def 用减法替代除法(输入, 不需要的):
        """
        除法：均匀分割（高成本）
        减法：直接过滤（低成本）
        
        替代逻辑：
        - 除法需要精确计算每份多少
        - 减法直接移除不需要的
        """
        return {
            "原运算": "除法",
            "替代运算": "减法",
            "原成本": "高（精确分割）",
            "替代成本": "低（直接过滤）",
            "策略": "移除不需要的，保留需要的"
        }
    
    @staticmethod
    def 成本决策(高维方案, 低维方案):
        """
        成本决策：谁的成本低，谁存活
        这是过滤的核心逻辑
        """
        高维成本 = 高维方案["成本"]
        低维成本 = 低维方案["成本"]
        
        if 低维成本 < 高维成本:
            return {
                "选择": "低维方案",
                "原因": f"成本更低（{低维成本} < {高维成本}）",
                "操作": "覆盖高维方案"
            }
        else:
            return {
                "选择": "高维方案",
                "原因": f"成本更低或相等（{高维成本} <= {低维成本}）",
                "操作": "保持高维方案"
            }


class 一进制:
    """
    一进制：进位与不进位
    不进位 = 静态 = 绝对参考系
    进位 = 动态 = 公倍数匹配
    """
    
    @staticmethod
    def 是否进位(数字):
        """
        一进制规则：
        - 0遇到0 → 进位变成1
        - 1遇到1 → 进位变成10（但一进制没有10，所以是新的开始）
        """
        if 数字 == 0:
            return {
                "当前": 0,
                "遇到": 0,
                "结果": "进位",
                "新值": 1,
                "状态": "动态"
            }
        elif 数字 == 1:
            return {
                "当前": 1,
                "遇到": 1,
                "结果": "进位（新起点）",
                "新值": "10（新维度）",
                "状态": "动态"
            }
        else:
            return {
                "当前": 数字,
                "状态": "静态",
                "说明": "不变化，不分类，绝对参考"
            }
    
    @staticmethod
    def 静态锚点(符号):
        """创建一个静态锚点（零维）"""
        return {
            "符号": 符号,
            "维度": "零维",
            "状态": "静态",
            "角色": "绝对参考系",
            "特点": "不进位，不分类，唯一存在"
        }
    
    @staticmethod
    def 动态匹配(静态锚点, 候选公倍数):
        """
        用动态的公倍数匹配静态的锚点
        目标：让公倍数替代锚点
        """
        if 候选公倍数["特征"] == 静态锚点["特征"]:
            return {
                "匹配": True,
                "策略": "用公倍数替代静态锚点",
                "成本": "低（照镜子匹配）"
            }
        else:
            return {
                "匹配": False,
                "策略": "继续寻找其他公倍数",
                "成本": "中（需要探索）"
            }


