/*
 * test_swarm.c — njsg-swarm 分布式智能体并行开发演示
 *
 * 本体-分身架构:
 *   协调器创建多子代理，分配任务，裁决冲突
 *   所有行动写入链式追踪
 */

#include <stdio.h>
#include <string.h>
#include "njsg_swarm.h"
#include "swarm_agents.h"

int main(void) {
    printf("╔══════════════════════════════════════════════════╗\n");
    printf("║     囡囝共生 SWARM · 分布式智能体演示         ║\n");
    printf("║     本体-分身 · 并行推进 · 冲突裁决           ║\n");
    printf("╚══════════════════════════════════════════════════╝\n");
    
    /* ══════════════════════════════════════════════════
     * 1. 创建协调器
     * ══════════════════════════════════════════════════ */
    printf("\n[1] 初始化协调器\n");
    swarm_coordinator_t coord;
    协调器_初始化(&coord, "主协调器");
    printf("  ✅ 协调器就绪\n");
    
    /* ══════════════════════════════════════════════════
     * 2. 创建并注册子代理
     * ══════════════════════════════════════════════════ */
    printf("\n[2] 注册子代理\n");
    
    swarm_agent_t* a1 = create_agent("bootstrap", "bootstrap-1");
    swarm_agent_t* a2 = create_agent("metaime", "metaime-2");
    swarm_agent_t* a3 = create_agent("yinyang", "yinyang-3");
    swarm_agent_t* a4 = create_agent("fiveyuan", "fiveyuan-4");
    
    协调器_注册代理(&coord, a1);
    协调器_注册代理(&coord, a2);
    协调器_注册代理(&coord, a3);
    协调器_注册代理(&coord, a4);
    
    printf("  ✅ 4个子代理注册完成\n");
    
    /* ══════════════════════════════════════════════════
     * 3. 创建任务链
     * ══════════════════════════════════════════════════ */
    printf("\n[3] 创建任务链\n");
    
    任务链_init(&coord.tasks, &coord.action_chain);
    
    任务链_创建(&coord.tasks, "T001", "鼓膜自举: 振荡器启动");
    任务链_创建(&coord.tasks, "T002", "元输入法: 加载规则引擎");
    任务链_创建(&coord.tasks, "T003", "阴阳映射: 正向转换");
    任务链_创建(&coord.tasks, "T004", "五维审判: 新符号准入");
    任务链_创建(&coord.tasks, "T005", "阴阳映射: 反向寄生");
    任务链_创建(&coord.tasks, "T006", "元输入法: 编码缓存优化");
    
    printf("  ✅ 6个任务创建完成\n");
    
    /* ══════════════════════════════════════════════════
     * 4. 协调器迭代：分配任务
     * ══════════════════════════════════════════════════ */
    printf("\n[4] 协调器: 分配任务\n");
    printf("─────────────────────────────────────────────────\n");
    
    协调器_一轮迭代(&coord);
    
    /* ══════════════════════════════════════════════════
     * 5. 模拟冲突：两个代理争抢T004
     * ══════════════════════════════════════════════════ */
    printf("\n[5] 模拟冲突: 两个代理争抢同一任务\n");
    printf("─────────────────────────────────────────────────\n");
    
    printf("  [冲突] bootstrap-1 vs fiveyuan-4 争抢 T004\n");
    协调器_上报冲突(&coord, "T004", "bootstrap-1", "fiveyuan-4");
    
    printf("  [裁决] 协调器基于奖励分判决...\n");
    协调器_裁决冲突(&coord, "T004", "fiveyuan-4", "五维审判专业贡献更高");
    
    printf("  ✅ 冲突解决\n");
    
    /* ══════════════════════════════════════════════════
     * 6. 广播同步
     * ══════════════════════════════════════════════════ */
    printf("\n[6] 广播: 状态同步\n");
    printf("─────────────────────────────────────────────────\n");
    
    协调器_广播(&coord, "sync_round_1", "第一轮任务分配完成，等待下一轮");
    
    printf("  ✅ 已同步到所有活跃代理\n");
    
    /* ══════════════════════════════════════════════════
     * 7. 报告
     * ══════════════════════════════════════════════════ */
    printf("\n[7] 综合报告\n");
    printf("─────────────────────────────────────────────────\n");
    
    协调器_报告(&coord);
    
    printf("\n");
    printf("╔══════════════════════════════════════════════════╗\n");
    printf("║     SWARM 演示完成                              ║\n");
    printf("║                                                   ║\n");
    printf("║  协调器管理4个子代理                              ║\n");
    printf("║  所有行动写入链式追踪                             ║\n");
    printf("║  冲突通过奖励分裁决                               ║\n");
    printf("║  这就是本体-分身分布式开发                        ║\n");
    printf("╚══════════════════════════════════════════════════╝\n\n");
    
    return 0;
}
