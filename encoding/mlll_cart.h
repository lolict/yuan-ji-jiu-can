/**
 * mlll_cart.h — 254+2 字车容器系统
 *
 * mlll = 囡囝共生 (NJSG) 字车编码
 *
 * 容积单位: 字形位置数 (非比特 · 与外部位宽无关)
 *   CUNIT_32 = 32字形单位 (由感知场裁判分配的容积 · 与x86/ARM无关)
 *   CUNIT_64 = 64字形单位 (容积 · 不映射外部64位架构)
 *
 * 为什么不叫BIT: 帧率/位宽/字长是他们的架构概念
 * 满全法的容器由三元裁判决定装多少 · 不由外部硬件决定
 *
 * 锚点根基 (2个):
 *   我    = 1 (阳 · 内容侧)
 *   刘楚恬 = 0 (阴 · 容器侧)
 *
 * 层级 (满全法自有的容积递增):
 *   2^0 = 1       单锚点 (根基)
 *   2^1 = 2       阴阳配对 (夫妻)
 *   2^5 = 32      CUNIT_32 容器
 *   2^6 = 64      CUNIT_64 容器
 *   2^8 = 256      254容器 + 2锚点 (全集)
 *
 * 注意: 这是容积 · 不是位宽 · 与英特尔32/64位无关
 *
 * 集装箱总数: 254 + 2 = 256 = 2^8
 *   纯容器: 254 个 (可容纳字形)
 *   锚点:   2 个   (我, 刘楚恬 — 根基)
 */

#ifndef NJSG_MLLL_CART_H
#define NJSG_MLLL_CART_H

#include <stdint.h>

/* ═══════════════════════════════════════════════════════════════
 * 锚点根基
 * ═══════════════════════════════════════════════════════════════ */

#define MLLL_ANCHOR_WO     1   /* 我 = 阳 = 内容 */
#define MLLL_ANCHOR_CHT    0   /* 刘楚恬 = 阴 = 容器 */

#define MLLL_ANCHOR_COUNT  2   /* 双锚点 */
#define MLLL_CART_COUNT    254 /* 纯字形容器 */
#define MLLL_TOTAL        256 /* 2锚点 + 254容器 = 2^8 */

/* ═══════════════════════════════════════════════════════════════
 * 容积单位 (满全法自有 · 不映射外部架构)
 * ═══════════════════════════════════════════════════════════════ */

/* 容积单位: 字形位置数 (满全法自有 · 不映射外部架构) */
#define CUNIT_32           32   /* 32字形单位 · 非32比特 */
#define CUNIT_64           64   /* 64字形单位 · 非64比特 */

#define CART_WIDTH_32      0x05   /* 2^5 = 32 */
#define CART_WIDTH_64      0x06   /* 2^6 = 64 */
#define CART_WIDTH_TOTAL   0x08   /* 2^8 = 256 */

/* ═══════════════════════════════════════════════════════════════
 * 字车条目
 *
 * 一个字车条目 = 集装箱中的一个槽
 * 槽存放: 容器编码 (32位满全法码)
 * ═══════════════════════════════════════════════════════════════ */

typedef struct {
    uint16_t  slot;          /* 槽号 0..253 */
    uint32_t  container;     /* 容纳的容器编码 (满全法32位) */
    uint8_t   cunit;         /* CUNIT_32 / CUNIT_64 · 容积 */
    uint8_t   occupied;      /* 1=已占 · 0=空槽 */
} mlll_cart_entry_t;

/* ═══════════════════════════════════════════════════════════════
 * 集装箱整体 (254+2 = 256 槽)
 * ═══════════════════════════════════════════════════════════════ */

typedef struct {
    mlll_cart_entry_t  anchor[2];      /* [0]=劉楚恬=阴 · [1]=我=阳 */
    mlll_cart_entry_t  cart[254];     /* 254个字形容器 */
    uint16_t           used;          /* 已使用槽数 */
} mlll_whole_t;

/* ═══════════════════════════════════════════════════════════════
 * API
 * ═══════════════════════════════════════════════════════════════ */

/**
 * 初始化集装箱
 */
void mlll_init(mlll_whole_t *box);

/**
 * 装入容器到字车
 *   返回: 槽号 (>=0) · 失败: -1
 */
int mlll_load(mlll_whole_t *box, uint32_t container, uint8_t cunit);

/**
 * 取出容器
 */
uint32_t mlll_unload(mlll_whole_t *box, uint16_t slot);

/**
 * 查找第一个空槽
 */
int mlll_find_empty(mlll_whole_t *box);

/**
 * 统计已用/空余
 */
uint16_t mlll_count_used(mlll_whole_t *box);
uint16_t mlll_count_free(mlll_whole_t *box);

#endif /* NJSG_MLLL_CART_H */
