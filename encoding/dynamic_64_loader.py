    def 创建槽位(self, 槽位编号, 目标描述, 约束条件, 判定标准):
        """在指定位置创建一个目标槽位"""
        if 0 <= 槽位编号 < 64:
            self.槽位[槽位编号] = 目标槽位(槽位编号, 目标描述, 约束条件, 判定标准)
            return True
        return False
    
    def 装入符号(self, 槽位编号, 符号, 相位描述):
        """把一个符号装入指定槽位的近义词列表"""
        if 0 <= 槽位编号 < 64 and self.槽位[槽位编号]:
            self.槽位[槽位编号].添加近义词(符号, 相位描述)
            self.符号位置[符号] = 槽位编号
            return True
        return False
    
    def 添加纠错规则(self, 错别字, 正确符号):
        """在纠错膜中添加一条规则"""
        self.纠错膜[错别字] = 正确符号
    
    def 纠正(self, 输入符号):
        """
        纠错膜：输入一个符号，输出纠正后的符号
        在AI看到提示词之前，就把错别字纠正
        """
        # 如果输入本身就是正确的，直接返回
        if 输入符号 in self.符号位置:
            return 输入符号
        
        # 如果输入是错别字，返回正确的
        if 输入符号 in self.纠错膜:
            return self.纠错膜[输入符号]
        
        # 找不到，返回原样
        return 输入符号
    
    def 判定近似(self, 槽位编号, 符号A, 符号B):
        """在指定槽位的目标约束下，判定两个符号是否近似"""
        if 0 <= 槽位编号 < 64 and self.槽位[槽位编号]:
            return self.槽位[槽位编号].是否近似(符号A, 符号B)
        return False
    
    def 获取可替代符号(self, 槽位编号, 目标符号):
        """获取在指定槽位目标下，能替代目标符号的所有近义词"""
        if 0 <= 槽位编号 < 64 and self.槽位[槽位编号]:
            return self.槽位[槽位编号].获取可替代符号(目标符号)
        return []
    
    def 显示状态(self):
        """显示当前64槽位的状态"""
        print("=" * 60)
        print("动态64进制加载器 v2 —— 目标约束下的近似")
        print("=" * 60)
        for i in range(64):
            if self.槽位[i]:
                槽 = self.槽位[i]
                print(f"\n槽位{i:2d}: {槽.目标描述}")
                print(f"       约束: {槽.约束条件}")
                print(f"       判定: {槽.判定标准}")
                print(f"       近义词:")
                for 近义词 in 槽.近义词列表:
                    print(f"         - {近义词['符号']:12s} | {近义词['相位']}")
            else:
                print(f"\n槽位{i:2d}: [空——待定义]")
        print("\n" + "=" * 60)


