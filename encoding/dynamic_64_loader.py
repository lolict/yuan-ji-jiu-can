#!/usr/bin/env python3
"""
动态64进制加载器
- 64个槽位，每个槽位装一个相位
- 符号动态流动，插入新符号时其他符号自动让位
- 纠错膜：输入错别字，输出正确符号
- 近义词系统：同一个意思的不同符号互相映射
"""

class 动态64进制:
    def __init__(self):
        # 64个槽位，每个槽位是一个容器
        self.槽位 = [None] * 64
        
        # 符号现在在哪个槽位（动态映射）
        self.符号位置 = {}
        
        # 槽位上现在是什么符号（反向映射）
        self.槽位内容 = {}
        
        # 近义词表：正确符号 → [错别字列表]
        self.近义词家族 = {}
        
        # 相位表：符号 → 相位描述
        self.相位表 = {}
    
    def 装入(self, 符号, 相位=""):
        """把符号装进第一个空槽位"""
        for i in range(64):
            if self.槽位[i] is None:
                self.槽位[i] = 符号
                self.符号位置[符号] = i
                self.槽位内容[i] = 符号
                self.相位表[符号] = 相位
                return i
        return None  # 64槽位已满
    
    def 插入(self, 新符号, 位置, 相位=""):
        """在指定位置插入新符号，后面的符号自动后退"""
        if 位置 < 0 or 位置 >= 64:
            return False
        
        # 如果这个位置已经有符号，把后面的都往后推
        if self.槽位[位置] is not None:
            # 找到最后一个有符号的槽位
            最后 = 63
            while 最后 > 位置 and self.槽位[最后] is None:
                最后 -= 1
            
            # 从后往前移动，腾出位置
            for i in range(最后, 位置, -1):
                self.槽位[i+1] = self.槽位[i]
                if self.槽位[i] is not None:
                    self.符号位置[self.槽位[i]] = i+1
        
        # 装入新符号
        self.槽位[位置] = 新符号
        self.符号位置[新符号] = 位置
        self.槽位内容[位置] = 新符号
        self.相位表[新符号] = 相位
        return True
    
    def 移除(self, 符号):
        """移除一个符号，后面的符号自动前进填补"""
        if 符号 not in self.符号位置:
            return False
        
        位置 = self.符号位置[符号]
        
        # 从移除位置开始，后面的符号往前移动
        for i in range(位置, 63):
            self.槽位[i] = self.槽位[i+1]
            if self.槽位[i] is not None:
                self.符号位置[self.槽位[i]] = i
        
        # 清空最后一个槽位
        self.槽位[63] = None
        
        # 清理映射
        del self.符号位置[符号]
        del self.相位表[符号]
        return True
    
    def 添加近义词(self, 正确符号, 近义词):
        """添加一个近义词（错别字）"""
        if 正确符号 not in self.近义词家族:
            self.近义词家族[正确符号] = []
        self.近义词家族[正确符号].append(近义词)
    
    def 纠正(self, 输入符号):
        """
        纠错膜：输入一个符号，输出纠正后的符号
        如果输入的是错别字，返回正确的符号
        如果输入的是正确的，直接返回
        如果找不到，返回None
        """
        # 先检查是不是已经在槽位里（正确的符号）
        if 输入符号 in self.符号位置:
            return 输入符号
        
        # 检查近义词表
        for 正确符号, 近义词列表 in self.近义词家族.items():
            if 输入符号 in 近义词列表:
                return 正确符号
        
        return None  # 找不到
    
    def 获取相位(self, 符号):
        """获取符号的相位描述"""
        return self.相位表.get(符号, None)
    
    def 获取位置(self, 符号):
        """获取符号当前在哪个槽位"""
        return self.符号位置.get(符号, None)
    
    def 显示状态(self):
        """显示当前64槽位的状态"""
        print("=" * 50)
        print("当前64槽位状态：")
        print("=" * 50)
        for i in range(64):
            if self.槽位[i] is not None:
                相位 = self.相位表.get(self.槽位[i], "")
                print(f"  槽位{i:2d}: {self.槽位[i]:12s} | {相位}")
            else:
                print(f"  槽位{i:2d}: [空]")
        print("=" * 50)


