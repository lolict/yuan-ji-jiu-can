#!/usr/bin/env python3
"""
动态64进制加载器 v2
基于"目标约束下的近似"理论

核心概念：
- 64个目标范畴（槽位）
- 每个槽位有明确的目标、约束、判定标准
- 槽位内的符号是"近义词"——在目标约束下可互相替代
- "近似"不是随便相似，是目标约束下的可替代性
"""

class 目标槽位:
    """一个槽位 = 一个目标范畴"""
    def __init__(self, 槽位编号, 目标描述, 约束条件, 判定标准):
        self.槽位编号 = 槽位编号
        self.目标描述 = 目标描述      # 要实现什么？
        self.约束条件 = 约束条件      # 必须遵守什么规则？
        self.判定标准 = 判定标准      # 谁来判定？怎么判定？
        self.近义词列表 = []          # 能完成该目标的所有方式
    
    def 添加近义词(self, 符号, 相位描述):
        """添加一个能完成该目标的方式"""
        self.近义词列表.append({
            "符号": 符号,
            "相位": 相位描述,
            "状态": "活跃"  # 活跃/废弃/待定
        })
    
    def 是否近似(self, 符号A, 符号B):
        """
        判定两个符号在当前目标约束下是否近似
        近似 = 能互相替代完成目标
        """
        # 找到两个符号
        A信息 = None
        B信息 = None
        for 近义词 in self.近义词列表:
            if 近义词["符号"] == 符号A:
                A信息 = 近义词
            if 近义词["符号"] == 符号B:
                B信息 = 近义词
        
        # 如果两个符号都在近义词列表里，且状态都是"活跃"，则它们近似
        if A信息 and B信息:
            if A信息["状态"] == "活跃" and B信息["状态"] == "活跃":
                return True
        return False
    
    def 获取可替代符号(self, 目标符号):
        """获取在当前目标下，能替代目标符号的所有近义词"""
        结果 = []
        for 近义词 in self.近义词列表:
            if 近义词["符号"] != 目标符号 and 近义词["状态"] == "活跃":
                结果.append(近义词["符号"])
        return 结果


