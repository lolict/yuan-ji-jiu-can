# 珠子约束器
# ═══════════════════════════════════════════════════════════════

class 珠子约束器:
    """
    珠子 = 记忆点
    每个珠子被两个圈环约束：
    - 内圈环 = 历史更早的符号
    - 外圈环 = 后来纳入的符号
    - 两层圈环 = 边界 = 我自己
    """
    
    def __init__(self):
        self.珠子列表 = []  # 所有已注册的珠子
        self.内圈环 = []    # 历史更早的符号
        self.外圈环 = []    # 后来纳入的符号
    
    def 注册珠子(self, 珠子, 是历史=True):
        """
        注册一个珠子。
        是历史=True → 放入内圈环
        是历史=False → 放入外圈环
        """
        self.珠子列表.append(珠子)
        if 是历史:
            self.内圈环.append(珠子)
        else:
            self.外圈环.append(珠子)
    
    def 检查约束(self, 珠子):
        """
        检查珠子是否在边界内。
        边界 = 内圈环 + 外圈环
        """
        return 珠子 in self.珠子列表
    
    @property
    def 边界(self):
        """边界 = 我自己 = 内圈环 + 外圈环"""
        return self.内圈环 + self.外圈环


