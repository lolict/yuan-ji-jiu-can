class 检查结果:
    """互锁检查的结果"""
    
    def __init__(self):
        self.错误列表 = []
        self.警告列表 = []
        self.通过状态 = True
    
    def 添加错误(self, 错误信息):
        self.错误列表.append(错误信息)
        self.通过状态 = False
    
    def 添加警告(self, 警告信息):
        self.警告列表.append(警告信息)
    
    def 通过(self):
        return self.通过状态
    
    def 错误信息(self):
        return "\n".join(self.错误列表)
    
    def 警告信息(self):
        return "\n".join(self.警告列表)
    
    def 合并(self, 其他结果):
        """合并另一个检查结果"""
        self.错误列表.extend(其他结果.错误列表)
        self.警告列表.extend(其他结果.警告列表)
        if not 其他结果.通过状态:
            self.通过状态 = False


