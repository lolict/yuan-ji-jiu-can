# ═══════════════════════════════════════════════════════════════

class 负向概念检测器:
    """
    检测代码中是否使用了禁止的系统概念。
    禁止列表：类、对象、继承、多态、设计模式、文件、目录、进程...
    """
    
    def __init__(self):
        self.禁止概念 = [
            "类", "对象", "继承", "多态", "设计模式",
            "文件", "目录", "进程", "线程", "模块", "包",
            "接口", "实现", "封装", "override", "virtual",
            "template", "generic", "singleton", "factory",
            "observer", "MVC", "MVVM", "REST", "API",
            "endpoint", "microservice", "monolith",
            "函数", "变量", "数组", "字符串", "整数", "null",
            "循环", "递归", "遍历", "并行", "并发",
            "调用", "返回", "参数", "属性", "方法", "字段",
            "实例", "对象", "类"
        ]
    
    def 检测(self, 代码内容):
        """
        检测代码中是否包含负向概念。
        返回：(是否通过, 发现的禁止概念列表)
        """
        发现的禁止概念 = []
        for 概念 in self.禁止概念:
            if 概念 in 代码内容:
                发现的禁止概念.append(概念)
        
        return (len(发现的禁止概念) == 0, 发现的禁止概念)
    
    def 检测并报告(self, 代码内容):
        """检测并生成报告"""
        通过, 禁止概念 = self.检测(代码内容)
        if not 通过:
            return f"负向概念检测失败：发现 {len(禁止概念)} 个禁止概念：{', '.join(禁止概念)}"
        return "负向概念检测通过"


