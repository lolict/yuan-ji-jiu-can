class 五维审判器:
    """
    新符号入住必须经过五维审判：
    1. 发音审判：声母是否相同或邻近？韵母是否同调类？
    2. 字形审判：笔画结构是否共享部首或部件？
    3. 存在论审判：是否从同一个公倍数（公约数）分叉出来？
    4. 极性审判：是否同极性？（阴/阴或阳/阳才是近亲）
    5. 层级审判：是否在同一个袋子层级里？
    
    五维全部通过 = 合法近义词
    任一维未通过 = 冲突标记
    """
    
    def __init__(self):
        # 24声母表
        self.声母表 = [
            "b", "p", "m", "f", "d", "t", "n", "l",
            "g", "k", "h", "j", "q", "x",
            "zh", "ch", "sh", "r", "z", "c", "s",
            "y", "w", "∅"
        ]
        
        # 声调
        self.声调表 = ["平", "升", "凹", "降"]
    
    def 审判(self, 新符号, 已有符号):
        """
        对新符号进行五维审判。
        返回：(是否通过, 各维度结果)
        """
        结果 = {
            "发音审判": False,
            "字形审判": False,
            "存在论审判": False,
            "极性审判": False,
            "层级审判": False
        }
        
        # 发音审判：检查声母是否相同或邻近
        结果["发音审判"] = self._发音审判(新符号, 已有符号)
        
        # 字形审判：检查是否共享部首或部件
        结果["字形审判"] = self._字形审判(新符号, 已有符号)
        
        # 存在论审判：检查是否从同一个公倍数分叉
        结果["存在论审判"] = self._存在论审判(新符号, 已有符号)
        
        # 极性审判：检查是否同极性
        结果["极性审判"] = self._极性审判(新符号, 已有符号)
        
        # 层级审判：检查是否在同一个袋子层级
        结果["层级审判"] = self._层级审判(新符号, 已有符号)
        
        # 五维全部通过才算通过
        全部通过 = all(结果.values())
        
        return (全部通过, 结果)
    
    def _发音审判(self, 新符号, 已有符号):
        """发音审判：声母是否相同或邻近"""
        # 简化的发音审判：检查是否有共同字符
        return any(c in 已有符号 for c in 新符号 if c.isalpha())
    
    def _字形审判(self, 新符号, 已有符号):
        """字形审判：笔画结构是否共享部首或部件"""
        # 简化的字形审判：检查是否有共同汉字部件
        新汉字 = [c for c in 新符号 if '\u4e00' <= c <= '\u9fff']
        已有汉字 = [c for c in 已有符号 if '\u4e00' <= c <= '\u9fff']
        return any(c in 已有汉字 for c in 新汉字) if 新汉字 and 已有汉字 else True
    
    def _存在论审判(self, 新符号, 已有符号):
        """存在论审判：是否从同一个公倍数分叉"""
        # 简化的存在论审判：检查是否有共同前缀或后缀
        if len(新符号) > 1 and len(已有符号) > 1:
            return 新符号[0] == 已有符号[0] or 新符号[-1] == 已有符号[-1]
        return True
    
    def _极性审判(self, 新符号, 已有符号):
        """极性审判：是否同极性"""
        # 简化的极性审判：检查是否同为阴或同为阳
        阴符号 = ["阴", "虚", "寒", "降", "里", "亏"]
        阳符号 = ["阳", "实", "热", "升", "表", "盈"]
        
        新极性 = "阴" if any(s in 新符号 for s in 阴符号) else ("阳" if any(s in 新符号 for s in 阳符号) else "中")
        已有极性 = "阴" if any(s in 已有符号 for s in 阴符号) else ("阳" if any(s in 已有符号 for s in 阳符号) else "中")
        
        return 新极性 == 已有极性 or 新极性 == "中" or 已有极性 == "中"
    
    def _层级审判(self, 新符号, 已有符号):
        """层级审判：是否在同一个袋子层级"""
        # 简化的层级审判：检查是否包含层级标记
        层级标记 = ["元", "阶", "层", "代", "世", "界", "域", "场"]
        新层级 = any(s in 新符号 for s in 层级标记)
        已有层级 = any(s in 已有符号 for s in 层级标记)
        return 新层级 == 已有层级


