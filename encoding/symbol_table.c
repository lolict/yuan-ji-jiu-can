#define 符号总数 (sizeof(符号数据) / sizeof(符号数据[0]))

/* ═══════════════════════════════════════════════════════════════
 * 简单哈希索引 — 编译期确定大小，运行时一次建表
 * ═══════════════════════════════════════════════════════════════ */

#define 哈希容量 256  /* 2^8 > 195*1.3 */

static int 哈希表[哈希容量];     /* 值 = 符号地址, -1 = 空 */
static int 已建表 = 0;

static unsigned char 哈希函数(const char* str) {
    unsigned char h = 0;
    while (*str) {
        h = (h * 31) ^ (unsigned char)(*str);
        str++;
    }
    return h;
}

static void 建索引(void) {
    if (已建表) return;
    
    for (int i = 0; i < 哈希容量; i++) 哈希表[i] = -1;
    
    for (int i = 0; i < (int)符号总数; i++) {
        unsigned char h = 哈希函数(符号数据[i]);
        /* 线性探测 */
        while (哈希表[h] != -1) {
            h = (h + 1) & (哈希容量 - 1);
        }
        哈希表[h] = i;
    }
    
    已建表 = 1;
}

static int 静态查找(const char* 符号) {
    unsigned char h = 哈希函数(符号);
    while (哈希表[h] != -1) {
        int idx = 哈希表[h];
        if (strcmp(符号数据[idx], 符号) == 0) return idx;
        h = (h + 1) & (哈希容量 - 1);
    }
    return -1;
}

/* ═══════════════════════════════════════════════════════════════
 * 查询接口 — O(1) 查表
 * ═══════════════════════════════════════════════════════════════ */

int 查地址(const char* 符号) {
    if (!符号) return -1;
    建索引();
    return 静态查找(符号);
}

const char* 查符号(int 地址) {
    if (地址 < 0 || 地址 >= (int)符号总数) return NULL;
    return 符号数据[地址];
}

int 存在(const char* 符号) {
    return 查地址(符号) >= 0;
}

int 符号数量(void) {
    return (int)符号总数;
}

