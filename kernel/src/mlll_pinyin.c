#define KB_SIZE ((int)(sizeof(KB)/sizeof(KB[0])-1))

/* ============================================================
 * 基础查询
 * ============================================================ */
int mlll_pinyin_count(void) { return KB_SIZE; }

const pinyin_entry_t* mlll_pinyin_get(int idx) {
    static pinyin_entry_t cache[512];
    static int initialized = 0;
    if (!initialized) {
        for (int i = 0; i < KB_SIZE; i++) {
            memcpy(cache[i].utf8, KB[i].utf8, 4);
            strncpy(cache[i].pinyin, KB[i].py, 8);
            cache[i].prop.stroke    = KB[i].stroke;
            cache[i].prop.tone      = KB[i].tone;
            cache[i].prop.radical   = KB[i].radical;
            cache[i].prop.structure = KB[i].structure;
            cache[i].prop.vowel     = KB[i].vowel;
            cache[i].prop.initial   = KB[i].initial;
        }
        initialized = 1;
    }
    if (idx < 0 || idx >= KB_SIZE) return NULL;
    return &cache[idx];
}

const pinyin_entry_t* mlll_pinyin_lookup_by_char(const char* ch) {
    if (!ch) return NULL;
    int len = (int)strlen(ch);
    for (int i = 0; i < KB_SIZE; i++) {
        if (strncmp(KB[i].utf8, ch, len) == 0 && KB[i].utf8[len] == 0)
            return mlll_pinyin_get(i);
    }
    return NULL;
}

int mlll_pinyin_find_by_pinyin(int initial_idx, int vowel_idx, int tone_idx, int* out, int max_out) {
    int cnt = 0;
    for (int i = 0; i < KB_SIZE && cnt < max_out; i++) {
        if ((initial_idx < 0 || (int)KB[i].initial == initial_idx) &&
            (vowel_idx   < 0 || (int)KB[i].vowel   == vowel_idx)   &&
            (tone_idx   < 0 || (int)KB[i].tone    == tone_idx)) {
            out[cnt++] = i;
        }
    }
    return cnt;
}

/* ============================================================
 * 拼音串 → 声母索引
 * 优先匹配双字母声母 (zh/ch/sh)，再匹单字母。
 * ============================================================ */
int mlll_pinyin_initial(const char* pinyin) {
    if (!pinyin || !*pinyin) return -1;
    /* 去除声调符号后的纯拉丁副本 */
    char pure[16]; int pn = 0;
    for (int i = 0; pinyin[i] && pn < 15; i++) {
        unsigned char c = (unsigned char)pinyin[i];
        if (c >= 'a' && c <= 'z') pure[pn++] = c;
        else if (c == 'v') pure[pn++] = 'v';
        else if (c == 0xC4) { /* 开头可能无声调 */
            /* 跳过备用 */
        }
    }
    pure[pn] = 0;
    if (pn == 0) return -1;

    /* 双字母优先 */
    char two[3] = { pure[0], pure[1] ? pure[1] : 0, 0 };
    for (int i = 14; i <= 16; i++) {  /* zh ch sh */
        if (strcmp(two, INITIAL_TABLE[i]) == 0) return i;
    }
    /* 单字母 */
    for (int i = 0; i < 14; i++) {
        if (pure[0] == INITIAL_TABLE[i][0] && INITIAL_TABLE[i][1] == 0) return i;
    }
    /* y/w */
    if (pure[0] == 'y') return 21;
    if (pure[0] == 'w') return 22;
    /* 零声母 */
    if (pure[0] == 'a' || pure[0] == 'o' || pure[0] == 'e') return 23;
    return -1;
}

/* ============================================================
 * 拼音串 → 韵母索引
 * 先剥离声母，剩余即韵母。
 * ============================================================ */
int mlll_pinyin_vowel(const char* pinyin) {
    if (!pinyin || !*pinyin) return -1;
    char pure[16]; int pn = 0;
    for (int i = 0; pinyin[i] && pn < 15; i++) {
        unsigned char c = (unsigned char)pinyin[i];
        if (c >= 'a' && c <= 'z') pure[pn++] = c;
        else if (c >= 0xc0) pure[pn++] = 'v'; /* ü in UTF-8 starts with 0xc3 0xbc */
    }
    pure[pn] = 0;
    if (pn == 0) return -1;
    int ini = mlll_pinyin_initial(pinyin);
    const char* istr = NULL;
    if (ini >= 0 && ini < 24) {
        if (ini == 23) return -1;
        istr = INITIAL_TABLE[ini];
    }
    int ilen = istr ? (int)strlen(istr) : 0;
    if (ilen >= pn) return -1;
    char rem[16];
    int rn = 0;
    for (int i = ilen; i < pn; i++) rem[rn++] = pure[i];
    rem[rn] = 0;

    int best = -1, best_len = 0;
    for (int i = 0; i < N_VOWELS; i++) {
        int l = (int)strlen(VOWEL_TABLE[i]);
        if (rn >= l && strncmp(rem, VOWEL_TABLE[i], l) == 0 && l > best_len) {
            best = i; best_len = l;
        }
    }
    return best;
}

/* ============================================================
 * 拼音串 → 声调
 * 从原始拼音串检测声调符号。
 * ============================================================ */
int mlll_pinyin_tone(const char* pinyin) {
    if (!pinyin) return -1;
    /* 检测声调: 阴平(¯) 阳平(´) 上声(ˇ) 去声(ˋ) 轻声(无) */
    for (int i = 0; pinyin[i]; i++) {
        unsigned char c = (unsigned char)pinyin[i];
        if (c == 0xc4) return 0;  /* ā 阴平 */
        if (c == 0xc3) {
            unsigned char nxt = (unsigned char)pinyin[i+1];
            if (nxt == 0xa1) return 1;  /* á 阳平 */
            if (nxt == 0xa0) return 2;  /* ǎ 上声 */
            if (nxt == 0xa0) return 3;  /* à 去声 */
        }
    }
    return 4;  /* 默认轻声 */
}

/* ============================================================
 * 计算完整 MLLL 属性（从串 + 笔画 + 部首外部注入）
 * ============================================================ */
void mlll_pinyin_compute_prop(const char* pinyin, int stroke, int radical, int structure, char_prop_t* out) {
    out->stroke    = stroke;
    out->tone      = mlll_pinyin_tone(pinyin);
    out->radical   = radical;
    out->structure = structure;
    out->vowel     = mlll_pinyin_vowel(pinyin);
    out->initial   = mlll_pinyin_initial(pinyin);
}

/* ============================================================
 * 基于拼音的夫妻对偶查询
 *   在知识库中找与给定拼音"互补"的字（声母差 + 韵母差 + 声调差最大化）
 * ============================================================ */
typedef struct {
    int idx;
    double score;
} spouse_candidate_t;

/* 找最匹配夫妻对偶的字 */
int mlll_find_spouse(const char* utf8_char, int* out_indices, int max_out) {
    const pinyin_entry_t* me = mlll_pinyin_lookup_by_char(utf8_char);
    if (!me) return 0;

    spouse_candidate_t* cands = (spouse_candidate_t*)malloc(KB_SIZE * sizeof(spouse_candidate_t));
    int nc = 0;
    for (int i = 0; i < KB_SIZE; i++) {
        /* 跳过字身 */
        if (strncmp(KB[i].utf8, utf8_char, 4) == 0 && KB[i].utf8[strlen(utf8_char)] == 0) continue;
        /* 互补度声母异+韵母异+声调异 */
        double score = abs((int)KB[i].initial - (int)me->prop.initial) * 1.0
                     + abs((int)KB[i].vowel   - (int)me->prop.vowel)   * 1.0
                     + abs((int)KB[i].tone    - (int)me->prop.tone)    * 1.0;
        cands[nc].idx   = i;
        cands[nc].score = score;
        nc++;
    }
    /* 按互补度降序排列 */
    for (int i = 0; i < nc - 1; i++)
        for (int j = i + 1; j < nc; j++)
            if (cands[j].score > cands[i].score) {
                spouse_candidate_t t = cands[i]; cands[i] = cands[j]; cands[j] = t;
            }
    int n = nc < max_out ? nc : max_out;
    for (int i = 0; i < n; i++)
        out_indices[i] = cands[i].idx;
    free(cands);
    return n;
}
