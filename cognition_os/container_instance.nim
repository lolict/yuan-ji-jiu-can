# ═══════════════════════════════════════════════════════════════
# 三维声音地址实例(实物)
# ═══════════════════════════════════════════════════════════════
type
  SoundAddress* = object
    sheng*: string    # 声母(来自声母容器)
    yun*: string      # 韵母(来自韵母容器)
    tone*: string     # 声调(来自声调容器 · 贴附)
    address*: string  # 完整地址 = 声母+韵母+声调

func make_address*(s, y, t: string): SoundAddress =
  result.sheng = s
  result.yun = y
  result.tone = t
  result.address = s & y & t

