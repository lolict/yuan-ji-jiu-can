proc 构建依赖图*(e: var 统一引擎) =
  for i in 0..<e.注册表.len:
    for 依赖名 in e.注册表[i].依赖:
      for j in 0..<e.注册表.len:
        if e.注册表[j].名字 == 依赖名:
          e.注册表[j].被依赖.add(e.注册表[i].名字)

#==============================================================
#  接口对齐验证
#==============================================================

func 验证接口对齐*(e: 统一引擎): tuple[通过: int; 失败: int; 详情: seq[string]] =
  var 详情: seq[string] = @[]
  var 通过 = 0
  var 失败 = 0

  for 引擎 in e.注册表:
    for 依赖名 in 引擎.依赖:
      var 找到 = false
      for 候选 in e.注册表:
        if 候选.名字 == 依赖名:
          找到 = true
          break
      if 找到:
        通过 += 1
        详情.add "  ✓ " & 引擎.名字 & " → " & 依赖名
      else:
        失败 += 1
        详情.add "  ✗ " & 引擎.名字 & " → " & 依赖名 & " [未找到]"

  (通过, 失败, 详情)

