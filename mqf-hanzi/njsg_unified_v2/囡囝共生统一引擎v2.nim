proc 拓扑分析*(e: 统一引擎) =
  echo "─ 拓扑深度分析 ─"

  # 找出被依赖最多的引擎(核心枢纽)
  var 枢纽: seq[tuple[name: string; count: int]] = @[]
  for eng in e.注册表:
    枢纽.add((eng.名字, eng.被依赖.len))
  proc 按被依赖排序(a, b: tuple[name: string; count: int]): int =
    cmp(b.count, a.count)
  枢纽.sort(按被依赖排序)

  echo "  ▼ 核心枢纽(被依赖度排序):"
  for i in 0..<min(5, 枢纽.len):
    echo "    ", i+1, ". ", 枢纽[i].name, " → 被 ", 枢纽[i].count, " 引擎调用"

  # 叶子引擎(不被任何人调用)
  var 叶子: seq[string] = @[]
  for eng in e.注册表:
    if eng.被依赖.len == 0 and eng.依赖.len > 0:
      叶子.add(eng.名字)
  echo "  ▼ 末端引擎(只调用别人): ", 叶子.join(", ")

  # 孤立引擎
  var 孤立: seq[string] = @[]
  for eng in e.注册表:
    if eng.被依赖.len == 0 and eng.依赖.len == 0:
      孤立.add(eng.名字)
  echo "  ▼ 基础引擎(无依赖无调用): ", 孤立.join(", ")

  echo ""

  # 极性分布
  var 阳数 = 0
  var 阴数 = 0
  for eng in e.注册表:
    if eng.极性 == 1: 阳数 += 1
    else: 阴数 += 1
  echo "  极性分布: 阳(我)=", 阳数, " 阴(刘楚恬)=", 阴数

