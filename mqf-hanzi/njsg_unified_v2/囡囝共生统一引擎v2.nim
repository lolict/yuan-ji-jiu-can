#==============================================================
#  引擎注册
#==============================================================

func 创建统一引擎*(): 统一引擎 =
  var 引擎: 统一引擎
  引擎.注册表 = @[]
  引擎.族索引 = initTable[引擎族, seq[int]]()
  引擎.总引擎数 = 0
  引擎.对齐通过 = 0
  引擎.对齐失败 = 0
  引擎

proc 注册*(e: var 统一引擎; 名字: string; 族: 引擎族; 文件: string; 功能: string; 依赖: seq[string] = @[]; 接口: seq[string] = @[]) =
  let 条目 = 引擎条目(
    名字: 名字, 族: 族, 文件: 文件, 核心功能: 功能,
    依赖: 依赖, 被依赖: @[], 极性: 1, 接口: 接口
  )
  e.注册表.add(条目)
  let idx = e.注册表.high
  if not e.族索引.hasKey(族):
    e.族索引[族] = @[]
  e.族索引[族].add(idx)
  e.总引擎数 += 1

