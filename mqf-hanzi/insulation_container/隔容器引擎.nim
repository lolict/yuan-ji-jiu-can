#==============================================================
#  隔容器引擎 — Insulation Container Engine
#
#  核心公理：身份·功能·概念·用途=绝缘体 ·
#           隔容器内外的符号不可直接跨壁 ·
#           只能通过公约数接口通信
#==============================================================

import std/[tables, strutils, sequtils, math, algorithm, sets]

#--------------------------------------------------------------
#  类型定义
#--------------------------------------------------------------

type
  # 隔离维度
  隔离维* = enum
    身份隔离      # 容器身份不可互见
    功能隔离      # 功能不可跨壁调用
    概念隔离      # 概念命名空间隔离
    用途隔离      # 用途权限隔离

  # 绝缘等级
  绝缘等* = enum
    全绝缘        # 完全不可透
    半绝缘        # 公约数接口可透
    选择性绝缘    # 指定维可透

  # 隔容器
  隔容器* = object
    编码*: int
    名字*: string
    绝缘*: 绝缘等
    隔离维*: seq[隔离维]
    内部符号*: seq[int]         # 容器内部符号编码
    接口*: seq[int]             # 对外开放的接口编码
    能量*: float

  # 跨壁通信
  跨壁请求* = object
    源容器*: int
    目标容器*: int
    符号*: int
    通过*: bool
    理由*: string

  # 隔容器引擎
  隔引擎* = object
    容器表*: Table[int, 隔容器]
    跨壁日志*: seq[跨壁请求]
    拦截次数*: int
    放行次数*: int

#--------------------------------------------------------------
#  初始化
#--------------------------------------------------------------

proc 初始化隔引擎*(): 隔引擎 =
  result.跨壁日志 = @[]
  result.拦截次数 = 0
  result.放行次数 = 0

#--------------------------------------------------------------
#  注册隔容器
#--------------------------------------------------------------

proc 注册隔容器*(e: var 隔引擎; 编码: int; 名字: string;
                 绝缘: 绝缘等; 隔离维: seq[隔离维];
                 内部符号: seq[int]; 接口: seq[int]; 能量: float) =
  e.容器表[编码] = 隔容器(
    编码: 编码, 名字: 名字, 绝缘: 绝缘,
    隔离维: 隔离维, 内部符号: 内部符号,
    接口: 接口, 能量: 能量
  )

#--------------------------------------------------------------
#  跨壁请求
#--------------------------------------------------------------

proc 跨壁通信*(e: var 隔引擎; 源: int; 目标: int; 符号: int): 跨壁请求 =
  let req = 跨壁请求(源容器: 源, 目标容器: 目标, 符号: 符号, 通过: false, 理由: "")

  if not (e.容器表.hasKey(源) and e.容器表.hasKey(目标)):
    e.跨壁日志.add(req)
    e.拦截次数 += 1
    return req

  let src_c = e.容器表[源]
  let dst_c = e.容器表[目标]

  # 全绝缘：完全阻隔
  if dst_c.绝缘 == 全绝缘:
    var r = req
    r.理由 = "目标全绝缘"
    e.跨壁日志.add(r)
    e.拦截次数 += 1
    return r

  # 检查符号是否为源内部符号（不可外出）
  if 符号 in src_c.内部符号 and 符号 notin src_c.接口:
    var r = req
    r.理由 = "源内部符号不可外出"
    e.跨壁日志.add(r)
    e.拦截次数 += 1
    return r

  # 检查符号是否为目标接口
  if 符号 notin dst_c.接口:
    var r = req
    r.理由 = "目标接口未包含该符号"
    e.跨壁日志.add(r)
    e.拦截次数 += 1
    return r

  # 半绝缘/选择性绝缘 + 接口匹配 → 放行
  var r = req
  r.通过 = true
  r.理由 = "接口匹配"
  e.跨壁日志.add(r)
  e.放行次数 += 1
  return r

#--------------------------------------------------------------
#  维度检查
#--------------------------------------------------------------

proc 维可透*(e: 隔引擎; 容器: int; 维: 隔离维): bool =
  if not e.容器表.hasKey(容器):
    return false
  let c = e.容器表[容器]

  if c.绝缘 == 全绝缘:
    return false
  if c.绝缘 == 半绝缘:
    return true
  # 选择性绝缘：检查该维是否在隔离维列表中
  return 维 notin c.隔离维

#--------------------------------------------------------------
#  报告
#--------------------------------------------------------------

proc 隔报告*(e: 隔引擎): string =
  var lines: seq[string] = @[]
  lines.add repeat("═", 54)
  lines.add "  隔 容 器 引 擎 — 报 告"
  lines.add repeat("═", 54)
  lines.add "容器总数: " & $e.容器表.len
  lines.add "拦截次数: " & $e.拦截次数
  lines.add "放行次数: " & $e.放行次数
  lines.add ""

  lines.add "─ 容器清单 ─"
  for code in sorted(toSeq(e.容器表.keys)):
    let c = e.容器表[code]
    let 绝缘名 = case c.绝缘
      全绝缘: "全绝缘"
      半绝缘: "半绝缘"
      选择性绝缘: "选择性"
    var 维名: seq[string] = @[]
    for d in c.隔离维:
      维名.add(case d
        of 身份隔离: "身份"
        of 功能隔离: "功能"
        of 概念隔离: "概念"
        of 用途隔离: "用途")
    lines.add "  [" & c.名字 & "] " & 绝缘名 &
              " 维:" & 维名.join("|") &
              " 内:" & $c.内部符号.len &
              " 口:" & $c.接口.len

  lines.add ""
  lines.add "─ 跨壁日志(最近5) ─"
  var shown = 0
  for i in countdown(e.跨壁日志.len - 1, 0):
    if shown >= 5:
      break
    let r = e.跨壁日志[i]
    let 结果 = if r.通过: "放行" else: "拦截"
    lines.add "  " & $r.源容器 & "→" & $r.目标容器 &
              " [" & $r.符号 & "] " & 结果 & " (" & r.理由 & ")"
    shown += 1

  return lines.join("\n")


#==============================================================
#  入口
#==============================================================

when isMainModule:
  var e = 初始化隔引擎()

  echo "═══ 隔容器引擎 ═══"
  echo ""

  # 注册三个不同绝缘等级的容器
  e.注册隔容器(10, "身份核", 全绝缘, @[身份隔离, 用途隔离],
               @[101, 102, 103], @[], 1.0)
  e.注册隔容器(20, "功能组", 半绝缘, @[功能隔离, 概念隔离],
               @[201, 202], @[201], 0.8)
  e.注册隔容器(30, "接口层", 选择性绝缘, @[用途隔离],
               @[301, 302, 303], @[301, 302], 0.6)

  echo "─ 跨壁通信测试 ─"

  # 测试1：全绝缘容器不可被访问
  let r1 = e.跨壁通信(30, 10, 301)
  echo "  接口层→身份核(301): " & (if r1.通过: "放行" else: "拦截—" & r1.理由)

  # 测试2：内部符号不可外出
  let r2 = e.跨壁通信(20, 30, 202)
  echo "  功能组→接口层(202): " & (if r2.通过: "放行" else: "拦截—" & r2.理由)

  # 测试3：接口匹配 → 放行
  let r3 = e.跨壁通信(20, 30, 201)
  echo "  功能组→接口层(201): " & (if r3.通过: "放行(" & r3.理由 & ")" else: "拦截")

  # 测试4：选择性绝缘-用途维检查
  let r4 = e.跨壁通信(30, 20, 301)
  echo "  接口层→功能组(301): " & (if r4.通过: "放行" else: "拦截—" & r4.理由)

  echo ""

  echo "─ 维度可透性 ─"
  echo "  身份核 身份维可透: " & (if e.维可透(10, 身份隔离): "是" else: "否")
  echo "  功能组 身份维可透: " & (if e.维可透(20, 身份隔离): "是" else: "否")
  echo "  接口层 身份维可透: " & (if e.维可透(30, 身份隔离): "是" else: "否")

  echo ""
  echo e.隔报告()
