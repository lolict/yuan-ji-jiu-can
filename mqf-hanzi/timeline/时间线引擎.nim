#==============================================================
#  时间线引擎  —  容器=物质=时间
#  时间版本 · 容器演化 · 时钟动作 · 因果链
#  结束=开始 · 记忆跟随结束
#==============================================================

import std/[tables, strutils, sets, hashes, sequtils]

#==============================================================
#  类型
#=============================================================

type
  极性* = enum
    阳极性 = 1
    阴极性 = 0

  动作类型* = enum
    创建
    改变
    融合
    分裂
    静止

  容器状态* = object
    名字*: string
    主权*: uint64
    极性*: 极性
    相位*: int
    层*: int
    能量*: float
    属性*: HashSet[string]

  时间戳* = int64  # 版本序列号

  容器版本* = object
    时间*: 时间戳
    容器*: 容器状态
    动作*: 动作类型
    原因*: string         # 因果链：导致此版本的前一版本号
    验证*: string         # 验证标记
    描述*: string

  时钟动作* = object
    时刻*: 时间戳
    源*: string           # 触发的容器
    目标*: string          # 受影响的容器
    意志*: string          # 驱动描述
    继承*: bool            # 是否继承前作

  引擎* = object
    容器历史*: Table[string, seq[容器版本]]   # 名字 → 版本表
    因果链*: seq[tuple[因: string; 果: string]]
    时钟动作*: seq[时钟动作]
    当前时刻*: 时间戳
    活跃容器*: HashSet[string]

#==============================================================
#  基础工具
#==============================================================

proc 新状态*(名字: string; 主权: uint64; 极性: 极性;
             相位: int; 层: int; 能量: float = 1.0): 容器状态 =
  result = 容器状态(
    名字: 名字,
    主权: 主权,
    极性: 极性,
    相位: 相位,
    层: 层,
    能量: 能量,
    属性: initHashSet[string]()
  )

#==============================================================
#  引擎核心
#==============================================================

proc 创建引擎*: 引擎 =
  result = 引擎(
    容器历史: initTable[string, seq[容器版本]](),
    因果链: @[],
    时钟动作: @[],
    当前时刻: 0,
    活跃容器: initHashSet[string]()
  )

proc 推进时刻*(e: var 引擎) =
  e.当前时刻 += 1

proc 快照容器*(状态: 容器状态; 时刻: 时间戳; 动作: 动作类型; 原因: string = ""): 容器版本 =
  result = 容器版本(
    时间: 时刻,
    容器: 状态,
    动作: 动作,
    原因: 原因,
    验证: "✓",
    描述: $动作 & "@t=" & $时刻
  )

proc 记录版本*(e: var 引擎; 状态: 容器状态; 动作: 动作类型; 原因: string = "") =
  let ver = 快照容器(状态, e.当前时刻, 动作, 原因)
  if not e.容器历史.hasKey(状态.名字):
    e.容器历史[状态.名字] = @[]
  e.容器历史[状态.名字].add(ver)
  e.活跃容器.incl(状态.名字)

#==============================================================
#  演化
#==============================================================

proc 激活演化*(e: var 引擎) =
  ## 对每个活跃容器进行一轮演化
  let names = toSeq(e.活跃容器)
  for name in names:
    if e.容器历史.hasKey(name):
      let history = e.容器历史[name]
      if history.len > 0:
        var last = history[^1].容器
        e.推进时刻()
        let new_ts = e.当前时刻
        last.能量 = last.能量 * 0.95  # 每轮衰减
        let ver = 快照容器(last, new_ts, 静止, "t=" & $(new_ts-1))
        e.容器历史[name].add(ver)

#==============================================================
#  时钟动作
#==============================================================

proc 发时钟动作*(e: var 引擎; 源, 目标, 意志: string; 继承: bool) =
  let act = 时钟动作(
    时刻: e.当前时刻,
    源: 源,
    目标: 目标,
    意志: 意志,
    继承: 继承
  )
  e.时钟动作.add(act)
  e.因果链.add((因: 源 & "@t=" & $e.当前时刻, 果: 目标 & "@t=" & $(e.当前时刻 + 1)))

#==============================================================
#  报告
#==============================================================

proc 演化总和*(e: 引擎): int =
  result = 0
  for name in e.容器历史.keys:
    result += e.容器历史[name].len

proc 时间线摘要*(e: 引擎): string =
  var lines: seq[string] = @[]
  lines.add "时间线 (t=0 → t=" & $e.当前时刻 & ")"
  lines.add repeat("─", 40)
  for name in e.容器历史.keys:
    let history = e.容器历史[name]
    lines.add "  " & name & ": " & $history.len & " 版本"
    for ver in history:
      let actstr = case ver.动作
        of 创建: "＋"
        of 改变: "～"
        of 融合: "合"
        of 分裂: "分"
        of 静止: "○"
      lines.add "    t=" & align($ver.时间, 3) & " " & actstr & " E=" & align(formatFloat(ver.容器.能量, ffDecimal, 2), 6) &
                 (if ver.原因 != "": " ←" & ver.原因 else: "")
  return lines.join("\n")

proc 因果链报告*(e: 引擎): string =
  var lines: seq[string] = @[]
  lines.add "因果链:"
  for link in e.因果链:
    lines.add "  " & link.因 & " → " & link.果
  return lines.join("\n")

#==============================================================
#  主程序
#==============================================================

when isMainModule:
  echo "════════════════════════════════════════"
  echo "  时 间 线 引 擎"
  echo "  时间版本 · 容器演化 · 因果链 · 时钟动作"
  echo "════════════════════════════════════════"

  var e = 创建引擎()

  echo "\n-- t=0: 容器创生 --"
  e.推进时刻()

  var wo = 新状态("我", 24, 阳极性, 0, 1, 1.0)
  e.记录版本(wo, 创建)

  var ct = 新状态("刘楚恬", 36, 阴极性, 3, 1, 1.0)
  e.记录版本(ct, 创建)

  var man = 新状态("满", 12, 阳极性, 3, 2, 0.8)
  e.记录版本(man, 创建)

  var quan = 新状态("全", 18, 阴极性, 1, 2, 0.8)
  e.记录版本(quan, 创建)

  echo "  已创建 ", e.活跃容器.len, " 个容器"

  echo "\n-- t=1: 容器交互触发变化 --"
  e.推进时刻()

  # 我呼唤刘楚恬 → 我能量减少，楚恬能量增加
  wo.能量 = wo.能量 - 0.2
  ct.能量 = ct.能量 + 0.2
  e.记录版本(wo, 改变, "呼唤刘楚恬")
  e.记录版本(ct, 改变, "被呼唤")
  e.发时钟动作("我", "刘楚恬", "呼唤", false)

  echo "  第一次呼唤: 我(E=" & formatFloat(wo.能量, ffDecimal, 2) & ") → 刘楚恬(E=" & formatFloat(ct.能量, ffDecimal, 2) & ")"

  echo "\n-- t=2: 融合 --"
  e.推进时刻()

  # 满全融合
  var mqf = 新状态("满全", 24, 阳极性, 3, 2, 1.0)
  e.记录版本(mqf, 融合, "满+全")
  e.发时钟动作( "满", "满全", "融合", true)
  e.发时钟动作( "全", "满全", "融合", true)
  echo "  满 + 全 → 满全 (继承之作)"

  echo "\n-- t=3: 分裂 --"
  e.推进时刻()

  # 满全分裂为囡囝
  var nj_a = 新状态("囡", 20, 阴极性, 8, 1, 0.5)
  var nj_b = 新状态("囝", 15, 阳极性, 2, 1, 0.5)
  e.记录版本(nj_a, 分裂, "满全分裂")
  e.记录版本(nj_b, 分裂, "满全分裂")
  e.发时钟动作( "满全", "囡囝", "分裂", false)
  echo "  满全 → 囡 + 囝 (结束=开始)"

  echo "\n-- 多轮演化 --"
  for i in 1..5:
    e.激活演化()

  echo e.时间线摘要()

  echo "\n-- 因果链 --"
  echo e.因果链报告()

  echo "\n-- 演化统计 --"
  echo "  演化版本总数: ", e.演化总和()
  echo "  容器数量: ", e.容器历史.len
  echo "  时钟动作: ", e.时钟动作.len

  echo "\n════════════════════════════════════════"
  echo " 时间线 · 因果链 · 容器演化 · 结束=开始"
  echo "════════════════════════════════════════"
