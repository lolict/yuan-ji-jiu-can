#==============================================================
#  基本类型
#=============================================================

type
  极性* = enum
    阳极性 = 1  # 我=1(阳)
    阴极性 = 0  # 刘楚恬=0(阴)

  真值* = enum
    真
    假
    未定

  容器* = object
    名字*: string
    主权*: uint64
    极性*: 极性
    相位*: int
    层*: int
    属性*: HashSet[string]

  命题* = object
    名字*: string
    主体*: string      # 容器名
    谓词*: string      # 属性名
    真值*: 真值
    证据*: seq[string]  # 证据链
    判断依据*: string   # 判断引擎给出的理由

  推理规则* = object
    前提*: seq[string]   # 前提命题名
    结论*: string        # 结论命题名
    规则类型*: string    # 演绎/归纳/类比

  判断引擎* = object
    容器表*: Table[string, 容器]
    命题表*: Table[string, 命题]
    规则表*: seq[推理规则]
    判断历史*: seq[string]
    裁定计数*: int

#==============================================================
#  GCD
#==============================================================

proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

#==============================================================
#  引擎与注册
#==============================================================

proc 创建判断引擎*: 判断引擎 =
  result = 判断引擎(
    容器表: initTable[string, 容器](),
    命题表: initTable[string, 命题](),
    规则表: @[],
    判断历史: @[],
    裁定计数: 0
  )

proc 注册容器*(e: var 判断引擎; 名字: string; 主权: uint64;
               极性: 极性; 相位: int; 层: int) =
  e.容器表[名字] = 容器(
    名字: 名字,
    主权: 主权,
    极性: 极性,
    相位: 相位,
    层: 层,
    属性: initHashSet[string]()
  )

proc 加属性*(e: var 判断引擎; 名字: string; 属性名: string) =
  if e.容器表.hasKey(名字):
    e.容器表[名字].属性.incl(属性名)

#==============================================================
#  核心判断：基于极性与公约数的真值裁定
#==============================================================

proc 裁定真值*(e: var 判断引擎; 主体名: string; 谓词: string): 真值 =
  if not e.容器表.hasKey(主体名):
    return 未定

  let c = e.容器表[主体名]

  # 规则1：若容器已有此属性，则为真
  if 谓词 in c.属性:
    return 真

  # 规则2：基于极性推导
  # "生"属性：阳极性容器倾向于"生"
  # "归"属性：阴极性容器倾向于"归"
  var derived = false
  if 谓词 == "生" and c.极性 == 阳极性:
    derived = true
  if 谓词 == "归" and c.极性 == 阴极性:
    derived = true
  if 谓词 == "动" and c.极性 == 阳极性 and c.层 <= 2:
    derived = true
  if 谓词 == "静" and c.极性 == 阴极性 and c.层 >= 2:
    derived = true

  if derived:
    return 真

  # 规则3：基于主权公约数推导
  # 阳极性主权为偶数的容器可"合"
  if 谓词 == "合":
    if c.极性 == 阳极性 and (c.主权 mod 2'u64) == 0'u64:
      return 真
    elif c.极性 == 阴极性 and (c.主权 mod 3'u64) == 0'u64:
      return 真

  # 规则4：层判别
  if 谓词 == "根" and c.层 == 1:
    return 真
  if 谓词 == "枝" and c.层 == 2:
    return 真
  if 谓词 == "叶" and c.层 >= 3:
    return 真

  # 判定为假的情形
  if 谓词 == "生" and c.极性 == 阴极性:
    return 假
  if 谓词 == "归" and c.极性 == 阳极性:
    return 假

  return 未定

#==============================================================
#  提交命题
#==============================================================

proc 提交命题*(e: var 判断引擎; 名字: string; 主体: string; 谓词: string): 命题 =
  let tv = e.裁定真值(主体, 谓词)
  var 依据: string
  case tv
  of 真:
    依据 = "极性+属性推导"
    加属性(e, 主体, 谓词)
  of 假:
    依据 = "极性排斥"
  of 未定:
    依据 = "证据不足"

  result = 命题(
    名字: 名字,
    主体: 主体,
    谓词: 谓词,
    真值: tv,
    证据: @[依据],
    判断依据: 依据
  )
  e.命题表[名字] = result
  e.判断历史.add("裁定[" & 名字 & "]: " & 主体 & "." & 谓词 & " = " & $tv)
  e.裁定计数 += 1

#==============================================================
#  关系推理：基于公约数的关系判定
#==============================================================

proc 裁定关系*(e: 判断引擎; 甲名: string; 乙名: string): string =
  if not e.容器表.hasKey(甲名) or not e.容器表.hasKey(乙名):
    return "未知"
  let a = e.容器表[甲名]
  let b = e.容器表[乙名]
  let g = gcd(a.主权, b.主权)
  let gap = ord(a.极性) xor ord(b.极性)
  let 层距 = abs(a.层 - b.层)

  if gap == 1 and g > 0:
    if 层距 == 0:
      return "合(同层)"
    elif 层距 == 1:
      return "续(跨层)"
    else:
      return "遥(远距)"
  elif gap == 0:
    if g > 0:
      return "争(同极性有公约)"
    else:
      return "斥(同极性无公约)"
  else:
    return "离(无公约)"

#==============================================================
#  逻辑组织：命题网络
#==============================================================

proc 加规则*(e: var 判断引擎; 前提: seq[string]; 结论: string; 规则类型: string) =
  e.规则表.add(推理规则(前提: 前提, 结论: 结论, 规则类型: 规则类型))

proc 应用规则*(e: var 判断引擎; 规则: 推理规则): string =
  var 全为真 = true
  for 前提名 in 规则.前提:
    if e.命题表.hasKey(前提名):
      if e.命题表[前提名].真值 != 真:
        全为真 = false
    else:
      全为真 = false

  if 全为真:
    if e.命题表.hasKey(规则.结论):
      return "规则激活[" & 规则.规则类型 & "] → " & 规则.结论 & " (真)"
    else:
      return "规则激活[" & 规则.规则类型 & "] → " & 规则.结论 & "(新)"
  else:
    return "规则待触发[" & 规则.规则类型 & "] → 前提未全满足"

#==============================================================
#  报告
#==============================================================

proc 命题报告*(e: 判断引擎): string =
  var lines: seq[string] = @[]
  lines.add "命题       主体.谓词        真值     依据"
  lines.add "──────── ────────────── ──────── ──────────"
  for name in e.命题表.keys:
    let p = e.命题表[name]
    let tvstr = case p.真值
      of 真: "真"
      of 假: "假"
      of 未定: "未定"
    lines.add align(p.名字, 10) & " " &
             align(p.主体 & "." & p.谓词, 14) & " " &
             align(tvstr, 8) & " " & p.判断依据
  return lines.join("\n")

proc 关系矩阵*(e: 判断引擎): string =
  var lines: seq[string] = @[]
  let names = toSeq(e.容器表.keys)
  lines.add "关系矩阵: 甲 → 乙"
  lines.add repeat("─", 50)
  for a in names:
    var parts: seq[string] = @[]
    for b in names:
      if a != b:
        let r = e.裁定关系(a, b)
        parts.add b & ":" & r
    if parts.len > 0:
      lines.add "  " & align(a, 8) & " → " & parts.join(", ")
  return lines.join("\n")

