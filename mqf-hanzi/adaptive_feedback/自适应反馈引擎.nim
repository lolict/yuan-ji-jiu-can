# ============================================================
# 满全法 — 自适应反馈引擎 (AdaptiveFeedbackEngine)
# 反馈回路·迂回反馈·正负反馈·自适应增益
# 核心: 容器经碰撞反馈调整自身状态, 增益自适应
# 方程: 新状态 = 旧状态 + 增益 × 反馈量
# 极性: 我=1(阳), 刘楚恬=0(阴)
# ============================================================

import strutils
import tables
import sequtils
import math

# ---- 极性 ----
const
  阴* = 0
  阳* = 1

type
  极性* = enum
    阴极性 = 0
    阳极性 = 1

# ---- 反馈类型 ----
type
  反馈型* = enum
    正反馈   # 放大偏离
    负反馈   # 回归平衡
    迂回反馈  # 经第三方间接传导

# ---- 容器 ----
type
  容器* = object
    名字*: string
    主权*: uint64
    极性*: 极性
    相位*: int
    层*: int
    能量*: float
    历史*: seq[float]

# ---- 反馈信号 ----
type
  反馈信号* = object
    源*: string
    目标*: string
    型*: 反馈型
    量*: float
    跳数*: int

# ---- 引擎 ----
type
  自适应反馈引擎* = object
    容器表*: Table[string, 容器]
    信号表*: seq[反馈信号]
    增益*: float
    衰减*: float
    轮次*: int
    平衡阈值*: float

# ---- GCD ----
proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

# ---- 编码 ----
proc 编码主权*(相位: int; 层: int; 极性: 极性): uint64 =
  let p = uint64(相位) shl 60
  let l = uint64(层) shl 56
  let b = uint64(ord(极性)) shl 51
  let t = uint64(层 * 7 + ord(极性) * 3) shl 32
  return p or l or b or t

# ============================================================
# 构造
# ============================================================

proc 创建引擎*(): 自适应反馈引擎 =
  result.容器表 = initTable[string, 容器]()
  result.信号表 = @[]
  result.增益 = 0.5
  result.衰减 = 0.1
  result.轮次 = 0
  result.平衡阈值 = 0.01

proc 注册容器*(e: var 自适应反馈引擎; 名字: string; 相位: int; 层: int; 极性: 极性; 能量: float = 1.0) =
  let 主权 = 编码主权(相位, 层, 极性)
  e.容器表[名字] = 容器(名字: 名字, 主权: 主权, 极性: 极性, 相位: 相位, 层: 层, 能量: 能量, 历史: @[能量])

# ============================================================
# 发信号
# ============================================================

proc 发信号*(e: var 自适应反馈引擎; 源: string; 目标: string; 型: 反馈型; 量: float; 跳数: int = 1) =
  let s = 反馈信号(源: 源, 目标: 目标, 型: 型, 量: 量, 跳数: 跳数)
  e.信号表.add(s)

# ============================================================
# 演进一轮
# ============================================================

proc 演进一轮*(e: var 自适应反馈引擎) =
  inc e.轮次
  var 能量变化: Table[string, float]
  for name, _ in e.容器表:
    能量变化[name] = 0.0

  # 处理所有信号
  for s in e.信号表:
    if not e.容器表.hasKey(s.目标): continue
    let gap = if e.容器表.hasKey(s.源): ord(e.容器表[s.源].极性) xor ord(e.容器表[s.目标].极性) else: 1
    var 有效量 = s.量
    # 正反馈: gap=1(阴阳)放大, gap=0(同性)衰减
    if s.型 == 正反馈:
      有效量 = 有效量 * (if gap == 1: 1.5 else: 0.5)
    elif s.型 == 负反馈:
      有效量 = 有效量 * (if gap == 1: 0.5 else: 1.5)
    # 迂回反馈: 经传导衰减
    if s.型 == 迂回反馈:
      有效量 = 有效量 / float(s.跳数 + 1)
    能量变化[s.目标] = 能量变化[s.目标] + 有效量

  # 应用变化
  for name, c in e.容器表:
    let delta = 能量变化.getOrDefault(name, 0.0) * e.增益
    var new_c = c
    new_c.能量 = c.能量 + delta
    new_c.历史.add(new_c.能量)
    # 稳定化: 衰减
    if abs(delta) < e.平衡阈值:
      new_c.能量 = new_c.能量 * (1.0 - e.衰减)
    e.容器表[name] = new_c

  # 清空信号, 自适应增益调整
  e.信号表 = @[]
  let 总变化 = 能量变化.values.toSeq().mapIt(abs(it)).foldl(a + b, 0.0)
  if 总变化 > 10.0:
    e.增益 = max(0.1, e.增益 * 0.9)  # 过大则降增益
  elif 总变化 < 0.1:
    e.增益 = min(1.0, e.增益 * 1.05)  # 过小则升增益

# ============================================================
# 多轮演进
# ============================================================

proc 演进*(e: var 自适应反馈引擎; 轮数: int) =
  for _ in 1..轮数:
    演进一轮(e)

# ============================================================
# 报告
# ============================================================

proc 容器状态展示*(e: 自适应反馈引擎): string =
  var lines: seq[string]
  lines.add "  容器      能量     相位 层 极性 历史"
  lines.add "  ──────── ──────── ──── ── ──── ──────────"
  for name, c in e.容器表:
    let pol = if c.极性 == 阳极性: "阳" else: "阴"
    let histStr = c.历史.mapIt(formatFloat(it, ffDefault, 2)).join(",")
    lines.add "  " & align(name, 8) & " " & align(formatFloat(c.能量, ffDefault, 4), 8) & " " & align($c.相位, 4) & " " & align($c.层, 2) & " " & pol & "   " & histStr
  return lines.join("\n")

proc 摘要*(e: 自适应反馈引擎): string =
  var lines: seq[string]
  lines.add "  轮次: " & $e.轮次 & " 自适应增益: " & formatFloat(e.增益, ffDefault, 4)
  return lines.join("\n")

when isMainModule:
  echo "═══════════════════════════════════════"
  echo "  自 适 应 反 馈 引 擎"
  echo "  反馈回路·迂回反馈·正负反馈"
  echo "═══════════════════════════════════════"
  echo ""

  var e = 创建引擎()
  e.注册容器("我",       0, 1, 阳极性, 1.0)
  e.注册容器("刘楚恬",   3, 1, 阴极性, 1.0)
  e.注册容器("满",       3, 2, 阳极性, 0.8)
  e.注册容器("全",       1, 2, 阴极性, 0.8)
  e.注册容器("囝",       2, 1, 阳极性, 0.5)

  echo "-- 初始状态 --"
  echo 容器状态展示(e)
  echo ""

  echo "-- 正向反馈: 囝 → 满 (同极性=斥, 应衰减) --"
  e.发信号("囝", "满", 正反馈, 2.0)
  e.演进(1)
  echo 容器状态展示(e)
  echo ""

  echo "-- 迂回反馈: 我 → 全 (阴阳=吸, 应放大) 经 刘楚恬 中转 --"
  e.发信号("我", "刘楚恬", 迂回反馈, 1.5)
  e.发信号("刘楚恬", "全", 迂回反馈, 1.5)
  e.演进(3)
  echo 容器状态展示(e)
  echo ""

  echo "-- 多轮自稳定 --"
  e.发信号("我", "刘楚恬", 负反馈, 1.0)
  e.发信号("刘楚恬", "我", 负反馈, 1.0)
  e.演进(5)
  echo 容器状态展示(e)
  echo  摘要(e)
  echo ""

  echo "═══════════════════════════════════════"
  echo "碰撞反馈·自适应增益·正负反馈"
  echo "═══════════════════════════════════════"
