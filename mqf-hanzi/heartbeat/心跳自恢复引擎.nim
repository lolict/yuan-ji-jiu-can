# ============================================================
# 满全法 — 全系统心跳自恢复引擎 (Heartbeat Self-Recovery Engine)
# 使软件系统难以被摧毁: 检测失效 → 自动恢复 → 韧性增强
#
# 四级恢复策略:
#   L0 重启: 子系统状态重置
#   L1 复活: 从内存/历史重生
#   L2 降级: 功能缩减但保持核心
#   L3 隔离: 无法恢复则隔离不影响其他
# ============================================================

import strutils

# ---- 基本类型 ----

type
  极性* = enum
    阴 = 0
    阳 = 1

  容器* = object
    名字*: string
    相位*: int
    层*: int
    极性*: 极性
    物质*: string
    活性*: bool

  分身* = object
    名字*: string
    极性*: 极性
    主权*: uint64
    活性*: bool
    已完成*: seq[string]

  子系统类型* = enum
    时钟系统
    容器系统
    Swarm系统
    身份系统
    管线系统

  健康状态* = enum
    健康
    疲劳
    濒死
    死亡

  恢复级别* = enum
    重启     # L0: 重置状态
    复活     # L1: 从记忆重生
    降级     # L2: 缩减功能保核心
    隔离     # L3: 放弃但隔离

  子系统* = object
    类型*: 子系统类型
    名称*: string
    活性*: bool
    健康*: 健康状态
    心跳计数*: int
    上次响应*: int
    记忆*: seq[string]       # 历史状态碎片
    重试次数*: int
    最大重试*: int
    子单元*: seq[string]     # 包含哪些容器/分身

  恢复记录* = object
    轮次*: int
    子系统*: string
    级别*: 恢复级别
    原因*: string
    成功*: bool

  心跳引擎* = object
    滴答*: int
    注册系统*: seq[子系统]
    日志*: seq[string]
    恢复记录*: seq[恢复记录]
    记忆总库*: seq[string]
    总注入失效*: int
    总成功恢复*: int
    总隔离*: int
    隔离系统*: seq[int]

# ---- 工具 ----

proc 健康标签*(h: 健康状态): string =
  case h
  of 健康: "●"
  of 疲劳: "◐"
  of 濒死: "○"
  of 死亡: "⊘"

proc 级别标签*(l: 恢复级别): string =
  case l
  of 重启: "L0"
  of 复活: "L1"
  of 降级: "L2"
  of 隔离: "L3"

proc 系统标签*(t: 子系统类型): string =
  case t
  of 时钟系统: "时钟"
  of 容器系统: "容器"
  of Swarm系统: "Swarm"
  of 身份系统: "身份"
  of 管线系统: "管线"

# ---- 健康检查 ----

proc 健康检查*(s: 子系统): 健康状态 =
  if not s.活性:
    result = 死亡
  elif s.重试次数 >= s.最大重试:
    result = 濒死
  elif s.重试次数 > s.最大重试 div 2:
    result = 疲劳
  else:
    result = 健康

proc 批量检查*(引擎: var 心跳引擎): seq[tuple[索引: int; 状态: 健康状态]] =
  for i in 0 ..< len(引擎.注册系统):
    let h = 健康检查(引擎.注册系统[i])
    引擎.注册系统[i].健康 = h
    result.add((i, h))

# ---- 四级恢复策略 ----

proc L0重启*(引擎: var 心跳引擎; 索引: int): bool =
  var s = 引擎.注册系统[索引]
  if s.活性:
    return true

  inc s.重试次数
  if s.重试次数 > s.最大重试:
    return false

  # 重启: 激活系统, 清心跳计数
  引擎.注册系统[索引].活性 = true
  引擎.注册系统[索引].心跳计数 = 0
  引擎.注册系统[索引].健康 = 健康

  if len(s.记忆) > 0:
    # 保留最近一条记忆作为重启锚点
    discard s.记忆[^1]
  else:
    引擎.注册系统[索引].记忆.add("L0重启@" & $引擎.滴答)

  return true

proc L1复活*(引擎: var 心跳引擎; 索引: int): bool =
  var s = 引擎.注册系统[索引]
  if s.活性 and s.健康 != 死亡:
    return true

  # 从记忆总库寻找最后已知状态
  var 记忆匹配: seq[string]
  for m in 引擎.记忆总库:
    if m.contains(s.名称):
      记忆匹配.add(m)

  if len(记忆匹配) > 0:
    # 复活: 使用记忆恢复
    引擎.注册系统[索引].活性 = true
    引擎.注册系统[索引].健康 = 疲劳
    引擎.注册系统[索引].记忆.add("L1复活@" & $引擎.滴答 & " <- " & 记忆匹配[^1])
    return true
  else:
    # 无记忆 → 只能降级
    return false

proc L2降级*(引擎: var 心跳引擎; 索引: int): bool =
  var s = 引擎.注册系统[索引]

  # 降级: 缩减子单元但保持核心活性
  if len(s.子单元) > 1:
    引擎.注册系统[索引].子单元 = s.子单元[0..^2]  # 丢弃最后一个子单元
  引擎.注册系统[索引].活性 = true
  引擎.注册系统[索引].健康 = 疲劳
  引擎.注册系统[索引].记忆.add("L2降级@" & $引擎.滴答 & " 保留" & $引擎.注册系统[索引].子单元.len & "子单元")

  return true

proc L3隔离*(引擎: var 心跳引擎; 索引: int) =
  # 无法恢复 → 隔离: 标记死亡且不参与后续循环
  引擎.注册系统[索引].活性 = false
  引擎.注册系统[索引].健康 = 死亡
  inc 引擎.总隔离
  引擎.隔离系统.add(索引)

# ---- 引擎核心 ----

proc 创建引擎*(): 心跳引擎 =
  心跳引擎(
    滴答: 0,
    注册系统: @[],
    日志: @[],
    恢复记录: @[],
    记忆总库: @[],
    总注入失效: 0,
    总成功恢复: 0,
    总隔离: 0,
    隔离系统: @[]
  )

proc 注册系统*(引擎: var 心跳引擎; 类型: 子系统类型; 名称: string; 最大重试: int = 3; 子单元: seq[string] = @[]): string =
  # 检查重复
  for s in 引擎.注册系统:
    if s.名称 == 名称 and s.类型 == 类型:
      return "[拒绝] 系统'" & 名称 & "'已注册"

  引擎.注册系统.add(子系统(
    类型: 类型,
    名称: 名称,
    活性: true,
    健康: 健康,
    心跳计数: 0,
    上次响应: 0,
    记忆: @[],
    重试次数: 0,
    最大重试: 最大重试,
    子单元: 子单元
  ))
  return "[注册] " & 系统标签(类型) & "/" & 名称 & " 最大重试=" & $最大重试

proc 注入失效*(引擎: var 心跳引擎; 索引: int): string =
  if 索引 < 0 or 索引 >= len(引擎.注册系统):
    return "[错误] 索引越界"
  if not 引擎.注册系统[索引].活性:
    return "[无效] 已死亡"

  引擎.注册系统[索引].活性 = false
  引擎.注册系统[索引].健康 = 死亡
  inc 引擎.总注入失效
  let msg = "[注入] " & 引擎.注册系统[索引].名称 & " 死亡"
  引擎.日志.add("T" & $引擎.滴答 & " " & msg)
  return msg

proc 心跳一轮*(引擎: var 心跳引擎): string =
  inc 引擎.滴答
  var reports: seq[string]

  # 1. 收集已知状态到记忆总库
  for i, s in 引擎.注册系统:
    if s.活性:
      引擎.记忆总库.add(s.名称 & "@T" & $引擎.滴答 & "=" & $s.健康)

  # 2. 批量健康检查
  let 检查结果 = 批量检查(引擎)

  # 3. 对不健康系统执行恢复
  for (索引, 状态) in 检查结果:
    case 状态
    of 健康:
      inc 引擎.注册系统[索引].心跳计数
      引擎.注册系统[索引].上次响应 = 引擎.滴答

    of 疲劳:
      inc 引擎.注册系统[索引].心跳计数

    of 濒死:
      let s = 引擎.注册系统[索引]
      # 尝试 L0 重启
      var 恢复 = L0重启(引擎, 索引)
      var rec: 恢复记录
      rec.轮次 = 引擎.滴答
      rec.子系统 = s.名称
      rec.级别 = 重启
      rec.原因 = "濒死"
      rec.成功 = 恢复
      引擎.恢复记录.add(rec)
      if 恢复:
        inc 引擎.总成功恢复
        reports.add(s.名称 & ":L0重启成功")
      else:
        # L0失败 → L1复活
        恢复 = L1复活(引擎, 索引)
        rec.级别 = 复活
        rec.成功 = 恢复
        if 恢复:
          reports.add(s.名称 & ":L1复活成功")
        else:
          reports.add(s.名称 & ":L1复活失败→将隔离")

    of 死亡:
      if 引擎.注册系统[索引].重试次数 >= 引擎.注册系统[索引].最大重试 + 2:
        # 已无法恢复 → 隔离
        L3隔离(引擎, 索引)
        reports.add(引擎.注册系统[索引].名称 & ":L3隔离")
      else:
        # 先尝试复活
        let 复活成功 = L1复活(引擎, 索引)
        if 复活成功:
          inc 引擎.总成功恢复
          reports.add(引擎.注册系统[索引].名称 & ":L1复活成功")
        else:
          # 复活失败 → 降级
          let 降级成功 = L2降级(引擎, 索引)
          if 降级成功:
            inc 引擎.总成功恢复
            reports.add(引擎.注册系统[索引].名称 & ":L2降级运行")
          else:
            inc 引擎.注册系统[索引].重试次数
            reports.add(引擎.注册系统[索引].名称 & ":恢复等待")

  var summary = "[T" & $引擎.滴答 & "]"
  if len(reports) > 0:
    summary.add " " & reports.join(" | ")
  else:
    summary.add " 全部健康"

  引擎.日志.add(summary)
  return summary

# ---- 报告 ----

proc 系统快照*(引擎: 心跳引擎): string =
  var lines: seq[string]
  lines.add "═══ 心跳T" & $引擎.滴答 & " ════ 活跃:" & $len(引擎.注册系统) & " 隔离:" & $len(引擎.隔离系统)
  for s in 引擎.注册系统:
    lines.add "  " & 系统标签(s.类型) & "/" & s.名称 & " " & 健康标签(s.健康) & " 心跳=" & $s.心跳计数 & " 重试=" & $s.重试次数 & "/" & $s.最大重试 & " 子=" & $len(s.子单元)
  return lines.join("\n")

proc 恢复报告*(引擎: 心跳引擎; 最大: int = 10): string =
  var lines: seq[string]
  lines.add "═══ 恢复记录 ═══"
  let start = max(0, len(引擎.恢复记录) - 最大)
  for r in 引擎.恢复记录[start..^1]:
    lines.add "  T" & $r.轮次 & " " & r.子系统 & " " & 级别标签(r.级别) & " 原因=" & r.原因 & " " & (if r.成功: "✓" else: "✗")
  return lines.join("\n")

proc 总结报告*(引擎: 心跳引擎): string =
  var lines: seq[string]
  lines.add "══════════════════════════════════"
  lines.add "心跳引擎总结 | 总滴答=" & $引擎.滴答
  lines.add "注入失效: " & $引擎.总注入失效
  lines.add "成功恢复: " & $引擎.总成功恢复
  lines.add "隔离系统: " & $引擎.总隔离
  lines.add "记忆条目: " & $len(引擎.记忆总库)
  if 引擎.总注入失效 > 0:
    let rate = (引擎.总成功恢复 * 100) div max(1, 引擎.总注入失效)
    lines.add "恢复率: " & $rate & "%"
  lines.add "══════════════════════════════════"
  return lines.join("\n")

