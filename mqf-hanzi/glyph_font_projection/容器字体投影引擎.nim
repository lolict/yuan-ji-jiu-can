proc 引擎报告*(e: 投影引擎) =
  echo "══════════════════════════════════════════════════════"
  echo "  容 器 字 体 投 影 引 擎 — 报 告"
  echo "══════════════════════════════════════════════════════"
  echo "字体版本: ", e.字体.版本
  echo "容器尺寸: ", e.字体.尺寸
  echo "已注册字数: ", e.字体.字表.len
  echo "极性锚: ", (if e.极性锚 == 1: "阳(我)" else: "阴(刘楚恬)")
  echo "引导器链: ", e.引导器栈.join(" → ")
  echo ""

  for k in sorted(toSeq(e.字体.字表.keys)):
    let 字 = e.字体.字表[k]
    let g = 字.几何
    let 极 = if 字.极化 == 1: "阳" else: "阴"
    let 通 = if 字.通断: "通" else: "断"
    let 声几 = g.声母
    let 韵几 = g.韵母
    let 调几 = g.声调

    echo "─ 字码 " & $字.字码 & " ─"
    echo "  声母: " & $声几.类别 & " → " & 几何名(声几.基元) &
         " ∠" & $声几.角度 & "°" &
         " 长" & $声几.长度 &
         " (" & $声几.起点.x & "," & $声几.起点.y & ")" &
         "→(" & $声几.终点.x & "," & $声几.终点.y & ")"
    echo "  韵母: " & $韵几.类别 & " → " & 几何名(韵几.基元) &
         " R" & $韵几.曲率 &
         " " & (if 韵几.方向 == 0: "顺" else: "逆") &
         " " & (if 韵几.对称: "对称" else: "非对称") &
         " 顶(" & $韵几.顶点.x & "," & $韵几.顶点.y & ")"
    echo "  声调: " & $调几.类别 & " → 相位" & $调几.相位 &
         " " & 高低名(调几.高低) &
         " 摆" & $调几.摆动 &
         " 偏(" & $调几.偏移.x & "," & $调几.偏移.y & ")"
    echo "  综合: " & 几何名(g.基元) &
         " 3D(" & formatFloat(g.坐标.x, ffDecimal, 2) &
         ", " & formatFloat(g.坐标.y, ffDecimal, 2) &
         ", " & formatFloat(g.坐标.z, ffDecimal, 2) &
         ") " & 极 & " " & 通 &
         " " & (if g.可见: "可见" else: "不可见")
    echo ""

