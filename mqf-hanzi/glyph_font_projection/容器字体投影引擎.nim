    of 1: "升"
    of 2: "降"
    else: "曲"

#--------------------------------------------------------------
#  渲染步骤: 每一步都由引导器引导
#--------------------------------------------------------------

func 引导布局*(e: 投影引擎; 字码: int): seq[string] =
  let 字 = e.取字形(字码)
  if 字.字码 == 0:
    return @[]

  var 步骤: seq[string] = @[]

  # 引导器1: 声母角度定位
  步骤.add "① 声母引导: 类别=" & $字.几何.声母.类别 &
           " 角度=" & $字.几何.声母.角度 &
           " 长度=" & $字.几何.声母.长度

  # 引导器2: 韵母弧度叠加
  步骤.add "② 韵母引导: 曲率=" & $字.几何.韵母.曲率 &
           " 基元=" & $字.几何.韵母.基元 &
           " 对称=" & (if 字.几何.韵母.对称: "是" else: "否")

  # 引导器3: 声调高度校准
  步骤.add "③ 声调引导: 相位=" & $字.几何.声调.相位 &
           " 高低=" & 高低名(字.几何.声调.高低) &
           " 摆动=" & $字.几何.声调.摆动

  # 综合: 三维坐标输出
  步骤.add "④ 综合投影: (" & formatFloat(字.几何.坐标.x, ffDecimal, 2) &
           ", " & formatFloat(字.几何.坐标.y, ffDecimal, 2) &
           ", " & formatFloat(字.几何.坐标.z, ffDecimal, 2) &
           ") 极性=" & (if 字.极化 == 1: "阳" else: "阴") &
           " 可见=" & (if 字.几何.可见: "✓" else: "✗")

  步骤

#==============================================================
#  批量加载: 连续字节码流 → 字形流
#  如同存算一体芯片的三维索引空间
#==============================================================

func 解析字节流*(字节流: seq[int]; 起始声: int = 0; 起始韵: int = 0; 起始调: int = 0): seq[综合几何] =
  var 声 = 起始声
  var 韵 = 起始韵
  var 调 = 起始调

  for 码 in 字节流:
    let 极性 = if (码 mod 2) == 1: 1 else: 0
    let geo = 综合投影(声, 韵, 调, 码, 极性)
    result.add(geo)

    # 地址递增: 调→韵→声 级联进位
    调 += 1
    if 调 >= 60:
      调 = 0
      韵 += 1
      if 韵 >= 30:
        韵 = 0
        声 += 1
        if 声 >= 24:
          声 = 0

