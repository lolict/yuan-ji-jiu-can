#==============================================================

proc 时间扫描报告*(e: 投影引擎; 时间起点: float; 步数: int = 8) =
  echo "─ 时间触发扫描 ─"
  for i in 0..<步数:
    let t = 时间起点 + float(i) * 0.125
    let 相位 = 时间相位(t)
    var 激活数 = 0
    for 码 in e.字体.字表.keys:
      if 时间触发(t, e.字体.字表[码]):
        激活数 += 1
    var 激活列表: seq[string] = @[]
    for 码 in sorted(toSeq(e.字体.字表.keys)):
      if 时间触发(t, e.字体.字表[码]):
        激活列表.add $码
    echo "  t=" & formatFloat(t, ffDecimal, 3) &
         " 相位=" & $相位 &
         " 激活=" & $激活数 &
         (if 激活列表.len > 0: " (" & 激活列表.join(",") & ")" else: "")

