#==============================================================
#  声母→几何映射  (24进制)
#  24声母，每声母对应角度 = (类别 × 15) mod 360
#==============================================================

func 声母转几何*(类别: int): 声母几何 =
  let idx = 类别 mod 24
  var geo: 声母几何
  geo.类别 = idx
  if idx < 12:
    geo.基元 = 线
  else:
    geo.基元 = 折
  geo.长度 = (idx mod 8) + 1
  geo.角度 = idx * 15  # 每声母15度
  geo.起点 = (0, 0)
  let rad = float(geo.角度) * PI / 180.0
  geo.终点 = (
    int(round(cos(rad) * float(geo.长度))),
    int(round(sin(rad) * float(geo.长度)))
  )
  geo

#==============================================================
#  韵母→几何映射  (30进制)
#  30韵母，每韵母对应曲率半径 = (类别 mod 8) + 1
#  韵母决定"韵"的弧度与闭合形态
#==============================================================

func 韵母转几何*(类别: int): 韵母几何 =
  let idx = 类别 mod 30
  var geo: 韵母几何
  geo.类别 = idx

  # 曲率半径 1-8
  geo.曲率 = (idx mod 8) + 1

  # 基元: 开口韵=弧, 闭口韵=环, 鼻韵=曲
  if idx < 10:
    geo.基元 = 弧       # 开口韵 (a/o/e类)
  elif idx < 20:
    geo.基元 = 环       # 闭口韵 (i/u/ü类)
  else:
    geo.基元 = 曲       # 鼻韵 (n/ng类)

  # 方向: 单双数决定顺逆
  geo.方向 = idx mod 2

  # 对称: 元音交替决定
  geo.对称 = (idx mod 3) != 0

  # 顶点位置 (由曲率决定)
  geo.顶点 = (geo.曲率, geo.曲率 * 2)

  geo

#==============================================================
#  声调→几何映射  (60进制→相位/高度)
#  30-60调，每调对应0-7相位和高中低坐标
#==============================================================

func 声调转几何*(类别: int): 声调几何 =
  let idx = 类别 mod 60
  var geo: 声调几何
  geo.类别 = idx

  # 相位: 8相位对应田字格8方位
  geo.相位 = (idx mod 8)

  # 高低: 0-19低, 20-39中, 40-59高
  geo.高低 = if idx < 20: 0 elif idx < 40: 1 else: 2

  # 偏移: 声调走向(平/升/降/曲折)
  let 走向 = idx mod 4  # 0=平, 1=升, 2=降, 3=曲折
  geo.摆动 = 走向
  case 走向
    of 0: geo.偏移 = (0, 0)   # 平
    of 1: geo.偏移 = (1, 1)   # 升
    of 2: geo.偏移 = (1, -1)  # 降
    of 3: geo.偏移 = (2, 0)   # 曲折(来回)
    else: geo.偏移 = (0, 0)

  geo

#==============================================================
#  综合几何 — 声母+韵母+声调 三位合一
#  3D坐标 =
#    x = 声母角度投影
#    y = 韵母曲率深度
#    z = 声调高低相位
#==============================================================

func 综合投影*(声: int, 韵: int, 调: int, 编码: int, 极性: int): 综合几何 =
  let 声几 = 声母转几何(声)
  let 韵几 = 韵母转几何(韵)
  let 调几 = 声调转几何(调)

  var 综合: 综合几何
  综合.声母 = 声几
  综合.韵母 = 韵几
  综合.声调 = 调几
  综合.编码 = 编码
  综合.极性 = 极性

  # 合成基元: 声母(1D) × 韵母(2D) → 声调(3D) = 体
  综合.基元 = 体  # 最终合成三维体

  # 3D坐标 =
  #   x = 声母角度(辐射)决定横坐标
  let ang_rad = float(声几.角度) * PI / 180.0
  综合.坐标.x = cos(ang_rad) * float(韵几.曲率)

  # y = 韵母曲率 + 声调偏移
  综合.坐标.y = float(韵几.曲率) + float(调几.偏移.y)

  # z = 声调高低 × 摆动
  if 调几.高低 == 0:
    综合.坐标.z = -1.0 * float(调几.摆动 + 1)
  elif 调几.高低 == 1:
    综合.坐标.z = 0.0
  else:
    综合.坐标.z = float(调几.摆动 + 1)

  # 角度分量
  综合.角度分量.横 = ang_rad
  综合.角度分量.纵 = float(韵几.曲率) * PI / 8.0
  综合.角度分量.深 = float(调几.高低) * PI / 3.0

  # 可见性: 在视锥内即为可见
  综合.可见 = (
    综合.坐标.x >= -8.0 and 综合.坐标.x <= 8.0 and
    综合.坐标.y >= -8.0 and 综合.坐标.y <= 8.0 and
    综合.坐标.z >= -4.0 and 综合.坐标.z <= 4.0
  )

  综合

#==============================================================
#  时间触发器 — 容器=时间 投影的时间维度
#==============================================================

func 时间触发*(时间戳: float, 字: 字形容器): bool =
  ## 时间触发加载: 特定时刻激活特定字形
  ## 时间戳的小数部分对应64进制循环
  let 循环相位 = int(时间戳 * 64.0) mod 64
  (字.字码 mod 64) == 循环相位

func 时间相位*(时间戳: float): int =
  ## 0-7 相位, 对应田字格8方位
  int(时间戳 * 8.0) mod 8

#==============================================================
#  极性锚定 — 容器=物质=时间的私有锚点
#==============================================================

func 极性校准*(极性: int, 锚点: int): int =
  ## 校准极性: 确保以私有锚点为参照
  ## 锚点=1(我), 极性=1 → 阳; 锚点=1, 极性=0 → 阴
  if 锚点 == 1:
    return 极性  # 我=1为锚
  else:
    return 1 - 极性  # 反向校准

