proc 注册字形*(e: var 投影引擎; 字码: int; 声: int; 韵: int; 调: int; 极化: int) =
  ## 一字节码 → 一字形 封装
  let 编码 = (声 * 30 * 60 + 韵 * 60 + 调) mod 256
  let 校准极 = 极性校准(极化, e.极性锚)
  let 投影 = 综合投影(声, 韵, 调, 编码, 校准极)

  var 字: 字形容器
  字.字码 = 字码
  字.声类 = 声
  字.韵类 = 韵
  字.调类 = 调
  字.几何 = 投影
  字.极化 = 校准极
  字.通断 = true

  e.字体.字表[字码] = 字

func 取字形*(e: 投影引擎; 字码: int): 字形容器 =
  if e.字体.字表.hasKey(字码):
    return e.字体.字表[字码]
  字形容器()

#==============================================================
#  引导器 — 布局引导链
#  以规则引导秩序、用秩序创造渲染、让每一步都有引导器引导完成布局
#==============================================================

proc 推入引导器*(e: var 投影引擎; 引导器名: string) =
  e.引导器栈.add(引导器名)

proc 弹出引导器*(e: var 投影引擎): string =
  if e.引导器栈.len > 0:
    result = e.引导器栈[^1]
    e.引导器栈.del(e.引导器栈.len - 1)
  else:
    result = ""

func 当前引导器*(e: 投影引擎): string =
  if e.引导器栈.len > 0:
    result = e.引导器栈[^1]
  else:
    result = "无"

