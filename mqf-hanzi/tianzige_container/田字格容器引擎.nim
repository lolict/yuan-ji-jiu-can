#==============================================================
#  田字格容器引擎 — 填表编程 · 8相位变换 · 通断路约束 · 线性镜像对称
#
#  田字格: 2×2 = 4格, 每格携带编码/极性/通断状态
#  8相位变换: 上/下/左/右/内/外/包围/原位
#  通断路: 通=可通行, 断=阻断 (电路隐喻)
#  线性镜像对称: 水平翻转/垂直翻转
#==============================================================

type
  相位* = enum
    原位,
    上, 下, 左, 右,
    内, 外,
    包围

  田字格单元* = object
    编码*: int           # 64进制容器编码
    极性*: int           # 0=阴(刘楚恬) / 1=阳(我)
    通断*: bool          # 通=true 可通行 / 断=false 阻断
    地址*: int           # 地址(公约数定位)

  田字格* = object
    格*: array[4, 田字格单元]   # 2×2 = 4格 [0=左上, 1=右上, 2=左下, 3=右下]
    名称*: string
    版本*: int

  田字格引擎* = object
    格表*: Table[string, 田字格]
    注册计数*: int

#--------------------------------------------------------------
#  基础工具
#--------------------------------------------------------------

func 格索引(行: int, 列: int): int =
  # 2×2 映射到 0..3
  行 * 2 + 列

func 公约数定位(a: int, b: int): int =
  # 两地址的公约数即为它们的关系锚点
  gcd(a, b)

func 是倍数(底: int, 被测: int): bool =
  if 底 == 0: return false
  (被测 mod 底) == 0

#--------------------------------------------------------------
#  相位变换
#--------------------------------------------------------------

func 相位变换*(格: 田字格, 相位: 相位): 田字格 =
  ## 8相位变换田字格内容
  ##  上/下: 上下两行交换 (0↔2, 1↔3)
  ##  左/右: 左右两列交换 (0↔1, 2↔3)
  ##  内/外: 四角向中心收缩/外扩 (编码取反极性)
  ##  包围: 四角同时内收 (编码叠加均值)
  ##  原位: 不变
  result = 格
  case 相位
    of 原位:
      return
    of 上:
      # 上移: 下→上, 上丢失 (下覆盖上)
      result.格[0] = 格.格[2]
      result.格[1] = 格.格[3]
    of 下:
      # 下移: 上→下, 下丢失
      result.格[2] = 格.格[0]
      result.格[3] = 格.格[1]
    of 左:
      # 左移: 右→左
      result.格[0] = 格.格[1]
      result.格[2] = 格.格[3]
    of 右:
      # 右移: 左→右
      result.格[1] = 格.格[0]
      result.格[3] = 格.格[2]
    of 内:
      # 内收: 四角极性翻转, 编码叠加中心均值
      var 均值 = 0
      for i in 0..3:
        均值 += 格.格[i].编码
      均值 = 均值 div 4
      for i in 0..3:
        result.格[i].极性 = 1 - 格.格[i].极性
        result.格[i].编码 = (格.格[i].编码 + 均值) div 2
    of 外:
      # 外扩: 编码翻倍, 极性不变 (外扩运动)
      for i in 0..3:
        result.格[i].编码 = 格.格[i].编码 * 2
    of 包围:
      # 包围: 四角编码围剿中心 (= 公约数叠合)
      var 叠 = 格.格[0].编码
      for i in 1..3:
        叠 = gcd(叠, 格.格[i].编码)
      for i in 0..3:
        result.格[i].编码 = 叠

#--------------------------------------------------------------
#  镜像对称
#--------------------------------------------------------------

func 水平镜像*(格: 田字格): 田字格 =
  ## 左右镜像 — 水平翻转 (交换列)
  result = 格
  result.格[0] = 格.格[1]
  result.格[1] = 格.格[0]
  result.格[2] = 格.格[3]
  result.格[3] = 格.格[2]

func 垂直镜像*(格: 田字格): 田字格 =
  ## 上下镜像 — 垂直翻转 (交换行)
  result = 格
  result.格[0] = 格.格[2]
  result.格[2] = 格.格[0]
  result.格[1] = 格.格[3]
  result.格[3] = 格.格[1]

func 对角镜像*(格: 田字格): 田字格 =
  ## 对角镜像 — 主对角交换 (0↔3, 1↔2)
  result = 格
  result.格[0] = 格.格[3]
  result.格[3] = 格.格[0]
  result.格[1] = 格.格[2]
  result.格[2] = 格.格[1]

#--------------------------------------------------------------
#  通断路约束
#--------------------------------------------------------------

func 检查通路*(格: 田字格, 起点: int, 终点: int): bool =
  ## 检查从起点到终点的通断链
  ## 相邻定义: 上下左右直接相邻
  ## 通断链 = 路径上所有格均为 "通"
  if 起点 < 0 or 起点 > 3 or 终点 < 0 or 终点 > 3:
    return false

  # BFS 在2×2网格中寻路
  var visited = initHashSet[int]()
  var queue: seq[int] = @[起点]

  while queue.len > 0:
    let cur = queue[0]
    queue.del(0)

    if cur == 终点:
      if 格.格[cur].通断:
        return true
      else:
        return false

    if cur in visited:
      continue
    visited.incl(cur)

    if not 格.格[cur].通断:
      continue  # 断点不可通行

    # 2×2 邻居: 0→[1,2], 1→[0,3], 2→[0,3], 3→[1,2]
    let 邻居 = case cur
      of 0: @[1, 2]
      of 1: @[0, 3]
      of 2: @[0, 3]
      of 3: @[1, 2]
      else: @[]

    for n in 邻居:
      if n notin visited:
        queue.add(n)

  return false

func 设置通断*(格: var 田字格, 索引: int, 状态: bool) =
  if 索引 >= 0 and 索引 <= 3:
    格.格[索引].通断 = 状态

func 全部通*(格: var 田字格) =
  for i in 0..3:
    格.格[i].通断 = true

func 全部断*(格: var 田字格) =
  for i in 0..3:
    格.格[i].通断 = false

#--------------------------------------------------------------
#  填表编程
#--------------------------------------------------------------

func 填表*(格: var 田字格, 位置: int, 编码: int, 极性: int = 1, 通断: bool = true) =
  ## 在指定位置填入内容
  if 位置 >= 0 and 位置 <= 3:
    格.格[位置].编码 = 编码
    格.格[位置].极性 = 极性
    格.格[位置].通断 = 通断
    格.格[位置].地址 = 编码  # 地址即编码

func 取值*(格: 田字格, 位置: int): 田字格单元 =
  if 位置 >= 0 and 位置 <= 3:
    return 格.格[位置]
  田字格单元()

func 批量填表*(格: var 田字格, 编码序列: seq[int], 极性序列: seq[int]) =
  let n = min(min(编码序列.len, 极性序列.len), 4)
  for i in 0..<n:
    格.格[i].编码 = 编码序列[i]
    格.格[i].极性 = 极性序列[i]
    格.格[i].通断 = true
    格.格[i].地址 = 编码序列[i]

#--------------------------------------------------------------
#  公约数关系
#--------------------------------------------------------------

func 格间关系*(格: 田字格, 甲: int, 乙: int): string =
  ## 判断两格之间的关系: 合(公约>1) / 斥(无公约) / 通断阻断
  if 甲 < 0 or 甲 > 3 or 乙 < 0 or 乙 > 3:
    return "越界"

  let a = 格.格[甲].编码
  let b = 格.格[乙].编码

  # 极性互斥
  if 格.格[甲].极性 == 格.格[乙].极性:
    let g = gcd(a, b)
    if g > 1:
      return "合(gcd=" & $g & ")"
    else:
      return "斥(极性同)"
  else:
    # 极性相吸需通路
    if 格.格[甲].通断 and 格.格[乙].通断:
      return "吸(极性异·通路)"
    else:
      return "断(极性异·阻断)"

#--------------------------------------------------------------
#  引擎
