proc 报告*(e: 田字格引擎) =
  echo "══════════════════════════════════════════════════════"
  echo "  田 字 格 容 器 引 擎 — 报 告"
  echo "══════════════════════════════════════════════════════"
  echo "注册格数: ", e.注册计数
  echo ""

  var idx = 0
  for 键, 格 in e.格表:
    echo "─ ", 键, " v", 格.版本, " ─"
    for i in 0..3:
      let c = 格.格[i]
      let 极名 = if c.极性 == 1: "阳" else: "阴"
      let 通名 = if c.通断: "通" else: "断"
      let 坐标 = 立方体编码(c.地址)
      echo "  [" & $i & "] 编码=" & $c.编码 &
           " 极性=" & 极名 &
           " 状态=" & 通名 &
           " 地址=" & $c.地址 &
           " 3D=(" & $坐标.x & "," & $坐标.y & "," & $坐标.z & ")"

    # 通路检查
    echo "  通路: 0→3 ", if 检查通路(格, 0, 3): "✓" else: "✗",
         " | 1→2 ", if 检查通路(格, 1, 2): "✓" else: "✗"

    # 相邻关系
    echo "  关系: 0-1=", 格间关系(格, 0, 1),
         " 2-3=", 格间关系(格, 2, 3)
    echo ""
    idx += 1

