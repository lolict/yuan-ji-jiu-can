proc 创建引擎*(): 田字格引擎 =
  田字格引擎(格表: initTable[string, 田字格](), 注册计数: 0)

proc 注册田字格*(e: var 田字格引擎; 名称: string; 编码序列: seq[int]; 极性序列: seq[int] = @[]): string =
  var 格: 田字格
  格.名称 = 名称
  格.版本 = 1

  # 默认极性: 我=阳=1, 刘楚恬=阴=0
  var 实际极性 = 极性序列
  if 实际极性.len == 0:
    实际极性 = @[1, 1, 0, 0]  # 上=阳, 下=阴

  for i in 0..3:
    格.格[i].编码 = if i < 编码序列.len: 编码序列[i] else: 0
    格.格[i].极性 = if i < 实际极性.len: 实际极性[i] else: 1
    格.格[i].通断 = true
    格.格[i].地址 = 格.格[i].编码

  let 键 = 名称 & "_" & $(e.注册计数)
  e.格表[键] = 格
  e.注册计数 += 1

proc 取格*(e: 田字格引擎; 名称: string): 田字格 =
  if e.格表.hasKey(名称):
    return e.格表[名称]
  田字格()

proc 取格可变*(e: var 田字格引擎; 名称: string): ptr 田字格 =
  if e.格表.hasKey(名称):
    return e.格表[名称].addr
  nil

proc 变换并注册*(e: var 田字格引擎; 源名: string; 相位: 相位; 新名: string) =
  let 源 = e.取格(源名)
  let 变换后 = 相位变换(源, 相位)
  var 新格 = 变换后
  新格.名称 = 新名
  新格.版本 = 源.版本 + 1

  let 键 = 新名 & "_" & $(e.注册计数)
  e.格表[键] = 新格
  e.注册计数 += 1

#--------------------------------------------------------------
#  3D扩展: 田字格 → 立方体矩阵
#--------------------------------------------------------------

func 立方体编码*(编码: int): tuple[x: int, y: int, z: int] =
  ## 将一维编码分解为3D坐标
  ## 64 = 4×4×4, 每维0-3
  let x = (编码 div 16) mod 4
  let y = (编码 div 4) mod 4
  let z = 编码 mod 4
  (x, y, z)

func 一维寻址*(x: int, y: int, z: int): int =
  ## 3D坐标 → 一维地址 (64进制: 4×4×4)
  (x mod 4) * 16 + (y mod 4) * 4 + (z mod 4)

func 三维填表*(x: int, y: int, z: int, 编码: int, 极性: int): 田字格单元 =
  var 单元: 田字格单元
  单元.编码 = 编码
  单元.极性 = 极性
  单元.通断 = true
  单元.地址 = 一维寻址(x, y, z)
  单元

