  可编程格.名称 = "可编程"
  全部通(可编程格)

  # 基于声母24进制、韵母30进制、声调5进制的地址
  # 编码 = 声母×30×5 + 韵母×5 + 声调
  let 声 = 12  # 声母地址
  let 韵 = 18  # 韵母地址
  let 调 = 3   # 声调地址
  let 音码 = 声 * 150 + 韵 * 5 + 调  # 12×150 + 18×5 + 3 = 1893

  填表(可编程格, 0, 音码, 1)  # 阳(我)填入
