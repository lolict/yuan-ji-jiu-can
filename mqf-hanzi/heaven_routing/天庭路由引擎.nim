  let r2 = e.升天(2, "刘楚恬", 0, 3, 0.0)
  echo "  刘楚恬(阴,层3) 升天: " & (if r2: "通过 ✓" else: "拒绝 ○（守卫拒阴）")

  let r3 = e.升天(3, "容器•满", 1, 1, 0.0)
  echo "  容器满(阳,层1) 升天: " & (if r3: "通过 ✓" else: "拒绝 ○")

  let r4 = e.升天(4, "容器•全", 1, 2, 0.0)
  echo "  容器全(阳,层2) 升天: " & (if r4: "通过 ✓" else: "拒绝 ○")

  echo ""

  # 路由测试
  echo "─ 路由 ─"
  let p1 = e.路由到殿(1, 朱雀殿)
  if p1.成功:
    var hall_names: seq[string] = @[]
    for h in p1.路径:
      let hn = case h
         of 南天门: "南天门"
         of 青龙殿: "青龙殿"
         of 朱雀殿: "朱雀殿"
         of 白虎殿: "白虎殿"
         of 玄武殿: "玄武殿"
         of 凌霄殿: "凌霄殿"
      hall_names.add(hn)
    echo " 我→朱雀殿: " & hall_names.join(" → ") & " (" & $p1.距离 & ") "

  let p2 = e.路由到殿(4, 凌霄殿)
  if p2.成功:
    echo "  全→凌霄殿: 成功 ✓ (八流汇聚)"
  else:
    echo "  全→凌霄殿: 被拒绝（层级不足）"

  let p3 = e.路由到殿(1, 凌霄殿)
  if p3.成功:
    echo "  我→凌霄殿: 成功 ✓ (层级=3，足够)"
  else:
    echo "  我→凌霄殿: 被拒绝"

  echo ""
  echo e.天庭报告()
