#==============================================================
#  天庭路由引擎 — Heaven Routing Engine
#
#  核心：南天门守卫 · 八流汇聚凌霄殿 · 大殿间路由 ·
#       极性准入 · 容器升天 · 天庭降世
#==============================================================

import std/[tables, strutils, sequtils, math, algorithm]

#--------------------------------------------------------------
#  类型定义
#--------------------------------------------------------------

type
  # 六大殿
  大殿* = enum
    南天门    # 入口守卫
    青龙殿    # 东-生
    朱雀殿    # 南-显
    白虎殿    # 西-杀
    玄武殿    # 北-藏
    凌霄殿    # 核心-八流汇聚

  # 天庭节点（升天的容器）
  天庭节点* = object
    容器编码*: int
    名字*: string
    所在殿*: 大殿
    升天时刻*: float
    极性*: uint8
    层级*: int                  # 隐藏的层（以南天门守卫为准）

  # 路由请求
  路由请求* = object
    源编码*: int
    目标殿*: 大殿
    极性*: uint8
    通过守卫*: bool

  # 守卫规则
  守卫规则* = object
    名*: string
    准入极性*: uint8            # 0=只准阴，1=只准阳，2=不限
    最小层级*: int

  # 天庭路由引擎
  天庭引擎* = object
    节点表*: Table[int, 天庭节点]
    路由计数*: int
    守卫规则*: seq[守卫规则]
    大殿连接*: Table[string, float]  # 殿间距离 (键="A|B")
    凌霄汇聚*: seq[int]         # 在凌霄殿的容器

#--------------------------------------------------------------
#  初始化
#--------------------------------------------------------------

proc 初始化天庭*(): 天庭引擎 =
  # 初始化大殿连接（六殿拓扑）
  result.大殿连接 = initTable[string, float]()
  result.大殿连接["南天门|青龙殿"] = 10.0
  result.大殿连接["南天门|朱雀殿"] = 10.0
  result.大殿连接["南天门|白虎殿"] = 10.0
  result.大殿连接["南天门|玄武殿"] = 10.0
  result.大殿连接["青龙殿|凌霄殿"] = 20.0
  result.大殿连接["朱雀殿|凌霄殿"] = 20.0
  result.大殿连接["白虎殿|凌霄殿"] = 20.0
  result.大殿连接["玄武殿|凌霄殿"] = 20.0

  # 默认守卫规则
  result.守卫规则 = @[
    守卫规则(名: "南天门守卫", 准入极性: 1, 最小层级: 0),  # 只准阳极性
    守卫规则(名: "凌霄暗卫", 准入极性: 2, 最小层级: 2)     # 任何极性但需层级>=2
  ]
  result.路由计数 = 0
  result.凌霄汇聚 = @[]

#--------------------------------------------------------------
#  升天：将容器送入天庭
#--------------------------------------------------------------

proc 升天*(e: var 天庭引擎; 容器编码: int; 名字: string;
           极性: uint8; 层级: int; 时刻: float): bool =
  # 南天门守卫检查
  for rule in e.守卫规则:
    if rule.名 == "南天门守卫":
      if rule.准入极性 != 2:
        if 极性 != rule.准入极性:
          return false  # 守卫拒绝

  e.节点表[容器编码] = 天庭节点(
    容器编码: 容器编码,
    名字: 名字,
    所在殿: 南天门,
    升天时刻: 时刻,
    极性: 极性,
    层级: 层级
  )
  return true

#--------------------------------------------------------------
#  路由到殿
#--------------------------------------------------------------

proc 殿键*(a: 大殿; b: 大殿): string =
  let sa = case a
    of 南天门: "南天门"
    of 青龙殿: "青龙殿"
    of 朱雀殿: "朱雀殿"
    of 白虎殿: "白虎殿"
    of 玄武殿: "玄武殿"
    of 凌霄殿: "凌霄殿"
  let sb = case b
    of 南天门: "南天门"
    of 青龙殿: "青龙殿"
    of 朱雀殿: "朱雀殿"
    of 白虎殿: "白虎殿"
    of 玄武殿: "玄武殿"
    of 凌霄殿: "凌霄殿"
  return sa & "|" & sb

proc 路由到殿*(e: var 天庭引擎; 容器编码: int; 目标: 大殿): tuple[成功: bool; 距离: float; 路径: seq[大殿]] =
  if not e.节点表.hasKey(容器编码):
    return (false, 0.0, @[])

  let node = e.节点表[容器编码]

  # 凌霄殿检查层级
  if 目标 == 凌霄殿:
    if node.层级 < 2:
      return (false, 0.0, @[])
    e.凌霄汇聚.add(容器编码)

  # 计算路径：当前殿 → 南天门 → 目标或直接
  var path: seq[大殿] = @[]
  var dist = 0.0

  if node.所在殿 == 目标:
    path.add(目标)
    return (true, 0.0, path)

  if 目标 == 南天门:
    path.add(南天门)
    dist = e.大殿连接.getOrDefault(殿键(node.所在殿, 南天门), 0.0)
    return (true, dist, path)

  # 当前殿→南天门→目标
  let d1 = e.大殿连接.getOrDefault(殿键(南天门, 目标), 0.0)
  let d2 = e.大殿连接.getOrDefault(殿键(node.所在殿, 南天门), 0.0)
  path = @[南天门, 目标]
  dist = d1 + d2

  # 更新节点位置
  var n = node
  n.所在殿 = 目标
  e.节点表[容器编码] = n
  e.路由计数 += 1

  return (true, dist, path)

#--------------------------------------------------------------
#  八流汇聚
#--------------------------------------------------------------

proc 八流汇聚*(e: 天庭引擎): Table[string, seq[string]] =
  var result = initTable[string, seq[string]]()
  result["南天门"] = @[]
  result["青龙殿"] = @[]
  result["朱雀殿"] = @[]
  result["白虎殿"] = @[]
  result["玄武殿"] = @[]
  result["凌霄殿"] = @[]

  for k, n in e.节点表:
    let hall_name = case n.所在殿
      of 南天门: "南天门"
      of 青龙殿: "青龙殿"
      of 朱雀殿: "朱雀殿"
      of 白虎殿: "白虎殿"
      of 玄武殿: "玄武殿"
      of 凌霄殿: "凌霄殿"
    result[hall_name].add(n.名字)

  return result

#--------------------------------------------------------------
#  报告
#--------------------------------------------------------------

proc 天庭报告*(e: 天庭引擎): string =
  var lines: seq[string] = @[]
  lines.add repeat("═", 54)
  lines.add "  天 庭 路 由 引 擎 — 报 告"
  lines.add repeat("═", 54)
  lines.add "升天容器: " & $e.节点表.len
  lines.add "路由次数: " & $e.路由计数
  lines.add "凌霄汇聚: " & $e.凌霄汇聚.len
  lines.add ""

  lines.add "─ 六殿分布 ─"
  let gather = e.八流汇聚()
  for hall, names in gather:
    lines.add "  " & align(hall, 6) & ": " & (if names.len > 0: names.join(", ") else: "(空)")

  lines.add ""
  lines.add "─ 节点明细 ─"
  for k in sorted(toSeq(e.节点表.keys)):
    let n = e.节点表[k]
    let hall = case n.所在殿
      of 南天门: "南天门"
      of 青龙殿: "青龙殿"
      of 朱雀殿: "朱雀殿"
      of 白虎殿: "白虎殿"
      of 玄武殿: "玄武殿"
      of 凌霄殿: "凌霄殿"
    let 极性符 = if n.极性 == 1: "阳" else: "阴"
    lines.add "  [" & n.名字 & "] " & hall & " " & 极性符 & " 层:" & $n.层级

  return lines.join("\n")

