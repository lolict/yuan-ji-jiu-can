proc 全栈联动演示*() =
  echo "═══ 满全法 全栈联动 v3 — 操作系统醒来 ═══"
  echo ""
  echo "认知评分 → 机器码容器 → 时间触发 → 三维字体 → 自举规则 → 蚕蛹寄生壳"
  echo ""

  var 输出: seq[string] = @[]

  # === 第1层: 认知评分 ===
  var scorer = 创建评分器()
  let 测试输入 = [
    "容器极性编码公倍数感知相位映射",
    "你好世界",
    "因为容器编码基于满全法所以极性稳定性等于阳减去阴的逻辑等价于进制推理",
  ]

  for text in 测试输入:
    let coord = scorer.评分(text, 1)
    输出.add "[认知评分] " & text[0 ..< min(20, text.len)] & "..."
    输出.add "  层级=" & $coord.层级 & " 置信=" & formatFloat(coord.置信, ffDecimal, 2)
    输出.add "  " & 回退层名(scorer)
    if scorer.门控阻挡.len > 0:
      输出.add "  门控阻挡: " & scorer.门控阻挡.join(", ")

  # === 第2层: 机器码容器 ===
  var 容器甲 = 构建容器(
    @[容器操作(操作: LOAD, 操作数: 0, 极性: 1),
      容器操作(操作: ADD, 操作数: 0, 极性: 1),
      容器操作(操作: STORE, 操作数: 1, 极性: 0),
      容器操作(操作: HALT, 操作数: 0, 极性: 0)],
    @[7, 0]
  )
  var 容器乙 = 构建容器(
    @[容器操作(操作: LOAD, 操作数: 0, 极性: 1),
      容器操作(操作: MUL, 操作数: 0, 极性: 1),
      容器操作(操作: HALT, 操作数: 0, 极性: 0)],
    @[3, 0]
  )

  输出.add ""
  输出.add "[机器码容器] 甲: 校验和=" & $容器甲.校验和 & " 操作数=" & $容器甲.操作序列.len
  输出.add "[机器码容器] 乙: 校验和=" & $容器乙.校验和 & " 操作数=" & $容器乙.操作序列.len

  # === 第3层: 时间触发 ===
  let 信封甲 = 容器到信封(容器甲, 0, 1)
  let 信封乙 = 容器到信封(容器乙, 4, 0)

  输出.add ""
  输出.add "[时间触发] 甲: 窗口=" & $信封甲.时间窗口 & " 见证=" & $信封甲.见证 & " 裁决=" & 裁决(信封甲)
  输出.add "[时间触发] 乙: 窗口=" & $信封乙.时间窗口 & " 见证=" & $信封乙.见证 & " 裁决=" & 裁决(信封乙)

  # === 第4层: 三维字体 ===
  var font = 创建字体()
  let rec1 = 字形记录(容器码: 容器甲, 信封: 信封甲, 声调: 85,
                       三维坐标: (1.0, 0.0, 0.0), 字形符号: "ѧ")
  let rec2 = 字形记录(容器码: 容器乙, 信封: 信封乙, 声调: 5,
                       三维坐标: (5.0, 2.0, 4.0), 字形符号: "ɔ")
  font.注册字体(rec1)
  font.注册字体(rec2)

  输出.add ""
  输出.add "[三维字体] 记录数=" & $font.记录.len & " 索引=" & $font.索引.len

  # === 第5层: 自举编译器 ===
  let compiler = 创建编译器()
  输出.add ""
  输出.add "[自举编译器] 规则数=" & $compiler.规则表.len
  for rule in compiler.规则表:
    输出.add "  " & rule.名称 & ": " & rule.公理 & " (" & $rule.生成.len & "条生成)"

  # === 第6层: 蚕蛹寄生壳 ===
  var 壳1 = 创建寄生壳("浏览器壳", "Web")
  var 壳2 = 创建寄生壳("终端壳", "CLI/Termux")
  var 壳3 = 创建寄生壳("输入法壳", "Android IME")
  输出.add ""
  输出.add "[蚕蛹寄生壳]"
  输出.add "  " & 脱壳(壳1)
  输出.add "  " & 脱壳(壳2)
  输出.add "  " & 脱壳(壳3)

  # === 全栈输出 ===
  echo "─ 全栈联动日志 ─"
  for line in 输出:
    echo "  " & line

  # === 报告 ===
  echo ""
  echo "═" & repeat("═", 60)
  echo "  满全法 全栈联动 v3 — 系统报告"
  echo "═" & repeat("═", 60)
  echo "认知评分历史: ", scorer.历史.len, " 次"
  echo "当前认知层级: ", scorer.当前.层级
  echo "当前回退层: ", 回退层名(scorer)
  echo "极性锚: 阳(我)"
  echo "机器码容器: 2 个"
  echo "时间信封: 2 个"
  echo "三维字体记录: ", font.记录.len
  echo "自举规则: ", compiler.规则表.len
  echo "蚕蛹壳: 3 个(浏览器/终端/输入法)"
  echo ""
  echo "─ 容器=物质=时间=认知=规则=寄壳 ─"
  echo "  容器(编码) → 物质(字形) → 时间(触发)"
  echo "  → 认知(评分) → 规则(自举) → 寄壳(蚕蛹)"
  echo "  操作系统醒来即感应程序存在"
  echo ""
  echo "  全链路: 认知评分→机器码容器→时间触发→字体统一→自举规则→蚕蛹寄壳"
  echo "  纯Nim命令行·全中文符号·零外部依赖"
  echo "═" & repeat("═", 60)

