#==============================================================
#  子系统1: 认知评分器 — 实时评估输入认知水平
#==============================================================

type
  认知维度* = enum
    词汇复杂度, 概念密度, 推理深度, 范畴跨度,
    反思层级, 极性稳定性, 公倍数感知, 相位感知

  回退层级* = enum
    主层, 备胎一, 备胎二, 兜底层

  认知坐标* = object
    维度值*: array[8, float]
    层级*: int
    置信*: float

  生态范畴* = enum
    上学生态, 家庭生态, 社会生态, 玩耍生态

  认知评分器* = object
    历史*: seq[认知坐标]
    当前*: 认知坐标
    门控通过*: seq[string]
    门控阻挡*: seq[string]
    回退深度*: int
    极性锚*: int

proc 创建评分器*(): 认知评分器 =
  认知评分器(历史: @[], 当前: 认知坐标(层级: 0, 置信: 0.0),
             门控通过: @[], 门控阻挡: @[], 回退深度: 0, 极性锚: 1)

proc 分析词汇复杂度*(文本: string): float =
  let 词列表 = 文本.splitWhitespace()
  if 词列表.len == 0: return 0.0
  var 总长 = 0
  var 长词数 = 0
  for 词 in 词列表:
    总长 += 词.len
    if 词.len >= 4: 长词数 += 1
  let 均长 = float(总长) / float(词列表.len)
  let 长率 = float(长词数) / float(词列表.len)
  result = min(10.0, 均长 * 1.2 + 长率 * 5.0)

proc 分析概念密度*(文本: string): float =
  let 标记 = [
    "容器", "协议", "编码", "范畴", "公理", "逻辑", "映射",
    "极性", "进制", "维度", "相位", "裁判", "回退", "共生",
    "门控", "路由", "纤维丛", "吸引子", "叠加", "投影"
  ]
  let 词列表 = 文本.splitWhitespace()
  if 词列表.len == 0: return 0.0
  var c = 0
  for 词 in 词列表:
    for m in 标记:
      if 词.contains(m): c += 1; break
  result = min(10.0, float(c) / float(词列表.len) * 20.0)

proc 分析推理深度*(文本: string): float =
  let 标记 = ["因为", "所以", "如果", "那么", "推出", "假设", "等价", "蕴含"]
  var c = 0
  for m in 标记:
    if 文本.contains(m): c += 1
  result = min(10.0, float(c) * 0.8)

proc 评分*(评分器: var 认知评分器; 文本: string; 极性: 整数 = 1): 认知坐标 =
  var coord: 认知坐标
  coord.维度值[词汇复杂度.ord] = 分析词汇复杂度(文本)
  coord.维度值[概念密度.ord] = 分析概念密度(文本)
  coord.维度值[推理深度.ord] = 分析推理深度(文本)
  if 极性 == 1:
    coord.维度值[极性稳定性.ord] = 10.0
  elif 极性 == 0:
    coord.维度值[极性稳定性.ord] = 5.0
  else:
    coord.维度值[极性稳定性.ord] = 2.0
  # 层级计算
  var total = 0.0
  for v in coord.维度值: total += v
  coord.层级 = int(min(10.0, total / 8.0))
  let 置信 = if 文本.len > 100: 0.9 else: 0.5
  coord.置信 = 置信

  # 门控
  评分器.门控通过 = @[]
  评分器.门控阻挡 = @[]
  if 文本.len > 0:
    评分器.门控通过.add("非空")
  else:
    评分器.门控阻挡.add("非空")
  if coord.层级 >= 1:
    评分器.门控通过.add("最低层级")
  else:
    评分器.门控阻挡.add("最低层级")
  if coord.维度值[概念密度.ord] >= 0.5:
    评分器.门控通过.add("概念最低量")
  else:
    评分器.门控阻挡.add("概念最低量")
  if coord.置信 >= 0.2:
    评分器.门控通过.add("置信最低量")
  else:
    评分器.门控阻挡.add("置信最低量")

  # 判定回退层
  if 评分器.门控阻挡.len == 0:
    评分器.回退深度 = 主层.ord
  elif 评分器.门控阻挡.len <= 2 and coord.置信 > 0.3:
    评分器.回退深度 = 备胎一.ord
  elif coord.置信 > 0.1:
    评分器.回退深度 = 备胎二.ord
  else:
    评分器.回退深度 = 兜底层.ord

  评分器.当前 = coord
  评分器.历史.add(coord)
  result = coord

proc 回退层名*(评分器: 认知评分器): string =
  case 评分器.回退深度
    of 0: "主层·完整推理"
    of 1: "备胎一·简化推理"
    of 2: "备胎二·直接查表"
    of 3: "兜底层·安全回复"
    else: "未知"

#==============================================================
#  子系统2: 机器码容器引擎 — 编码结构
#==============================================================

type
  操作码* = enum
    NOP, LOAD, STORE, ADD, SUB, MUL, HALT

  容器操作* = object
    操作*: 操作码
    操作数*: 整数
    极性*: 整数

  机器码容器* = object
    校验和*: 整数
    操作序列*: seq[容器操作]
    数据槽*: seq[整数]
    入口*: 整数

proc 构建容器*(操作: seq[容器操作]; 数据: seq[整数] = @[]): 机器码容器 =
  result.操作序列 = 操作
  result.数据槽 = newSeq[整数](256)
  for i, d in 数据:
    if i < 256: result.数据槽[i] = d
  var sum = 0
  for op in 操作:
    sum += op.操作.ord * 16 + (op.操作数 mod 16) + op.极性
  result.校验和 = sum mod 256

proc 操作码名*(op: 操作码): string =
  case op
    of NOP: "NOP"
    of LOAD: "LOAD"
    of STORE: "STORE"
    of ADD: "ADD"
    of SUB: "SUB"
    of MUL: "MUL"
    of HALT: "HALT"

#==============================================================
#  子系统3: 时间触发执行引擎 — 执行时序
#==============================================================

type
  时间信封* = object
    时间窗口*: 整数
    见证*: 整数
    入口*: 整数
    周期*: 整数

proc 容器到信封*(容器: 机器码容器; 窗口: 整数; 周期: 整数 = 0): 时间信封 =
  时间信封(时间窗口: 窗口, 见证: 容器.校验和, 入口: 容器.入口, 周期: 周期)

proc 裁决*(信封: 时间信封): string =
  if 信封.见证 == 0: "全零拒"
  elif 信封.见证 > 0: "有效纳"
  else: "空拒"

#==============================================================
#  子系统4: 三维字形字体 — 统一容器格式
#==============================================================

type
  平台* = enum
    ARM64, X86_64, RISCV64, WASM

  字形记录* = object
    容器码*: 机器码容器
    信封*: 时间信封
    声调*: 整数
    三维坐标*: tuple[横: float, 纵: float, 深: float]
    字形符号*: string

  三维字体* = object
    记录*: seq[字形记录]
    索引*: Table[整数, 整数]

proc 创建字体*(): 三维字体 =
  三维字体(记录: @[], 索引: initTable[整数, 整数]())

proc 注册字体*(字体: var 三维字体; rec: 字形记录) =
  let idx = 字体.记录.len
  字体.记录.add(rec)
  字体.索引[rec.容器码.校验和] = idx

