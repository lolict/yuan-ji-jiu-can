type
  寄生壳* = object
    壳类型*: string
    宿主平台*: string
    脱壳次数*: int
    活跃*: bool

proc 创建寄生壳*(类型: string; 平台: string): 寄生壳 =
  寄生壳(壳类型: 类型, 宿主平台: 平台, 脱壳次数: 0, 活跃: true)

