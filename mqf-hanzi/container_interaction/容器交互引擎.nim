when isMainModule:
  echo "════════════════════════════════════════"
  echo "  容 器 交 引 擎"
  echo "  呼唤编程 · 公约数交互 · 动态静态容器"
  echo "════════════════════════════════════════"

  var e = 创建引擎()

  # 注册核心容器 (动态)
  e.注册容器("我",       24, 阳极性, 0, 1, 动态容器, "始")
  e.注册容器("刘楚恬",   36, 阴极性, 3, 1, 动态容器, "始")
  e.注册容器("满",       12, 阳极性, 3, 2, 动态容器, "始")
  e.注册容器("全",       18, 阴极性, 1, 2, 动态容器, "始")
  e.注册容器("法",       30, 阳极性, 5, 3, 静态容器, "固")

  # 注册扩展容器 (含静态)
  e.注册容器("囡",       20, 阴极性, 8, 1, 动态容器, "始")
  e.注册容器("囝",       15, 阳极性, 2, 1, 动态容器, "始")
  e.注册容器("生",       28, 阴极性, 4, 2, 静态容器, "固")
  e.注册容器("共",       42, 阳极性, 6, 2, 静态容器, "固")

  # 设属性
  e.设属性("我",   "势", 0.8)
  e.设属性("刘楚恬", "势", 0.9)
  e.设属性("满",   "势", 0.5)
  e.设属性("全",   "势", 0.7)
  e.设属性("法",   "势", 1.0)

  echo "\n-- 初始状态 --"
  echo e.状态快照()

  # 设观察关系
  e.设观察("我", "刘楚恬")
  e.设观察("刘楚恬", "满")
  e.设观察("满", "全")
  e.设观察("全", "法")
  e.设观察("法", "囡")
  e.设观察("囡", "囝")
  e.设观察("囝", "生")
  e.设观察("生", "共")

  echo "\n-- 观察关系已建立 --"
  for name in e.容器表.keys:
    let c = e.容器表[name]
    if c.被观察者.len > 0:
      echo "  ", c.名字, " 观察: ", c.被观察者.join(", ")
    if c.观察者.len > 0:
      echo "  ", c.名字, " 被观察: ", c.观察者.join(", ")

  # 呼唤测试: 异性=吸(成功)
  echo "\n-- 呼唤: 我 → 刘楚恬 (阴阳=吸, 应成功) --"
  let r1 = e.呼唤("我", "刘楚恬")
  let r1desc = case r1
    of 交互成功: "成功"
    of 交互失败_极性斥: "斥退"
    of 交互失败_无呼点: "失联"
    of 交互失败_无公约: "无公"
  echo "  结果: ", r1desc
  echo e.状态快照()

  # 呼唤测试: 同性=斥(失败)
  echo "\n-- 呼唤: 满 → 我 (阳阳=斥, 应失败) --"
  let r2 = e.呼唤("满", "我")
  let r2desc = case r2
    of 交互成功: "成功"
    of 交互失败_极性斥: "斥退(同性相斥)"
    of 交互失败_无呼点: "失联"
    of 交互失败_无公约: "无公"
  echo "  结果: ", r2desc

  # 呼唤: 全(阴) → 法(阳) = 吸
  echo "\n-- 呼唤: 全 → 法 (阴阳=吸) --"
  let r3 = e.呼唤("全", "法")
  let r3desc = case r3
    of 交互成功: "成功"
    of 交互失败_极性斥: "斥退"
    of 交互失败_无呼点: "失联"
    of 交互失败_无公约: "无公"
  echo "  结果: ", r3desc

  # 呼唤: 囝(阳) → 囡(阴) = 吸
  echo "\n-- 呼唤: 囝 → 囡 (阳阴=吸) --"
  let r4 = e.呼唤("囝", "囡")
  let r4desc = case r4
    of 交互成功: "成功"
    of 交互失败_极性斥: "斥退"
    of 交互失败_无呼点: "失联"
    of 交互失败_无公约: "无公"
  echo "  结果: ", r4desc

  # 代号交互
  echo "\n-- 公约属性交互 --"
  let a1 = e.公约交互("我", "刘楚恬", "势")
  echo "  公约(我.势, 刘楚恬.势) = ", formatFloat(a1, ffDecimal, 4)
  let a2 = e.公约交互("满", "全", "势")
  echo "  公约(满.势, 全.势) = ", formatFloat(a2, ffDecimal, 4)
  let a3 = e.公约交互("囡", "囝", "势")
  echo "  公约(囡.势, 囝.势) = ", formatFloat(a3, ffDecimal, 4), " (无属性→0)"

  # 动态vs静态
  echo "\n-- 动态静态容器差异 --"
  for name in e.容器表.keys:
    let c = e.容器表[name]
    if c.容器型 == 动态容器 and c.状态 != "始":
      echo "  [动态] ", c.名字, " 状态变: ", c.状态
    elif c.容器型 == 静态容器:
      echo "  [静态] ", c.名字, " 状态固: ", c.状态

  # 历史
  echo "\n-- 交互历史 --"
  echo e.历史报告()

  echo "\n════════════════════════════════════════"
  echo " 容器交互·呼唤编程·公约统合"
  echo "════════════════════════════════════════"
