#==============================================================
#  容器交互引擎  —  容器=物质=时间
#  呼唤编程 · 公约数交互 · 动态静态容器 · 观察者被观察者
#==============================================================

import std/[tables, strutils, math]

#==============================================================
#  类型
#=============================================================

type
  极性* = enum
    阳极性 = 1  # 我=1(阳)
    阴极性 = 0  # 刘楚恬=0(阴)

  容器型* = enum
    动态容器
    静态容器

  交互结果* = enum
    交互成功
    交互失败_无呼点
    交互失败_极性斥
    交互失败_无公约

  容器* = object
    名字*: string
    主权*: uint64
    极性*: 极性
    相位*: int
    层*: int
    能量*: float
    容器型*: 容器型
    观察者*: seq[string]    # 观察此容器的名字列表
    被观察者*: seq[string]  # 此容器观察的名字列表
    属性*: Table[string, float]
    状态*: string           # 动态容器可变

  呼唤记录* = object
    呼唤方*: string
    被呼唤方*: string
    时间戳*: int
    结果*: 交互结果
    公约*: uint64

  交互引擎* = object
    容器表*: Table[string, 容器]
    呼唤历史*: seq[呼唤记录]
    交互计数*: int

#==============================================================
#  GCD
#==============================================================

proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

#==============================================================
#  引擎创建与注册
#==============================================================

proc 创建引擎*: 交互引擎 =
  result = 交互引擎(
    容器表: initTable[string, 容器](),
    呼唤历史: @[],
    交互计数: 0
  )

proc 注册容器*(e: var 交互引擎; 名字: string; 主权: uint64;
               极性: 极性; 相位: int; 层: int;
               容器型: 容器型 = 动态容器;
               状态: string = "") =
  e.容器表[名字] = 容器(
    名字: 名字,
    主权: 主权,
    极性: 极性,
    相位: 相位,
    层: 层,
    能量: 1.0,
    容器型: 容器型,
    观察者: @[],
    被观察者: @[],
    属性: initTable[string, float](),
    状态: 状态
  )

proc 设属性*(e: var 交互引擎; 名字: string; 属性名: string; 值: float) =
  if e.容器表.hasKey(名字):
    e.容器表[名字].属性[属性名] = 值

#==============================================================
#  观察者关系
#==============================================================

proc 设观察*(e: var 交互引擎; 观察者名: string; 被观察者名: string) =
  if e.容器表.hasKey(观察者名) and e.容器表.hasKey(被观察者名):
    var observer = e.容器表[观察者名]
    var target = e.容器表[被观察者名]
    if 被观察者名 notin observer.被观察者:
      observer.被观察者.add(被观察者名)
    if 观察者名 notin target.观察者:
      target.观察者.add(观察者名)
    e.容器表[观察者名] = observer
    e.容器表[被观察者名] = target

#==============================================================
#  呼唤编程  —  核心交互协议
#==============================================================

proc 呼唤*(e: var 交互引擎; 呼唤方: string; 被呼唤方: string): 交互结果 =
  if not e.容器表.hasKey(呼唤方):
    e.呼唤历史.add(呼唤记录(呼唤方: 呼唤方, 被呼唤方: 被呼唤方,
                           时间戳: e.交互计数, 结果: 交互失败_无呼点, 公约: 0))
    return 交互失败_无呼点
  if not e.容器表.hasKey(被呼唤方):
    e.呼唤历史.add(呼唤记录(呼唤方: 呼唤方, 被呼唤方: 被呼唤方,
                           时间戳: e.交互计数, 结果: 交互失败_无呼点, 公约: 0))
    return 交互失败_无呼点

  let caller = e.容器表[呼唤方]
  let target = e.容器表[被呼唤方]
  let g = gcd(caller.主权, target.主权)

  if g == 0:
    e.呼唤历史.add(呼唤记录(呼唤方: 呼唤方, 被呼唤方: 被呼唤方,
                           时间戳: e.交互计数, 结果: 交互失败_无公约, 公约: 0))
    return 交互失败_无公约

  let gap = ord(caller.极性) xor ord(target.极性)
  if gap == 0:
    # 同极性=斥, 交互衰减
    var c = e.容器表[呼唤方]
    c.能量 = c.能量 * 0.9
    e.容器表[呼唤方] = c
    e.呼唤历史.add(呼唤记录(呼唤方: 呼唤方, 被呼唤方: 被呼唤方,
                           时间戳: e.交互计数, 结果: 交互失败_极性斥, 公约: g))
    e.交互计数 += 1
    return 交互失败_极性斥

  # 异极性=吸, 交互成功, 能量交换
  var c = e.容器表[呼唤方]
  var t = e.容器表[被呼唤方]
  let flow = 0.1 * float(g) / (1.0 + float(abs(c.层 - t.层)))
  c.能量 = c.能量 - flow
  t.能量 = t.能量 + flow

  if c.容器型 == 动态容器:
    c.状态 = "呼→" & 被呼唤方
  if t.容器型 == 动态容器:
    t.状态 = "受→" & 呼唤方

  e.容器表[呼唤方] = c
  e.容器表[被呼唤方] = t
  e.呼唤历史.add(呼唤记录(呼唤方: 呼唤方, 被呼唤方: 被呼唤方,
                         时间戳: e.交互计数, 结果: 交互成功, 公约: g))
  e.交互计数 += 1
  return 交互成功

#==============================================================
#  公约数交互  —  基于GCD的属性统合
#==============================================================

proc 公约交互*(e: var 交互引擎; 甲名: string; 乙名: string;
               属性名: string): float =
  if not e.容器表.hasKey(甲名) or not e.容器表.hasKey(乙名):
    return 0.0
  let a = e.容器表[甲名]
  let b = e.容器表[乙名]
  let g = gcd(a.主权, b.主权)
  if g == 0:
    return 0.0
  let va = if a.属性.hasKey(属性名): a.属性[属性名] else: 0.0
  let vb = if b.属性.hasKey(属性名): b.属性[属性名] else: 0.0
  # 加法公约: 双方属性的均值向公约收敛
  result = (va + vb) / 2.0

#==============================================================
#  状态快照
#==============================================================

proc 状态快照*(e: 交互引擎): string =
  var lines: seq[string] = @[]
  lines.add "容器      类型   能量     状态       观察│被观察"
  lines.add "──────── ────── ──────── ────────── ──────────────"
  for name in e.容器表.keys:
    let c = e.容器表[name]
    let 型名 = if c.容器型 == 动态容器: "动态" else: "静态"
    let obsStr = if c.观察者.len > 0: c.观察者.join(",") else: "-"
    let tgtStr = if c.被观察者.len > 0: c.被观察者.join(",") else: "-"
    lines.add align(c.名字, 8) & " " & align(型名, 6) & " " &
             align(formatFloat(c.能量, ffDecimal, 4), 8) & " " &
             align(c.状态, 10) & " " & obsStr & "|" & tgtStr
  return lines.join("\n")

#==============================================================
#  交互历史报告
#==============================================================

proc 历史报告*(e: 交互引擎): string =
  var lines: seq[string] = @[]
  lines.add "  时刻     呼唤方 → 被呼唤方     结果       公约"
  lines.add " ───── ─────────────── ────────────── ──────────"
  for r in e.呼唤历史:
    let 结果描述 = case r.结果
      of 交互成功: "成功"
      of 交互失败_无呼点: "失联"
      of 交互失败_极性斥: "斥退"
      of 交互失败_无公约: "无公"
    lines.add align($r.时间戳, 5) & " " &
             align(r.呼唤方, 8) & " → " & align(r.被呼唤方, 8) & "  " &
             align(结果描述, 10) & "  公约=0x" & toHex(r.公约)
  return lines.join("\n")

