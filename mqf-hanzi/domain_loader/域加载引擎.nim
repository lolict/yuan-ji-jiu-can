when isMainModule:
  var e = 初始化域加载器()

  echo "═══ 域加载引擎 ═══"
  echo ""

  # 创建核心域
  e.创建域("满全法核心")
  e.创建域("容器本体")
  e.创建域("路由与聚类")

  # 注册符号
  discard e.注册符号("满全法核心", "我", 1, 变量符号, "我=1=阳", @[])
  discard e.注册符号("满全法核心", "刘楚恬", 2, 变量符号, "刘楚恬=0=阴", @[])
  discard e.注册符号("满全法核心", "共生", 3, 函数符号, "共生(我,刘楚恬)", @[1, 2])
  discard e.注册符号("满全法核心", "合魂", 4, 函数符号, "合魂(阴,阳)", @[2, 1])
  discard e.注册符号("满全法核心", "判", 5, 函数符号, "判断之力", @[1, 2])

  discard e.注册符号("容器本体", "根基族", 10, 容器符号, "8族×1", @[])
  discard e.注册符号("容器本体", "扩容族", 20, 容器符号, "8族×2", @[])
  discard e.注册符号("容器本体", "权柄族", 30, 容器符号, "8族×4", @[])
  discard e.注册符号("容器本体", "归藏族", 40, 容器符号, "8族×8", @[])

  discard e.注册符号("路由与聚类", "满", 0x22801, 路由符号, "m+an,阳", @[10])
  discard e.注册符号("路由与聚类", "漫", 0xC4C01, 路由符号, "m+an,阴", @[20])
  discard e.注册符号("路由与聚类", "全", 0xC4C010, 路由符号, "q+uan,阴", @[30])
  discard e.注册符号("路由与聚类", "法", 0x30031, 路由符号, "f+a,阳", @[40])
  discard e.注册符号("路由与聚类", "声", 0x1A005, 路由符号, "sh+eng,阳", @[10])

  echo "注册完成: " & $e.全局索引.len & " 符号"

  # 锁定域（注册阶段结束）
  discard e.锁定域("满全法核心")
  discard e.锁定域("容器本体")
  discard e.锁定域("路由与聚类")
  echo "全部锁定 ✓"

  # 锁后不可注册测试
  let fail = e.注册符号("满全法核心", "测试", 99, 变量符号, "应失败", @[])
  echo "锁后注册: " & (if fail: "错误—不应成功" else: "正确拒绝 ✓")

  echo ""

  # 激活满全法核心域
  echo "─ 域激活 ─"
  discard e.激活域("满全法核心")
  echo "当前域: " & e.当前域

  echo ""

  # 符号解析测试
  echo "─ 符号解析（索引查找,O(1)） ─"
  for code in [1, 2, 3, 10, 0x22801, 0x30031, 99]:
    let name = e.解析符号(code)
    if name.len > 0:
      echo "  0x" & toHex(code, 4) & " → " & name
    else:
      echo "  0x" & toHex(code, 4) & " → (未找到)"

  echo ""

  # 域叠加
  echo "─ 域叠加 ─"
  discard e.域叠加("统一域", "满全法核心", "容器本体")
  let ud = e.域表["统一域"]
  echo "统一域 = 满全法核心 + 容器本体 → " & $ud.大小 & " 符号"

  # 导出
  echo "─ 域导出 ─"
  echo "满全法核心导出: " & (if e.导出域("满全法核心").len > 10: "有效 ✓" else: "空")

  echo ""
  echo e.加载报告()
