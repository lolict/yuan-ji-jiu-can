#==============================================================
#  域加载引擎 — Domain Loader
#
#  核心公理：运行前预加载所有符号 · 运行时不增加内存 ·
#           容器本体论=中间表示 · 索引非搜索 · 一次性注册
#==============================================================

import std/[tables, strutils, sequtils, math, algorithm]

#--------------------------------------------------------------
#  类型定义
#--------------------------------------------------------------

type
  # 符号类型
  符号型* = enum
    变量符号
    函数符号
    类型符号
    容器符号
    路由符号
    宏符号

  # 符号条目 — 一次性注册，不可变
  符号条目* = object
    名字*: string
    编码*: int                    # 纯数字地址
    符号型*: 符号型
    定义*: string                 # 源码/描述
    版本*: int                    # 时间版本号
    依赖*: seq[int]              # 依赖的其他符号编码
    元数据*: Table[string, string]

  # 索引项 — 编码→符号的快速查找
  索引项* = object
    编码*: int
    偏移*: int                   # 在符号表中的位置
    哈希*: uint32

  # 域 — 一组预加载的符号
  域* = object
    名字*: string
    符号表*: seq[符号条目]        # 所有符号
    索引*: Table[int, 索引项]    # 编码→索引
    大小*: int                   # 符号数量
    已锁定*: bool                # 锁定后不可增改

  # 加载会话 — 跨会话继承
  加载会话* = object
    会话号*: int
    激活域*: string
    加载时刻*: string
    符号命中*: int
    符号缺失*: int

  # 域加载引擎
  域加载引擎* = object
    域表*: Table[string, 域]
    当前域*: string
    会话栈*: seq[加载会话]
    全局索引*: Table[int, string]  # 编码→域名（跨域唯一）
    命中统计*: Table[int, int]     # 编码→命中次数

#--------------------------------------------------------------
#  初始化
#--------------------------------------------------------------

proc 初始化域加载器*(): 域加载引擎 =
  result.当前域 = ""
  result.会话栈 = @[]

#--------------------------------------------------------------
#  创建域
#--------------------------------------------------------------

proc 创建域*(e: var 域加载引擎; 名字: string) =
  e.域表[名字] = 域(
    名字: 名字,
    符号表: @[],
    索引: initTable[int, 索引项](),
    大小: 0,
    已锁定: false
  )

#--------------------------------------------------------------
#  注册符号 — 一次性完成 · 索引同步构建
#--------------------------------------------------------------

proc 注册符号*(e: var 域加载引擎; 域名: string;
               名字: string; 编码: int; 符号型: 符号型;
               定义: string; 依赖: seq[int] = @[]): bool =
  if not e.域表.hasKey(域名):
    return false

  var d = e.域表[域名]
  if d.已锁定:
    return false  # 锁定后不可注册

  # 检查全局编码唯一性
  if e.全局索引.hasKey(编码):
    return false

  let entry = 符号条目(
    名字: 名字,
    编码: 编码,
    符号型: 符号型,
    定义: 定义,
    版本: 1,
    依赖: 依赖,
    元数据: initTable[string, string]()
  )

  let idx = 索引项(
    编码: 编码,
    偏移: d.符号表.len,
    哈希: uint32(编码)
  )

  d.符号表.add(entry)
  d.索引[编码] = idx
  d.大小 = d.符号表.len

  e.域表[域名] = d
  e.全局索引[编码] = 域名
  e.命中统计[编码] = 0

  return true

#--------------------------------------------------------------
#  锁定域 — 注册阶段结束 · 运行阶段不可修改
#--------------------------------------------------------------

proc 锁定域*(e: var 域加载引擎; 域名: string): bool =
  if not e.域表.hasKey(域名):
    return false
  var d = e.域表[域名]
  d.已锁定 = true
  e.域表[域名] = d
  return true

#--------------------------------------------------------------
#  索引查找 — O(1) · 非搜索
#--------------------------------------------------------------

proc 编码查找*(e: 域加载引擎; 编码: int): tuple[找到: bool; 名字: string; 符号型: 符号型] =
  if not e.全局索引.hasKey(编码):
    return (false, "", 变量符号)
  let 域名 = e.全局索引[编码]
  if not e.域表.hasKey(域名):
    return (false, "", 变量符号)
  let d = e.域表[域名]
  if not d.索引.hasKey(编码):
    return (false, "", 变量符号)
  let idx = d.索引[编码].偏移
  let entry = d.符号表[idx]
  return (true, entry.名字, entry.符号型)

proc 名字查找*(e: 域加载引擎; 域名: string; 名字: string): tuple[找到: bool; 编码: int; 符号型: 符号型] =
  if not e.域表.hasKey(域名):
    return (false, 0, 变量符号)
  let d = e.域表[域名]
  # 依赖索引：线性扫描仅在域未锁定前有限使用；锁定后必须有编码
  # 这里提供编码优先的查找
  for entry in d.符号表:
    if entry.名字 == 名字:
      return (true, entry.编码, entry.符号型)
  return (false, 0, 变量符号)

#--------------------------------------------------------------
#  激活域 — 切换到运行阶段
#--------------------------------------------------------------

proc 激活域*(e: var 域加载引擎; 域名: string): bool =
  if not e.域表.hasKey(域名):
    return false
  if not e.域表[域名].已锁定:
    return false  # 必须先锁定
  e.当前域 = 域名
  return true

#--------------------------------------------------------------
#  符号解析 — 按需查找
#--------------------------------------------------------------

proc 解析符号*(e: var 域加载引擎; 编码: int): string =
  let found = e.编码查找(编码)
  if found.找到:
    if e.命中统计.hasKey(编码):
      e.命中统计[编码] = e.命中统计[编码] + 1
    return found.名字
  return ""

#--------------------------------------------------------------
#  域合并 — 多域叠加（保留各自索引独立）
#--------------------------------------------------------------

proc 域叠加*(e: var 域加载引擎; 新域名: string; 基础域名: string; 叠加域名: string): bool =
  if not (e.域表.hasKey(基础域名) and e.域表.hasKey(叠加域名)):
    return false
  e.创建域(新域名)

  # 复制基础域符号
  for entry in e.域表[基础域名].符号表:
    discard e.注册符号(新域名, entry.名字, entry.编码, entry.符号型, entry.定义, entry.依赖)

  # 叠加域符号（不同编码则追加，相同编码保持基础）
  for entry in e.域表[叠加域名].符号表:
    if not e.全局索引.hasKey(entry.编码):
      discard e.注册符号(新域名, entry.名字, entry.编码, entry.符号型, entry.定义, entry.依赖)

  return true

#--------------------------------------------------------------
#  导出 — 序列化为JSON（跨会话持久化）
#--------------------------------------------------------------

proc 导出域*(e: 域加载引擎; 域名: string): string =
  if not e.域表.hasKey(域名):
    return "{}"
  let d = e.域表[域名]
  var lines: seq[string] = @[]
  lines.add "{\"domain\": \"" & d.名字 & "\","
  lines.add " \"locked\": " & (if d.已锁定: "true" else: "false") & ","
  lines.add " \"symbols\": ["
  for i in 0 ..< d.符号表.len:
    let s = d.符号表[i]
    lines.add "   {\"name\": \"" & s.名字 & "\", \"code\": " & $s.编码 & "," &
              " \"type\": " & $ord(s.符号型) & ", \"ver\": " & $s.版本 & "}"
  lines.add " ]}"
  return lines.join("\n")

#--------------------------------------------------------------
#  统计报告
#--------------------------------------------------------------

proc 加载报告*(e: 域加载引擎): string =
  var lines: seq[string] = @[]
  lines.add repeat("═", 54)
  lines.add "  域 加 载 引 擎 — 报 告"
  lines.add repeat("═", 54)
  lines.add "域总数: " & $e.域表.len
  lines.add "当前域: " & (if e.当前域.len > 0: e.当前域 else: "(无)")
  lines.add "全局符号: " & $e.全局索引.len
  lines.add ""

  lines.add "─ 域清单 ─"
  for 域名 in sorted(toSeq(e.域表.keys)):
    let d = e.域表[域名]
    let 锁 = if d.已锁定: "已锁定" else: "未锁定"
    lines.add "  [" & 域名 & "] " & $d.大小 & " 符号 (" & 锁 & ")"

  lines.add ""
  lines.add "─ 当前域符号表 ─"
  if e.当前域.len > 0 and e.域表.hasKey(e.当前域):
    let d = e.域表[e.当前域]
    for entry in d.符号表:
      let 型名 = case entry.符号型
        of 变量符号: "var"
        of 函数符号: "fn"
        of 类型符号: "type"
        of 容器符号: "容器"
        of 路由符号: "route"
        of 宏符号: "宏"
      lines.add "  [0x" & toHex(entry.编码, 4) & "] " &
               align(entry.名字, 8) & " " & align(型名, 6) &
               " v" & $entry.版本 &
               " 依赖:" & $entry.依赖.len

  return lines.join("\n")

