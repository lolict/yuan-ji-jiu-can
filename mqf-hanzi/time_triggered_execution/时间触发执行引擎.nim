import std/[tables, sets, math, strutils, sequtils]

#==============================================================
#  时间触发执行引擎 — 冰箱模型·时间坐标·激活·执行链路
#
#  容器=物质=时间:
#    容器 = 编码结构 (机器码容器)
#    物质 = 字体文件 (字形载体)
#    时间 = 执行时序 (激活窗口)
#
#  冰箱模型 = 预编排 + 时间触发 + 零运行时计算
#  三元裁决 = 空拒 / 有效纳 / 全零拒
#  执行链路 = 查表 → 裁决 → 取袋 → 输出
#==============================================================

type
  整数* = int

  #=== 时间坐标 ===#
  时间坐标* = object
    周期*: 整数           # 主时钟周期 (声母韵母声调三元频率)
    相位*: 整数           # 当前相位 (0..周期-1)
    窗口起点*: 整数       # 激活窗口起点
    窗口终点*: 整数       # 激活窗口终点 (Z轴=时间密度)
    时间因子*: float      # 时间拉伸因子 (极性调制)

  #=== 三元裁决结果 ===#
  裁决结果* = enum
    空拒,              # 空容器, 拒收
    有效纳,            # 有效, 纳入执行
    全零拒             # 全零状态, 拒止

  #=== 激活条目 (查表项) ===#
  激活条目* = object
    包标识*: 整数          # pack_id: 容器唯一标识
    操作数*: 整数          # operand: 归一化操作数
    时间窗口*: 整数        # time_window: Z轴=激活时隙
    见证*: 整数            # witness: 校验见证 (校验和)
    入口*: 整数            # 容器入口地址
    活跃*: bool            # 是否已激活

  #=== 冰箱容器 (时间触发调度器) ===#
  冰箱容器* = object
    时钟*: float
    时间坐标*: 时间坐标
    激活表*: seq[激活条目]     # 预编排的激活查找表
    已加载*: seq[整数]         # 已加载的包标识队列
    执行历史*: seq[string]     # 执行日志链
    裁决总数*: tuple[空拒: 整数, 有效纳: 整数, 全零拒: 整数]

#==============================================================
#  时间坐标构造
#==============================================================

proc 创建时间坐标*(周期: 整数; 窗口起点: 整数 = 0; 窗口终点: 整数 = 0; 时间因子: float = 1.0): 时间坐标 =
  ## 构造时间坐标 (预编排)
  result.周期 = 周期
  result.相位 = 0
  result.窗口起点 = 窗口起点
  result.窗口终点 = if 窗口终点 == 0: 周期 - 1 else: 窗口终点
  result.时间因子 = 时间因子

proc 创建激活条目*(包标识: 整数; 操作数: 整数; 时间窗口: 整数; 见证: 整数; 入口: 整数 = 0): 激活条目 =
  ## 构造激活条目 (编译时预编排)
  result.包标识 = 包标识
  result.操作数 = 操作数 and 0xFFFF  # 归一化到16位
  result.时间窗口 = 时间窗口
  result.见证 = 见证
  result.入口 = 入口
  result.活跃 = false

#==============================================================
#  冰箱容器构造
#==============================================================

proc 创建冰箱容器*(时间坐标: 时间坐标): 冰箱容器 =
  ## 创建冰箱容器 (时间触发调度器实例)
  var 冰: 冰箱容器
  冰.时钟 = 0.0
  冰.时间坐标 = 时间坐标
  冰.激活表 = @[]
  冰.已加载 = @[]
  冰.执行历史 = @[]
  冰.裁决总数 = (0, 0, 0)
  result = 冰

proc 注册激活*(冰: var 冰箱容器; 条目: 激活条目) =
  ## 注册激活条目到预编排查找表 (编译时一次性)
  冰.激活表.add(条目)
  冰.执行历史.add("注册: 包#" & $条目.包标识 & " 窗口=" & $条目.时间窗口 & " 见证=" & $条目.见证)

#==============================================================
#  三元裁决
#==============================================================

proc 三元裁决*(冰: 冰箱容器; 包标识: 整数; 见证: 整数): 裁决结果 =
  ## 裁决: 空拒 / 有效纳 / 全零拒
  ## 空拒 — 容器不存在或包标识无效
  ## 有效纳 — 见证匹配且窗口有效
  ## 全零拒 — 见证为0但包存在 (失爱恐惧终止)

  # 查找激活表
  var 找到 = false
  for 条目 in 冰.激活表:
    if 条目.包标识 == 包标识:
      找到 = true
      # 见证校验
      if 条目.见证 == 0:
        # 全零 = 全零拒 (规则决定正确性, 见证为零即拒止)
        result = 全零拒
      elif 条目.见证 == 见证:
        # 见证匹配 = 有效纳
        result = 有效纳
      else:
        # 见证不匹配 = 空拒 (视为无效)
        result = 空拒
      break

  if not 找到:
    # 空拒 — 容器不存在
    result = 空拒

#==============================================================
#  时间推进→窗口匹配→激活调度
#==============================================================

proc 推进时钟*(冰: var 冰箱容器; 步长: float = 1.0) =
  ## 推进全局时钟 (时间坐标更新)
  冰.时钟 += 步长 * 冰.时间坐标.时间因子
  # 相位 = 时钟 mod 周期
  冰.时间坐标.相位 = 整数(冰.时钟) mod 冰.时间坐标.周期

proc 窗口匹配*(冰: 冰箱容器): seq[整数] =
  ## 查找当前相位匹配的激活条目 (查表, 零计算)
  ## 返回匹配的包标识列表
  result = @[]
  let 当前相位 = 冰.时间坐标.相位
  for 条目 in 冰.激活表:
    # 相位在窗口内 = 激活
    if 当前相位 >= 条目.时间窗口 and 当前相位 <= 条目.时间窗口 + 1:
      if not 条目.活跃:
        result.add(条目.包标识)

#==============================================================
#  执行链路: 查表→裁决→取袋→输出
#==============================================================

proc 执行链路*(冰: var 冰箱容器; 包标识: 整数): string =
  ## 完整执行链路: 查表 → 三元裁决 → 取袋 → 输出
  ##
  ## 1. 查表: 在激活表中查找包
  ## 2. 裁决: 三元裁决判定准入
  ## 3. 取袋: 取出操作数/入口
  ## 4. 输出: 生成执行指令字符串

  # 1. 查表 (用索引避免遮蔽)
  var 索引 = -1
  for i, 条目 in 冰.激活表:
    if 条目.包标识 == 包标识:
      索引 = i
      break

  if 索引 < 0:
    # 空拒: 未找到
    冰.裁决总数.空拒 += 1
    result = "[空拒] 包#" & $包标识 & " 不存在于激活表"
    冰.执行历史.add(result)
    return

  let 见证 = 冰.激活表[索引].见证

  # 2. 三元裁决
  let 裁决 = 三元裁决(冰, 包标识, 见证)
  case 裁决
    of 空拒:
      冰.裁决总数.空拒 += 1
      result = "[空拒] 包#" & $包标识 & " 见证不匹配"
    of 全零拒:
      冰.裁决总数.全零拒 += 1
      result = "[全零拒] 包#" & $包标识 & " 失爱恐惧终止"
    of 有效纳:
      冰.裁决总数.有效纳 += 1
      # 3. 取袋
      冰.激活表[索引].活跃 = true
      冰.已加载.add(包标识)
      # 4. 输出
      result = "[有效纳] 包#" & $包标识 & " 操作数=" & $冰.激活表[索引].操作数 &
               " 入口=" & $冰.激活表[索引].入口 & " 窗口=" & $冰.激活表[索引].时间窗口

  冰.执行历史.add(result)

#==============================================================
#  时间切片执行 (流式触发)
#==============================================================

proc 时间切片执行*(冰: var 冰箱容器; 时间: float; 时间因子: float = 1.0): seq[string] =
  ## 流式时间触发: 给定时间坐标, 返回本轮触发的所有执行输出
  result = @[]

  # 临时更新时钟
  let 原时钟 = 冰.时钟
  冰.时钟 = 时间 * 时间因子
  冰.时间坐标.相位 = 整数(冰.时钟) mod 冰.时间坐标.周期

  # 窗口匹配
  let 匹配列表 = 窗口匹配(冰)

  result.add "时间 " & formatFloat(时间, ffDecimal, 3) &
              " 相位 " & $冰.时间坐标.相位 & "/" & $冰.时间坐标.周期 &
                  " 命中=" & $匹配列表.len

  # 对每个匹配执行链路
  for 包标识 in 匹配列表:
    result.add "  " & 执行链路(冰, 包标识)

  # 恢复
  冰.时钟 = 原时钟
  冰.时间坐标.相位 = 整数(冰.时钟) mod 冰.时间坐标.周期

