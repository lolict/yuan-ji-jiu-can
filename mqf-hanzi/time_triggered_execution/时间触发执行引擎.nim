proc 全周期演示*() =
  ## 完整演示: 预编排 → 时间推进 → 窗口匹配 → 执行链路 → 报告

  echo "═══ 时间触发执行引擎 ═══"
  echo ""
  echo "冰箱模型: 预编排 + 时间触发 + 零运行时计算"
  echo "执行链路: 查表 → 三元裁决(空拒/有效纳/全零拒) → 取袋 → 输出"
  echo ""

  # 构造时间坐标 (周期=12, 对应地支12进制容器)
  let 坐标 = 创建时间坐标(周期=12, 窗口起点=0, 窗口终点=11, 时间因子=1.0)
  var 冰 = 创建冰箱容器(坐标)

  # 预编排: 注册6个激活条目
  # 条目 = pack_id, operand, time_window, witness, entry
  注册激活(冰, 创建激活条目(101, 0x0100, 0, 42, 0))    # LOAD: 时钟0激活
  注册激活(冰, 创建激活条目(102, 0x0300, 3, 43, 1))     # ADD: 时钟3激活
  注册激活(冰, 创建激活条目(103, 0x0C05, 6, 44, 4))     # GLYPH: 时钟6激活
  注册激活(冰, 创建激活条目(104, 0x0200, 9, 45, 7))     # STORE: 时钟9激活
  注册激活(冰, 创建激活条目(105, 0x0000, 0, 0, 0))      # 全零见证: 全零拒
  注册激活(冰, 创建激活条目(106, 0x0F00, 6, 99, 10))     # HALT: 时钟6, 见证不匹配→空拒

  echo "─ 预编排激活表 ─"
  for 条目 in 冰.激活表:
    echo "  包#" & $条目.包标识 &
         " 操作数=0x" & toHex(条目.操作数, 4) &
         " 窗口=" & $条目.时间窗口 &
         " 见证=" & $条目.见证 &
         " 入口=" & $条目.入口
  echo ""

  # 时间推进: 逐时钟演示全周期
  echo "─ 时间推进·全周期触发 ─"
  for 时钟 in 0..11:
    let 输出 = 时间切片执行(冰, float(时钟))
    for line in 输出:
      echo line
    echo ""

  # 非编排时间: 正常推进
  echo "─ 推进时钟到相位5 ─"
  冰.时钟 = 0.0
  for _ in 1..6:
    推进时钟(冰)
  echo "  时钟=" & formatFloat(冰.时钟, ffDecimal, 1) &
       " 相位=" & $冰.时间坐标.相位

  # 直接触发一个未注册的包
  echo ""
  echo "─ 触发未注册包#999 ─"
  echo "  " & 执行链路(冰, 999)

  # 报告
  echo ""
  echo "═" & repeat("═", 50)
  echo "  时间触发执行引擎 — 裁决报告"
  echo "═" & repeat("═", 50)
  echo "激活表条目: ", 冰.激活表.len
  echo "已激活: ", 冰.已加载.len
  echo "空拒: ", 冰.裁决总数.空拒
  echo "有效纳: ", 冰.裁决总数.有效纳
  echo "全零拒: ", 冰.裁决总数.全零拒
  echo "执行历史条数: ", 冰.执行历史.len
  echo ""

  echo "─ 执行历史 ─"
  for i, entry in 冰.执行历史:
    echo "  ", i + 1, ". ", entry
  echo ""

  echo "─ 容器=物质=时间 验证 ─"
  echo "  预编排: 所有激活条目在编译时构建 (无运行时分配)"
  echo "  查表: 零计算, 直接匹配 (相位∈窗口)"
  echo "  裁决: 三元判定 (空拒/有效纳/全零拒)"
  echo "  容器: 编码结构 → 物质: 字体载体 → 时间: 激活时隙"
  echo "  端到端: 查表→裁决→取袋→输出 全链路不依赖外部工具"

#==============================================================
#  主入口
#==============================================================

when isMainModule:
  全周期演示()
