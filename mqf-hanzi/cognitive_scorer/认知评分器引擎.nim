func 更新生态*(评分器: var 认知评分器; 范畴: 生态范畴; 文本: string) =
  let 新坐标 = 估计认知坐标(文本)
  if 评分器.生态表.hasKey(范畴):
    var 评估 = 评分器.生态表[范畴]
    # 滑动平均更新
    for i in 0..7:
      评估.坐标.维度[i] = 评估.坐标.维度[i] * 0.6 + 新坐标.维度[i] * 0.4
    var 总和 = 0.0
    for v in 评估.坐标.维度: 总和 += v
    评估.坐标.层级 = int(round(总和 / 8.0))
    评分器.生态表[范畴] = 评估

