func 备胎回复*(层级: 回退层级; 原始结果: 评分结果): 评分结果 =
  ## 当主推理失败时，以递减复杂度回退
  var 回退 = 原始结果
  回退.回退层 = 层级
  case 层级
    of 主层:
      回退.摘要 = "主推理: " & 原始结果.摘要
      回退.建议回复层级 = 原始结果.建议回复层级
    of 备胎一:
      # 简化推理
      回退.摘要 = "简化推理: 降级至层级 " & $max(0, 原始结果.建议回复层级 - 2)
      回退.建议回复层级 = max(0, 原始结果.建议回复层级 - 2)
      回退.门控后 = 原始结果.门控后 * 0.8
    of 备胎二:
      # 直接查表
      回退.摘要 = "直接查表: 固定层级 3"
      回退.建议回复层级 = 3
      回退.门控后 = 3.0
    of 兜底层:
      # 最低限度安全回复
      回退.摘要 = "兜底安全回复: 层级 1"
      回退.建议回复层级 = 1
      回退.门控后 = 1.0
  回退

