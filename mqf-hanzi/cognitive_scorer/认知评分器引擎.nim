func 创建规则链*(): seq[门控规则] =
  ## 规则门控链: 按优先级排序的过滤规则
  ## 规则1: 空文本直接拒绝
  result.add(门控规则(名称: "非空", 条件: "文本长度>0", 阈值: 1.0, 优先级: 1, 通过: false))
  ## 规则2: 最低认知层级
  result.add(门控规则(名称: "最低层级", 条件: "层级>=1", 阈值: 1.0, 优先级: 2, 通过: false))
  ## 规则3: 极性有效
  result.add(门控规则(名称: "极性有效", 条件: "极性!=0.5(中立)", 阈值: 0.0, 优先级: 3, 通过: false))
  ## 规则4: 概念密度最低要求
  result.add(门控规则(名称: "概念最低量", 条件: "概念密度>=0.5", 阈值: 0.5, 优先级: 4, 通过: false))
  ## 规则5: 置信度最低要求
  result.add(门控规则(名称: "置信最低量", 条件: "置信>=0.2", 阈值: 0.2, 优先级: 5, 通过: false))

func 应用门控*(规则链: var seq[门控规则]; 坐标: 认知坐标; 文本: string): tuple[通过: bool; 阻挡规则: string] =
  ## 应用门控链，所有规则都通过才放行
  for i in 0..<规则链.len:
    var 规则 = 规则链[i]
    case 规则.名称
      of "非空":
        规则.通过 = 文本.len > 0
      of "最低层级":
        规则.通过 = float(坐标.层级) >= 规则.阈值
      of "极性有效":
        let 极稳 = 坐标.维度[认知维度.极性稳定性.ord]
        规则.通过 = 极稳 != 5.0  # 5.0=完全中立=无效
      of "概念最低量":
        let 概密 = 坐标.维度[认知维度.概念密度.ord]
        规则.通过 = 概密 >= 规则.阈值
      of "置信最低量":
        规则.通过 = 坐标.置信 >= 规则.阈值
      else:
        规则.通过 = true

    规则链[i] = 规则

    if not 规则.通过:
      return (false, 规则.名称)

  (true, "")

