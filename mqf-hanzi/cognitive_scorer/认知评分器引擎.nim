func 分析极性稳定性*(文本: string): float =
  ## 极性稳定性: 判断的一致性与方向感
  let 正向标记 = ["是", "对", "要", "行", "好", "可以"]
  let 反向标记 = ["不", "没", "难", "无", "别", "未"]
  var 正数 = 0
  var 反数 = 0
  for 标记 in 正向标记:
    if 文本.contains(标记): 正数 += 1
  for 标记 in 反向标记:
    if 文本.contains(标记): 反数 += 1

  # 方向明确 = |正-反| / (正+反+1) 归一化
  let 总 = 正数 + 反数
  if 总 == 0:
    result = 3.0  # 中性
  else:
    let 方向强度 = abs(正数 - 反数) / 总
    result = 方向强度 * 10.0

