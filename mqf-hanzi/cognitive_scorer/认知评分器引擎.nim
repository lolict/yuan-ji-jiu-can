func 分析词汇复杂度*(文本: string): float =
  ## 词汇复杂度: 基于词长分布与罕用词比例
  let 词列表 = 文本.splitWhitespace()
  if 词列表.len == 0: return 0.0

  var 总长 = 0
  var 长词数 = 0
  for 词 in 词列表:
    总长 += 词.len
    if 词.len >= 4: 长词数 += 1

  let 平均词长 = float(总长) / float(词列表.len)
  let 长词率 = float(长词数) / float(词列表.len)

  # 综合评分 0-10
  result = min(10.0, 平均词长 * 1.2 + 长词率 * 5.0)

func 分析概念密度*(文本: string): float =
  ## 概念密度: 独立概念数 / 总词数
  ## 概念指示词: 方程/函数/逻辑/容器/协议/编码/范畴/公理/映射/纤维丛/...
  let 概念标记 = [
    "方程", "函数", "逻辑", "容器", "协议", "编码", "范畴", "公理",
    "映射", "纤维丛", "极性", "进制", "寻址", "门控", "回退",
    "共生", "叠加", "投影", "和声", "裁判", "维度", "相位",
    "公约数", "公倍数", "通断", "镜像", "拓扑", "路由",
    "吸引子", "振荡", "纤维", "丛", "基", "元", "阶"
  ]
  let 词列表 = 文本.splitWhitespace()
  if 词列表.len == 0: return 0.0

  var 概念数 = 0
  for 词 in 词列表:
    for 标记 in 概念标记:
      if 词.contains(标记):
        概念数 += 1
        break

  result = min(10.0, float(概念数) / float(词列表.len) * 20.0)

func 分析推理深度*(文本: string): float =
  ## 推理深度: 基于逻辑连接词密度与推理链长度指示
  let 推理标记 = [
    "因为", "所以", "如果", "那么", "因此", "由于", "从而",
    "推出", "推导", "归纳", "演绎", "反证", "假设",
    "当且仅当", "等价", "蕴含", "因果", "充要",
    "第一", "第二", "第三", "首先", "其次", "综上"
  ]
  var 推理数 = 0
  for 标记 in 推理标记:
    if 文本.contains(标记):
      推理数 += 1

  # 标点密度 (复合句指标)
  var 复合标点数 = 0
  for ch in 文本:
    if ch in {',', '.', ';', ':'}:
      复合标点数 += 1
  # 中文标点: 逐字节匹配
  for 标 in ["，", "。", "；", "："]:
    if 文本.contains($标):
      复合标点数 += 1

  result = min(10.0, float(推理数) * 0.8 + float(复合标点数) * 0.1)

