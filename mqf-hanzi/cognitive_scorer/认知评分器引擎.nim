  引擎.回退计数 = 0
  引擎.最大回退 = 3
  引擎.极性锚 = 1
  初始化生态(引擎)
  引擎

proc 评分*(e: var 认知评分器; 文本: string; 场景: 生态范畴 = 上学生态): 评分结果 =
  ## 先估计认知坐标
  let 坐标 = 估计认知坐标(文本)

  ## 应用门控规则
  var 规则链 = e.门控表
  let 门控结果 = 应用门控(规则链, 坐标, 文本)
  e.门控表 = 规则链

  if not 门控结果.通过:
    return 评分结果(
      原始分: 0.0, 门控后: 0.0,
      使用规则: "阻挡于:" & 门控结果.阻挡规则,
      回退层: 兜底层, 建议回复层级: 1,
      摘要: "规则阻挡: " & 门控结果.阻挡规则
    )

  # 原始评分
  var 原始 = 0.0
  for v in 坐标.维度:
    原始 += v
  原始 = 原始 / 8.0

  # 门控后评分
  var 门控评分 = 原始
  var 最严规则 = ""
  for 规则 in e.门控表:
    if 规则.通过:
      门控评分 = max(门控评分, 规则.阈值)
      最严规则 = 规则.名称

  # 建议回复层级
  let 回复层级 = min(10, max(1, int(round(门控评分))))

  # 更新状态
  e.当前坐标 = 坐标
  e.历史.add(坐标)
  更新生态(e, 场景, 文本)

  评分结果(
    原始分: 原始, 门控后: 门控评分,
    使用规则: 最严规则,
    回退层: 主层, 建议回复层级: 回复层级,
    摘要: "评分=" & formatFloat(门控评分, ffDecimal, 2) & " 层级=" & $回复层级
  )

proc 评分带回退*(e: var 认知评分器; 文本: string; 场景: 生态范畴 = 上学生态): 评分结果 =
  ## 带备胎回退的评分
  var 评分器 = e.评分(文本, 场景)

  # 如果门控阻挡或评分太低，逐级回退
  if 评分器.门控后 < 1.0:
    评分器 = 备胎回复(备胎一, 评分器)

  if 评分器.门控后 < 0.5 and e.回退计数 < e.最大回退:
    e.回退计数 += 1
    评分器 = 备胎回复(兜底层, 评分器)
  else:
    e.回退计数 = 0

  评分器

