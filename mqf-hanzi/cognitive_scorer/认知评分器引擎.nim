  坐标.维度[认知维度.公倍数感知.ord] = 分析公倍数感知(文本)
  坐标.维度[认知维度.相位感知.ord] = 分析相位感知(文本)

  # 总量化层级 = 8维均值
  var 总和 = 0.0
  for v in 坐标.维度:
    总和 += v
  坐标.层级 = int(round(总和 / 8.0))
  坐标.置信 = min(1.0, float(文本.len) / 50.0)  # 文本越长置信越高
  坐标.时间戳 = 时间戳
  坐标

