proc 添加子*(父: 容器节点; 子: 容器节点) =
  ## 添加子容器到父容器
  父.子容器.add(子)
  # 继承符号: 子能访问父的符号 (直接修改刚添加的子)
  let 子索引 = 父.子容器.high
  for k, v in 父.符号:
    父.子容器[子索引].符号[k] = v

proc 删除子*(父: 容器节点; 子名字: string) =
  ## 删除子容器
  var 删除索引 = -1
  for i, 子 in 父.子容器:
    if 子.名字 == 子名字:
      删除索引 = i
      break
  if 删除索引 >= 0:
    父.子容器[删除索引].活标记 = false
    # 不物理删除, 标记死亡(版本控制溯源)

proc 注册符号*(父: 容器节点; 名字: string; 编码: int) =
  ## 在容器中注册符号
  父.符号[名字] = 编码
  # 符号传递给所有活着的子容器
  for i in 0..<父.子容器.len:
    if 父.子容器[i].活标记:
      父.子容器[i].符号[名字] = 编码

proc 查找符号*(节点: 容器节点; 名字: string): tuple[找到: bool; 编码: int; 来源: string] =
  ## 查找符号: 先从自身找, 再向父回溯
  if 节点.符号.hasKey(名字):
    return (true, 节点.符号[名字], 节点.地址)
  # 如果找不到，返回自身地址
  (false, 0, 节点.地址)

#==============================================================
#  门禁验证 — 极性/层级/公约数三重门禁
#==============================================================

func 检查门禁*(引擎: 嵌套容器引擎; 请求: 容器节点): bool =
  ## 检查请求容器是否满足当前门的准入规则
  let 规则 = 引擎.根.门禁

  # 极性检查: 请求的极性是否在准入集合中
  if not (请求.极性 in 规则.极性准入):
    return false

  # 层级检查: 请求深度是否在规定范围内
  if 请求.深度 < 规则.层级下限 or 请求.深度 > 规则.层级上限:
    return false

  # 极性签名: 是否来自同一极性锚
  if 规则.需签名 and 请求.极性 != 引擎.极性锚:
    return false

  return true

func 递归门禁*(引擎: 嵌套容器引擎; 节点: 容器节点; 请求极性: int; 请求深度: int): bool =
  ## 递归检查从根到节点的路径上所有门禁
  # 检查当前层门禁
  let 请求 = 容器节点(极性: 请求极性, 深度: 请求深度)
  if not 检查门禁(引擎, 请求):
    return false

  # 如果节点是干的子，需要逐层回溯检查
  for 子 in 节点.子容器:
    if 子.活标记:
      if not 递归门禁(引擎, 子, 请求极性, 子.深度):
        return false
  true

#==============================================================
#  极性继承体系
#==============================================================

func 继承极性*(父极性: int; 翻转: bool = false): int =
  ## 子容器从父继承极性
  if 翻转:
    return 1 - 父极性
  return 父极性

func 子树极性统计*(节点: 容器节点): tuple[阳数: int; 阴数: int; 总: int] =
  ## 统计子树的极性分布
  var 阳 = 0
  var 阴 = 0
  if 节点.活标记:
    if 节点.极性 == 1: 阳 += 1
    else: 阴 += 1
  for 子 in 节点.子容器:
    let 子统计 = 子树极性统计(子)
    阳 += 子统计.阳数
    阴 += 子统计.阴数
  (阳, 阴, 阳 + 阴)

