proc 收集所有节点*(节点: 容器节点; 列表: var seq[容器节点]) =
  ## 递归收集所有活着的节点
  if 节点.活标记:
    列表.add(节点)
  for 子 in 节点.子容器:
    收集所有节点(子, 列表)

proc 按层收集*(节点: 容器节点; 层: 容器层级; 列表: var seq[容器节点]) =
  ## 按层级收集节点
  if 节点.活标记 and 节点.层级 == 层:
    列表.add(节点)
  for 子 in 节点.子容器:
    按层收集(子, 层, 列表)

func 总深度*(节点: 容器节点): int =
  ## 计算子树最大深度
  if 节点.子容器.len == 0:
    return 节点.深度
  var 最深 = 节点.深度
  for 子 in 节点.子容器:
    最深 = max(最深, 总深度(子))
  最深

func 子树大小*(节点: 容器节点): int =
  ## 统计子树节点数(活着的)
  var 数量 = 0
  if 节点.活标记: 数量 += 1
  for 子 in 节点.子容器:
    数量 += 子树大小(子)
  数量

#==============================================================
#  路由: 按地址查找节点
#==============================================================

func 路由查找*(根: 容器节点; 地址: string): tuple[找到: bool; 节点: 容器节点] =
  ## 按地址在嵌套树中查找节点
  if 根.地址 == 地址 and 根.活标记:
    return (true, 根)
  for 子 in 根.子容器:
    let 结果 = 路由查找(子, 地址)
    if 结果.找到:
      return 结果
  (false, 容器节点())

