proc 打印树*(节点: 容器节点; 缩进: int = 0) =
  ## 递归打印容器树
  let 前缀 = repeat("  │ ", 缩进)
  let 状态 = if 节点.活标记: "●" else: "○"
  let 极性 = if 节点.极性 == 1: "阳" else: "阴"
  echo 前缀, 状态, " [", 层级名(节点.层级), "/", 极性, "] ",
       节点.名字, " @", 节点.地址, " (编码=", $节点.编码, " D=", $节点.深度, ")"

  for 子 in 节点.子容器:
    打印树(子, 缩进 + 1)

