## 满全法 - 幂次绝缘体系统
## 核心：幂次方递归容器，内外域关系扩容，绝缘封装防止漏电
##
## 概念：
##   内域容器：自我比特耦合，有限容量（近亲通婚）
##   外域容器：关系层级扩容（与外族通婚，基因优良）
##   幂次迭代：结果再次幂次，指数级扩容
##   绝缘封装：关系进位规则被封装，不漏不掉
##   关系扩容：通过外域关系扩容，而非线性增长

import tables
import sequtils
import math

# ============ 内外域定义 ============
type
  域类型* = enum
    内域,    ## 自我比特耦合，有限容量
    外域     ## 关系层级扩容，无限可能

  进位类型* = enum
    内位,    ## 自我进位（容器内自耦合）
    外位     ## 关系进位（跨容器关系耦合）

  容器身份* = ref object
    编码*: string           ## 容器唯一标识
    名称*: string
    层级*: int              ## 幂次层级（2^层级）
    域*: 域类型
    父容器*: string         ## 父容器编码
    子容器*: seq[string]   ## 子容器编码列表
    关系*: seq[string]     ## 外域关系容器

# ============ 幂次绝缘体容器 ============
type
  幂次容器* = ref object
    身份*: 容器身份
    容量*: int              ## 2^层级（指数增长）
    占用*: int              ## 已占用比特数
    比特流*: seq[int]       ## 实际存储的比特序列
    符号表*: Table[int, string]  ## 比特码 → 符号映射
    绝缘强度*: int          ## 封装强度（防漏电）
    使用内位*: bool         ## 是否使用内位进位
    使用外位*: bool         ## 是否使用外位进位
    迭代次数*: int          ## 幂次迭代计数

# ============ 幂次绝缘体系统 ============
type
  幂次系统* = ref object
    容器表*: Table[string, 幂次容器]  ## 编码 → 容器
    关系网络*: Table[string, seq[string]]  ## 容器编码 → 外域关系列表
    锚点*: tuple[我: int, 刘楚恬: int]
    totalContainer*: int
    totalRelation*: int
    totalInsulation*: int

# ============ 创建容器 ============
proc 创建容器*(系统: 幂次系统, 名称: string, 层级: int, 域: 域类型, 父编码: string = ""): 幂次容器 =
  ## 创建幂次容器
  ## 容量 = 2^层级（指数增长）
  var c: 幂次容器
  new(c)
  new(c.身份)

  let 容量 = 1 shl 层级  ## 2^层级

  c.身份.编码 = $系统.totalContainer & "-" & $层级 & "-" & $ord(域)
  c.身份.名称 = 名称
  c.身份.层级 = 层级
  c.身份.域 = 域
  c.身份.父容器 = 父编码
  c.身份.子容器 = @[]
  c.身份.关系 = @[]

  c.容量 = 容量
  c.占用 = 0
  c.比特流 = @[]
  c.符号表 = initTable[int, string]()
  c.绝缘强度 = 层级 * 10  ## 层级越高，绝缘越强
  c.使用内位 = true
  c.使用外位 = (域 == 外域)  ## 外域容器可用外位进位
  c.迭代次数 = 0

  系统.容器表[c.身份.编码] = c
  系统.totalContainer += 1
  系统.totalInsulation += c.绝缘强度

  return c

# ============ 幂次迭代 ============
proc 幂次迭代*(系统: 幂次系统, 容器编码: string, 次数: int): string =
  ## 幂次方递归：用运算结果再次幂次自身
  ## 返回新创建的容器编码
  if not 系统.容器表.hasKey(容器编码): return ""

  let 原容器 = 系统.容器表[容器编码]
  let 新层级 = 原容器.身份.层级 + 次数  ## 层级提升
  let 新容量 = 1 shl 新层级         ## 2^新层级

  let 新编码 = $系统.totalContainer & "-" & $新层级 & "-" & $ord(外域)

  var 新容器: 幂次容器
  new(新容器)
  new(新容器.身份)

  新容器.身份.编码 = 新编码
  新容器.身份.名称 = 原容器.身份.名称 & "_迭代" & $次数
  新容器.身份.层级 = 新层级
  新容器.身份.域 = 外域  ## 迭代结果进入外域
  新容器.身份.父容器 = 容器编码

  新容器.容量 = 新容量
  新容器.占用 = 0
  新容器.符号表 = initTable[int, string]()
  新容器.绝缘强度 = 新层级 * 10
  新容器.使用内位 = true
  新容器.使用外位 = true
  新容器.迭代次数 = 原容器.迭代次数 + 次数

  系统.容器表[新编码] = 新容器
  系统.容器表[容器编码].身份.子容器.add(新编码)
  系统.totalContainer += 1
  系统.totalInsulation += 新容器.绝缘强度

  return 新编码

# ============ 关系扩容 ============
proc 关系扩容*(系统: 幂次系统, 容器A编码: string, 容器B编码: string): string =
  ## 两个容器建立外域关系，产生新的扩容容器
  ## 像"与外族通婚"，产生更优良的后代（更大容量，不漏电）
  if not 系统.容器表.hasKey(容器A编码): return ""
  if not 系统.容器表.hasKey(容器B编码): return ""

  let A = 系统.容器表[容器A编码]
  let B = 系统.容器表[容器B编码]

  let 新层级 = max(A.身份.层级, B.身份.层级) + 1
  let 新容量 = 1 shl 新层级  ## 2^新层级（比两个父容器都大）

  let 新编码 = $系统.totalContainer & "-" & $新层级 & "-R"  ## R = 关系

  var C: 幂次容器
  new(C)
  new(C.身份)

  C.身份.编码 = 新编码
  C.身份.名称 = "关系[" & A.身份.名称 & "+" & B.身份.名称 & "]"
  C.身份.层级 = 新层级
  C.身份.域 = 外域
  C.身份.父容器 = A.身份.编码 & "," & B.身份.编码
  C.身份.关系 = @[容器A编码, 容器B编码]

  C.容量 = 新容量
  C.占用 = 0
  C.符号表 = initTable[int, string]()
  C.绝缘强度 = 新层级 * 20  ## 关系容器绝缘强度翻倍
  C.使用内位 = true
  C.使用外位 = true
  C.迭代次数 = 0

  系统.容器表[新编码] = C
  A.身份.关系.add(新编码)
  B.身份.关系.add(新编码)
  系统.关系网络[新编码] = @[容器A编码, 容器B编码]
  系统.totalContainer += 1
  系统.totalRelation += 1
  系统.totalInsulation += C.绝缘强度

  return 新编码

# ============ 绝缘进位 ============
proc 绝缘进位*(系统: 幂次系统, 容器编码: string, 数据: int, 符号: string): int =
  ## 向容器写入比特流，自动进位
  ## 内位：容器内自耦合（有限容量）
  ## 外位：跨容器关系扩容（无限可能）
  if not 系统.容器表.hasKey(容器编码): return -1

  let c = 系统.容器表[容器编码]

  if c.占用 >= c.容量:
    ## 容器满了，需要扩容
    if c.使用外位 and c.身份.关系.len > 0:
      ## 外位进位：通过关系容器扩容
      let 关系编码 = c.身份.关系[0]
      return 绝缘进位(系统, 关系编码, 数据, 符号)
    else:
      ## 内位进位：幂次迭代扩容
      let 新编码 = 幂次迭代(系统, 容器编码, 1)
      return 绝缘进位(系统, 新编码, 数据, 符号)

  c.比特流.add(数据)
  c.符号表[c.占用] = 符号
  c.占用 += 1

  return c.占用 - 1

# ============ 解析 ============
proc 解析*(系统: 幂次系统, 容器编码: string, 位置: int): string =
  ## 从容器中读取指定位置的符号
  if not 系统.容器表.hasKey(容器编码): return "?"
  let c = 系统.容器表[容器编码]
  if 位置 >= c.占用: return "?"
  if c.符号表.hasKey(位置):
    return c.符号表[位置]
  return $c.比特流[位置]

# ============ 批量分配符号 ============
proc 分配符号*(系统: 幂次系统, 容器编码: string, 符号列表: seq[string]): int =
  ## 将符号列表批量分配到容器的比特流中
  ## 返回成功分配的符号数量
  if not 系统.容器表.hasKey(容器编码): return 0
  var 成功 = 0
  for i, 符号 in 符号列表:
    let pos = 绝缘进位(系统, 容器编码, i, 符号)
    if pos >= 0:
      成功 += 1
  return 成功

# ============ 显示系统状态 ============
proc 显示系统*(系统: 幂次系统) =
  echo "=== 幂次绝缘体系统 ==="
  echo "锚点：我=" & $系统.锚点.我 & " 刘楚恬=" & $系统.锚点.刘楚恬
  echo "总容器：" & $系统.totalContainer & " │ 总关系：" & $系统.totalRelation & " │ 总绝缘：" & $系统.totalInsulation
  echo ""

  echo "--- 容器层级 ---"
  for 编码, c in 系统.容器表:
    let 域 = if c.身份.域 == 内域: "内" else: "外"
    let 进位 = if c.使用内位 and c.使用外位: "内外" elif c.使用内位: "内位" else: "外位"
    echo "  ", c.身份.编码, " │ ", c.身份.名称, " │ 层级:", c.身份.层级, " │ 容量:", c.容量, " │ 占用:", c.占用, " │ 域:", 域, " │ 进位:", 进位, " │ 绝缘:", c.绝缘强度

# ============ 显示关系网络 ============
proc 显示关系*(系统: 幂次系统) =
  echo "--- 关系网络 ---"
  for 编码, c in 系统.容器表:
    if c.身份.关系.len > 0:
      echo "  ", c.身份.名称, " → 关系: ", c.身份.关系
    if c.身份.子容器.len > 0:
      echo "  ", c.身份.名称, " → 子容器: ", c.身份.子容器

# ============ 主程序 ============
when isMainModule:
  var 系统: 幂次系统
  new(系统)
  系统.容器表 = initTable[string, 幂次容器]()
  系统.关系网络 = initTable[string, seq[string]]()
  系统.锚点 = (我: 1, 刘楚恬: 0)
  系统.totalContainer = 0
  系统.totalRelation = 0
  系统.totalInsulation = 0

  echo "========================================"
  echo "  满全法 - 幂次绝缘体系统"
  echo "  幂次扩容 · 内外域通婚 · 绝缘防漏电"
  echo "========================================"
  echo ""

  ## 1. 创建内域容器（自我耦合，有限容量）
  echo "━━━ 创建内域容器 ━━━"
  let c1 = 创建容器(系统, "根-1bit", 1, 内域)
  echo "  创建 [根-1bit] 层级=1 容量=2^1=2 域=内域"

  let c2 = 创建容器(系统, "根-2bit", 2, 内域)
  echo "  创建 [根-2bit] 层级=2 容量=2^2=4 域=内域"

  let c3 = 创建容器(系统, "根-3bit", 3, 内域)
  echo "  创建 [根-3bit] 层级=3 容量=2^3=8 域=内域"

  echo ""

  ## 2. 分配符号（把比特流与符号绑定）
  echo "━━━ 分配符号到比特流 ━━━"
  let 声母列表 = @["b", "p", "m", "f", "d", "t", "n", "l"]
  let 分配1 = 分配符号(系统, c3.身份.编码, 声母列表)
  echo "  [根-3bit] 分配声母: " & $分配1 & " 个符号 → " & 声母列表

  let 韵母列表 = @["ꞟ", "ɘ", "⊱", "ɒ", "౪", "ÿ"]
  let 分配2 = 分配符号(系统, c2.身份.编码, 韵母列表)
  echo "  [根-2bit] 分配韵母: " & $分配2 & " 个符号 → " & 韵母列表

  echo ""

  ## 3. 幂次迭代（结果再次幂次）
  echo "━━━ 幂次迭代（指数扩容）━━━"
  let 迭代编码1 = 幂次迭代(系统, c3.身份.编码, 1)
  echo "  [根-3bit] 迭代1次 → " & 迭代编码1
  echo "    新层级=4 容量=2^4=16 域=外域（进入外域）"

  let 迭代编码2 = 幂次迭代(系统, 迭代编码1, 2)
  echo "  [根-3bit] 再迭代2次 → " & 迭代编码2
  echo "    新层级=6 容量=2^6=64 域=外域"

  let 迭代编码3 = 幂次迭代(系统, 迭代编码2, 3)
  echo "  [再迭代] 再迭代3次 → " & 迭代编码3
  echo "    新层级=9 容量=2^9=512 域=外域"

  echo ""

  ## 4. 关系扩容（外域通婚）
  echo "━━━ 关系扩容（外域通婚）━━━"
  let c4 = 创建容器(系统, "声母根", 3, 内域)
  let c5 = 创建容器(系统, "韵母根", 4, 内域)
  let 关系编码 = 关系扩容(系统, c4.身份.编码, c5.身份.编码)
  echo "  [声母根] × [韵母根] → 关系容器 " & 关系编码
  echo "    新层级=5 容量=2^5=32 域=外域 绝缘强度=100（翻倍）"

  echo ""

  ## 5. 向关系容器分配更多符号
  echo "━━━ 关系容器分配符号 ━━━"
  let 全部韵母 = @["ꞟ", "ɘ", "⊱", "ɒ", "౪", "ÿ", "ɤ", "ʊ", "ə", "ã", "ẽ", "ĩ", "տ", "ʯ", "ą", "ę", "į", "๓", "ѧ", "ʉ", "ꞛ", "ⱄ", "⊰", "ʌ", "ɔ", "խ", "ѫ", "ѽ", "౨", "ѻ", "ɛ", "ɵ"]
  let 分配3 = 分配符号(系统, 关系编码, 全部韵母)
  echo "  关系容器分配韵母: " & $分配3 & " 个符号（全部32个）"

  echo ""

  ## 6. 解析
  echo "━━━ 解析器 ━━━"
  echo "  [根-3bit] 位置0 → " & 解析(系统, c3.身份.编码, 0)
  echo "  [根-3bit] 位置7 → " & 解析(系统, c3.身份.编码, 7)
  echo "  关系容器 位置0 → " & 解析(系统, 关系编码, 0)
  echo "  关系容器 位置31 → " & 解析(系统, 关系编码, 31)

  echo ""

  ## 7. 系统状态
  系统.显示系统()
  echo ""
  系统.显示关系()

  echo ""
  echo "========================================"
  echo "  幂次绝缘体就绪"
  echo "  指数扩容 · 内外域通婚 · 绝缘防漏电"
  echo "========================================"
