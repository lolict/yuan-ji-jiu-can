## 满全法 - 清官编码系统
## 一个符号 = 一个字节，不依赖外部映射表
## 工藤新一心理预期：声母 + 韵母 + 声调 + 颜色 + 数字
## 预加载自定义韵母（拉丁字母注释 + 声调标记）

import tables
import sequtils

# ============ 声调类型 ============
type
  声调* = enum
    阴平 = 0  # 第一声
    阳平 = 1  # 第二声
    上声 = 2  # 第三声
    去声 = 3  # 第四声
    轻声 = 4  # 轻声
    # 扩展声调（超过4声的特殊标记）
    变调5 = 5
    变调6 = 6
    变调7 = 7

# ============ 清官编码：一个符号一个字节 ============
# 每字节 = 声母索引(3bit) + 韵母索引(3bit) + 声调标记(2bit)
# 但声调用2bit最多4种，所以我们用更宽的表

type
  清官符号* = object
    声母*: string      # 声母（拉丁字母）
    韵母*: string      # 韵母（拉丁字母 + 自定义声调标记）
    声调*: 声调        # 声调
    颜色*: string      # 对应的颜色容器符号
    字节码*: byte      # 编码后的单字节
    内存占用*: int     # 真实内存占用（目标：1字节）

# ============ 容器：清官码表 ============
type
  清官容器* = ref object
    声母表*: seq[string]
    韵母表*: seq[string]       # 预加载自定义韵母（带声调标记）
    颜色表*: seq[string]       # 对应颜色
    符号集合*: seq[清官符号]
    计数*: int                 # 总量（加法登记）

# ============ 初始化清官容器 ============
proc 初始明清官容器*(): 清官容器 =
  new(result)
  
  # 声母（23个基础声母）
  result.声母表 = @[
    "b", "p", "m", "f", "d", "t", "n", "l",
    "g", "k", "h", "j", "q", "x",
    "zh", "ch", "sh", "r", "z", "c", "s",
    "y", "w"
  ]
  
  # 自定义韵母（预加载，带声调标记，超过50个）
  # 规则：基础韵母 + 声调数字后缀 = 独立韵母符号
  # 例如：a1=阴平 a2=阳平 a3=上声 a4=去声
  result.韵母表 = @[
    "a1", "a2", "a3", "a4",        # a 的四声
    "o1", "o2", "o3", "o4",        # o 的四声
    "e1", "e2", "e3", "e4",        # e 的四声
    "i1", "i2", "i3", "i4",        # i 的四声
    "u1", "u2", "u3", "u4",        # u 的四声
    "v1", "v2", "v3", "v4",        # ü 的四声（v代表ü）
    "ai1", "ai2", "ai3", "ai4",    # ai 四声
    "ei1", "ei2", "ei3", "ei4",    # ei 四声
    "ao1", "ao2", "ao3", "ao4",    # ao 四声
    "ou1", "ou2", "ou3", "ou4",    # ou 四声
    "an1", "an2", "an3", "an4",    # an 四声
    "en1", "en2", "en3", "en4",    # en 四声
    "ang1", "ang2", "ang3", "ang4",# ang 四声
    "eng1", "eng2", "eng3", "eng4",# eng 四声
    "ong1", "ong2", "ong3", "ong4",# ong 四声
    "er1", "er2", "er3", "er4"     # er 四声
  ]
  
  # 颜色对应表（与颜色容器对齐）
  result.颜色表 = @[
    "妃", "粉", "彤", "赤", "棕", "绛", "赭",
    "缃", "金", "黄", "褐", "黧", "乌", "黑",
    "缥", "翠", "绿", "青", "苍", "黛", "玄"
  ]
  
  result.符号集合 = @[]
  result.计数 = 0

# ============ 注册清官符号 ============
proc 注册*(容器: 清官容器, 声母: string, 韵母: string, 声调: 声调, 颜色: string): 清官符号 =
  var 符号: 清官符号
  符号.声母 = 声母
  符号.韵母 = 韵母
  符号.声调 = 声调
  符号.颜色 = 颜色
  
  # 计算单字节编码（简化版：声母索引 XOR 韵母索引 XOR 声调）
  var 声索引 = 容器.声母表.find(声母)
  if 声索引 < 0: 声索引 = 0
  var 韵索引 = 容器.韵母表.find(韵母)
  if 韵索引 < 0: 韵索引 = 0
  
  let 声部 = (声索引 and 0x07) shl 5    # 3bit 在高位
  let 韵部 = (韵索引 and 0x07) shl 2    # 3bit 在中位
  let 声部2 = (ord(声调) and 0x03)       # 2bit 在低位
  符号.字节码 = byte(声部 or 韵部 or 声部2)
  符号.内存占用 = 1  # 目标：一个符号只占1字节
  
  容器.符号集合.add(符号)
  容器.计数 += 1  # 加法登记
  
  return 符号

# ============ 批量注册演示 ============
proc 预加载演示*(容器: 清官容器) =
  # 常用音节 + 颜色映射
  const 演示数据 = [
    ("m", "a1", 阴平, "妃"),    # 妈
    ("m", "a2", 阳平, "粉"),    # 麻
    ("m", "a3", 上声, "彤"),    # 马
    ("m", "a4", 去声, "赤"),    # 骂
    ("h", "ao1", 阴平, "棕"),   # 蒿
    ("h", "ao2", 阳平, "绛"),   # 豪
    ("h", "ao3", 上声, "赭"),   # 好
    ("h", "ao4", 去声, "缃"),   # 号
    ("ch", "ang1", 阴平, "金"), # 昌
    ("ch", "ang2", 阳平, "黄"), # 长
    ("ch", "ang3", 上声, "褐"), # 厂
    ("ch", "ang4", 去声, "黧"), # 唱
    ("l", "i1", 阴平, "苍"),    # 哩
    ("l", "i2", 阳平, "黛"),    # 离
    ("l", "i3", 上声, "玄"),    # 李
    ("l", "i4", 去声, "素")     # 力
  ]

  for i in 0..<演示数据.len:
    let (声, 韵, 调, 色) = 演示数据[i]
    discard 容器.注册(声, 韵, 调, 色)

