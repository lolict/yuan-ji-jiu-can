# Part 3: 六元对称裁决器（简化联动版）
# ===================================================================

type
  极性* = enum
    pol囡, pol囝

  面色* = enum
    s右, s左, s天, s地, s前, s后

  六面体* = ref object
    A面*: array[6, string]    # 极性囡三面 + 极性囝三面
    A极性*: array[6, 极性]
    名称*: int

  裁决结果* = ref object
    信任*: string
    一致数*: int
    描述*: string

proc 新六面体*(名称: int): 六面体 =
  new(result)
  result.名称 = 名称
  for i in 0..5:
    result.A极性[i] = if i mod 2 == 0: pol囡 else: pol囝

proc 六面裁决*(体: 六面体, 五元: 五元组): 裁决结果 =
  # 将五元符号放入六面体
  for i in 0..<min(6, 五元.旋钮.len):
    体.A面[i] = 五元.旋钮[i].符号

  # 判定：对面的极性互补且符号一致 → 信任
  var 一致 = 0
  # s右(0) vs s左(1), s天(2) vs s地(3), s前(4) vs s后(5)
  体.A面[0] = 五元.旋钮[0].符号 & "囡"
  体.A面[1] = 五元.旋钮[1].符号 & "囝"
  体.A面[2] = 五元.旋钮[2].符号 & "囡"
  体.A面[3] = 五元.旋钮[3].符号 & "囝"
  体.A面[4] = 五元.旋钮[4].符号 & "囡"
  # s后(5) 由裁决器填充：囝极性锚点
  体.A面[5] = "囝锚"

  # 检查三对对面的一致性
  if 五元.旋钮[0].占存 and 五元.旋钮[1].占存: 一致 += 1  # 声韵互补
  if 五元.旋钮[2].占存 and 五元.旋钮[3].占存: 一致 += 1  # 数色互补
  if 五元.旋钮[4].占存: 一致 += 1                        # 时序+锚

  new(result)
  result.一致数 = 一致
  case 一致
  of 3:
    result.信任 = "全交集"; result.描述 = "完全信任 — 三面互补闭合"
  of 2:
    result.信任 = "部分";  result.描述 = "有条件信任"
  of 1:
    result.信任 = "微弱";  result.描述 = "单点信任 — 需见证"
  else:
    result.信任 = "无";    result.描述 = "不可信任"

proc 六面可视化*(体: 六面体): string =
  var sb = ""
  sb.add("    ┌────┐\n")
  sb.add("    │" & 体.A面[2] & "│\n")
  sb.add("  ┌─┼────┼─┬─┐\n")
  sb.add("  │" & 体.A面[0] & "│" & 体.A面[4] & "│" & 体.A面[1] & "│\n")
  sb.add("  └─┼────┼─┴─┘\n")
  sb.add("    │" & 体.A面[3] & "│\n")
  sb.add("    └────┘\n")
  sb.add("    │" & 体.A面[5] & "│\n")
  result = sb

