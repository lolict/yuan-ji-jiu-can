# Part 5: 统一时间轴
# ===================================================================

type
  事件类型* = enum
    ev五元推进, ev惩法裁决, ev六元判定, ev蜂窝注入

  事件* = ref object
    时间*: int
    类型*: 事件类型
    名称*: string
    结果*: string

  时间轴* = ref object
    当前*: int
    事件*: seq[事件]
    日志*: seq[string]

proc 新时间轴*(): 时间轴 =
  new(result)
  result.当前 = 0
  result.事件 = @[]
  result.日志 = @[]

proc 触发*(轴: 时间轴, 类型: 事件类型, 名称, 结果: string) =
  var e: 事件
  new(e)
  e.时间 = 轴.当前
  e.类型 = 类型
  e.名称 = 名称
  e.结果 = 结果
  轴.事件.add(e)
  let 类型符号 = case 类型
    of ev五元推进: "[五]"
    of ev惩法裁决: "[惩]"
    of ev六元判定: "[六]"
    of ev蜂窝注入: "[蜂]"
  let 记录 = "[T" & $轴.当前 & "]" & 类型符号 & " " & 名称 & " → " & 结果
  轴.日志.add(记录)
  轴.当前 += 1
  discard

proc 时间轴摘要*(轴: 时间轴): string =
  var sb = "━━━ 时间轴摘要 ━━━\n"
  sb.add("  总事件: " & $轴.事件.len & "  当前: T" & $轴.当前 & "\n\n")
  for e in 轴.事件:
    sb.add("  " & e.结果 & "\n")
  result = sb

