type
  五元类型* = enum
    y声母, y韵母, y颜色, y数字, y时序

  五元旋钮* = ref object
    元*: 五元类型
    符号*: string
    步*: int
    角度*: float
    力道*: float
    进入*: float
    离开*: float
    刻度*: int
    占存*: bool

  五元组* = ref object
    旋钮*: seq[五元旋钮]
    名称*: string
    推力*: int

proc 五元初始化*(): 五元组 =
  new(result)
  result.名称 = "五元组"
  result.推力 = 0
  result.旋钮 = @[
    五元旋钮(元: y声母, 符号: "b", 步: 0, 角度: 0, 力道: 0, 进入: 0.5, 离开: 0.3, 刻度: 0, 占存: false),
    五元旋钮(元: y韵母, 符号: "a", 步: 0, 角度: 0, 力道: 0, 进入: 0.4, 离开: 0.4, 刻度: 0, 占存: false),
    五元旋钮(元: y颜色, 符号: "红", 步: 0, 角度: 0, 力道: 0, 进入: 0.3, 离开: 0.5, 刻度: 0, 占存: false),
    五元旋钮(元: y数字, 符号: "1", 步: 0, 角度: 0, 力道: 0, 进入: 0.2, 离开: 0.6, 刻度: 0, 占存: false),
    五元旋钮(元: y时序, 符号: "春", 步: 0, 角度: 0, 力道: 0, 进入: 0.6, 离开: 0.2, 刻度: 0, 占存: false)
  ]

proc 五元推进*(组: 五元组, 元Idx: int, 角度, 力道: float, 惩: 惩法引擎, 符号源: 符号源): string =
  var k = 组.旋钮[元Idx]
  k.步 = (k.步 + 1); if k.步 > 4: k.步 = 0
  k.角度 = (k.角度 + 角度) mod 360.0
  if k.角度 < 0: k.角度 += 360.0
  k.力道 += 力道
  k.刻度 += 1
  if k.刻度 > 2: k.占存 = true

  # 符号更新
  let ct = case k.元
    of y声母: ct声母
    of y韵母: ct韵母
    of y颜色: ct颜色
    of y数字: ct数字
    of y时序: ct时序
  k.符号 = 取符号(符号源, ct, k.刻度)

  # 惩法检查（与相邻旋钮拼接）
  var 惩法文本 = ""
  if 元Idx > 0:
    let prev = 组.旋钮[元Idx - 1]
    let ctPrev = case prev.元
      of y声母: ct声母
      of y韵母: ct韵母
      of y颜色: ct颜色
      of y数字: ct数字
      of y时序: ct时序
    let r = 惩.惩法(ctPrev, prev.符号, prev.刻度, ct, k.符号, k.刻度)
    惩法文本 = "(惩法:" & $r.等级 & "/" & $r.铆合 & ")"

  # 联动相邻
  let left = (元Idx - 1 + 5) mod 5
  var r = 组.旋钮[left]
  r.角度 = (r.角度 + 角度 * 0.3) mod 360.0
  r.刻度 += 1

  组.推力 += 1
  let 元名 = ["声母","韵母","颜色","数字","时序"][元Idx]
  result = "  " & 元名 & "→步" & $k.步 & " 角" & $k.角度 & "° 力" & $k.力道 &
           " 符:" & k.符号 & " 占:" & (if k.占存: "铭" else: "暂") & " " & 惩法文本

proc 五元状态*(组: 五元组): string =
  var sb = "  [五元]"
  for k in 组.旋钮:
    sb.add(" " & k.符号 & (if k.占存: "●" else: "○"))
  result = sb

