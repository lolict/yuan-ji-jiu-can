# Part 4: 七元蜂窝承载器（简化联动版）
# ===================================================================

type
  蜂室* = ref object
    符号*: string
    裁决信任*: string
    五元快照*: string
    深度*: int

  蜂房* = ref object
    中心*: 蜂室
    环层*: seq[seq[蜂室]]
    层数*: int

proc 新建蜂房*(层数: int): 蜂房 =
  new(result)
  result.层数 = 层数
  result.中心 = 蜂室(符号: "我", 裁决信任: "核", 五元快照: "锚", 深度: 0)
  result.环层 = @[]
  for ring in 1..层数:
    var 环: seq[蜂室] = @[]
    for j in 1..(if ring == 0: 1 else: ring * 6):
      环.add(蜂室(符号: "-", 裁决信任: "空", 五元快照: "", 深度: ring))
    result.环层.add(环)

proc 注入裁决*(蜂房: var 蜂房, 环: int, 位置: int, 符号, 信任, 快照: string) =
  if 环 < 0 or 环 >= 蜂房.环层.len: return
  if 位置 < 0 or 位置 >= 蜂房.环层[环].len: return
  var c = 蜂房.环层[环][位置]
  c.符号 = 符号
  c.裁决信任 = 信任
  c.五元快照 = 快照

proc 蜂房摘要*(蜂房: 蜂房): string =
  var sb = "  [蜂房] 中心:" & 蜂房.中心.符号 & " 层数:" & $蜂房.层数
  for ring in 0..<蜂房.环层.len:
    var 环信息 = ""
    for c in 蜂房.环层[ring]:
      if c.裁决信任 != "空":
        环信息.add(c.符号 & "(" & c.裁决信任[0] & ")")
      else:
        环信息.add("-")
    sb.add("\n  环" & $(ring+1) & "(" & $len(蜂房.环层[ring]) & "): " & 环信息)
  result = sb

