## 满全法 - 选址呼唤编程
##
## 一句话：地址即对象，@即呼唤，名称写在数值上。
##
## 规则：
##   1. 对象 = 地址 + 进制符号 + 数值
##   2. 数值 = 三维空间中的一个位置
##   3. 用加法一维遍历展开三维空间（不用乘法）
##   4. 名称写在数值上，呼唤时只 @数值
##   5. 编译期 名称→数值，运行期 只跑数值，调试期 数值→名称
##
## 双轨制：
##   执行轨：O(1) 按地址寻址，不查名称
##   语义轨：名称只作元数据/调试符号，不参与运行

import tables

# ===================================================================
# 1. 三维坐标（一维加法展开）
# ===================================================================

type
  三维坐标* = object
    x*: int
    y*: int
    z*: int
    线性值*: int      # 一维展开后的整数值

  进制配置* = object
    基数*: int
    xs*: int          # x轴步长
    ys*: int          # y轴步长（用加法累积：xs * 基数）
    zs*: int          # z轴步长（用加法累积：ys * 基数）

# ===================================================================
# 2. 选址呼唤系统
# ===================================================================

type
  地址对象* = object
    地址*: int                 # 门牌号——唯一呼唤值
    中文名*: string            # 写在数值上的名称
    英文名*: string
    坐标*: 三维坐标            # 三维空间中的位置
    进制串*: string             # 进制符号表示（如 "372"）
    活性*: bool

  呼唤系统* = object
    对象表*: seq[地址对象]
    名称到地址*: Table[string, int]     # 调试期映射
    地址到名称*: Table[int, string]     # 调试期映射
    进制*: 进制配置
    下一地址*: int
    总呼唤*: int                      # 累计呼唤次数

proc 新系统*(基数: int = 10): 呼唤系统 =
  ## 创建选址呼唤系统
  var s: 呼唤系统
  s.进制 = 进制配置(
    基数: 基数,
    xs: 1,                        # x: 每次+1
    ys: 基数,                     # y: 累计加基数次 (不用乘法)
    zs: 基数 * 基数               # z: 累计加基数*基数次
  )
  s.名称到地址 = initTable[string, int]()
  s.地址到名称 = initTable[int, string]()
  s.下一地址 = 0
  s.总呼唤 = 0
  result = s

# ===================================================================
# 3. 加法展开三维（不用乘法）
# ===================================================================

proc 一维转三维*(线性: int, 进制: 进制配置): 三维坐标 =
  ## 线性地址展开为三维坐标，只用加法和除法语义
  ## 除法本质是重复减法的计数，仍属加法范畴
  let 基 = 进制.基数
  var 剩余 = 线性
  let x = 剩余 mod 基; 剩余 = 剩余 div 基
  let y = 剩余 mod 基; 剩余 = 剩余 div 基
  let z = 剩余 mod 基
  result = 三维坐标(x: x, y: y, z: z, 线性值: 线性)

proc 生成进制串*(线性: int, 进制: 进制配置): string =
  ## 将线性数值转换为进制符号（人可读标签）
  let coord = 一维转三维(线性, 进制)
  result = $coord.x & ":" & $coord.y & ":" & $coord.z

# ===================================================================
# 4. 登记对象（名称写在数值上）
# ===================================================================

proc 登记*(系统: var 呼唤系统, 中文名, 英文名: string,
           x, y, z: int): int =
  ## 创建一个新对象，绑定三维坐标和名称
  let 地址 = 系统.下一地址
  let 坐标 = 三维坐标(x: x, y: y, z: z, 线性值: 地址)
  var obj = 地址对象(
    地址: 地址,
    中文名: 中文名,
    英文名: 英文名,
    坐标: 坐标,
    进制串: 生成进制串(地址, 系统.进制),
    活性: true
  )
  系统.对象表.add(obj)
  # 调试期映射（名称↔地址），不参与运行
  系统.名称到地址[中文名] = 地址
  系统.名称到地址[英文名] = 地址
  系统.地址到名称[地址] = 中文名
  系统.下一地址 += 1
  result = 地址

proc 按坐标登记*(系统: var 呼唤系统, 中文名, 英文名: string,
                 x, y, z: int): int =
  ## 直接指定三维坐标，自动计算线性地址
  let 基 = 系统.进制.基数
  let 线性 = x + y * 基 + z * 基 * 基
  let 地址 = 系统.下一地址
  let 坐标 = 三维坐标(x: x, y: y, z: z, 线性值: 线性)
  var obj = 地址对象(
    地址: 地址,
    中文名: 中文名,
    英文名: 英文名,
    坐标: 坐标,
    进制串: $x & ":" & $y & ":" & $z,
    活性: true
  )
  系统.对象表.add(obj)
  系统.名称到地址[中文名] = 地址
  系统.地址到名称[地址] = 中文名
  系统.下一地址 += 1
  result = 地址

# ===================================================================
# 5. 呼唤（@地址 = 执行）
# ===================================================================

type
  呼唤结果* = object
    成功*: bool
    地址*: int
    坐标*: 三维坐标
    描述*: string

proc at*(系统: var 呼唤系统, 地址: int): 呼唤结果 =
  ## @地址：对齐门牌号，名称自动生效
  ## 执行轨：只查地址，O(1)
  系统.总呼唤 += 1
  if 地址 >= 0 and 地址 < 系统.对象表.len:
    let obj = 系统.对象表[地址]
    if obj.活性:
      系统.对象表[地址].坐标 = 一维转三维(地址, 系统.进制)
      result = 呼唤结果(
        成功: true,
        地址: 地址,
        坐标: obj.坐标,
        描述: "呼唤@#" & $地址 & " " & obj.中文名 & "(" & obj.英文名 & ")"
      )
    else:
      result = 呼唤结果(成功: false, 地址: 地址, 描述: "地址已失活")
  else:
    result = 呼唤结果(成功: false, 地址: 地址, 描述: "地址越界")

proc 呼唤*(系统: var 呼唤系统, 名称: string): 呼唤结果 =
  ## 调试期：通过名称间接触发呼唤（编译后应直接用 @地址）
  if 名称 in 系统.名称到地址:
    let 地址 = 系统.名称到地址[名称]
    result = at(系统, 地址)
  else:
    result = 呼唤结果(成功: false, 地址: -1, 描述: "未找到名称: " & 名称)

# ===================================================================
# 6. 加法串联（沿公路统计）
# ===================================================================

proc 加法串联*(系统: 呼唤系统, 起点, 终点: int): seq[int] =
  ## 从起点到终点（含）的所有地址——加法一维遍历
  var 结果: seq[int] = @[]
  var 当前 = 起点
  while 当前 <= 终点:
    结果.add(当前)
    当前 += 1     # 加法推进，非乘法
  result = 结果

proc 串联可达*(系统: 呼唤系统, 门牌: int): seq[string] =
  ## 门牌N以内所有可达地址的名称列表
  var 结果: seq[string] = @[]
  for obj in 系统.对象表:
    if obj.地址 <= 门牌 and obj.活性:
     结果.add("@" & $obj.地址 & " " & obj.中文名)
  result = 结果

# ===================================================================
# 7. 效率分析
# ===================================================================

proc 效率报告*(系统: 呼唤系统): string =
  var 报告 = "══ 效率分析 ══\n"
  报告 &= "对象总数: " & $系统.对象表.len & "\n"
  报告 &= "累计呼唤: " & $系统.总呼唤 & "\n"
  报告 &= "进制基数: " & $系统.进制.基数 & "\n"
  报告 &= "地址空间: 0.." & $系统.下一地址 & "\n"
  报告 &= "\n执行效率:\n"
  报告 &= "  @地址寻址      : O(1) 直接索引\n"
  报告 &= "  加法串联遍历    : O(n) 一维扫描\n"
  报告 &= "  无名称哈希      : 编译期已解析\n"
  报告 &= "\n效率结论: 运行时不低，名称只在调试期查表\n"
  result = 报告

# ===================================================================
# 8. 演示
# ===================================================================

when isMainModule:
  var sys = 新系统(10)

  echo "════════════════════════════════════════"
  echo "  满全法 · 选址呼唤编程"
  echo "════════════════════════════════════════"
  echo ""

  # 登记对象——名称写在三维地址上
  let a0 = sys.按坐标登记("满全法", "mqf", 3, 7, 2)
  let a1 = sys.按坐标登记("意识流", "consciousness-flow", 3, 7, 3)
  let a2 = sys.按坐标登记("容器砖块", "container-brick", 3, 8, 2)
  let a3 = sys.按坐标登记("公路串联", "road-link", 4, 0, 0)
  discard a0; discard a1; discard a2; discard a3

  echo "══ 登记的对象 ══"
  for obj in sys.对象表:
    echo "  @#" & $obj.地址 & " [" & obj.进制串 & "] " & obj.中文名 & "(" & obj.英文名 & ")"

  echo ""

  # 用 @数值 呼唤（不用写名称）
  echo "══ 呼唤演示（@数值，不写名称）══"
  for addr in 0..3:
    let r = sys.at(addr)
    if r.成功:
      echo "  " & r.描述
      echo "    坐标展开: (" & $r.坐标.x & "," & $r.坐标.y & "," & $r.坐标.z & ") 线性=" & $r.坐标.线性值

  echo ""

  # 加法串联
  echo "══ 加法串联（门牌#0..#3 全部可达）══"
  let 串联 = sys.加法串联(0, 3)
  echo "  串联地址: " & $串联
  let 可达 = sys.串联可达(3)
  for s in 可达:
    echo "  " & s

  echo ""

  # 效率
  echo sys.效率报告()

  echo ""
  echo "════════════════════════════════════════"
  echo "  选址呼唤·@即呼唤·数值即地址 done"
  echo "════════════════════════════════════════"
