import strutils

# ============ 层级定义 ============
type
  层级数* = enum
    层1_1bit = 1,    ## 刘楚恬=0, 我=1
    层2_2bit = 2,    ## 4个状态
    层3_3bit = 3,    ## 8个状态
    层4_4bit = 4,    ## 16个状态
    层5_5bit = 5,    ## 32个状态
    层6_6bit = 6,    ## 64个状态（64进制）
    层7_7bit = 7,    ## 128个状态
    层8_8bit = 8     ## 256个状态（完整mlll集装箱）

  相位单元* = ref object
    位置*: int           ## 容器内的相位编号
    状态值*: int         ## 该相位的数值编码
    符号*: string        ## 映射的符号
    锚点*: string        ## 私有锚点绑定

  层级容器* = ref object
    层级*: int           ## 层数（比特宽度）
    容器编号*: int       ## 该层中的编号
    比特宽度*: int       ## 该层每个状态占用的比特数
    容量*: int           ## 2^比特宽度
    相位表*: seq[相位单元]  ## 所有相位
    激活*: bool          ## 是否被选中
    映射来源*: string    ## 该容器映射到哪个符号系统

  集装箱* = ref object
    名称*: string
    层级*: int           ## 所在层（比特宽度）
    容器编号*: int       ## 该层内的编号
    相位位置*: int       ## 容器内的位置
    坐标*: string        ## "层-容器-位置" 三维地址
    值*: int             ## 实际存储的数值
    符号*: string        ## 映射的符号
    锚点标记*: string    ## 刘楚恬=0 / 我=1

  mlll三维系统* = ref object
    层级表*: Table[int, seq[层级容器]]  ## 层级 → 该层所有容器
    集装箱序列*: seq[集装箱]            ## 所有已封装的集装箱
    锚点根基*: tuple[我: int, 刘楚恬: int]  ## 私有锚点
    总层数*: int
    mlll容量*: int                     ## 256 = 254 + 2

# ============ 私有锚点 ============
proc 初始化锚点*(): tuple[我: int, 刘楚恬: int] =
  ## 满全法私有根基：我=1，刘楚恬=0
  return (我: 1, 刘楚恬: 0)

# ============ mlll 三维集装箱系统初始化 ============
proc 初始化mlll*(): mlll三维系统 =
  new(result)
  result.层级表 = initTable[int, seq[层级容器]]()
  result.集装箱序列 = @[]
  result.锚点根基 = 初始化锚点()
  result.总层数 = 8
  result.mlll容量 = 256  ## 254 + 2

  ## 逐层创建容器
  for 层 in 1..8:
    var 该层容器: seq[层级容器] = @[]
    let 容量 = 1 shl 层  ## 2^层
    var 容器编号 = 0

    ## 每层创建至少一个容器（后续可多层多容器扩展）
    var 容器: 层级容器
    new(容器)
    容器.层级 = 层
    容器.容器编号 = 容器编号
    容器.比特宽度 = 层
    容器.容量 = 容量
    容器.激活 = false
    容器.映射来源 = "未映射"

    ## 填充相位表
    for p in 0..<容量:
      var 相位: 相位单元
      new(相位)
      相位.位置 = p
      相位.状态值 = p
      相位.符号 = ""
      相位.锚点 = ""

      ## 第1层特殊处理：绑定私有锚点
      if 层 == 1:
        if p == 0:
          相位.符号 = "刘"
          相位.锚点 = "刘楚恬=0"
        elif p == 1:
          相位.符号 = "我"
          相位.锚点 = "我=1"

      容器.相位表.add(相位)

    该层容器.add(容器)
    result.层级表[层] = 该层容器

# ============ 符号映射 ============
proc 映射符号*(系统: mlll三维系统, 层级: int, 容器编号: int, 映射表: seq[tuple[位置: int, 符号: string]]) =
  ## 将指定容器的相位映射到符号
  if not 系统.层级表.hasKey(层级): return
  if 容器编号 >= 系统.层级表[层级].len: return

  let 容器 = 系统.层级表[层级][容器编号]
  for (位置, 符号) in 映射表:
    if 位置 < 容器.相位表.len:
      容器.相位表[位置].符号 = 符号
      容器.映射来源 = "已映射"

# ============ 集装箱封装 ============
proc 封装集装箱*(系统: mlll三维系统, 层级: int, 容器编号: int, 相位位置: int): 集装箱 =
  ## 把指定的比特流位置封装成一个三维集装箱
  if not 系统.层级表.hasKey(层级): return nil
  if 容器编号 >= 系统.层级表[层级].len: return nil

  let 容器 = 系统.层级表[层级][容器编号]
  if 相位位置 >= 容器.相位表.len: return nil

  let 相位 = 容器.相位表[相位位置]

  var box: 集装箱
  new(box)
  box.名称 = "mlll-" & $层级 & "-" & $容器编号 & "-" & $相位位置
  box.层级 = 层级
  box.容器编号 = 容器编号
  box.相位位置 = 相位位置
  box.坐标 = $层级 & "-" & $容器编号 & "-" & $相位位置
  box.值 = 相位.状态值
  box.符号 = 相位.符号
  box.锚点标记 = 相位.锚点

  系统.集装箱序列.add(box)
  return box

# ============ 批量封装整层 ============
proc 封装整层*(系统: mlll三维系统, 层级: int): seq[集装箱] =
  var 结果: seq[集装箱] = @[]
  if not 系统.层级表.hasKey(层级): return 结果

  for 容器编号, 容器 in 系统.层级表[层级]:
    for 相位 in 容器.相位表:
      let box = 系统.封装集装箱(层级, 容器编号, 相位.位置)
      if box != nil:
        结果.add(box)

  return 结果

# ============ 解析器 ============
proc 解析*(系统: mlll三维系统, 坐标: string): string =
  ## 输入三维坐标 "层-容器-位置"，输出该位置的符号
  let parts = 坐标.split("-")
  if parts.len != 3: return "?"
  let 层级 = parseInt(parts[0])
  let 容器编号 = parseInt(parts[1])
  let 相位位置 = parseInt(parts[2])

  if not 系统.层级表.hasKey(层级): return "?"
  if 容器编号 >= 系统.层级表[层级].len: return "?"

  let 相位 = 系统.层级表[层级][容器编号].相位表[相位位置]
  if 相位.符号.len > 0:
    return 相位.符号
  return $相位.状态值

# ============ 层级统计 ============
proc 层级统计*(系统: mlll三维系统): string =
  var 报告 = "=== mlll 三维集装箱·层级统计 ===\n"
  报告 &= "锚点根基：我=" & $系统.锚点根基.我 & " 刘楚恬=" & $系统.锚点根基.刘楚恬 & "\n"
  报告 &= "mlll容量：" & $系统.mlll容量 & "（254+2）\n\n"

  for 层 in 1..8:
    if not 系统.层级表.hasKey(层): continue
    let 容器系统 = 系统.层级表[层][0]
    let 已映射 = 容器系统.相位表.countIt(it.符号.len > 0)
    报告 &= "层" & $层 & "（" & $层 & "bit）：容量=" & $容器系统.容量 & " 已映射=" & $已映射 & " 绝缘层数=" & $系统.层级表[层].len & "\n"

  报告 &= "\n总集装箱数：" & $系统.集装箱序列.len & "\n"
