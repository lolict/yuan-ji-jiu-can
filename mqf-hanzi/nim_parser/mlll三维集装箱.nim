## 满全法 - mlll 三维集装箱系统
## 核心：层级化比特流容器，从1比特到8比特的三维进制封装
##
## 三维坐标：（层数，容器编号，相位位置）
##   层数 L: 1-8（比特宽度）
##   容器编号 C: 该层中的第几个容器
##   相位位置 P: 容器内的第几个状态
##
## 私有锚点根基：我=1，刘楚恬=0
## 集装箱容量：254 + 2 = 256 = 2^8（完整字节）
## mlll：三维集装箱，专为定制封装服务

import tables
import sequtils
