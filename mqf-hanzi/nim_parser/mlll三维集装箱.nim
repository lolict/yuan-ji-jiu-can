# ============ 显示三维结构 ============
proc 显示三维结构*(系统: mlll三维系统, 最大层: int = 8) =
  echo "=== mlll 三维集装箱·结构 ==="
  echo "锚点：我=" & $系统.锚点根基.我 & " 刘楚恬=" & $系统.锚点根基.刘楚恬
  echo "mlll容量：256 = 254+2"
  echo ""

  for 层 in 1..min(最大层, 8):
    if not 系统.层级表.hasKey(层): continue
    let 容器 = 系统.层级表[层][0]
    let 容量 = 容器.容量

    echo "【层", 层, "】", 层, "bit → ", 容量, "个状态"
    echo "  比特层级: ", (1 shl 层), " = 2^", 层
    echo "  容器编号: 0  映射: ", 容器.映射来源

    ## 显示前16个状态（4bit以上显示省略）
    let 显示数 = if 容量 <= 16: 容量 else: 16
    for i in 0..<显示数:
      let 相位 = 容器.相位表[i]
      if 相位.锚点.len > 0:
        echo "    [", i, "] 值=", 相位.状态值, " ◆ ", 相位.锚点
      elif 相位.符号.len > 0:
        echo "    [", i, "] 值=", 相位.状态值, " → ", 相位.符号
      else:
        echo "    [", i, "] 值=", 相位.状态值
    if 容量 > 16:
      echo "    ...（共", 容量, "个状态）"
    echo ""

