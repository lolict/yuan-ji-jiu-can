type
  工作状态* = enum
    ws规划中, ws施工中, ws完成, ws待修改, ws已归档

# ===================================================================
# 3. 容器（砖块/插件）
##    容器索引地址 = 公路门牌号
##    声明为容器才能让符号可用
# ===================================================================

type
  容器* = object
    索引地址*: int              # 公路门牌号
    标识*: string               # 注册名称
    中文名*: string
    英文名*: string
        符号*: seq[string]          # 容器内的符号（加法串联·非锁死）
    符号总数*: int              # 就是自己的统计身份
    相位*: 相位坐标             # 九宫摆放位置
    代数*: int                  # 自我递归显现（当前版本的第几代）
    状态*: 工作状态
    版本号*: int
    创建时间*: int              # 创建时公路修到的位置
    完成时间*: int
    需求描述*: string
    方法论*: string
    预期值*: string
    约束方案*: string
    错误总结*: string
    认知更新*: string
    依赖*: seq[int]            # 指向其他容器的索引地址（外包对象）
    活性*: bool

# ===================================================================
# 4. 公路（加法串联·非乘法）
##    公路[i] 串联 container[0] + container[1] + ... + container[i]
##    覆盖范围 = 加法累计值 = i+1 个容器
# ===================================================================

type
  公路* = object
    当前门牌*: int             # 公路修到了哪个容器
    串联累积*: int             # 加法总数（经过了几个容器）
    最大功率*: int              # 当前公路最大覆盖的容器数

# ===================================================================
# 5. 乘法口诀表（跨容器符号统计）
##    用于统计两个容器的符号总数·快速判断覆盖范围
##    乘法仅用于统计·不用于串联（串联永远用加法）
# ===================================================================

type
  口诀表* = object
    容器甲*: int
    容器乙*: int
    甲符号数*: int
    乙符号数*: int
    交叉覆盖率*: float         # |A∩B| / |A∪B| ·判断重复度

proc 造口诀*(集群: seq[容器], 甲, 乙: int): 口诀表 =
  if 甲 < 0 or 甲 >= 集群.len or 乙 < 0 or 乙 >= 集群.len:
    return
  var 甲符号 = 集群[甲].符号
  var 乙符号 = 集群[乙].符号
  var 交集 = 0
  for s in 甲符号:
    if s in 乙符号: 交集 += 1
  let 并集 = 甲符号.len + 乙符号.len - 交集
  result = 口诀表(
    容器甲: 甲,
    容器乙: 乙,
    甲符号数: 甲符号.len,
    乙符号数: 乙符号.len,
    交叉覆盖率: if 并集 > 0: float(交集) / float(并集) else: 0.0
  )

# ===================================================================
# 6. 注册系统（容器 + 公路管理）
# ===================================================================

type
  注册系统* = object
    容器组*: seq[容器]
    公路*: 公路
    下一门牌*: int            # 下一个可用门牌号
        总符号数*: int            # 全城符号总数（加法累计）
    口诀缓存*: seq[口诀表]

proc 新系统*(): 注册系统 =
  result.公路.当前门牌 = 0
  result.公路.串联累积 = 0
  result.公路.最大功率 = 0
  result.下一门牌 = 0
  result.总符号数 = 0

proc 登记*(系统: var 注册系统, 中文名, 英文名: string,
          符号: seq[string], 需求描述: string = ""): int =
  ## 创建一个新的容器（声明它为容器 → 符号可用）
  let 序 = 系统.下一门牌
  let 相 = 相位偏移(序)
  var c = 容器(
    索引地址: 序,
    标识: 中文名 & "(" & 英文名 & ")",
    中文名: 中文名,
    英文名: 英文名,
    符号: 符号,
    符号总数: 符号.len,
    相位: 相,
    代数: 0,
    状态: ws规划中,
    版本号: 1,
    创建时间: 序,
    完成时间: 0,
    需求描述: 需求描述,
    认知更新: "",
    活性: true
  )
  系统.容器组.add(c)
  # 公路修到了这个门牌（加法修路）
  系统.公路.当前门牌 = 序
  系统.公路.串联累积 = 序 + 1
  系统.公路.最大功率 = max(系统.公路.最大功率, 系统.公路.串联累积)
    # 全城符号总数 = 加法累计（所有已到达容器的符号和）
  系统.总符号数 += 符号.len
  系统.下一门牌 += 1
  result = 序

proc 修公路*(系统: var 注册系统, 门牌: int): bool =
  ## 公路是否修到了指定门牌
  if 门牌 <= 系统.公路.当前门牌:
    result = true
  else:
    result = false

proc 可用符号*(系统: var 注册系统, 门牌: int): seq[string] =
  ## 公路修到了门牌N → 所有≤N的容器符号可用（加法串联）
  if not 修公路(系统, 门牌): return @[]
  var 结果: seq[string] = @[]
  for c in 系统.容器组:
    if c.索引地址 <= 门牌 and c.活性:
      结果.add(c.符号)
  # 去重
  result = 结果.deduplicate

# ===================================================================
# 7. 外包选址（不重新发明轮子的解析器）
##    给定目标容器的符号，查找已经存在可以配套的容器
##    替代方案：自己重造 → 天价成本，不可行
# ===================================================================

proc 外包选址*(系统: 注册系统, 目标索引: int, 阈值: float = 0.5): seq[int] =
  ## 查找与目标容器高度相似（交叉覆盖率>阈值）的已存在容器
  ## 如果覆盖率够高 → 打电话给它做（外包）
  var 结果: seq[int] = @[]
  if 目标索引 < 0 or 目标索引 >= 系统.容器组.len: return
  for i in 0..<系统.容器组.len:
    if i == 目标索引: continue
    let k = 造口诀(系统.容器组, 目标索引, i)
    if k.交叉覆盖率 >= 阈值:
      结果.add(i)
  result = 结果

# ===================================================================
# 8. 文档映射：文件→容器→注册清单
##    文件命名空间可直接忽视，直接用进制的数值索引
##    括号内放中英注释，括号外放公路门牌号
# ===================================================================

proc 文件映射*(系统: 注册系统, 文件中文, 文件英文: string,
             容器索引: int): string =
  ## 生成一条注册清单记录
  if 容器索引 >= 系统.容器组.len: return ""
  let c = 系统.容器组[容器索引]
  var 状态词 = ""
  case c.状态
  of ws规划中: 状态词 = "规划中"
  of ws施工中: 状态词 = "施工中"
  of ws完成:   状态词 = "完成"
  of ws待修改: 状态词 = "待修改"
  of ws已归档: 状态词 = "已归档"
  result = "$1 ($2) 门牌=#$3 v$4 代数=$5 [$6]" % [
    c.中文名, c.英文名, $c.索引地址, $c.版本号, $c.代数, 状态词
  ]

