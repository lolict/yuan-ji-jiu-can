## 满全法 - 容器注册系统
##
## 一句话：容器=砖块=插件，公路修到哪里，符号就通到哪里。
## 不重新发明轮子——找到地址，打电话叫它，外包它。
##
## 加法串联（不是乘法）：公路N修到容器N → 0..N全部符号可用。
## 相位摆放：九宫位（四角·四腰·中心）= 三维立体感知。
## 注册清单：地址+命名空间+工作状态+版本+关联依赖。

import tables
