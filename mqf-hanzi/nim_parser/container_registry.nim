proc 打印清单*(系统: 注册系统) =
  echo "┌─────────────────────────────────────────┐"
  echo "│         容 器 注 册 清 单                │"
  echo "├─────────────────────────────────────────┦"
  echo "│ 公路: 当前门牌=#$1  串联累积=$2  最大功率=$3" % [
    $系统.公路.当前门牌, $系统.公路.串联累积, $系统.公路.最大功率
  ]
  echo "│ 全城可达符号总数(加法): $1" % [$系统.总符号数]
  echo "├─────────────────────────────────────────┤"
  for i, c in 系统.容器组:
    let 相位名 = case c.相位.位
      of 左上: "↖"
      of 上: "↑"
      of 右上: "↗"
      of 左腰: "←"
      of 中: "⊙"
      of 右腰: "→"
      of 左下: "↙"
      of 下: "↓"
      of 右下: "↘"
    echo "│ #$1$2 $3($4) 符号=$5" % [
      $c.索引地址, 相位名, c.中文名, c.英文名, $c.符号总数
    ]
    echo "│   符号: $1" % [c.符号.join(" ")]
    if c.依赖.len > 0:
      echo "│   外包→#$1" % [$c.依赖.join(",#")]
  echo "└─────────────────────────────────────────┘"

proc 渲染九宫*(系统: 注册系统): string =
  ## 3D ASCII九宫容器布局
  var grid = newSeqWith(3, newSeqWith(3, "        "))
  for c in 系统.容器组:
    let px = c.相位.x + 1
    let py = 1 - c.相位.y     # 翻转Y（上正下负→行号上小下大）
    if px >= 0 and px < 3 and py >= 0 and py < 3:
      let 标签 = "#" & $c.索引地址 & c.中文名[0..<(min(3, c.中文名.len))]
      grid[py][px] = 标签.center(8)
  for row in grid:
    result &= "│ " & row.join(" │ ") & " │"

