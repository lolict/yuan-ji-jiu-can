# ===================================================================
# 1. 相位摆放（九宫位置·三维立体感知）
# ===================================================================

type
  相位* = enum
    左上,  上,  右上
    左腰,  中,  右腰
    左下,  下,  右下

  相位坐标* = object
    x*: int     # -1,0,1
    y*: int     # -1,0,1
    位*: 相位

# 相位九宫映射表
const
  相位表*: array[9, 相位坐标] = [
    相位坐标(x: -1, y:  1, 位: 左上),
    相位坐标(x:  0, y:  1, 位: 上),
    相位坐标(x:  1, y:  1, 位: 右上),
    相位坐标(x: -1, y:  0, 位: 左腰),
    相位坐标(x:  0, y:  0, 位: 中),
    相位坐标(x:  1, y:  0, 位: 右腰),
    相位坐标(x: -1, y: -1, 位: 左下),
    相位坐标(x:  0, y: -1, 位: 下),
    相位坐标(x:   1, y: -1, 位: 右下),
  ]

proc 相位偏移*(容器序号: int): 相位坐标 =
  ## 按容器序号自动分配九宫位（循环摆放）
  相位表[容器序号 mod 9]

