## 满全法 - 韵母编码容器注册器
## 第一个可选择的编码韵母容器（32个自定义符号）
## 支持：导入容器 + 预加载编码 + 一维时间串联空间 + 20种默认排序方案
##
## 核心：
## 1. 容器 = 一组编码符号 + 属性（名称、大小写、来源）
## 2. 一维时间串联空间 = 用时间顺序把多个容器排列起来
## 3. 20种默认排序方案 = 预设的容器排列逻辑，一键应用

import tables
import sequtils
import strutils
import algorithm

# ============ 韵母符号 ============
type
  韵母符号* = ref object
    序号*: int
    拼音*: string          # 如 "ai", "ei"
    小写*: string          # 自定义小写符号
    大写*: string          # 自定义大写符号
    来源*: string          # 符号来源（拉丁扩展、西里尔、原生大写等）
    内存字节*: int        # 占用字节数（目标：1字节）

# ============ 韵母容器 ============
type
  韵母容器* = ref object
    名称*: string          # 容器名称
    符号表*: seq[韵母符号]
    创建时间*: int
    描述*: string

# ============ 默认排序方案 ============
type
  排序方案* = enum
    方案1_按序号升序
    方案2_按序号降序
    方案3_按拼音字母顺序
    方案4_按拼音字母逆序
    方案5_按来源分组_拉丁系列优先
    方案6_按来源分组_西里尔优先
    方案7_按来源分组_原生大写优先
    方案8_按来源分组_自用专属优先
    方案9_大小写配对排列
    方案10_交错排列
    方案11_奇数序号在前
    方案12_偶数序号在前
    方案13_按内存占用升序
    方案14_按内存占用降序
    方案15_自定义符号视觉密度排序
    方案16_按来源分组_拉丁扩展优先
    方案17_按来源分组_拉丁大写优先
    方案18_按来源分组_混合排列
    方案19_按拼音长度排序
    方案20_随机排列

# ============ 容器注册器 ============
type
  容器注册器* = ref object
    所有容器*: Table[string, 韵母容器]   # 名称 → 容器
    容器顺序*: seq[string]               # 一维时间串联顺序
    当前活跃*: string                    # 当前使用的容器
    排序方案*: 排序方案                # 当前排序方案

