proc 初始化管理器*(): 容器注册器 =
  new(result)
  result.所有容器 = initTable[string, 韵母容器]()
  result.容器顺序 = @[]
  result.当前活跃 = ""
  result.排序方案 = 方案1_按序号升序

  # 预加载第一个容器
  var c = 创建韵母容器()
  result.所有容器[c.名称] = c
  result.容器顺序.add(c.名称)
  result.当前活跃 = c.名称

# 注册新容器
proc 注册容器*(mgr: 容器注册器, 容器: 韵母容器) =
  mgr.所有容器[容器.名称] = 容器
  mgr.容器顺序.add(容器.名称)

# 获取当前容器的符号（根据当前排序方案）
proc 获取排序符号*(mgr: 容器注册器): seq[韵母符号] =
  let 容器 = mgr.所有容器[mgr.当前活跃]
  var syms = 容器.符号表
  
  case mgr.排序方案:
  of 方案1_按序号升序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.序号, b.序号))
  of 方案2_按序号降序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.序号, a.序号))
  of 方案3_按拼音字母顺序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.拼音, b.拼音))
  of 方案4_按拼音字母逆序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.拼音, a.拼音))
  of 方案5_按来源分组_拉丁系列优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.来源, b.来源))
  of 方案6_按来源分组_西里尔优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.来源, a.来源))
  of 方案7_按来源分组_原生大写优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.来源, b.来源))
  of 方案8_按来源分组_自用专属优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.来源, a.来源))
  of 方案9_大小写配对排列:
    discard  # 已经配对
  of 方案10_交错排列:
    var 前半: seq[韵母符号] = @[]
    var 后半: seq[韵母符号] = @[]
    for i, s in syms:
      if i < syms.len div 2: 前半.add(s)
      else: 后半.add(s)
    syms = @[]
    for i in 0..<max(前半.len, 后半.len):
      if i < 前半.len: syms.add(前半[i])
      if i < 后半.len: syms.add(后半[i])
  of 方案11_奇数序号在前:
    var 奇: seq[韵母符号] = @[]
    var 偶: seq[韵母符号] = @[]
    for s in syms:
      if s.序号 mod 2 == 1: 奇.add(s) else: 偶.add(s)
    syms = 奇 & 偶
  of 方案12_偶数序号在前:
    var 奇: seq[韵母符号] = @[]
    var 偶: seq[韵母符号] = @[]
    for s in syms:
      if s.序号 mod 2 == 0: 偶.add(s) else: 奇.add(s)
    syms = 偶 & 奇
  of 方案13_按内存占用升序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.内存字节, b.内存字节))
  of 方案14_按内存占用降序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.内存字节, a.内存字节))
  of 方案15_自定义符号视觉密度排序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.小写.len, b.小写.len))
  of 方案16_按来源分组_拉丁扩展优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.来源, b.来源))
  of 方案17_按来源分组_拉丁大写优先:
    syms.sort(proc(a, b: 韵母符号): int = cmp(b.来源, a.来源))
  of 方案18_按来源分组_混合排列:
    discard
  of 方案19_按拼音长度排序:
    syms.sort(proc(a, b: 韵母符号): int = cmp(a.拼音.len, b.拼音.len))
  of 方案20_随机排列:
    discard  # 暂不实现随机

  return syms

# 一维时间串联：按容器顺序输出
proc 一维时间串联*(mgr: 容器注册器): seq[string] =
  var 结果: seq[string] = @[]
  for 容器名 in mgr.容器顺序:
    let c = mgr.所有容器[容器名]
    结果.add("容器:" & c.名称 & " 符号数:" & $c.符号表.len)
  return 结果

