# ============ 核心解析函数 ============
proc 解析汉字*(字: string): tuple[左: string, 右: string, 结构: 结构类型] =
  if 左右拆解表.hasKey(字):
    let (左, 右) = 左右拆解表[字]
    return (左, 右, 左右结构)
  else:
    return ("", "", 未知结构)

# ============ 计算左右距离 ============
# 基于码点距离作为几何亲密度的近似
proc 计算亲密度*(左: string, 右: string): float =
  if 左.len == 0 or 右.len == 0:
    return 0.0
  let 左码点 = 左.runeAt(0).int
  let 右码点 = 右.runeAt(0).int
  let 距离 = abs(左码点 - 右码点).float
  # 归一化：距离越小越亲密，值域 [0, 1]
  return 1.0 / (1.0 + 距离.float / 1000.0)

# ============ 汉字编码输出 ============
proc 编码汉字*(字: string): string =
  let (左, 右, 结构) = 解析汉字(字)
  if 结构 == 未知结构:
    return "[未知:" & 字 & "]"
  let 亲密度 = 计算亲密度(左, 右)
  return 字 & "=" & 左 & "+" & 右 & "|距离=" & $亲密度 & "|" & $结构

