proc 解析汉字*(字: string): tuple[左: string, 右: string, 结构: 结构类型] =
  if 左右拆解表.hasKey(字):
    let (左, 右) = 左右拆解表[字]
    return (左, 右, 左右结构)
  else:
    return ("", "", 未知结构)

proc 计算亲密度*(左: string, 右: string): float =
  if 左.len == 0 or 右.len == 0: return 0.0
  let 距离 = abs(左.runeAt(0).int - 右.runeAt(0).int).float
  return 1.0 / (1.0 + 距离 / 1000.0)

