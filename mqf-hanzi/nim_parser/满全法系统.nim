proc 注册*(容器: 清官容器, 声母: string, 韵母: string, 声调: 声调, 颜色: string): 清官符号 =
  var 符号: 清官符号
  符号.声母 = 声母
  符号.韵母 = 韵母
  符号.声调 = 声调
  符号.颜色 = 颜色
  var 声索引 = 容器.声母表.find(声母)
  if 声索引 < 0: 声索引 = 0
  var 韵索引 = 容器.韵母表.find(韵母)
  if 韵索引 < 0: 韵索引 = 0
  let 声部 = (声索引 and 0x07) shl 5
  let 韵部 = (韵索引 and 0x07) shl 2
  let 声部2 = (ord(声调) and 0x03)
  符号.字节码 = byte(声部 or 韵部 or 声部2)
  符号.内存占用 = 1
  容器.符号集合.add(符号)
  容器.计数 += 1
  return 符号

# ============ 工藤新一心理预期压缩 ============
proc toHex2*(b: byte): string =
  let hexChars = "0123456789ABCDEF"
  let hi = int(b) shr 4
  let lo = int(b) and 0x0F
  return $hexChars[hi] & $hexChars[lo]

proc 编码*(声母idx: int, 韵母idx: int, 声调idx: int): byte =
  let 线性码 = 声母idx * 64 + 韵母idx * 4 + 声调idx
  return byte(线性码 mod 256)

proc 码到颜色*(码: byte): string =
  let idx = int(码) mod 基础颜色.len
  return 基础颜色[idx]

