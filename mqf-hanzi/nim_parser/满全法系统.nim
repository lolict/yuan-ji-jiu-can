proc 计算接近度(甲: 容器, 乙: 容器): float =
  let 层差 = abs(甲.层级 - 乙.层级).float
  let 时差 = abs(甲.出生时间 - 乙.出生时间).float
  return 1.0 / (层差 * 2.0 + 时差 + 1.0)

proc 寻找晋升目标(管理器: 容器管理器): int =
  let 当前 = 管理器.所有容器[管理器.当前活跃]
  var 最佳目标 = -1
  var 最佳亲近 = -1.0
  for i, 候选 in 管理器.所有容器:
    if i == 管理器.当前活跃: continue
    if 候选.饱和: continue
    let 亲近 = 计算接近度(当前, 候选)
    if 亲近 > 最佳亲近:
      最佳亲近 = 亲近
      最佳目标 = i
  return 最佳目标

proc 消耗符号*(管理器: 容器管理器): tuple[符号: string, 晋升: bool, 容器名: string] =
  let 当前 = 管理器.所有容器[管理器.当前活跃]
  if 当前.已用 >= 当前.符号.len:
    当前.饱和 = true
    let 目标 = 寻找晋升目标(管理器)
    if 目标 == -1: return ("[所有容器耗尽]", false, "")
    管理器.当前活跃 = 目标
    管理器.时间线 += 1
    let 新容器 = 管理器.所有容器[管理器.当前活跃]
    let 符号 = 新容器.符号[新容器.已用]
    新容器.已用 += 1
    管理器.历史记录.add(新容器.名称 & "/" & 符号 & "(晋升)")
    return (符号, true, 新容器.名称)
  let 符号 = 当前.符号[当前.已用]
  当前.已用 += 1
  管理器.历史记录.add(当前.名称 & "/" & 符号)
  return (符号, false, 当前.名称)

