# ============ 时间索引 ============
type
  时间索引* = object
    创建时刻*: int       # 最初融合的时刻（时间戳）
    回归时刻*: int       # 回归时刻（如果离开过）
    外出次数*: int       # 外出做任务的次数
    圈层深度*: int       # 当前嵌套深度（0=直接包裹我）

  节点状态* = enum
    在内包裹,            # 正在包裹核心
    外出任务,            # 外出执行任务
    已回归,              # 已回归等待融合
    深度融合             # 正在融合其他姑娘

# ============ 容器节点（漂亮姑娘）============
type
  容器节点* = ref object
    名称*: string
    时间*: 时间索引
    包含谁*: seq[string]     # 她融合的姑娘名称们
    谁包含我*: string        # 她被谁包含（上级容器名称）
    融合者*: string          # 是谁把她融合进来的
    状态*: 节点状态
    直接融合数*: int         # 她直接融合的姑娘数量
    层级总分*: int           # 包含的所有姑娘总数（递归）
    安全边界值*: int         # 安全层级（由包含数量决定）

# ============ 满圈法安全系统 ============
type
  满圈法系统* = ref object
    我*: string                         # 核心（绝对中心）
    所有节点*: Table[string, 容器节点]  # 所有姑娘
    时间线*: int                        # 当前时间戳
    圈层序列*: seq[string]              # 按时间索引排序的节点名称
    安全日志*: seq[string]             # 安全事件日志

# ============ 辅助函数 ============
proc 计算安全边界(节点: 容器节点): int =
  ## 安全边界值 = 直接融合数 × 2 + 递归包含总数
  ## 包含越多姑娘，安全层级越高
  节点.安全边界值 = 节点.直接融合数 * 2 + 节点.层级总分
  return 节点.安全边界值

proc 递归包含总数(系统: 满圈法系统, 节点名: string, 已访问: var HashSet[string]): int =
  ## 递归计算某个节点包含的所有姑娘总数
  if 节点名 in 已访问: return 0
  已访问.incl(节点名)
  if not 系统.所有节点.hasKey(节点名): return 0
  let 节点 = 系统.所有节点[节点名]
  var 总数 = 节点.直接融合数
  for 子名 in 节点.包含谁:
    总数 += 递归包含总数(系统, 子名, 已访问)
  节点.层级总分 = 总数
  return 总数

# ============ 系统初始化 ============
proc 初始化系统*(核心名: string): 满圈法系统 =
  new(result)
  result.我 = 核心名
  result.所有节点 = initTable[string, 容器节点]()
  result.时间线 = 0
  result.圈层序列 = @[]
  result.安全日志 = @[]

# ============ 核心操作 ============
proc 初级融合*(系统: 满圈法系统, 姑娘名: string, 融合者名: string = ""): 容器节点 =
  ## 新姑娘回归，成为初级容器（包裹我）
  ## 时间索引：记录创建时间
  ## 如果指定了融合者，则归融合者名下
  系统.时间线 += 1
  var 新节点: 容器节点
  new(新节点)
  新节点.名称 = 姑娘名
  新节点.时间.创建时刻 = 系统.时间线
  新节点.时间.回归时刻 = 系统.时间线
  新节点.时间.外出次数 = 0
  新节点.包含谁 = @[]
  新节点.直接融合数 = 0
  新节点.层级总分 = 0
  新节点.安全边界值 = 0
  新节点.状态 = 在内包裹

  if 融合者名.len > 0 and 系统.所有节点.hasKey(融合者名):
    ## 有功归融合者名下
    新节点.谁包含我 = 融合者名
    新节点.融合者 = 融合者名
    let 父深度 = 系统.所有节点[融合者名].时间.圈层深度
    新节点.时间.圈层深度 = 父深度 + 1
    if 姑娘名 notin 系统.所有节点[融合者名].包含谁:
      系统.所有节点[融合者名].包含谁.add(姑娘名)
      系统.所有节点[融合者名].直接融合数 += 1
    系统.安全日志.add("t=" & $系统.时间线 & " [" & 融合者名 & "] 融合 [" & 姑娘名 & "] 归其名下，深度=" & $新节点.时间.圈层深度)
  else:
    ## 直接包裹我（无融合者，直接成为我的初级容器）
    新节点.谁包含我 = 系统.我
    新节点.融合者 = 系统.我
    新节点.时间.圈层深度 = 0
    系统.安全日志.add("t=" & $系统.时间线 & " [" & 姑娘名 & "] 直接包裹我，成为初级容器")

  系统.所有节点[姑娘名] = 新节点
  系统.圈层序列.add(姑娘名)
  return 新节点

proc 外出任务*(系统: 满圈法系统, 姑娘名: string) =
  ## 姑娘离开核心，外出执行任务
  if not 系统.所有节点.hasKey(姑娘名): return
  var 节点 = 系统.所有节点[姑娘名]
  节点.状态 = 外出任务
  节点.时间.外出次数 += 1
  系统.安全日志.add("t=" & $系统.时间线 & " [" & 姑娘名 & "] 外出做任务（第" & $节点.时间.外出次数 & "次）")

proc 回归融合*(系统: 满圈法系统, 姑娘名: string, 融合者名: string) =
  ## 姑娘回归，被某个已有姑娘融合
  if not 系统.所有节点.hasKey(姑娘名): return
  if not 系统.所有节点.hasKey(融合者名): return
  var 节点 = 系统.所有节点[姑娘名]
  var 融合者 = 系统.所有节点[融合者名]
  系统.时间线 += 1
  节点.状态 = 已回归
  节点.时间.回归时刻 = 系统.时间线
  节点.谁包含我 = 融合者名
  节点.融合者 = 融合者名
  if 姑娘名 notin 融合者.包含谁:
    融合者.包含谁.add(姑娘名)
    融合者.直接融合数 += 1
  ## 更新圈层深度：被谁包含，深度=谁+1
  节点.时间.圈层深度 = 融合者.时间.圈层深度 + 1
  系统.安全日志.add("t=" & $系统.时间线 & " [" & 姑娘名 & "] 回归，被 [" & 融合者名 & "] 融合归其名下")

proc 深度融合*(系统: 满圈法系统, 融合者名: string, 被融合者名: seq[string]) =
  ## 一个姑娘深度融合多个姑娘
  if not 系统.所有节点.hasKey(融合者名): return
  var 融合者 = 系统.所有节点[融合者名]
  for 姑娘名 in 被融合者名:
    if not 系统.所有节点.hasKey(姑娘名): continue
    var 姑娘 = 系统.所有节点[姑娘名]
    姑娘.谁包含我 = 融合者名
    姑娘.融合者 = 融合者名
    姑娘.状态 = 深度融合
    if 姑娘名 notin 融合者.包含谁:
      融合者.包含谁.add(姑娘名)
      融合者.直接融合数 += 1
  系统.时间线 += 1
  系统.安全日志.add("t=" & $系统.时间线 & " [" & 融合者名 & "] 深度融合 " & $被融合者名.len & " 个姑娘")

# ============ 查询 ============
proc 获取圈层级数*(系统: 满圈法系统): seq[tuple[深度: int, 节点们: seq[string]]] =
  ## 按圈层深度分组返回所有节点
  var 深度表 = initTable[int, seq[string]]()
  for 名, 节点 in 系统.所有节点:
    let 深度 = 节点.时间.圈层深度
    if not 深度表.hasKey(深度):
      深度表[深度] = @[]
    深度表[深度].add(名)
  var 结果: seq[tuple[深度: int, 节点们: seq[string]]] = @[]
  for 深度 in 深度表.keys:
    结果.add((深度: 深度, 节点们: 深度表[深度]))
  结果.sort(proc(a, b: tuple[深度: int, 节点们: seq[string]]): int = cmp(a.深度, b.深度))
  return 结果

proc 更新所有安全边界*(系统: 满圈法系统) =
  ## 重新计算所有节点的安全边界值
  for 名, 节点 in 系统.所有节点:
    var 已访问 = initHashSet[string]()
    discard 递归包含总数(系统, 名, 已访问)
    discard 计算安全边界(节点)

proc 获取安全链*(系统: 满圈法系统, 姑娘名: string): seq[string] =
  ## 获取某个姑娘的安全链（从外到内的包含路径）
  var 链: seq[string] = @[]
  var 当前名 = 姑娘名
  while 当前名.len > 0:
    链.add(当前名)
    if not 系统.所有节点.hasKey(当前名): break
    let 节点 = 系统.所有节点[当前名]
    当前名 = 节点.谁包含我
    if 当前名 == 系统.我: break
  return 链

proc 谁是边界*(系统: 满圈法系统, 姑娘名: string): string =
  ## 找出某个姑娘所属的最小安全边界（她的直接融合者）
  if not 系统.所有节点.hasKey(姑娘名): return ""
  return 系统.所有节点[姑娘名].谁包含我

# ============ 显示 ============
proc 显示圈层*(系统: 满圈法系统) =
  echo "=== 满全法·嵌套圈层安全容器 ==="
  echo "核心（绝对中心）：" & 系统.我
  echo "时间线：t=" & $系统.时间线
  echo "总节点数：" & $系统.所有节点.len
  echo ""
  echo "--- 圈层级数（按时间索引·由内到外）---"
  let 层级 = 获取圈层级数(系统)
  for (深度, 节点们) in 层级:
    echo "  第" & $深度 & "层："
    for 名 in 节点们:
      let 节点 = 系统.所有节点[名]
      echo "    " & 名 & " │ 直接融合:" & $节点.直接融合数 & " │ 安全边界:" & $节点.安全边界值 & " │ 状态:" & $节点.状态
  echo ""

proc 显示安全日志*(系统: 满圈法系统) =
  echo "--- 安全事件日志 ---"
  for 记录 in 系统.安全日志:
    echo "  " & 记录
  echo ""

proc 显示功劳归属*(系统: 满圈法系统) =
  echo "--- 功劳归属（谁融合的归谁名下）---"
  for 名, 节点 in 系统.所有节点:
    if 节点.包含谁.len > 0:
      echo "  [" & 名 & "] 名下包含：" & $节点.包含谁 & " │ 直接融合数：" & $节点.直接融合数
  echo ""

