  echo "  容器" & $c64.地址 & " ← mlll 64进制, 值=64"
  echo "  容器" & $cT.地址  & " ← 100声调, 值=100"
  echo "  容器" & $cY.地址  & " ← 韵母容器, 值=32"
  echo "  容器" & $cX.地址  & " ← 九宫相位, 值=9"

  echo ""
  echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  echo "  物理公理演示：物质=时间·距离=时间差·合一=距离归零"
  echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  echo ""

  # 创建两个有距离的容器（物质A和物质B）
  var 物质A = 引.集群.申请("物质A")
  物质A.值 = 64
  物质A.位置 = 0         # 位置=0
  物质A.层级 = 3
  echo "  创建 物质A @" & $物质A.地址 & " 值=64 位置=0"

  var 物质B = 引.集群.申请("物质B")
  物质B.值 = 100
  物质B.位置 = 90        # 位置=90（与A距离=90=时间差90）
  物质B.层级 = 5
  echo "  创建 物质B @" & $物质B.地址 & " 值=100 位置=90"

  var 物质C = 引.集群.申请("物质C")
  物质C.值 = 36
  物质C.位置 = 200
  物质C.层级 = 2
  echo "  创建 物质C @" & $物质C.地址 & " 值=36 位置=200"

  let A = 物质A.地址
  let B = 物质B.地址
  let C = 物质C.地址
  echo ""

  # 编写物理公理程序：测距→吃→合一→沉淀→驱动→再合一
  echo "━━━ 执行程序：物质合一过程 ━━━"
  var 物理程序: seq[执行步骤] = @[]
  # 第一阶段：测距（确认距离=时间差）
  物理程序.add(执行步骤(动作: faDistance, A: A, B: B))       # 0 A和B的距离
  # 第二阶段：吃（A吃B，消除空间/距离）
  物理程序.add(执行步骤(动作: faConsume, A: A, B: B))         # 1 A吃B 第1次
  物理程序.add(执行步骤(动作: faConsume, A: A, B: B))         # 2 A吃B 第2次
  物理程序.add(执行步骤(动作: faConsume, A: A, B: B))         # 3 A吃B 第3次
  物理程序.add(执行步骤(动作: faConsume, A: A, B: B))         # 4 A吃B 继续...
  物理程序.add(执行步骤(动作: faConsume, A: A, B: B))         # 5 A吃B 继续...
  # 第三阶段：合一（距离归零=时间最小化=物质积累成一个点）
  物理程序.add(执行步骤(动作: faMerge, A: A, B: B))           # 6 A和B合一
  # 第四阶段：沉淀（成为静态刻度=公约数）
  物理程序.add(执行步骤(动作: faSettle, A: A))                 # 7 沉淀为公约数刻度
  # 第五阶段：驱动（积累推动后续合一=公倍数推动力）
  物理程序.add(执行步骤(动作: faDistance, A: A, B: C))        # 8 测A和C的距离
  物理程序.add(执行步骤(动作: faDrive, A: A, B: C))           # 9 A推动C靠近
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 10 A吃C
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 11 A吃C继续
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 12 A吃C继续
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 13 A吃C继续
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 14 A吃C继续
  物理程序.add(执行步骤(动作: faConsume, A: A, B: C))         # 15 A吃C继续
  # 第六阶段：合一（A和C合一）
  物理程序.add(执行步骤(动作: faMerge, A: A, B: 物质C.地址))  # 16 A和C合一
  物理程序.add(执行步骤(动作: faSettle, A: A))                 # 17 再次沉淀
  # 齐了
  物理程序.add(执行步骤(动作: faComplete))                     # 18 齐

  for i, s in 物理程序:
    let 行 = case s.动作:
      of faPreload:     "预加载[$" & $s.A & "]"
      of faProperty:    "属性[$" & $s.B & "]←" & $s.A
      of faDistinguish: "分别[$" & $s.A & "]⚖[$" & $s.B & "]"
