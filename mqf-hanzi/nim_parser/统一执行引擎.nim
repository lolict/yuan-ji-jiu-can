  var c64  = 引.集群.申请("mlll_64进制");  c64.值 = 64; c64.层级 = 6
  var cT   = 引.集群.申请("声调_100调");   cT.值 = 100; cT.层级 = 7
  var cY   = 引.集群.申请("韵母_32个");    cY.值 = 32
