## 满全法 - 统一执行引擎
## 不引入新命名。全部使用已有术语：八流 + 对齐阶段 + 选址呼唤 + 加法串联
##
## 执行步骤 = 八流的顺序流过地址空间
## 地址空间 = 单值线性选址（起点对齐→终点对齐→纵向进位→高度楼梯→齐）
## 控制流 = 呼唤编程（@地址 = 跳过去）
## 数据流 = 加法串联（两个容器公路接通 = 求和）
## 判决流 = 分别流（聚类后做区分判决）
## 时间流 = 冰箱模型（触发器按全局时钟调度）
##
## ═══════════════════════════════════════════
## 物理公理层（物质=时间·距离=时间差·合一=距离归零）
## ═══════════════════════════════════════════
## 物质 = 容器（不可再分的最小时空单元）
## 时间 = 容器合并运动的尺度（距离=时间差）
## 空间/距离 = 容器之间的间隙（虚无=待消除）
## 合一/加法 = 消除距离 = 时间最小化
## 公路 = 缩短距离 = 加快合一
## 吃 = 把外部物质纳入自身 = 写入容器内部
## 积累成点 = 静态刻度 = 公约数（统计稳定态）
## 运动痕迹 = 动态 = 时间流（驱动后续合一的公倍数推动力）

import tables
import sequtils
import strutils

# ============================================================================
# 第一部分：容器（统一寻址）
# ============================================================================

type
  容器态* = enum
    csEmpty, csLoaded, csLocked, csOverflow

  统一容器* = ref object
    地址* : int
    态* : 容器态
    值* : int
    素材* : string
    来源* : string
    锚点极性* : int       # 我=1 / 刘楚恬=0
    时间戳* : int
    能量* : int           # 积累的能量（公倍数推动力）
    层级* : int
    相位* : int           # 九宫相位 0-8
    位置* : int           # 空间坐标（用于计算间距=时间差）
    持久度* : int         # 物质维持存在的时间刻度
    已吃* : seq[int]      # 已经被它吃掉的容器地址列表
    公约数刻度* : bool     # 是否已成为静态刻度

  集群* = ref object
    池* : Table[int, 统一容器]
    下一个* : int
    锚点* : tuple[我: int, 刘楚恬: int]

proc 创建集群*(): 集群 =
  new(result)
  result.池 = initTable[int, 统一容器]()
  result.下一个 = 0
  result.锚点 = (我: 1, 刘楚恬: 0)

proc 申请*(c: 集群, 来源: string = "统一"): 统一容器 =
  new(result)
  result.地址 = c.下一个
  result.态 = csEmpty
  result.值 = 0
  result.来源 = 来源
  result.锚点极性 = if result.地址 mod 2 == 0: c.锚点.刘楚恬 else: c.锚点.我
  result.能量 = 100
  result.相位 = 4
  result.位置 = c.下一个 * 10   # 初始位置按地址等间距分布
  result.持久度 = 0
  result.已吃 = @[]
  result.公约数刻度 = false
  c.池[result.地址] = result
  c.下一个 += 1

proc 取*(c: 集群, 地址: int): 统一容器 =
  if c.池.hasKey(地址): return c.池[地址]
  var 空: 统一容器; new(空); 空.地址 = -1; 空.态 = csEmpty; return 空

# ============================================================================
# 第二部分：流步骤（不叫操作码，叫流阶段）
# ============================================================================

type
  ## 八流中的核心几流 + 物理公理动作
  流动作* = enum
    faPreload,     ## 预加载：从地址取值
    faProperty,    ## 属性流：往地址写值
    faDistinguish, ## 分别流：两个容器做区分/判决
    faRelation,    ## 关系流：两个容器加法串联
    faConcept,     ## 概念流：地址跳到新位置（=呼唤编程）
    faComplete,    ## 对齐阶段：齐了
    ## ── 物理公理层 ──
    faDistance,    ## 测距：计算两个容器之间的距离（=时间差）
    faConsume,     ## 吃：把目标容器吃过来（消除空间/距离）
    faMerge,       ## 合一：两个容器合并（距离归零=时间最小化）
    faSettle,      ## 沉淀：合并后的物质成为静态刻度（公约数）
    faDrive        ## 驱动：积累的能量推动后续合一（公倍数推动力）

  执行步骤* = object
    动作* : 流动作
    A* : int           # 源地址（或立即数值）
    B* : int           # 目标地址
    偏移* : int        # 用于概念流：跳向哪里

# ============================================================================
# 第三部分：冰箱模型（触发器调度）
# ============================================================================

type
  触发类型* = enum
    ttTime, ttCollision, ttEnergy, ttOverflow

  触发器* = object
    类型* : 触发类型
    阈值* : int
    执行* : 执行步骤
    已触发* : bool
    循环* : bool

  冰箱* = ref object
    时钟* : int
    触发器表* : seq[触发器]
    待执行* : seq[执行步骤]
    温度* : float

proc 创建冰箱*(): 冰箱 =
  new(result)
  result.时钟 = 0
  result.触发器表 = @[]
  result.待执行 = @[]
  result.温度 = 0.0

proc 注册*(冰: 冰箱, 类型: 触发类型, 阈值: int, 步骤: 执行步骤, 循环: bool = false) =
  var t: 触发器
  t.类型 = 类型; t.阈值 = 阈值; t.执行 = 步骤; t.已触发 = false; t.循环 = 循环
  冰.触发器表.add(t)

proc 推进*(冰: 冰箱): seq[执行步骤] =
  result = @[]
  冰.时钟 += 1
  for i in 0..<冰.触发器表.len:
    var t = 冰.触发器表[i]
    let 该触发 = (t.类型 == ttTime and 冰.时钟 >= t.阈值)
    if 该触发 and (not t.已触发 or t.循环):
      result.add(t.执行); 冰.待执行.add(t.执行)
      if not t.循环: 冰.触发器表[i].已触发 = true

# ============================================================================
# 第四部分：执行引擎
# ============================================================================

type
  引擎* = ref object
    集群* : 集群
    冰箱* : 冰箱
    PC* : int              # 程序计数器
    天平* : int            # 分别流结论：-1左沉 0平 1右沉
    运行中* : bool
    执行总数* : int
    输出* : seq[string]

  天平结果* = enum
    eqLeft, eqEqual, eqRight

proc 创建引擎*(): 引擎 =
  new(result)
  result.集群 = 创建集群()
  result.冰箱 = 创建冰箱()
  result.PC = 0
  result.天平 = 0
  result.运行中 = false
  result.执行总数 = 0
  result.输出 = @[]

proc 执行一步*(引: var 引擎, 步骤: 执行步骤): bool =
  result = true
  引.执行总数 += 1

  case 步骤.动作:
  of faPreload:
    let c = 引.集群.取(步骤.A)
    if c.地址 >= 0:
      c.态 = csLoaded
      引.输出.add("预加载[$" & $步骤.A & "]=" & $c.值 & " (" & c.来源 & ")")
    else:
      引.输出.add("预加载[$" & $步骤.A & "] → 空容器")

  of faProperty:
    var c = 引.集群.取(步骤.B)
    if c.地址 < 0: c = 引.集群.申请("写入")
    c.值 = 步骤.A    # 在faProperty里，A=立即数值
    c.态 = csLoaded
    引.输出.add("属性流[$" & $步骤.B & "]←" & $步骤.A)

  of faRelation:   # 加法串联
    let a = 引.集群.取(步骤.A)
    let b = 引.集群.取(步骤.B)
    var r = 引.集群.申请("串联:" & $步骤.A & "+" & $步骤.B)
    r.值 = a.值 + b.值
    引.输出.add("加法串联[$" & $步骤.A & "]=" & $a.值 & " · [$" & $步骤.B & "]=" & $b.值 & " → @" & $r.地址 & "=" & $r.值)

  of faDistinguish:   # 分别流 = 天平判决
    let a = 引.集群.取(步骤.A)
    let b = 引.集群.取(步骤.B)
    if a.值 > b.值: 引.天平 = -1
    elif a.值 < b.值: 引.天平 = 1
    else: 引.天平 = 0
    let 结论 = if 引.天平 == -1: "左沉(A>B)" elif 引.天平 == 1: "右沉(A<B)" else: "平(A=B)"
    引.输出.add("分别流[$" & $步骤.A & "]=" & $a.值 & " ⚖ [$" & $步骤.B & "]=" & $b.值 & " → " & 结论)

  of faConcept:   # 呼唤编程 = @地址跳过去
    if 引.天平 == -1:
      引.输出.add("呼唤@$" & $步骤.偏移 & " (左沉成立→跳转)")
      引.PC = 步骤.偏移
    else:
      引.输出.add("不呼唤 (未满足左沉条件，继续)")

  of faComplete:   # 齐了
    引.输出.add("▣ 齐 → 全部用尽，回归起点")
    引.运行中 = false
    result = false

  # ── 物理公理层实现 ──

  of faDistance:   # 测距 = 计算时间差
    let a = 引.集群.取(步骤.A)
    let b = 引.集群.取(步骤.B)
    let 距离 = abs(a.位置 - b.位置)
    let 时间差 = 距离   # 距离 = 时间差（公理）
    引.输出.add("测距[A@" & $a.位置 & "]←→[B@" & $b.位置 & "] 距离=" & $距离 & "=时间差=" & $时间差)

  of faConsume:    # 吃 = 把B向A移动（消除空间）
    var a = 引.集群.取(步骤.A)
    var b = 引.集群.取(步骤.B)
    let 原距离 = abs(a.位置 - b.位置)
    if 原距离 > 0:
      # 把B向A移动一步（每次移动1/3距离，模拟加速靠近）
      let 移动量 = max(1, 原距离 div 3)
      let 方向 = if b.位置 > a.位置: -1 else: 1
      b.位置 += 方向 * 移动量
      if b.位置 == a.位置:
        b.位置 += 1   # 不允许完全重叠
      let 新距离 = abs(a.位置 - b.位置)
      let 消除的空间 = 原距离 - 新距离
      a.持久度 += 消除的空间    # 持久度增加=维持存在的时间延长
      引.输出.add("吃:[$" & $步骤.A & "(@" & $a.位置 & ")]→吃→[$" & $步骤.B & "(@" & $b.位置 & ")] " &
                   "原距" & $原距离 & "→新距" & $新距离 & " 消除空间=" & $消除的空间 & " 持久度+" & $消除的空间)
    else:
      引.输出.add("吃: 距离已为0，不可再吃")

  of faMerge:      # 合一 = 两个容器合并（距离归零=时间最小化）
    var a = 引.集群.取(步骤.A)
    var b = 引.集群.取(步骤.B)
    let 合并前距离 = abs(a.位置 - b.位置)
    # B并入A
    a.值 += b.值
    a.能量 += b.能量
    a.持久度 += b.持久度
    a.已吃.add(b.地址)
    # B位置归到A（距离=0=合一）
    b.位置 = a.位置
    b.态 = csLocked      # 被锁定（已被合并）
    b.值 = 0             # 物质转移完毕
    # 合一后的能量积累=公倍数推动力
    let 推动力 = a.值 + a.能量
    引.输出.add("合一:@" & $a.地址 & "←吞并→@" & $b.地址 &
                " 距离" & $合并前距离 & "→0 物质=" & $a.值 &
                " 能量=" & $a.能量 & " 推动力=" & $推动力)

  of faSettle:     # 沉淀 = 合并后的物质成为静态刻度（公约数）
    var a = 引.集群.取(步骤.A)
    a.公约数刻度 = true
    a.能量 = a.能量 div 2   # 一半能量用于维持刻度稳定
    引.输出.add("沉淀:@" & $a.地址 & " 成为公约数刻度 值=" & $a.值 & " 剩余能量=" & $a.能量 & " 持久度=" & $a.持久度)

  of faDrive:      # 驱动 = 积累的能量推动后续合一
    var a = 引.集群.取(步骤.B)   # B是被推动的目标
    let 驱动源 = 引.集群.取(步骤.A)   # A是驱动源
    if 驱动源.公约数刻度:
      let 推动能量 = 驱动源.值 div 10     # 刻度释放10%作为推动力
      a.能量 += 推动能量
      a.位置 -= 推动能量 div 2   # 推动目标移动（距离缩短=时间最小化）
      引.输出.add("驱动:刻度@" & $驱动源.地址 & "推动@" & $a.地址 & " 能量+" & $推动能量 & " 位置→" & $a.位置)
    else:
      引.输出.add("驱动: 驱动源不是公约数刻度，无推动力")

proc 运行*(引: var 引擎, 程序: seq[执行步骤]) =
  引.运行中 = true
  引.PC = 0
  while 引.运行中 and 引.PC < 程序.len:
    let 步骤 = 程序[引.PC]
    let 继续 = 执行一步(引, 步骤)
    if not 继续: break
    if 步骤.动作 == faConcept and 引.天平 == -1:
      discard   # PC已被跳转
    else:
      引.PC += 1
    discard 引.冰箱.推进()

