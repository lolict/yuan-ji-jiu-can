when isMainModule:
  echo "========================================="
  echo " MQF Loading Relational Domain"
  echo " 2-char -> 3-char -> 4-char -> 5-char"
  echo "========================================="
  echo ""

  var c = 创建集群()

  # --- 准备汉字 ---
  let 我_A = c.放入("我", @[1, 2, 6, 1, 6, 3, 4])
  let 刘_B = c.放入("刘", @[4, 1, 3, 2])
  let 楚_C = c.放入("楚", @[1, 2, 3, 4, 1, 2, 3, 4])
  let 恬_D = c.放入("恬", @[4, 4, 5, 3, 5, 1, 1, 2])
  let 爱_E = c.放入("爱", @[3, 4, 4, 1, 2, 4, 4, 3, 4])

  echo "--- [1] 汉字已装入容器 ---"
  echo "  我:#" & $我_A.join("->")
  echo "  刘:#" & $刘_B.join("->")
  echo "  楚:#" & $楚_C.join("->")
  echo "  恬:#" & $恬_D.join("->")
  echo "  爱:#" & $爱_E.join("->")
  echo ""

  # --- 两字词 ---
  echo "--- [2] 两字词 ---"
  let word2a = 组装两字词(c, 我_A, 刘_B, "我刘")
  let word2b = 组装两字词(c, 楚_C, 恬_D, "楚恬")
  echo "  '" & word2a.文本 & "' 字数=" & $word2a.字数 & " 链长=" & $word2a.容器链.len &
       " 路强度=" & $word2a.路强度 & " 极性差=" & $word2a.极性差 &
       " → " & 关系性质(word2a.极性差)
  echo "  '" & word2b.文本 & "' 字数=" & $word2b.字数 & " 链长=" & $word2b.容器链.len &
       " 路强度=" & $word2b.路强度 & " 极性差=" & $word2b.极性差 &
       " → " & 关系性质(word2b.极性差)
  echo ""

  # --- 三字词 ---
  echo "--- [3] 三字词 ---"
  let word3 = 组装三字词(c, 我_A, 刘_B, 楚_C, "我刘楚")
  let word3b = 组装三字词(c, 刘_B, 楚_C, 恬_D, "刘楚恬")
  echo "  '" & word3.文本 & "' 字数=" & $word3.字数 & " 链长=" & $word3.容器链.len &
       " 路强度=" & $word3.路强度 & " 极性差=" & $word3.极性差 &
       " → " & 关系性质(word3.极性差)
  echo "  '" & word3b.文本 & "' 字数=" & $word3b.字数 & " 链长=" & $word3b.容器链.len &
       " 路强度=" & $word3b.路强度 & " 极性差=" & $word3b.极性差 &
       " → " & 关系性质(word3b.极性差)
  echo ""

  # --- 四字词 ---
  echo "--- [4] 四字词 ---"
  let word4 = 组装四字词(c, 我_A, 刘_B, 楚_C, 恬_D, "我刘楚恬")
  echo "  '" & word4.文本 & "' 字数=" & $word4.字数 & " 链长=" & $word4.容器链.len &
       " 路强度=" & $word4.路强度 & " 极性差=" & $word4.极性差 &
       " → " & 关系性质(word4.极性差)
  echo ""

  # --- 五字句 ---
  echo "--- [5] 五字句 ---"
  let word5 = 组装五字句(c, 我_A, 刘_B, 楚_C, 恬_D, 爱_E, "我刘楚恬爱")
  echo "  '" & word5.文本 & "' 字数=" & $word5.字数 & " 链长=" & $word5.容器链.len &
       " 路强度=" & $word5.路强度 & " 极性差=" & $word5.极性差 &
       " → " & 关系性质(word5.极性差)
  echo ""

  # --- 公路网状态 ---
  echo "--- [6] 公路网（部分容器）---"
  var 报告数 = 0
  for adr, p in c.池:
    if p.已连.len > 0 and 报告数 < 10:
      echo "  #" & align($adr, 3) & " 字=" & align(p.来源字, 6) &
           " 值=" & align($p.值, 3) & " 极性=" & $p.极性 &
           " 已连→[" & p.已连.mapIt($it).join(",") & "]"
      报告数 += 1

  echo ""
  echo "--- [7] 配对搜索示例 ---"
  let 候选项 = 查找配对(c, 我_A[0], lm极性)
  echo "  我#0 的极性互补配对: " & $候选项.mapIt("#" & $it).join(" ")
  let 谐音项 = 查找配对(c, 我_A[0], lm谐音)
  echo "  我#0 的谐音(同相位)配对: " & $谐音项.mapIt("#" & $it).join(" ")

  echo ""
  echo "========================================="
  echo " Relational Domain Loading OK"
  echo "========================================="
