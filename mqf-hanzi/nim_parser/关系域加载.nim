## 满全法 - 关系域加载
## 2字词 → 3字词 → 4字词 → 5字句 组装
##
## 关系域：不是把字符简单拼接，而是让对应容器产生关系
## 两个容器之间的关系 = 它们之间的公路 = 加法串联
##
## 加载过程：
##   2字词：A的容器 ←→ B的容器 之间建立公路
##   3字词：A-B已形成的路 ←→ C的容器 之间建立路
##   以此类推每加一个字就是一次公路延伸
## 容器地址 = 笔画寻址叠加 + 关系偏移（字的序号决定偏移量）

import tables
import sequtils
import strutils

# ============================================================================
# 容器（简化引用统一模型）
# ============================================================================

type
  容器* = ref object
    地址* : int
    值* : int          # 容器主值（笔画编码或概念权重）
    极性* : int        # 1=我(阳) / 0=刘楚恬(阴)
    层级* : int        # 在词组中的位置层级
    相位* : int        # 九宫相位
    已连* : seq[int]   # 已连接的容器地址（公路网）
    来源字* : string   # 来自哪个字

  容器集群* = ref object
    池* : Table[int, 容器]
    起始地址* : int
    下一个* : int

proc 创建集群*(): 容器集群 =
  new(result)
  result.池 = initTable[int, 容器]()
  result.起始地址 = 0
  result.下一个 = 0

proc 放入*(c: 容器集群, 字: string, 笔画值: seq[int]): seq[int] =
  ## 把一个字的笔画序列放到容器集群，返回分配的地址列表
  var 地址列表: seq[int] = @[]
  for i, v in 笔画值:
    var p: 容器; new(p)
    p.地址 = c.下一个
    p.值 = v
    p.极性 = if i mod 2 == 0: 1 else: 0
    p.层级 = i
    p.相位 = v mod 9
    p.已连 = @[]
    p.来源字 = 字 & "#" & $i
    c.池[p.地址] = p
    地址列表.add(p.地址)
    c.下一个 += 1
  result = 地址列表

proc 连接*(c: 容器集群, 地址A, 地址B: int, 关系强度: int = 1) =
  ## 建立两个容器之间的"公路"——双向连接
  if not c.池.hasKey(地址A) or not c.池.hasKey(地址B): return
  var a = c.池[地址A]
  var b = c.池[地址B]
  if a.已连.find(地址B) < 0: a.已连.add(地址B)
  if b.已连.find(地址A) < 0: b.已连.add(地址A)
  # 关系强度叠加在值上（加法串联）
  a.值 += 关系强度
  b.值 += 关系强度

# ============================================================================
# 词组组装
# ============================================================================

type
  词组* = object
    文本* : string
    字数* : int
    容器链* : seq[int]     # 词组涉及的容器地址序列
    路强度* : int           # 词组内部连接的总强度
    极性差* : int           # 第一个字最后一个容器 vs 第二个字第一个容器的极性差

  词组链* = ref object
    词* : seq[词组]
    总路长* : int

# 连线规则：
# 两字词 → 连接A的最后一个容器 和 B的第一个容器（首尾对接）
# 三字词 → 连接A的末 B的首 + B的末 C的首（路中延伸）
# 四字词 → 三个连接点串联
# 五字词 → 四个连接点串联

proc 组装两字词*(c: 容器集群, 字A地址: seq[int], 字B地址: seq[int], 文本: string): 词组 =
  result.文本 = 文本
  result.字数 = 2
  result.容器链 = 字A地址 & 字B地址
  # 连接：A的末容器 ↔ B的首容器
  let a末 = 字A地址[字A地址.len - 1]
  let b首 = 字B地址[0]
  c.连接(a末, b首, 2)   # 字间连接强度=2（大于字内强度）
  result.路强度 = c.池[a末].值 + c.池[b首].值
  result.极性差 = abs(c.池[a末].极性 - c.池[b首].极性)

proc 组装三字词*(c: 容器集群, 地址A: seq[int], 地址B: seq[int], 地址C: seq[int], 文本: string): 词组 =
  result.文本 = 文本
  result.字数 = 3
  result.容器链 = 地址A & 地址B & 地址C
  # 连A末-B首 + B末-C首
  c.连接(地址A[地址A.len-1], 地址B[0], 2)
  c.连接(地址B[地址B.len-1], 地址C[0], 2)
  result.路强度 = 4
  result.极性差 = abs(c.池[地址C[0]].极性 - c.池[地址A[0]].极性)

proc 组装四字词*(c: 容器集群, a地址: seq[int], b地址: seq[int], d地址: seq[int], e地址: seq[int], 文本: string): 词组 =
  result.文本 = 文本
  result.字数 = 4
  result.容器链 = a地址 & b地址 & d地址 & e地址
  c.连接(a地址[a地址.len-1], b地址[0], 2)
  c.连接(b地址[b地址.len-1], d地址[0], 2)
  c.连接(d地址[d地址.len-1], e地址[0], 2)
  result.路强度 = 6
  result.极性差 = abs(c.池[e地址[0]].极性 - c.池[a地址[0]].极性)

proc 组装五字句*(x: 容器集群, a地址: seq[int], b地址: seq[int], c地址: seq[int], d地址: seq[int], e地址: seq[int], 文本: string): 词组 =
  result.文本 = 文本
  result.字数 = 5
  result.容器链 = a地址 & b地址 & c地址 & d地址 & e地址
  x.连接(a地址[a地址.len-1], b地址[0], 2)
  x.连接(b地址[b地址.len-1], c地址[0], 2)
  x.连接(c地址[c地址.len-1], d地址[0], 2)
  x.连接(d地址[d地址.len-1], e地址[0], 2)
  result.路强度 = 8
  result.极性差 = abs(x.池[e地址[0]].极性 - x.池[a地址[0]].极性)

# ============================================================================
# 关系计算：极性差决定关系性质
# ============================================================================

proc 关系性质*(极性差: int): string =
  ## 极性差=0 → 同极性=斥（同性相斥）
  ## 极性差=1 → 异极性=吸（异性相吸）
  case 极性差:
    of 0: "斥(同极性·平行)"
    of 1: "吸(异极性·互补)"
    else: "断(超距·无关系)"

# ============================================================================
# 域加载的两种模式
# ============================================================================

type
  加载方式 * = enum
    lm谐音,      ## 按谐音（声母遍历韵母）收编
    lm笔画,      ## 按笔画结构相似度聚类
    lm极性       ## 按阴阳极性互补配对

proc 查找配对*(c: 容器集群, 地址: int, 方式: 加载方式): seq[int] =
  ## 根据加载方式为目标容器寻找最佳配对
  if not c.池.hasKey(地址): return @[]
  let 目标 = c.池[地址]
  var 候选: seq[int] = @[]
  for adr, p in c.池:
    if adr == 地址: continue
    if 目标.已连.find(adr) >= 0: continue
    case 方式:
    of lm谐音:
      # 谐音匹配：相位相同或相差4（对称部位）
      if p.相位 == 目标.相位 or abs(p.相位 - 目标.相位) == 4:
        候选.add(adr)
    of lm笔画:
      # 笔画相似：值接近±2
      if abs(p.值 - 目标.值) <= 2:
        候选.add(adr)
    of lm极性:
      # 极性互补：相反极性
      if p.极性 != 目标.极性:
        候选.add(adr)
  result = 候选

