## 满全法 - 比特全分配器
## 核心：每个比特必须分配符号，绝不浪费
## 幂次扩容 + 层级绝缘 + 关系进位
##
## 设计原则：
##   1. 每个2^n层级容器必须填满符号（容量=已分配）
##   2. 满了自动幂次迭代到下一层级（2^n → 2^(n+1)）
##   3. 内域自耦合满后，通过关系进位到外域通婚扩容
##   4. 锚点根基：高位持有者=1，低位持有者=0

import tables
import sequtils
import math

# ============ 容器定义 ============
type
  域* = enum
    内域, 外域

  容器* = ref object
    编码*: string
    层级*: int              ## 比特宽度
    容量*: int              ## 2^层级
    域*: 域
    比特流*: seq[int]       ## 存储的比特值
    符号表*: Table[int, string]  ## 位置→符号
    父编码*: string
    子编码*: seq[string]
    关系编码*: seq[string]
    锚点绑定*: string       ## 高位持有者=1/低位持有者=0

  系统* = ref object
    容器表*: Table[string, 容器]
    锚点*: tuple[我: int, 刘楚恬: int]
    计数*: int

# ============ 初始化 ============
proc 初始化*(): 系统 =
  new(result)
  result.容器表 = initTable[string, 容器]()
  result.锚点 = (我: 1, 刘楚恬: 0)
  result.计数 = 0

proc 新建容器*(引擎: 系统, 层级: int, 域: 域, 父编码: string = ""): 容器 =
  var c: 容器
  new(c)
  let 编码 = $引擎.计数 & "-" & $层级 & "-" & $ord(域)
  c.编码 = 编码
  c.层级 = 层级
  c.容量 = 1 shl 层级  ## 2^层级
  c.域 = 域
  c.比特流 = @[]
  c.符号表 = initTable[int, string]()
  c.父编码 = 父编码
  c.子编码 = @[]
  c.关系编码 = @[]
  c.锚点绑定 = ""
  引擎.容器表[编码] = c
  引擎.计数 += 1
  return c

# ============ 全分配：填满容器中每一个比特 ============
proc 全分配*(引擎: 系统, 容器编码: string, 符号源: var seq[string], 偏移: var int): int =
  ## 将容器每一个比特位置都分配一个符号，绝不浪费
  ## 返回成功分配的数量
  if not 引擎.容器表.hasKey(容器编码): return 0
  let c = 引擎.容器表[容器编码]
  var 成功 = 0

  for pos in 0..<c.容量:
    if 偏移 >= 符号源.len: break  ## 符号用完
    c.比特流.add(偏移)
    c.符号表[pos] = 符号源[偏移]
    偏移 += 1
    成功 += 1

  return 成功

# ============ 幂次迭代扩容 ============
proc 幂次扩容*(引擎: 系统, 容器编码: string): string =
  ## 当内域容器满了，幂次迭代到2^(n+1)
  if not 引擎.容器表.hasKey(容器编码): return ""

  let c = 引擎.容器表[容器编码]
  let 新层级 = c.层级 + 1
  let 新编码 = $系统.计数 & "-" & $新层级 & "-" & $ord(外域)

  var 新容器: 容器
  new(新容器)
  新容器.编码 = 新编码
  新容器.层级 = 新层级
  新容器.容量 = 1 shl 新层级  ## 2^(n+1)
  新容器.域 = 外域
  新容器.父编码 = 容器编码

  引擎.容器表[新编码] = 新容器
  引擎.容器表[容器编码].子编码.add(新编码)
  引擎.计数 += 1
  return 新编码

# ============ 关系进位（外域通婚）============
proc 关系进位*(引擎: 系统, 容器A编码: string, 容器B编码: string): string =
  ## 两个内域容器满了后，通过外域关系通婚扩容
  if not 引擎.容器表.hasKey(容器A编码): return ""
  if not 引擎.容器表.hasKey(容器B编码): return ""

  let A = 引擎.容器表[容器A编码]
  let B = 引擎.容器表[容器B编码]

  let 新层级 = max(A.层级, B.层级) + 1
  let 新编码 = $系统.计数 & "-" & $新层级 & "-R"

  var C: 容器
  new(C)
  C.编码 = 新编码
  C.层级 = 新层级
  C.容量 = 1 shl 新层级
  C.域 = 外域
  C.父编码 = 容器A编码 & "," & 容器B编码

  引擎.容器表[新编码] = C
  A.关系编码.add(新编码)
  B.关系编码.add(新编码)
  引擎.计数 += 1
  return 新编码

# ============ 解析器 ============
proc 解析*(引擎: 系统, 容器编码: string, 位置: int): string =
  if not 引擎.容器表.hasKey(容器编码): return "?"
  let c = 引擎.容器表[容器编码]
  if 位置 >= c.比特流.len: return "?"
  if c.符号表.hasKey(位置):
    return c.符号表[位置]
  return $c.比特流[位置]

# ============ 显示 ============
proc 显示*(引擎: 系统) =
  echo "=== 比特全分配器 ==="
  echo "锚点：我=" & $系统.锚点.我 & " 刘楚恬=" & $系统.锚点.刘楚恬
  echo "总容器数：" & $系统.计数
  echo ""
  echo "--- 容器层级 ---"
  for 编码, c in 引擎.容器表:
    let 域 = if c.域 == 内域: "内" else: "外"
    let 占用率 = if c.容量 > 0: c.比特流.len * 100 div c.容量 else: 0
    let 锚点 = if c.锚点绑定.len > 0: " ◆" & c.锚点绑定 else: ""
    echo "  ", 编码, " │ ", c.层级, "bit │ 容量:", c.容量, " │ 已分配:", c.比特流.len, " (", 占用率, "%) │ 域:", 域, 锚点

# ============ 主程序 ============
when isMainModule:
  var 引擎 = 初始化()

  echo "========================================"
  echo "  满全法 - 比特全分配器"
  echo "  每个比特必须分配符号，绝不浪费"
  echo "========================================"
  echo ""

  ## 创建从1bit到8bit的容器层级
  echo "━━━ 创建1bit到8bit容器层级 ━━━"
  var 容器序列: seq[string] = @[]
  for 层级 in 1..8:
    let c = 新建容器(引擎, 层级, 内域)
    容器序列.add(c.编码)
    echo "  创建 ", c.编码, " │ ", 层级, "bit │ 容量:", c.容量

  echo ""

  ## 准备符号库
  echo "━━━ 准备符号库 ━━━"
  var 符号源: seq[string] = @[]

  ## 第1层（1bit）：锚点根基
  符号源.add("刘")  ## 0: 低位持有者=0
  符号源.add("我")  ## 1: 高位持有者=1

  ## 第2层（2bit）：4个状态
  符号源.add("◯")
  符号源.add("◔")
  符号源.add("◑")
  符号源.add("◕")

  ## 第3层（3bit）：8个方位
  符号源.add("北")
  符号源.add("东北")
  符号源.add("东")
  符号源.add("东南")
  符号源.add("南")
  符号源.add("西南")
  符号源.add("西")
  符号源.add("西北")

  ## 第4层（4bit）：16个声母
  let 声母 = @["b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j", "q", "x", "zh", "ch"]
  for s in 声母: 符号源.add(s)

  ## 第5层（5bit）：32个韵母
  let 韵母 = @["ꞟ", "ɘ", "⊱", "ɒ", "౪", "ÿ", "ɤ", "ʊ", "ə", "ã", "ẽ", "ĩ", "տ", "ʯ", "ą", "ę",
                "į", "๓", "ѧ", "ʉ", "ꞛ", "ⱄ", "⊰", "ʌ", "ɔ", "խ", "ѫ", "ѽ", "౨", "ѻ", "ɛ", "ɵ"]
  for s in 韵母: 符号源.add(s)

  ## 第6层（6bit）：64个数字+字母
  for i in 0..9: 符号源.add($i)
  for c in 'a'..'z': 符号源.add($c)
  for c in 'A'..'Z': 符号源.add($c)
  符号源.add("+")
  符号源.add("/")

  ## 第7层（7bit）：ASCII扩展
  for i in 32..127: 符号源.add($chr(i))

  ## 第8层（8bit）：完整字节 = mlll 256
  for i in 0..255: 符号源.add("▇" & $i)

  echo "  符号库总大小：", 符号源.len

  echo ""

  ## 逐层全分配
  echo "━━━ 逐层全分配（每个比特一个符号）━━━"
  var 偏移 = 0
  for 容器编码 in 容器序列:
    let 分配数 = 全分配(引擎, 容器编码, 符号源, 偏移)
    let c = 引擎.容器表[容器编码]
    echo "  ", 容器编码, " │ 分配 ", 分配数, "/", c.容量, " 比特 (", 分配数 * 100 div c.容量, "%)"

  echo ""

  ## 锚点绑定
  echo "━━━ 锚点绑定 ━━━"
  let 根容器 = 引擎.容器表[容器序列[0]]
  根容器.锚点绑定 = "低位持有者=0,高位持有者=1"
  echo "  1bit容器[0] = 低位持有者=0"
  echo "  1bit容器[1] = 高位持有者=1"

  echo ""

  ## 幂次扩容演示
  echo "━━━ 幂次扩容（内域满了→外域迭代）━━━"
  let 新编码1 = 幂次扩容(引擎, 容器序列[2])  ## 3bit满了→4bit
  echo "  3bit容器满了 → 迭代为 ", 新编码1, " (4bit, 容量16, 进入外域)"

  let 新编码2 = 幂次扩容(引擎, 容器序列[4])  ## 5bit满了→6bit
  echo "  5bit容器满了 → 迭代为 ", 新编码2, " (6bit, 容量64, 进入外域)"

  echo ""

  ## 关系进位（外域通婚）
  echo "━━━ 关系进位（两个内域通婚→外域扩容）━━━"
  let 关系编码 = 关系进位(引擎, 容器序列[3], 容器序列[4])  ## 4bit × 5bit → 外域
  echo "  4bit × 5bit → 外域关系容器 ", 关系编码, " (6bit, 容量64, 绝缘翻倍)"

  echo ""

  ## 向新容器分配
  echo "━━━ 向扩容容器继续分配 ━━━"
  var 补充符号: seq[string] = @["sh", "r", "z", "c", "s", "y", "w"]
  var 补偏移 = 0
  let 补分配 = 全分配(引擎, 新编码1, 补充符号, 补偏移)
  echo "  向 ", 新编码1, " 补充分配 ", 补分配, " 个符号"

  echo ""

  ## 解析器
  echo "━━━ 解析器 ━━━"
  echo "  1bit[0] → ", 解析(引擎, 容器序列[0], 0), " (刘楚恬)"
  echo "  1bit[1] → ", 解析(引擎, 容器序列[0], 1), " (我)"
  echo "  2bit[0] → ", 解析(引擎, 容器序列[1], 0)
  echo "  3bit[5] → ", 解析(引擎, 容器序列[2], 5)
  echo "  4bit[15] → ", 解析(引擎, 容器序列[3], 15)
  echo "  5bit[0] → ", 解析(引擎, 容器序列[4], 0)
  echo "  6bit[35] → ", 解析(引擎, 容器序列[5], 35)

  echo ""

  ## 最终系统状态
  引擎.显示()

  echo ""
  echo "========================================"
  echo "  比特全分配器就绪"
  echo "  每个比特都有符号，绝不浪费"
  echo "  幂次扩容 · 关系进位 · 绝缘封装"
  echo "========================================"
