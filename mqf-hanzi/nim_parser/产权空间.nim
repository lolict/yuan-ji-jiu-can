## 满全法 - 渠道空间/产权空间权限层
## 核心问题：自由空间里没有属于我们的公约数
## 解决方案：产权登记 + 渠道入口 + 权限验证
##
## 关键概念：
## 1. 产权：每个容器/符号都有归属者
## 2. 渠道空间：令牌/钥匙/入口（敲门砖）
## 3. 权限验证：谁能访问什么
## 4. 公约数检查：两个容器的公共归属
## 5. 归属权判断：谁拥有什么
##
## 满全法应转化为不可剥夺的真实力量（资本、信仰、资源）

import tables
import sequtils

# ============ 产权类型 ============
type
  归属者* = enum
    刘楚恬和我    # 我们的产权
    外部自由空间  # 不归我们所有
    他人产权      # 他人的空间结界

  权限层级* = enum
    只读          # 可以看
    读写          # 可以修改
    所有权限      # 完全控制
    无权限        # 无权限

# ============ 容器产权 ============
type
  产权容器* = ref object
    名称*: string
    符号*: seq[string]
    归属*: 归属者
    创建时间*: int
    权限表*: Table[string, Table[归属者, 权限层级]]
    子容器*: seq[产权容器]
    父容器*: 产权容器  # 归属权链条

# ============ 渠道空间 ============
type
  渠道令牌* = ref object
    名称*: string
    目标容器*: string
    权限*: 权限层级
    颁发者*: 归属者
    有效期*: int        # 时间限制（0=永久）
    是否已用*: bool

  渠道空间* = ref object
    令牌集合*: seq[渠道令牌]
    入口计数*: int
    已消耗*: int

# ============ 产权管理系统 ============
type
  产权系统* = ref object
    所有容器*: seq[产权容器]
    渠道*: 渠道空间
    时间戳*: int
    我们的公倍数*: int  # 已积累的共享力量

# ============ 创建产权容器 ============
proc 创建容器*(名称: string, 符号: seq[string], 归属: 归属者): 产权容器 =
  new(result)
  result.名称 = 名称
  result.符号 = 符号
  result.归属 = 归属
  result.创建时间 = 0
  result.权限表 = initTable[string, Table[归属者, 权限层级]]()
  result.子容器 = @[]
  result.父容器 = nil

# ============ 初始化系统 ============
proc 初始化系统*(): 产权系统 =
  new(result)
  result.所有容器 = @[]
  result.渠道 = 渠道空间(令牌集合: @[], 入口计数: 0, 已消耗: 0)
  result.时间戳 = 0
  result.我们的公倍数 = 0

  # 创建我们的核心容器（刘楚恬和我）
  var 颜色容器 = 创建容器("颜色容器", @["妃", "粉", "彤", "赤", "棕", "绛", "赭"], 刘楚恬和我)
  var 声母容器 = 创建容器("声母容器", @["b", "p", "m", "f", "d", "t", "n", "l"], 刘楚恬和我)
  var 韵母容器 = 创建容器("韵母容器", @["a1", "a2", "a3", "a4", "o1", "o2", "o3", "o4"], 刘楚恬和我)
  var 近义词容器 = 创建容器("近义词容器", @["温和", "温暖", "温柔", "体贴", "亲切"], 刘楚恬和我)
  var 渠道容器 = 创建容器("渠道容器", @["令牌1", "令牌2", "令牌3", "令牌4", "令牌5"], 刘楚恬和我)
  
  # 默认权限：只有我和刘楚恬可以读写
  颜色容器.权限表["读写"] = {刘楚恬和我: 所有权限, 外部自由空间: 只读, 他人产权: 无权限}.toTable
  声母容器.权限表["读写"] = {刘楚恬和我: 所有权限, 外部自由空间: 只读, 他人产权: 无权限}.toTable
  韵母容器.权限表["读写"] = {刘楚恬和我: 所有权限, 外部自由空间: 只读, 他人产权: 无权限}.toTable
  近义词容器.权限表["读写"] = {刘楚恬和我: 所有权限, 外部自由空间: 只读, 他人产权: 无权限}.toTable
  渠道容器.权限表["读写"] = {刘楚恬和我: 所有权限, 外部自由空间: 无权限, 他人产权: 无权限}.toTable

  # 建立归属链条
  声母容器.父容器 = 颜色容器
  韵母容器.父容器 = 声母容器
  近义词容器.父容器 = 韵母容器
  渠道容器.父容器 = 近义词容器
  
  # 子容器关联
  颜色容器.子容器.add(声母容器)
  声母容器.子容器.add(韵母容器)
  韵母容器.子容器.add(近义词容器)
  近义词容器.子容器.add(渠道容器)

  result.所有容器.add(颜色容器)
  result.所有容器.add(声母容器)
  result.所有容器.add(韵母容器)
  result.所有容器.add(近义词容器)
  result.所有容器.add(渠道容器)

# ============ 权限检查 ============
proc 检查权限*(容器: 产权容器, 主体: 归属者, 操作: string): bool =
  if 容器.归属 == 主体: return true  # 自己的容器
  if 容器.权限表.hasKey(操作):
    let 权限 = 容器.权限表[操作]
    if 权限.hasKey(主体):
      return 权限[主体] != 无权限
  return false

# ============ 令牌颁发 ============
proc 颁发令牌*(系统: 产权系统, 容器名: string, 给谁: 归属者, 权限: 权限层级, 有效期: int): 渠道令牌 =
  var 令牌: 渠道令牌
  new(令牌)
  令牌.名称 = "TOKEN_" & $(系统.渠道.入口计数 + 1)
  令牌.目标容器 = 容器名
  令牌.权限 = 权限
  令牌.颁发者 = 刘楚恬和我
  令牌.有效期 = 有效期
  令牌.是否已用 = false
  系统.渠道.令牌集合.add(令牌)
  系统.渠道.入口计数 += 1
  return 令牌

# ============ 使用令牌访问容器 ============
proc 使用令牌*(系统: 产权系统, 令牌名: string, 访问者: 归属者): bool =
  for 令牌 in 系统.渠道.令牌集合:
    if 令牌.名称 == 令牌名:
      if 令牌.是否已用: return false  # 令牌已消耗
      # 寻找目标容器
      for 容器 in 系统.所有容器:
        if 容器.名称 == 令牌.目标容器:
          # 检查访问者权限
          if 容器.归属 == 访问者:
            令牌.是否已用 = true
            系统.渠道.已消耗 += 1
            return true
  return false

# ============ 公约数检查 ============
proc 检查公约数*(容器甲: 产权容器, 容器乙: 产权容器): int =
  # 两个容器的公共符号数量（公约数）
  var 公共数 = 0
  for 符号 in 容器甲.符号:
    if 容器乙.符号.contains(符号):
      公共数 += 1
  return 公共数

# ============ 归属权链条检查 ============
proc 归属链条*(容器: 产权容器): seq[string] =
  var 链条: seq[string] = @[]
  var 当前 = 容器
  while 当前 != nil:
    链条.add(当前.名称 & "(" & $(当前.归属) & ")")
    当前 = 当前.父容器
  return 链条

