## 满全法 - 七元蜂窝套壳系统
## 核心命题：容器递归嵌套，蜂窝密铺空间填充，壳中壳无限层级
##
## 七元结构（蜂窝单元）：
##   中心 = 内核（第0层）
##   六邻 = 上/下/左上/左下/右上/右下（第1层六角）
##   每个邻又可作为子容器的中心 → 递归
##
## 蜂窝密铺 = 六边形紧密堆积
##   环0: 1格（中心）
##   环1: 6格（六角邻）
##   环2: 12格
##   环n: 6n格
##   总格数 = 1 + 3n(n+1)
##
## 壳中壳：
##   每个容器可被外壳包裹
##   外壳厚度（壳层级数）
##   穿壳成本 = 壳层数
##   内核永远是最深处的容器

import math
import strutils

# ============ 蜂窝坐标（六边形轴向坐标系）============
type
  蜂窝坐标* = object
    q*: int
    r*: int
    s*: int    ## s = -q-r

# ============ 蜂窝容器 ============
type
  容器极性* = enum
    核芯极性,    ## 最内核
    外壳极性     ## 容器壁

  蜂窝容器* = ref object
    坐标*: 蜂窝坐标
    层深*: int              ## 嵌套深度（0=最外层）
    极性*: 容器极性
    符号*: string
    内容*: string
    壳层厚度*: int          ## 如果是外壳：壳层厚度
    子容器*: 蜂窝容器       ## 壳中壳 — 递归嵌套
    活跃*: bool
    父容器*: 蜂窝容器       ## 指向外壳（双向）

# ============ 六边形方向 ============
const
  六方向*: array[6, 蜂窝坐标] = [
    蜂窝坐标(q: 1, r: 0, s: -1),  # 东
    蜂窝坐标(q: 1, r: -1, s: 0),  # 东北
    蜂窝坐标(q: 0, r: -1, s: 1),  # 西北
    蜂窝坐标(q: -1, r: 0, s: 1),  # 西
    蜂窝坐标(q: -1, r: 1, s: 0),  # 西南
    蜂窝坐标(q: 0, r: 1, s: -1)   # 东南
  ]

# ============ 蜂窝系统 ============
type
  蜂窝系统* = ref object
    容器表*: seq[蜂窝容器]
    层深计数*: int
    密铺环数*: int
    系统日志*: seq[string]
    容器计数*: int

# ============ 坐标计算 ============

proc 六边距离(a, b: 蜂窝坐标): int =
  ## 六边形距离 = (|dq| + |dr| + |ds|) / 2
  (abs(a.q - b.q) + abs(a.r - b.r) + abs(a.s - b.s)) div 2

proc 到中心距(c: 蜂窝坐标): int =
  (abs(c.q) + abs(c.r) + abs(c.s)) div 2

# ============ 容器创建 ============

proc 新容器(坐标: 蜂窝坐标, 极性: 容器极性, 符号, 内容: string, 层深: int): 蜂窝容器 =
  new(result)
  result.坐标 = 坐标
  result.极性 = 极性
  result.符号 = 符号
  result.内容 = 内容
  result.层深 = 层深
  result.活跃 = true
  result.壳层厚度 = 0
  result.子容器 = nil
  result.父容器 = nil

# ============ 系统初始化 ============

proc 新建系统*(): 蜂窝系统 =
  new(result)
  result.容器表 = @[]
  result.层深计数 = 0
  result.密铺环数 = 0
  result.系统日志 = @[]
  result.容器计数 = 0

# ============ 密铺生成 ============

proc 环形坐标(半径: int): seq[蜂窝坐标] =
  ## 生成指定半径环上的所有坐标（标准蜂窝环算法）
  if 半径 == 0:
    result.add(蜂窝坐标(q: 0, r: 0, s: 0))
    return
  # 从六方向[4] * 半径开始（西北）
  var c = 蜂窝坐标(q: 六方向[4].q * 半径, r: 六方向[4].r * 半径, s: 六方向[4].s * 半径)
  for dir_idx in 0..5:
    for _ in 1..半径:
      result.add(c)
      c.q += 六方向[dir_idx].q
      c.r += 六方向[dir_idx].r
      c.s += 六方向[dir_idx].s

proc 生成密铺*(系统: 蜂窝系统, 环数: int, 中心符号: string): int =
  ## 生成rings环蜂窝密铺，返回中心容器序号

  var 所有坐标: seq[蜂窝坐标] = @[]

  # 逐环生成
  for ring in 0..环数:
    let 环坐标 = 环形坐标(ring)
    for c in 环坐标:
      所有坐标.add(c)

  # 创建容器
  var 中心序号 = 0
  for i, c in 所有坐标:
    let dist = 到中心距(c)
    let 符号 = if dist == 0: 中心符号 else: $dist & "-" & $i
    let 内容 = "第" & $dist & "环"
    let 极性 = if dist == 0: 核芯极性 else: 外壳极性
    var 容器 = 新容器(c, 极性, 符号, 内容, 0)
    系统.容器表.add(容器)
    if dist == 0: 中心序号 = i

  系统.密铺环数 = 环数
  系统.容器计数 = 系统.容器表.len
  系统.系统日志.add("[密铺] 生成" & $环数 & "环蜂窝 共" & $系统.容器计数 & "格")

  result = 中心序号

# ============ 套壳操作 ============

proc 加壳*(系统: 蜂窝系统, 容器序号, 厚度: int, 材质: string) =
  if 容器序号 < 0 or 容器序号 >= 系统.容器表.len:
    return

  var 内核 = 系统.容器表[容器序号]

  # 创建壳序列（从外到内）
  var 当前外层: 蜂窝容器 = nil
  for i in 1..厚度:
    let 壳符号 = 材质 & $i
    var 壳 = 新容器(内核.坐标, 外壳极性, 壳符号, "壳层" & $i, i)
    壳.壳层厚度 = 厚度
    壳.父容器 = 当前外层
    if 当前外层 != nil:
      当前外层.父容器 = 壳
    当前外层 = 壳
    系统.容器表.add(壳)

  # 最外壳的子容器 = 原内核
  if 当前外层 != nil:
    当前外层.子容器 = 内核
    内核.父容器 = 当前外层
    内核.层深 = 厚度

  系统.层深计数 = max(系统.层深计数, 厚度)
  系统.系统日志.add("[套壳] 容器#" & $容器序号 & " 加" & $厚度 & "层「" & $材质 & "」")

# ============ 内核穿透 ============

proc 穿透路径*(系统: 蜂窝系统, 序号: int): tuple[深度: int, 代价: float, 路径: seq[string]] =
  var 深度 = 0
  var 代价 = 0.0
  var 路径: seq[string] = @[]

  if 序号 < 0 or 序号 >= 系统.容器表.len:
    result = (0, 0.0, @[])
    return

  var 当前 = 系统.容器表[序号]
  路径.add("→" & 当前.符号)

  # 沿父容器方向向外走到最外壳
  while 当前.父容器 != nil:
    当前 = 当前.父容器
    深度 += 1
    路径.add("→" & 当前.符号)

  # 从外到内穿透回内核
  while 当前.子容器 != nil:
    当前 = 当前.子容器
    代价 += 1.0
    路径.add("↘" & 当前.符号)

  result = (深度, 代价, 路径)

# ============ 验证 ============

proc 密铺完整*(系统: 蜂窝系统): bool =
  let 理论数 = 1 + 3 * 系统.密铺环数 * (系统.密铺环数 + 1)
  result = 系统.容器计数 >= 理论数

proc 按环查找*(系统: 蜂窝系统, 环数: int): seq[蜂窝容器] =
  for 容器 in 系统.容器表:
    if 到中心距(容器.坐标) == 环数:
      result.add(容器)

# ============ 输出 ============

proc 容器报告*(系统: 蜂窝系统, 序号: int): string =
  if 序号 < 0 or 序号 >= 系统.容器表.len:
    return "容器不存在"
  let c = 系统.容器表[序号]
  var sb = ""
  sb.add("  [" & $序号 & "][" & (if c.极性 == 核芯极性: "核" else: "壳") & "]\n")
  sb.add("  坐标:(" & $c.坐标.q & "," & $c.坐标.r & "," & $c.坐标.s & ")\n")
  sb.add("  符号:" & c.符号 & "  层深:" & $c.层深 & "  壳厚:" & $c.壳层厚度 & "\n")
  sb.add("  内容:" & c.内容 & "  子容器:" & (if c.子容器 != nil: "有" else: "无") & "\n")
  result = sb

proc 系统全览*(系统: 蜂窝系统): string =
  let 理论数 = 1 + 3 * 系统.密铺环数 * (系统.密铺环数 + 1)
  var sb = ""
  sb.add("┌─────────────────────────────────┐\n")
  sb.add("│    七元蜂窝套壳系统  v1.2       │\n")
  sb.add("├─────────────────────────────────┤\n")
  sb.add("│  密铺环数: " & $系统.密铺环数 & "\n")
  sb.add("│  容器总数: " & $系统.容器计数 & "\n")
  sb.add("│  最大嵌套: " & $系统.层深计数 & "层\n")
  sb.add("│  密铺完整: " & (if 密铺完整(系统): "✓" else: "✗") &
    " (" & $系统.容器计数 & "/" & $理论数 & ")\n")
  sb.add("└─────────────────────────────────┘\n")
  result = sb

proc 蜂窝俯视图*(系统: 蜂窝系统): string =
  var sb = "\n  【蜂窝密铺俯视图】\n\n"
  for ring in 0..系统.密铺环数:
    let 格 = 按环查找(系统, ring)
    let pad = 系统.密铺环数 - ring
    sb.add("  " & repeat("  ", pad))
    for c in 格:
      let m = if c.极性 == 核芯极性: "◉" else: "○"
      sb.add(m & c.符号 & " ")
    sb.add("\n")
  sb.add("\n  ◉=核芯  ○=外壳\n")
  result = sb

