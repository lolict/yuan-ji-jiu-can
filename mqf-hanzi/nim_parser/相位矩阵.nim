# ============ 解释器基因注入 ============
proc 注入基因*(矩阵: 相位矩阵, 容器编号: int): bool =
  ## 将指定容器的编码注入解释器基因
  ## 同一个解释器，注入不同编码即可切换解析类型
  if not 矩阵.容器表.hasKey(容器编号): return false
  let 容器 = 矩阵.容器表[容器编号]
  var 基因 = 矩阵.解释器
  基因.注入编码 = 容器.相位类型
  基因.容器编号 = 容器编号
  基因.解析表 = initTable[int, string]()

  ## 构建解析表：相位码 → 符号
  for 相位 in 容器.相位列表:
    基因.解析表[相位.相位码] = 相位.符号

  ## 设置解析规则
  case 容器.相位类型:
    of 声母相位: 基因.激活规则 = "声母相位解析：23个声母，相位码1-23"
    of 韵母相位: 基因.激活规则 = "韵母相位解析：32个自定义符号，相位码1-32"
    of 声调相位: 基因.激活规则 = "声调相位解析：4声+轻声，相位码1-5"
    of 颜色相位: 基因.激活规则 = "颜色相位解析：21色，相位码1-21"
    of 笔画相位: 基因.激活规则 = "笔画相位解析：1-36画，相位码1-36"
    of 五笔相位: 基因.激活规则 = "五笔相位解析：25键位，相位码1-25"
    of 部首相位: 基因.激活规则 = "部首相位解析：20部首，相位码1-20"
    else: 基因.激活规则 = "未知编码"

  ## 激活容器
  for k, v in 矩阵.容器表.mpairs:
    v.激活 = false
  容器.激活 = true
  矩阵.激活容器 = 容器编号
  矩阵.时间线 += 1

  return true

# ============ 相位重组 ============
proc 相位重组*(矩阵: 相位矩阵, 容器A: int, 容器B: int): seq[tuple[相位A: string, 相位B: string, 重组码: int]] =
  ## 两个容器的相位重组：生成所有可能的组合
  if not 矩阵.容器表.hasKey(容器A): return @[]
  if not 矩阵.容器表.hasKey(容器B): return @[]
  let ca = 矩阵.容器表[容器A]
  let cb = 矩阵.容器表[容器B]
  var 结果: seq[tuple[相位A: string, 相位B: string, 重组码: int]] = @[]
  for pa in ca.相位列表:
    for pb in cb.相位列表:
      let 重组码 = pa.相位码 * 100 + pb.相位码  ## 相位码组合
      结果.add((相位A: pa.符号, 相位B: pb.符号, 重组码: 重组码))
  return 结果

# ============ 解析 ============
proc 解析*(矩阵: 相位矩阵, 相位码: int): string =
  ## 用当前注入的解释器基因解析相位码
  let 基因 = 矩阵.解释器
  if 基因.解析表.hasKey(相位码):
    return 基因.解析表[相位码]
  return "?"

# ============ 显示 ============
proc 显示矩阵*(矩阵: 相位矩阵) =
  echo "=== 满全法·编码相位矩阵 ==="
  echo "容器数：" & $矩阵.容器计数 & " │ 相位总数：" & $矩阵.相位总数
  echo "时间线：t=" & $矩阵.时间线
  echo "激活容器：" & (if 矩阵.激活容器 >= 0: 矩阵.容器表[矩阵.激活容器].名称 else: "无")
  echo ""
  echo "--- 容器列表（绝缘层）---"
  for i in 0..<矩阵.容器计数:
    let c = 矩阵.容器表[i]
    let 激活标记 = if c.激活: " ◀激活" else: ""
    echo "  [" & $c.编号 & "] " & c.名称 & " │ 层级:" & $c.层级 & " │ 相位数:" & $c.相位列表.len & " │ 绝缘强度:" & $c.绝缘强度 & 激活标记
  echo ""
  echo "--- 解释器基因 ---"
  let 基因 = 矩阵.解释器
  echo "  注入编码：" & $基因.注入编码
  echo "  绑定容器：" & $基因.容器编号
  echo "  解析规则：" & 基因.激活规则
  echo "  解析表大小：" & $基因.解析表.len

proc 显示容器详情*(矩阵: 相位矩阵, 容器编号: int, 前几个: int = 10) =
  if not 矩阵.容器表.hasKey(容器编号): return
  let c = 矩阵.容器表[容器编号]
  echo "--- " & c.名称 & " 详情 ---"
  echo "  相位类型：" & $c.相位类型 & " │ 层级：" & $c.层级
  echo "  绝缘强度：" & $c.绝缘强度
  echo "  前" & $min(前几个, c.相位列表.len) & "个相位："
  for i, p in c.相位列表:
    if i >= 前几个: break
    echo "    " & $p.相位码 & " → " & p.符号

