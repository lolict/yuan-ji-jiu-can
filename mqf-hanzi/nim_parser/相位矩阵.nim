## 满全法 - 编码相位矩阵系统
## 核心：预加载多种编码维度的相位，一维时间串联空间
##
## 层级（由底向上）：
##   Layer 0: 比特流（最底层）
##   Layer 1: 二进制开关
##   Layer 2: 编码流（声母/韵母/声调/颜色/笔画/五笔/部首...）
##   Layer 3: 数学进制/排序流
##
## 容器 = 绝缘层：每一层被封装，电只能在层级内流动
## 解释器 = 基因注入：一个解释器，注入不同编码基因即可切换解析类型

import tables
