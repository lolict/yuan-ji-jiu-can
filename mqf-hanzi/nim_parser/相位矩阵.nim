# ============ 编码相位类型 ============
type
  相位类型* = enum
    声母相位,      ## 23个声母
    韵母相位,      ## 32个自定义韵母
    声调相位,      ## 4声+轻声
    颜色相位,      ## 21个颜色
    笔画相位,      ## 笔画数
    五笔相位,      ## 五笔字根
    部首相位,      ## 部首分类
    发音符号相位,  ## 国际音标符号
    数字相位,      ## 阿拉伯数字
    结构相位       ## 汉字结构

  层级* = enum
    比特层 = 0,    ## 最底层：0/1
    开关层 = 1,    ## 二进制开关
    编码层 = 2,    ## 编码流（所有相位在此）
    进制层 = 3     ## 数学进制/排序

# ============ 相位单元 ============
type
  相位单元* = ref object
    名称*: string
    相位类型*: 相位类型
    层级*: 层级
    相位码*: int        ## 该维度的相位值
    符号*: string       ## 可视化符号
    来源*: string       ## 来源描述
    容器编号*: int      ## 所属容器编号（绝缘边界）

# ============ 编码容器（绝缘层）============
type
  编码容器* = ref object
    编号*: int
    名称*: string
    相位类型*: 相位类型
    层级*: 层级
    相位列表*: seq[相位单元]
    绝缘强度*: int      ## 容器绝缘强度 = 相位数量 × 层级值
    激活*: bool         ## 是否被选中激活

# ============ 解释器基因 ============
type
  解释器基因* = ref object
    注入编码*: 相位类型    ## 当前注入的编码类型
    解析表*: Table[int, string]  ## 相位码 → 符号的映射
    容器编号*: int         ## 绑定的容器
    激活规则*: string      ## 解析规则描述

# ============ 相位矩阵系统 ============
type
  相位矩阵* = ref object
    容器表*: Table[int, 编码容器]       ## 所有容器
    解释器*: 解释器基因                  ## 单一解释器
    时间线*: int                        ## 一维时间串联
    激活容器*: int                      ## 当前激活的容器编号
    相位总数*: int
    容器计数*: int

