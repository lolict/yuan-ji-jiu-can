## 满全法 - 六元对称群 + 六面体系统
## 核心命题：两个三元裁判背靠背镜像对齐，六面三维可视裁决
##
## 架构定义：
##   三元A = 极性0侧（囡/容器/刘楚恬）
##   三元B = 极性1侧（囝/界线/我）
##   背靠背 = 镜像对称，法向量相反
##   六面体 = 3对对面 = 6个裁决视角
##
## 裁判机制：
##   三元A三面：阳性裁定 / 阴性裁定 / 见证裁定
##   三元B三面：阳性裁定 / 阴性裁定 / 见证裁定
##   同维度方向相反 → 交集判定信任
##   符号一致且极性互补 → 信任交集（可承认）
##   符号冲突或极性相同 → 不可信任（无交集）
##
## 六面命名（空间直角坐标系）：
##   +X 右面（入射面）  -X 左面（出射面）
##   +Y 上面（天面）    -Y 下面（地面）
##   +Z 前面（观察面）  -Z 后面（隐秘面）

# import tables  # future use

# ============ 极性与裁判面 ============
type
  极性* = enum
    极性囡,    ## 0 = 容器侧（刘楚恬）
    极性囝     ## 1 = 界线侧（我）

  面色* = enum
    右面,    ## +X 入射
    左面,    ## -X 出射
    天面,    ## +Y 上
    地面,    ## -Y 下
    前面,    ## +Z 观察
    后面     ## -Z 隐秘

  裁定* = enum
    阳性,    ## 准入/承认
    阴性,    ## 拒绝/驳回
    见证     ## 未决/待裁定

# ============ 三元裁判 ============
type
  三元面* = ref object
    面色*: 面色          ## 这个面在哪个方向
    极性*: 极性          ## 属于哪一侧
    裁定*: 裁定          ## 当前裁定结果
    符号*: string        ## 该面当前负载的符号
    极性码*: int         ## 64位编码中的极性bit

  三元裁判* = ref object
    极性*: 极性           ## 这一元的极性
    名称*: string         ## 标识
    三面*: seq[三元面]    ## 三个裁判面
    镜像伙伴*: int        ## 对面三元裁判的编号
    活跃*: bool           ## 当前是否参与裁决

# ============ 六面体（六元对称群）============
type
  六面体* = ref object
    三元A*: 三元裁判      ## 极性0（背靠背A）
    三元B*: 三元裁判      ## 极性1（背靠背B）
    对称轴*: string       ## 镜像对称轴描述
    裁决ID*: int          ## 本次裁决编号

# ============ 信任交集判定结果 ============
type
  信任等级* = enum
    全交集,      ## 三面全部一致互补 → 完全信任
    部分交集,    ## 2面一致互补 → 有条件信任
    单点交集,    ## 1面一致互补 → 微弱信任
    无交集,      ## 0面一致互补 → 不可信任
    矛盾的       ## 自指冲突 → Paradox

  交集结果* = ref object
    等级*: 信任等级
    一致面*: seq[面色]        ## 哪些面达成了一致
    冲突面*: seq[面色]        ## 哪些面产生了冲突
    描述*: string             ## 人类可读判决文本

# ============ 六元对称系统 ============
type
  六元系统* = ref object
    六面体组*: seq[六面体]
    裁决计数*: int
    系统日志*: seq[string]
    历史*: seq[交集结果]

# ============ 辅助函数 ============

proc 对位面(面色: 面色): 面色 =
  ## 获取一个面的对面（镜像对称）
  case 面色
  of 右面:
    左面
  of 左面:
    右面
  of 天面:
    地面
  of 地面:
    天面
  of 前面:
    后面
  of 后面:
    前面

proc 极性取码(极性: 极性): int =
  case 极性
  of 极性囡:
    0
  of 极性囝:
    1

# ============ 创建三元裁判 ============

proc 创建三元裁判(极性: 极性, 名称: string, 三面定义: seq[tuple[面: 面色, 符号: string]]): 三元裁判 =
  new(result)
  result.极性 = 极性
  result.名称 = 名称
  result.镜像伙伴 = -1
  result.活跃 = true
  result.三面 = @[]
  for def in 三面定义:
    var f: 三元面
    new(f)
    f.面色 = def.面
    f.极性 = 极性
    f.裁定 = 见证
    f.符号 = def.符号
    f.极性码 = 极性取码(极性)
    result.三面.add(f)

# ============ 创建六面体 ============

proc 新建六面体*(系统: 六元系统
    , a定义: seq[tuple[面: 面色, 符号: string]]
    , b定义: seq[tuple[面: 面色, 符号: string]]
    ): int =
  ## 新建一个六面体裁决结构
  var a = 创建三元裁判(极性囡, "三元A", a定义)
  var b = 创建三元裁判(极性囝, "三元B", b定义)
  a.镜像伙伴 = 1
  b.镜像伙伴 = 0

  var 体: 六面体
  new(体)
  体.三元A = a
  体.三元B = b
  体.对称轴 = "X-Y-Z三轴镜像对称"
  体.裁决ID = 系统.裁决计数

  系统.六面体组.add(体)
  系统.裁决计数 += 1
  系统.系统日志.add("[裁决#" & $(系统.裁决计数-1) & "] 新建六面体：「" &
    a定义[0].符号 & "↔" & b定义[0].符号 & "」")

  result = 系统.裁决计数 - 1

# ============ 核心：信任交集判定 ============

proc 信任交集判定*(体: 六面体): 交集结果 =
  ## 核心算法：对比两个三元裁判的对应面
  ## 信任条件：符号一致 AND 极性互补（背靠背）
  new(result)
  result.一致面 = @[]
  result.冲突面 = @[]

  for a面 in 体.三元A.三面:
    let 对应b面色 = 对位面(a面.面色)
    # 在B中找到对应面
    var b面: 三元面 = nil
    for f in 体.三元B.三面:
      if f.面色 == 对应b面色:
        b面 = f
        break
    if b面 == nil: continue

    # 信任条件：符号一致 + 极性互补
    if a面.符号 == b面.符号 and a面.极性 != b面.极性:
      result.一致面.add(a面.面色)
    else:
      result.冲突面.add(a面.面色)

  # 判定等级
  case len(result.一致面)
  of 3:
    result.等级 = 全交集
    result.描述 = "完全信任：三面极性互补且符号一致"
  of 2:
    result.等级 = 部分交集
    result.描述 = "有条件信任：2面一致互补，1面存在冲突"
  of 1:
    result.等级 = 单点交集
    result.描述 = "微弱信任：仅1面一致互补，需额外见证"
  of 0:
    result.等级 = 无交集
    result.描述 = "不可信任：三面全部冲突"
  else:
    result.等级 = 矛盾的
    result.描述 = "自指冲突：Paradox状态"

# ============ 六面体可视化 ============

proc 面显示(体: 六面体, 查询面色: 面色): string =
  ## 辅助：给定面色，返回该面显示字符串
  for f in 体.三元A.三面:
    if f.面色 == 查询面色:
      let pol = if f.极性 == 极性囡: "囡" else: "囝"
      return f.符号 & pol
  for f in 体.三元B.三面:
    if f.面色 == 查询面色:
      let pol = if f.极性 == 极性囡: "囡" else: "囝"
      return f.符号 & pol
  return "--"

proc 六面体视图*(体: 六面体): string =
  ## 输出六面体的三维展开图（二维投影）
  var sb = ""
  sb.add("╔══════════════════════════════════╗\n")
  sb.add("║      六面体 裁决图  #" & $体.裁决ID & "        ║\n")
  sb.add("╠══════════════════════════════════╣\n")
  sb.add("         ┌──────┐\n")
  sb.add("         │ " & 面显示(体, 天面) & "  │\n")
  sb.add("  ┌──────┼──────┼──────┬──────┐\n")
  sb.add("  │ " & 面显示(体, 左面) & " │ " & 面显示(体, 前面) & " │ " & 面显示(体, 右面) & " │ " & 面显示(体, 后面) & " │\n")
  sb.add("  └──────┼──────┼──────┴──────┘\n")
  sb.add("         │ " & 面显示(体, 地面) & "  │\n")
  sb.add("         └──────┘\n")
  sb.add("╚══════════════════════════════════╝\n")
  result = sb

proc 裁决报告*(体: 六面体, 结果: 交集结果): string =
  var sb = ""
  sb.add("\n━━━ 裁决报告 #" & $体.裁决ID & " ━━━\n")
  sb.add("  对称轴: " & 体.对称轴 & "\n")
  sb.add("  信任等级: " & $结果.等级 & "\n")
  sb.add("  判决: " & 结果.描述 & "\n")
  sb.add("  一致面(" & $len(结果.一致面) & "): ")
  for 面 in 结果.一致面: sb.add($面 & " ")
  sb.add("\n  冲突面(" & $len(结果.冲突面) & "): ")
  for 面 in 结果.冲突面: sb.add($面 & " ")
  sb.add("\n")
  result = sb

