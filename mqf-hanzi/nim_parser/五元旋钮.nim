## 满全法 - 五元旋钮运动步量系统
## 核心命题：五元 = 五个维度的旋钮，每转一步 = 一单位位移
##
## 维度定义：
##   元1 - 声母旋钮（发音维度）
##   元2 - 韵母旋钮（韵调维度）
##   元3 - 颜色旋钮（视觉维度）
##   元4 - 数字旋钮（量化维度）
##   元5 - 方位旋钮（空间维度）
##
## 运动机制：
##   5步位移累加，角度 wrap 0~360°，每步累加对360取模
##   注意力配比：ratio_in（进入节点的边权重）vs ratio_out（离开节点的边权重）
##   占存判定：accumulated_ticks > 阈值 → 占存铭记，否则可被遗忘
##
## 满全法规约：
##   不进位串联 — 步量是累加不是幂次
##   锚点保护 — 我=1 刘楚恬=0，锚点连通所有惩罚归零
##   惩法 — 跨元拼接有奖惩，距离过近过远都不利

import tables
import sequtils
import math

# ============ 五元类型 ============
type
  元类型* = enum
    元声母,    ## 发音维度
    元韵母,    ## 韵调维度
    元颜色,    ## 视觉维度
    元数字,    ## 量化维度
    元方位     ## 空间维度

# ============ 旋钮状态 ============
type
  旋钮状态* = ref object
    元*: 元类型              ## 这个旋钮属于哪个维度
    名称*: string            ## 显示名称
    步*: int                 ## 当前步数 0~4（五次运动）
    角度*: float             ## 累积角度 0.0~360.0（每步累加对360取模）
    力道*: float             ## 累积作用力 = weight 累加
    进入配比*: float         ## ratio_in：进入这个节点的边权重和
    离开配比*: float         ## ratio_out：离开这个节点的边权重和
    累积刻度*: int           ## accumulated_ticks：总累积位移刻度
    占存*: bool              ## 占存(铭记) / 不占存(可被遗忘)
    转动历史*: seq[string]   ## 每次转动的记录

# ============ 节点（五元旋钮组）============
type
  五元节点* = ref object
    标识*: int               ## 节点编号
    名称*: string            ## 节点名称
    旋钮组*: seq[旋钮状态]   ## 五个旋钮
    占存阈值*: int           ## 超过此阈值判定为占存
    总位移*: float           ## 节点整体位移量
    激活*: bool              ## 当前是否活跃
    占存*: bool              ## 节点级占存(铭记)状态

# ============ 五元系统 ============
type
  五元系统* = ref object
    节点表*: Table[int, 五元节点]
    当前节点*: int
    全局时间*: int
    系统日志*: seq[string]
    节点计数*: int

# ============ 辅助函数 ============

proc 角度归一化(角度: float): float =
  ## 角度 wrap 0~360°：累加后对360取模
  var 结果 = 角度 mod 360.0
  if 结果 < 0.0: 结果 += 360.0
  return 结果

proc 计算进入配比(节点: 五元节点): float =
  ## ratio_in：所有旋钮进入配比的均值（进入节点的边权重总和）
  if 节点.旋钮组.len == 0: return 0.0
  var 总和 = 0.0
  for 旋钮 in 节点.旋钮组:
    总和 += 旋钮.进入配比
  return 总和 / float(节点.旋钮组.len)

proc 计算离开配比(节点: 五元节点): float =
  ## ratio_out：所有旋钮离开配比的均值（离开节点的边权重总和）
  if 节点.旋钮组.len == 0: return 0.0
  var 总和 = 0.0
  for 旋钮 in 节点.旋钮组:
    总和 += 旋钮.离开配比
  return 总和 / float(节点.旋钮组.len)

proc 判定占存(节点: 五元节点): bool =
  ## 节点级占存：所有旋钮累积刻度之和 > 阈值 → 占存铭记
  var 总刻度 = 0
  for 旋钮 in 节点.旋钮组:
    总刻度 += 旋钮.累积刻度
  return 总刻度 > 节点.占存阈值

proc 注意力差值*(节点: 五元节点): float =
  ## 注意力配比差 = 进入 - 离开
  ##   > 0：注意力集中在节点内（内聚）
  ##   < 0：注意力在流出（外散）
  ##   ≈ 0：平衡状态
  return 计算进入配比(节点) - 计算离开配比(节点)

# ============ 系统初始化 ============

proc 新建系统*(): 五元系统 =
  new(result)
  result.节点表 = initTable[int, 五元节点]()
  result.当前节点 = -1
  result.全局时间 = 0
  result.系统日志 = @[]
  result.节点计数 = 0

proc 创建旋钮(元: 元类型, 名称: string, 初始进入, 初始离开: float): 旋钮状态 =
  new(result)
  result.元 = 元
  result.名称 = 名称
  result.步 = 0
  result.角度 = 0.0
  result.力道 = 0.0
  result.进入配比 = 初始进入
  result.离开配比 = 初始离开
  result.累积刻度 = 0
  result.占存 = false
  result.转动历史 = @[]

proc 新建节点*(系统: 五元系统, 名称: string, 占存阈值: int = 10): int =
  ## 创建一个五元节点，包含5个旋钮
  let 编号 = 系统.节点计数
  var 节点: 五元节点
  new(节点)
  节点.标识 = 编号
  节点.名称 = 名称
  节点.占存阈值 = 占存阈值
  节点.总位移 = 0.0
  节点.激活 = true

  # 五个旋钮初始化
  节点.旋钮组 = @[
    创建旋钮(元声母, "声母", 0.5, 0.3),
    创建旋钮(元韵母, "韵母", 0.4, 0.4),
    创建旋钮(元颜色, "颜色", 0.3, 0.5),
    创建旋钮(元数字, "数字", 0.2, 0.6),
    创建旋钮(元方位, "方位", 0.6, 0.2)
  ]

  系统.节点表[编号] = 节点
  系统.节点计数 += 1
  系统.当前节点 = 编号
  系统.全局时间 += 1
  系统.系统日志.add("[T" & $系统.全局时间 & "] 新建节点#" & $编号 & " 「" & 名称 & "」")
  result = 编号

# ============ 核心：五元推进 ============

proc 五元推进*(系统: 五元系统, 节点编号, 元索引: int, 角度增量, 力道: float): string =
  ## 核心函数：推进指定的元旋钮
  ## 参数：
  ##   系统      - 五元系统
  ##   节点编号  - 哪个节点
  ##   元索引    - 0=声母 1=韵母 2=颜色 3=数字 4=方位
  ##   角度增量  - 本步增加的角度（累加后对360取模）
  ##   力道      - 本步的作用力（累加到 weight）
  ##
  ## 返回：本次推进的状态描述
  if 节点编号 notin 系统.节点表:
    result = "错误：节点不存在"
    return

  var 节点 = 系统.节点表[节点编号]
  if 元索引 < 0 or 元索引 > 4:
    result = "错误：元索引超出范围(0~4)"
    return

  var 旋钮 = 节点.旋钮组[元索引]

  # 步数推进：0~4 循环
  旋钮.步 = (旋钮.步 + 1)
  if 旋钮.步 > 4: 旋钮.步 = 0  # 五步一个周期

  # 角度累积（关键：累加后 MOD 360）
  旋钮.角度 = 角度归一化(旋钮.角度 + 角度增量)

  # 力道累积
  旋钮.力道 += 力道

  # 累积刻度+1（每推一步，刻度+1）
  旋钮.累积刻度 += 1

  # 占存判定
  节点.占存 = 判定占存(节点)
  旋钮.占存 = 旋钮.累积刻度 > (节点.占存阈值 div 5)

  # 总位移更新
  节点.总位移 = 0.0
  for k in 节点.旋钮组:
    节点.总位移 += k.角度

  # 进入/离开配比微调（内聚/外散）
  if 力道 > 0.5:
    旋钮.进入配比 = min(1.0, 旋钮.进入配比 + 0.05)
    旋钮.离开配比 = max(0.0, 旋钮.离开配比 - 0.03)
  elif 力道 < -0.5:
    旋钮.进入配比 = max(0.0, 旋钮.进入配比 - 0.03)
    旋钮.离开配比 = min(1.0, 旋钮.离开配比 + 0.05)

  # 时间同步
  系统.全局时间 += 1

  # 记录
  let 元名 = case 元索引
    of 0: "声母"
    of 1: "韵母"
    of 2: "颜色"
    of 3: "数字"
    of 4: "方位"
    else: "未知"
  let 记录 = "[T" & $系统.全局时间 & "] 推动 「" & 元名 & "」→ 步=" & $旋钮.步 &
             " 角度=" & $旋钮.角度 & "° 力道=" & $旋钮.力道 &
             " 刻度=" & $旋钮.累积刻度 &
             " 进入=" & $旋钮.进入配比 & " 离开=" & $旋钮.离开配比 &
             " 占存=" & (if 旋钮.占存: "铭记" else: "暂留")
  旋钮.转动历史.add(记录)
  系统.系统日志.add(记录)

  result = 记录

# ============ 节点联动：旋钮间影响 ============
## 惩法扩展：当一个旋钮被推动，相邻旋钮会受到连带影响

proc 联动推进*(系统: 五元系统, 节点编号, 主控元: int, 角度增量, 力道: float): seq[string] =
  ## 推动一个元，相邻元受到50%的衰减影响（不进位串联的扩散）
  var 结果: seq[string] = @[]

  # 主推
  结果.add(五元推进(系统, 节点编号, 主控元, 角度增量, 力道))

  # 相邻两个元各受50%影响
  let 左邻 = (主控元 - 1 + 5) mod 5
  let 右邻 = (主控元 + 1) mod 5

  结果.add(五元推进(系统, 节点编号, 左邻, 角度增量 * 0.5, 力道 * 0.5))
  结果.add(五元推进(系统, 节点编号, 右邻, 角度增量 * 0.5, 力道 * 0.5))

  return 结果

# ============ 状态输出 ============

proc 节点状态*(系统: 五元系统, 节点编号: int): string =
  if 节点编号 notin 系统.节点表:
    result = "节点不存在"
    return
  let 节点 = 系统.节点表[节点编号]
  var sb = ""
  sb &= "━━━ 节点#" & $节点.标识 & "「" & $节点.名称 & "」━━━\n"
  sb &= "  占存阈值: " & $节点.占存阈值 & "  总位移: " & $节点.总位移 & "°\n"
  sb &= "  进入配比: " & $计算进入配比(节点) &
         "  离开配比: " & $计算离开配比(节点) &
         "  注意力差: " & $注意力差值(节点) & "\n"
  for i, 旋钮 in 节点.旋钮组:
    let 元名 = ["声母", "韵母", "颜色", "数字", "方位"][i]
    sb &= "  [" & $i & "] " & 元名 &
           " 步=" & $旋钮.步 &
           " 角度=" & $旋钮.角度 & "°" &
           " 力道=" & $旋钮.力道 &
           " 刻度=" & $旋钮.累积刻度 &
           " 占存=" & (if 旋钮.占存: "铭记●" else: "暂留○") &
           " 进入=" & $旋钮.进入配比 &
           " 离开=" & $旋钮.离开配比 & "\n"
  result = sb

proc 系统全览*(系统: 五元系统): string =
  var sb = ""
  sb.add("╔═══════════════════════════════════╗\n")
  sb.add("║     五元旋钮运动步量系统  v1.0     ║\n")
  sb.add("║   五步一转 · 角度wrap · 占存铭记   ║\n")
  sb.add("╚═══════════════════════════════════╝\n\n")
  sb.add("  全局时间: T" & $系统.全局时间 & "\n")
  sb.add("  节点数量: " & $系统.节点计数 & "\n")
  sb.add("  当前节点: #" & $系统.当前节点 & "\n\n")
  for 编号, 节点 in 系统.节点表:
    sb.add(节点状态(系统, 编号))
    sb.add("\n")
  result = sb

