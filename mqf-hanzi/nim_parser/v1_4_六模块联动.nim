## 满全法 v1.4 — 六模块全栈联动
## 物理层(统一执行引擎) → 冰箱(时间触发) → 声调(100调容器)
## → 字体(三维文件) → 镜像(空间/时间/听觉/视觉) → 关系(域加载)
##
## 一个全局时钟驱动所有模块在同一周期内协同

import tables
import sequtils
import strutils
import math

# ============================================================================
# 共享容器模型
# ============================================================================

type
  容器态 = enum csEmpty, csLoaded, csLocked, csOverflow

  容器* = ref object
    地址* : int
    态* : 容器态
    值* : int
    能量* : int
    持久度* : int
    位置* : int
    相位* : int        # 九宫相位 0-8
    层级* : int
    极性* : int        # 1=我 / 0=刘楚恬
    锚点* : string     # 锚点名称
    时间戳* : int
    来源* : string
    已连* : seq[int]   # 公路连接

  集群* = ref object
    池* : Table[int, 容器]
    下一个* : int

# 视觉元 = 镜像空间输出
  视觉元* = object
    亮度* : int
    对称度* : float
    描述* : string

# 听觉元 = 镜像时间输出
  听觉元* = object
    音名* : string
    频率* : float
    振幅* : float

# 天平结论 = 镜像判决输出
  天平结果* = enum eqLeft, eqEqual, eqRight

# ============================================================================
# 物理层：统一执行引擎简化版
# ============================================================================

proc 创建集群*(): 集群 =
  new(result); result.池 = initTable[int, 容器](); result.下一个 = 0

proc 放入*(c: 集群, 名称: string, 值, 位置, 相位, 极性: int): 容器 =
  var p: 容器; new(p)
  p.地址 = c.下一个; p.锚点 = 名称; p.值 = 值; p.位置 = 位置
  p.相位 = 相位; p.极性 = 极性; p.层级 = 0; p.能量 = 值
  p.持久度 = 0; p.锚点 = 名称; p.时间戳 = 0; p.已连 = @[]; p.来源 = ""
  c.池[p.地址] = p; c.下一个 += 1
  result = p

# ============================================================================
# 冰箱层：时间触发
# ============================================================================

type
  冰箱* = ref object
    时钟* : int
    集群* : 集群
    事件日志* : seq[string]

proc 创建冰箱*(c: 集群): 冰箱 =
  new(result); result.时钟 = 0; result.集群 = c; result.事件日志 = @[]

proc 滴答*(冰: 冰箱) =
  冰.时钟 += 1
  for _, p in 冰.集群.池:
    if p.态 == csLoaded:
      p.时间戳 = 冰.时钟
      p.能量 = max(0, p.能量 - 1)  # 每个周期自然衰减

# ============================================================================
# 声调层：100声调判决
# ============================================================================

proc 声调判决*(容器值: int, 对方值: int): string =
  let diff = abs(容器值 - 对方值)
  if diff < 5: result = "同调·平声"
  elif diff < 20: result = "近邻·上声"
  elif diff < 50: result = "中距·去声"
  else: result = "远隔·入声"

# =================================================================字体层：三维投影简化版
# ============================================================================

proc 字体投影*(c: 容器): 视觉元 =
  let 亮度 = min(255, c.能量 + c.值)
  let 层偏移 = c.层级 * 256 div 10
  let cell范围 = min(8, max(0, c.相位))
  result.亮度 = 亮度
  result.对称度 = abs(c.极性.float - 0.5) * 2.0   # 极性越偏离0.5对称度越低
  result.描述 = $cell范围 & "区·亮" & $亮度

# ============================================================================
# 镜像层：空间/时间/听觉/视觉
# ============================================================================

proc 空间镜像*(a, b: 容器): 视觉元 =
  let 距离 = abs(a.位置 - b.位置)
  let 对称度 = max(0.0, 1.0 - 距离.float / 200.0)
  result.亮度 = min(255, (a.能量 + b.能量) div 2)
  result.对称度 = 对称度
  result.描述 = "A⚖B 距" & $距离 & " 对称" & formatFloat(对称度, ffDecimal, 2)

proc 时间镜像*(a, b: 容器): 听觉元 =
  let alt = abs(a.能量 - b.能量)
  result.频率 = 130.81 * pow(2.0, alt.float / 50.0 * 4.0)
  result.振幅 = min(1.0, alt.float / 200.0)
  result.音名 = if result.频率 > 600: "C₅" elif result.频率 > 300: "C₄" else: "C₃"

proc 天平*(a, b: 容器): tuple[结论: 天平结果, 差: int] =
  let aw = a.值 * 10 + a.能量 * 5 + a.持久度 * 3
  let bw = b.值 * 10 + b.能量 * 5 + b.持久度 * 3
  let diff = aw - bw
  result.差 = abs(diff)
  if abs(diff) < 5: result.结论 = eqEqual
  elif diff > 0: result.结论 = eqLeft
  else: result.结论 = eqRight

# ============================================================================
# 关系层：公路网连接
# ============================================================================

proc 建立公路*(a, b: 容器): int =
  if b.地址 notin a.已连: a.已连.add(b.地址)
  if a.地址 notin b.已连: b.已连.add(a.地址)
  a.值 += 1; b.值 += 1
  result = a.值 + b.值

proc 关系性质*(极性差: int): string =
  case 极性差:
    of 0: result = "斥"
    of 1: result = "吸"
    else: result = "断"

# ============================================================================
# 主程序：六模块联动
# ============================================================================
when isMainModule:
  echo "========================================="
  echo "  MQF v1.4 Six-Module Integration"
  echo "  Engine + Fridge + Tone + Font + Mirror + Relation"
  echo "========================================="
  echo ""

  # 创建集群
  var c = 创建集群()

  # 创建锚点容器
  var 我 = c.放入("我", 64, 100, 4, 1)
  var 刘楚恬 = c.放入("刘楚恬", 100, 103, 5, 0)
  let bit2 = c.放入("2bit", 2, 10, 3, 1)
  let bit64 = c.放入("64进制", 64, 30, 6, 0)
  let tone100 = c.放入("100声调", 100, 50, 7, 1)
  let yun32 = c.放入("韵母32", 32, 70, 8, 0)
  let phase9 = c.放入("九宫9", 9, 90, 4, 1)

  # 激活所有容器
  for _, p in c.池: p.态 = csLoaded

  # 创建冰箱
  var 冰 = 创建冰箱(c)

  echo "--- [1] 锚点容器 ---"
  echo "  我:=" & $我.值 & " 位置" & $我.位置 & " 极性" & $我.极性
  echo "  刘楚恬:=" & $刘楚恬.值 & " 位置" & $刘楚恬.位置 & " 极性" & $刘楚恬.极性

  # --- 第1段：物理层判决 ---
  echo ""
  echo "--- [2] 物理层(统一执行引擎) ---"
  let j1 = 天平(我, 刘楚恬)
  let 结论str = if j1.结论 == eqLeft: "左沉A>B" elif j1.结论 == eqRight: "右沉A<B" else: "平"
  echo "  A综合值=" & $(我.值 * 10 + 我.能量 * 5)
  echo "  B综合值=" & $(刘楚恬.值 * 10 + 刘楚恬.能量 * 5)
  echo "  判决: " & 结论str & " (差=" & $j1.差 & ")"

  # --- 第2段：声调层 ---
  echo ""
  echo "--- [3] 声调层(100调判决) ---"
  let toneRes = 声调判决(我.值, 刘楚恬.值)
  echo "  |" & $我.值 & " - " & $刘楚恬.值 & "| = " & toneRes

  # --- 第3段：字体层 ---
  echo ""
  echo "--- [4] 字体层(三维投影) ---"
  let vis1 = 字体投影(我)
  let vis2 = 字体投影(刘楚恬)
  echo "  我→ " & vis1.描述
  echo "  刘楚恬→ " & vis2.描述

  # --- 第4段：镜像层 ---
  echo ""
  echo "--- [5] 镜像层(空间+时间+听觉+视觉) ---"
  let sm = 空间镜像(我, 刘楚恬)
  let tm = 时间镜像(我, 刘楚恬)
  echo "  空间: " & sm.描述
  echo "  时间: " & tm.音名 & " " & formatFloat(tm.频率, ffDecimal, 1) & "Hz 振幅" & formatFloat(tm.振幅, ffDecimal, 3)

  # --- 第5段：关系层 ---
  echo ""
  echo "--- [6] 关系层(公路网) ---"
  let road = 建立公路(我, 刘楚恬)
  echo "  建立公路:我↔刘楚恬 路总和=" & $road
  echo "  极性差=" & $abs(我.极性 - 刘楚恬.极性) & " → " & 关系性质(abs(我.极性 - 刘楚恬.极性))
  echo "  我.已连: " & $我.已连

  # --- 第6段：冰箱时间线推进 ---
  echo ""
  echo "--- [7] 冰箱时间线(推进7个周期) ---"
  for tick in 1..7:
    冰.滴答()
    if tick mod 2 == 0:
      # 偶数周期：推进物理层进位
      for _, p in c.池:
        if p.层级 < tick: p.层级 = tick
    # 每3个周期重新判决一次
    if tick == 3 or tick == 6:
      let jj = 天平(我, 刘楚恬)
      echo "    [t" & $tick & "] 重判决=" & (if jj.结论 == eqLeft: "左沉" elif jj.结论 == eqEqual: "平" else: "右沉") &
           " 差=" & $jj.差 & " 时钟=" & $冰.时钟

  echo ""
  echo "  最终时钟: " & $冰.时钟
  echo "  各容器能量:"
  for adr, p in c.池:
    echo "    #" & align($adr, 2) & " " & align(p.锚点, 8) &
         "值=" & align($p.值, 4) & " 能=" & align($p.能量, 3) &
         " 层=" & $p.层级 & " 连=" & $p.已连.len

  echo ""
  echo "========================================="
  echo " v1.4 Six-Module Integration OK"
  echo "========================================="
