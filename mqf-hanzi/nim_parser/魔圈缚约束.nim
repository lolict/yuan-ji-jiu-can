## 满全法 - 魔圈缚·最大公约数约束系统
## 核心命题：约束 = 把并集换算成交集
##
## 角色分工：
##   毛利兰：表面属性（模/面/名）
##   工藤新一：结构核心（骨/头/体）
##   灰原哀：约束后的产物（行页/行业），并集→交集
##   清官：执行约束的规则引擎
##   魔圈缚：约束制定者
##
## 约束逻辑：
##   最大公约数(GCD) = 最省力状态
##   公倍数以GCD为根基
##   所有并集通过约束换算成交集

