    范畴表*: Table[string, 范畴]
    清官引擎*: seq[string]   ## 执行约束的记录日志

# ============ 数学基础：GCD/LCM ============
proc gcd*(a, b: int): int =
  ## 最大公约数：寻找两个数的共同根基
  var x = a
  var y = b
  while y != 0:
    let t = y
    y = x mod y
    x = t
  return x

proc lcm*(a, b: int): int =
  ## 最小公倍数：以GCD为根基的扩展
  if a == 0 or b == 0: return 0
  return (a * b) div gcd(a, b)

proc gcd_of_list*(xs: seq[int]): int =
  ## 多个数的最大公约数 = 共同约束
  if xs.len == 0: return 1
  var result = xs[0]
  for i in 1..<xs.len:
    result = gcd(result, xs[i])
  return result

# ============ 约束核心：并集→交集 ============
proc 约束*(系统: 魔圈缚, 范畴名: string, 约束名称: string): 范畴 =
  ## 核心操作：把并集换算成交集
  ## 输入：一个大范畴（并集）
  ## 输出：约束后的精简范畴（交集）
  if not 系统.范畴表.hasKey(范畴名): return nil
  let 原始 = 系统.范畴表[范畴名]
  let 规则 = 系统.约束规则表[约束名称]
  
  var 约束后: 范畴
  new(约束后)
  约束后.名称 = 原始.名称 & "（约束后）"
  约束后.原始大小 = 原始.元素.len
  约束后.约束规则 = 约束名称

  ## 用GCD约束筛选元素：
  ## 保留的位置必须是GCD的整数倍
  var 筛选后: seq[string] = @[]
  for i, 元素 in 原始.元素:
    if i mod 规则.最大公约数 == 0:
      筛选后.add(元素)
  
  if 筛选后.len == 0 and 原始.元素.len > 0:
    ## 至少保留第一个（根基）
    筛选后.add(原始.元素[0])
  
  约束后.元素 = 筛选后
  约束后.约束后大小 = 筛选后.len
  
  系统.清官引擎.add("执行约束[" & 约束名称 & "]：" & 范畴名 & " " & $原始.元素.len & "→" & $筛选后.len & " 省力比:" & $(规则.省力比))
  
  系统.范畴表[约束后.名称] = 约束后
  return 约束后

# ============ 清官引擎 ============
proc 注册约束*(系统: 魔圈缚, 名称: string, gcd值: int, 描述: string = "") =
  ## 清官注册一条约束规则
  var 规则: 约束规则
  new(规则)
  规则.名称 = 名称
  规则.描述 = 描述
  规则.最大公约数 = gcd值
  规则.省力比 = if gcd值 > 0: 1.0 / float(gcd值) else: 1.0
  ## LCM以GCD为根基
  规则.最小公倍数 = gcd值 * 2
  系统.约束规则表[名称] = 规则

proc 注册范畴*(系统: 魔圈缚, 名称: string, 元素: seq[string]) =
  ## 注册一个范畴（并集）
  var cat: 范畴
  new(cat)
  cat.名称 = 名称
  cat.元素 = 元素
  cat.原始大小 = 元素.len
  cat.约束后大小 = 元素.len
  cat.约束规则 = "未约束"
  系统.范畴表[名称] = cat

proc 清官执行*(系统: 魔圈缚, 范畴名: string, 约束名: string): 范畴 =
  ## 清官执行约束，将并集换算成交集
  result = 约束(系统, 范畴名, 约束名)

# ============ 角色注册 ============
proc 注册角色*(系统: 魔圈缚, 名称: string, 属性层: 属性层, 描述: string, 范畴: seq[string]) =
  var r: 角色
