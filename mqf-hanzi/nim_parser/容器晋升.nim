# ============ 异构容器定义 ============
type
  容器类型* = enum
    颜色容器    # 颜色符号
    近义词容器  # 近义词符号
    同义词容器  # 同义词符号
    动物容器    # 动物符号
    草类容器    # 草类符号
    韵母容器    # 韵母符号
    声母容器    # 声母符号
    定义容器    # 概念定义符号

  容器* = ref object
    名称*: string
    类型*: 容器类型
    符号*: seq[string]      # 容器内所有符号
    层级*: int              # 自己的层级深度
    饱和*: bool             # 用完未
    已用*: int              # 已消耗到哪个位置
    出生时间*: int          # 创建时间戳（时间串联用）
    接近度*: float          # 与当前活跃容器的亲密值

# ============ 异构容器组 ============
type
  容器管理器* = ref object
    所有容器*: seq[容器]
    当前活跃*: int          # 当前正在用的容器
    时间线*: int            # 时间戳计数器
    历史记录*: seq[string]  # 用了哪些容器的什么符号

# ============ 创建容器 ============
proc 创建容器(名称: string, 类型: 容器类型, 符号: seq[string], 层级: int): 容器 =
  new(result)
  result.名称 = 名称
  result.类型 = 类型
  result.符号 = 符号
  result.层级 = 层级
  result.饱和 = false
  result.已用 = 0
  result.出生时间 = 0
  result.接近度 = 0.0

