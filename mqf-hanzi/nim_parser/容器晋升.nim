## 满全法 - 异构容器层级晋升系统
## 不是十进制循环，而是用完一个容器跳到下一个相近容器
## 每个容器都是异构的：颜色 ≠ 近义词 ≠ 动物 ≠ 草类
## 用时间串联所有容器的空间，用完层级就晋升

import tables
