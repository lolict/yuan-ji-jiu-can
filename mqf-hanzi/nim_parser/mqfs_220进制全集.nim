type
  容器类型* = enum
    ct数字    # 0-9
    ct声母    # 50个
    ct韵母    # 60+110个
    ct颜色    # 21色
    ct笔画    # 36种
    ct五笔    # 25键
    ct部首    # 20个
    ct汉字    # 完整字符

  惩罚等级* = enum
    pl禁止, pl高惩罚, pl中惩罚, pl低惩罚, pl奖励
  
  铆合效果* = enum
    re谐波    # 两符号频率共振
    re对比度  # 形成视觉/语义反差
    re抵消    # 相互抵消或中和
    re增幅    # 效果放大
    re化合    # 产生全新含义
    re无效    # 无作用

  ## 惩法规则：两个容器符号拼接时的惩罚判定
proc 惩法*(容器A: 容器类型, 符号A: string
          , 容器B: 容器类型, 符号B: string
          , 符号AIdx, 符号BIdx: int): tuple[等级: 惩罚等级, 铆合: 铆合效果] =
  ## 惩法核心逻辑：跨容器拼接不是自由的，需要付出代价或满足条件
  ##
  ## 惩罚计算依据：
  ## 1. 索引距离 — 两符号在各自容器中的位置距离
  ## 2. 极性匹配 — 奇数索引与偶数索引的匹配关系
  ## 3. 层级同步 — 两容器当前层级是否一致
  
  let 距离 = abs(符号AIdx - 符号BIdx)
  let 同奇偶 = (符号AIdx mod 2) == (符号BIdx mod 2)
  let 层级差 = ord(容器A) - ord(容器B)
  
  # 规则1：符号索引距离小于3 → 高惩罚（太过接近=冗余）
  if 距离 < 3:
    return (pl高惩罚, re抵消)
  
  # 2：奇偶匹配 → 奖励（谐振）
  if 同奇偶 and 距离 > 10:
    return (pl奖励, re谐波)
  
  # 3：层级差过大 → 惩罚（大容器不能直接拼接小容器）
  if abs(层级差) > 3:
    return (pl高惩罚, re抵消)
  
  # 4：相邻容器 → 化合奖励
  if abs(层级差) == 1:
    return (pl奖励, re化合)
  
  # 5：跨三层以上 → 禁止
  if abs(层级差) > 5:
    return (pl禁止, re无效)
  
  # 默认：中惩罚
  result = (pl中惩罚, re对比度)

  ## 私有锚点保护：我(1) 与 刘楚恬(0) 永不产生惩罚
proc 锚点保护*(符号A, 符号B: string): bool =
  ## 当两个符号分别是锚点"我"和"刘楚恬"时，所有惩罚归零
  let 锚点集 = ["我", "1", "刘楚恬", "0"]
  result = (符号A in 锚点集) and (符号B in 锚点集)

