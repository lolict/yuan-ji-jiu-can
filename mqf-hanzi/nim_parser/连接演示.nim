## 满全法 - 清官编码 + 容器晋升 连接演示
## 证明：清官编码的声母/韵母/颜色容器可以接入容器晋升的用完即晋升逻辑
## 规则：用完声母容器 → 跳到韵母容器 → 跳到颜色容器 → 跳到近义词容器

import unicode

# ============ 清官编码容器 ============
type
  清官符号* = ref object
    声母*: string
    韵母*: string
    声调*: int
    颜色*: string
    字节码*: byte

  清官容器* = ref object
    声母表*: seq[string]
    韵母表*: seq[string]
    颜色表*: seq[string]
    当前声索引*: int
    当前韵索引: int
    当前色索引: int
    计数: int

# ============ 容器晋升管理器 ============
type
  晋升阶段* = enum
    声母阶段, 韵母阶段, 颜色阶段, 近义词阶段, 草类阶段, 完成

  晋升管理器* = ref object
    声母容器*: 清官容器
    阶段*: 晋升阶段
    消耗计数: int
    输出序列: seq[string]

# ============= 清官容器方法 ============
proc 初始明清官容器*(): 清官容器 =
  new(result)
  result.声母表 = @[
    "b", "p", "m", "f", "d", "t", "n", "l",
    "g", "k", "h", "j", "q", "x",
    "zh", "ch", "sh", "r", "z", "c", "s", "y", "w"
  ]
  result.韵母表 = @[
    "a1", "a2", "a3", "a4", "o1", "o2", "o3", "o4",
    "e1", "e2", "e3", "e4", "i1", "i2", "i3", "i4",
    "u1", "u2", "u3", "u4", "v1", "v2", "v3", "v4",
    "ai1", "ai2", "ai3", "ai4", "ei1", "ei2", "ei3", "ei4",
    "ao1", "ao2", "ao3", "ao4", "ou1", "ou2", "ou3", "ou4",
    "an1", "an2", "an3", "an4", "en1", "en2", "en3", "en4",
    "ang1", "ang2", "ang3", "ang4", "eng1", "eng2", "eng3", "eng4",
    "ong1", "ong2", "ong3", "ong4", "er1", "er2", "er3", "er4"
  ]
  result.颜色表 = @[
    "妃", "粉", "彤", "赤", "棕", "绛", "赭",
    "缃", "金", "黄", "褐", "黧", "乌", "黑",
    "缥", "翠", "绿", "青", "苍", "黛", "玄"
  ]
  result.当前声索引 = 0
  result.当前韵索引 = 0
  result.当前色索引 = 0
  result.计数 = 0

proc 下一个声母*(c: 清官容器): string =
  if c.当前声索引 >= c.声母表.len:
    return ""  # 容器耗尽
  let s = c.声母表[c.当前声索引]
  c.当前声索引 += 1
  return s

proc 下一个韵母*(c: 清官容器): string =
  if c.当前韵索引 >= c.韵母表.len:
    return ""  # 容器耗尽
  let s = c.韵母表[c.当前韵索引]
  c.当前韵索引 += 1
  return s

proc 下一个颜色*(c: 清官容器): string =
  if c.当前色索引 >= c.颜色表.len:
    return ""  # 容器耗尽
  let s = c.颜色表[c.当前色索引]
  c.当前色索引 += 1
  return s

# ============ 晋升级别近义词容器 ============
type
  近义词容器* = ref object
    数据*: seq[string]
    位置*: int

proc 创建近义词容器*(数据: seq[string]): 近义词容器 =
  new(result)
  result.数据 = 数据
  result.位置 = 0

proc 下一个*(c: 近义词容器): string =
  if c.位置 >= c.数据.len: return ""
  let s = c.数据[c.位置]
  c.位置 += 1
  return s

# ============ 晋升管理器 ============
proc 初始化管理器*(): 晋升管理器 =
  new(result)
  result.声母容器 = 初始明清官容器()
  result.阶段 = 声母阶段
  result.消耗计数 = 0
  result.输出序列 = @[]

# ============ 消耗 + 晋闭合 =
proc 消耗*(m: 晋升管理器): string =
  case m.阶段:
  of 声母阶段:
    let s = m.声母容器.下一个声母()
    if s == "":
      m.阶段 = 韵母阶段
      return m.消耗()  # 递归晋升
    m.输出序列.add("声母:" & s)
    return s
  of 韵母阶段:
    let s = m.声母容器.下一个韵母()
    if s == "":
      m.阶段 = 颜色阶段
      return m.消耗()  # 递归晋升
    m.输出序列.add("韵母:" & s)
    return s
  of 颜色阶段:
    let s = m.声母容器.下一个颜色()
    if s == "":
      m.阶段 = 近义词阶段
      return m.消耗()  # 递归晋升
    m.输出序列.add("颜色:" & s)
    return s
  of 近义词阶段:
    # 创建临时近义词容器
    var 近义词 = 创建近义词容器(@["温和", "温暖", "温柔", "体贴", "亲切"])
    var 结果 = 近义词.下一个()
    if 结果 == "":
      m.阶段 = 草类阶段
      return m.消耗()  # 晋升到草类
    m.输出序列.add("近义词:" & 结果)
    return 结果
  of 草类阶段:
    var 草类 = 创建近义词容器(@["兰", "蕙", "芷", "蘅", "荃", "荪", "萱"])
    var 结果 = 草类.下一个()
    if 结果 == "":
      m.阶段 = 完成
      return "[全部完成]"
    m.输出序列.add("草类:" & 结果)
    return 结果
  of 完成:
    return "[全部完成]"

# ============ 运行演示 ============
when isMainModule:
  echo "=== 满全法：清官编码 + 容器晋升 连接演示 ==="
  echo "=== 规则：声母用完 → 跳到韵母 → 跳到颜色 → 跳到近义词 ==="
  echo ""
  
  var 管理器 = 初始化管理器()
  
  echo "声母表: " & $管理器.声母容器.声母表.len & " 个"
  echo "韵母表: " & $管理器.声母容器.韵母表.len & " 个 (带声调标记)"
  echo "颜色表: " & $管理器.声母容器.颜色表.len & " 个"
  echo ""
  
  echo "--- 连续消耗 50 次，观察自动晋升 ---"
  for i in 1..50:
    let 结果 = 管理器.消耗()
    if 结果 == "[全部完成]":
      echo "  t=" & $i & ": *** 所有容器耗尽，系统完成 ***"
      break
    var 阶段名 = ""
    if 管理器.阶段 == 声母阶段: 阶段名 = "[声]"
    elif 管理器.阶段 == 韵母阶段: 阶段名 = "[韵]"
    elif 管理器.阶段 == 颜色阶段: 阶段名 = "[色]"
    elif 管理器.阶段 == 近义词阶段: 阶段名 = "[近]"
    else: 阶段名 = "[完]"
    echo "  t=" & $i & " " & 阶段名 & " " & 结果
  
  echo ""
  echo "--- 消耗序列（前30条）---"
  for i, 记录 in 管理器.输出序列:
    if i >= 30: break
    echo "  " & $i & ": " & 记录
  
  echo ""
  echo "--- 容器最终状态 ---"
  echo "  声母: " & $管理器.声母容器.当前声索引 & "/" & $管理器.声母容器.声母表.len
  echo "  韵母: " & $管理器.声母容器.当前韵索引 & "/" & $管理器.声母容器.韵母表.len
  echo "  颜色: " & $管理器.声母容器.当前色索引 & "/" & $管理器.声母容器.颜色表.len
  echo "  当前阶段: " & $管理器.阶段
  
  echo ""
  echo "=== 连接验证通过 ==="
  echo "=== 清官编码的三个容器用完即晋升，完整接入层级晋升系统 ==="
