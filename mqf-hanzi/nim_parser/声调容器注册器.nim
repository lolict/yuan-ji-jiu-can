## 满全法 - 声调容器注册器
## 100声调 = 容器状态×反馈层级的完整编码
##
## 五维属性：
##   维度1: 声调值（传统四声 + 自定义扩展）
##   维度2: 容器状态（阴/阳/平）
##   维度3: 碰撞反馈（正/负/绝缘）
##   维度4: 自我感知位（0=纯反射, 1=观察到自己在反射）
##   维度5: 资源连线（权值 = 此次发声消耗/获得的资源刻度）
##
## 声调不是"声音的高低变化"
## 声调 = "容器在碰撞中的姿态"

import tables
import sequtils
import strutils

# ============ 碰撞反馈 ============
type
  碰撞反馈* = enum
    cfPositive   ## 正：对方容器接受了此次碰撞
    cfNegative   ## 负：对方容器拒绝了此次碰撞
    cfInsulated  ## 绝缘：碰撞未到达对方容器

# ============ 容器状态（阴阳） ============
type
  容器状态* = enum
    csYin   ## 阴：容器处于接收态
    csYang  ## 阳：容器处于发出态
    csPing  ## 平：容器处于中性漂浮态

# ============ 自我感知位 ============
type
  感知层级* = enum
    plReactive    ## 纯反射：碰撞→反应，无需自我
    plObserving   ## 观察：我能看到自己在反应
    plSelfAware   ## 自感知：我知道"我在观察自己反应"

# ============ 声调单元 ============
type
  声调单元* = object
    地址* : int              ## 声调整体地址（单值寻址）
    声调值* : int             ## 传统调类 1-100
    容器状态* : 容器状态      ## 此声调对应的容器发出态
    反馈类型* : 碰撞反馈      ## 此声调碰撞后得到的反馈类型
    感知位* : 感知层级       ## 此声调的自我感知层级
    权值* : int              ## 此次碰撞消耗/获得的资源刻度（正=获得，负=消耗）
    名称* : string           ## 声调命名
    相位* : int              ## 九宫相位（声调在容器内的空间位置）
    笔画序* : int            ## 笔画顺序对应的地址

# ============ 声调容器 ============
type
  声调容器* = object
    声调表* : seq[声调单元]
    总量* : int

# ============================================================================
# 初始化100声调系统
# ============================================================================
proc 初始化声调容器*(): 声调容器 =
  result.声调表 = @[]
  result.总量 = 100

  # ------- 第1层：基础四声（1-4）-------
  # 阴平/阳平/上声/去声 = 汉语传统四声
  for i in 1..4:
    var u: 声调单元
    u.地址 = i
    u.声调值 = i
    u.容器状态 = csPing
    u.反馈类型 = cfPositive
    u.感知位 = plReactive
    u.权值 = 0
    u.相位 = 4  # 中心
    u.笔画序 = i
    u.名称 = case i:
      of 1: "阴平"
      of 2: "阳平"
      of 3: "上声"
      of 4: "去声"
      else: "未知"
    result.声调表.add(u)

  # ------- 第2层：轻声/入声（5-10）-------
  for i in 5..10:
    var u: 声调单元
    u.地址 = i
    u.声调值 = i
    u.容器状态 = csYin
    u.反馈类型 = cfInsulated
    u.感知位 = plReactive
    u.权值 = -1  # 轻声消耗资源（被忽略）
    u.笔画序 = i
    u.名称 = "轻声入声簇" & $(i - 4)
    # 九宫四角
    u.相位 = case (i - 5) mod 4:
      of 0: 0  # 左上
      of 1: 2  # 右上
      of 2: 6  # 左下
      else: 8  # 右下
    result.声调表.add(u)

  # ------- 第3层：阴阳变调（11-40）-------
  # 传统四声 × 阴阳二态 = 8种基础变调，再×变调位置（首/中/尾）
  var tick = 11
  for 基 in 1..4:             # 基础四声
    for 态 in [csYin, csYang]: # 阴阳二态
      for 位 in 0..2:          # 位置：首/中/尾
        if tick <= 40:
          var u: 声调单元
          u.地址 = tick
          u.声调值 = tick
          u.容器状态 = 态
          u.反馈类型 = case 态:
            of csYang: cfPositive
            of csYin: cfInsulated
            else: cfNegative
          u.感知位 = plObserving
          u.权值 = if 态 == csYang: +1 else: -1
          u.笔画序 = 基 * 3 + 位
          u.名称 = "变调" & $基 & (if 态 == csYang: "阳" else: "阴") & ["首", "中", "尾"][位]
          u.相位 = 基 * 2 + 位  # 分布在九宫
          result.声调表.add(u)
          tick += 1

  # ------- 第4层：情境调（41-70）-------
  # 与容器素材绑定：同韵母在不同容器素材中声调不同
  # 例："好"在"好物"vs"好听"中声调不同 = 碰撞到了不同的容器材质
  for i in 41..70:
    var u: 声调单元
    u.地址 = i
    u.声调值 = i
    # 情境调的容器状态由外部碰撞决定
    u.容器状态 = case (i - 41) mod 3:
      of 0: csYin
      of 1: csYang
      else: csPing
    u.反馈类型 = cfNegative  # 情境调默认碰撞后暂时未确定
    u.感知位 = plObserving
    u.权值 = 0  # 情境调暂时阴阳未判
    u.笔画序 = i - 30  # 笔画序相对压缩
    u.名称 = "情境调" & $(i - 40)
    u.相位 = (i - 41) mod 9  # 分散在九宫
    result.声调表.add(u)

  # ------- 第5层：反射调（71-100）-------
  # 声调本身成为了观察者：我能观察自己在发音
  for i in 71..100:
    var u: 声调单元
    u.地址 = i
    u.声调值 = i
    u.容器状态 = csPing
    u.反馈类型 = cfPositive
    u.感知位 = plSelfAware   # 自感知
    u.权值 = +2  # 自感知层获得正资源（因为"知道自己在做"本身就是资源积累）
    u.笔画序 = i - 60
    u.名称 = "反射调" & $(i - 70)
    u.相位 = (i - 71) mod 9
    result.声调表.add(u)

  result.总量 = result.声调表.len

# ============================================================================
# 查询方法
# ============================================================================

proc 按地址*(容器: 声调容器, 地址: int): 声调单元 =
  for u in 容器.声调表:
    if u.地址 == 地址:
      return u
  # 默认返回
  var u: 声调单元
  u.地址 = -1
  u.名称 = "未找到"
  return u

proc 按感知层级*(容器: 声调容器, 层级: 感知层级): seq[声调单元] =
  result = @[]
  for u in 容器.声调表:
    if u.感知位 == 层级:
      result.add(u)

proc 碰撞*(容器: 声调容器, 我的地址: int, 对方状态: 容器状态): 碰撞反馈 =
  let 我的 = 容器.按地址(我的地址)
  if 我的.容器状态 == csYang and 对方状态 == csYin:
    result = cfPositive
  elif 我的.容器状态 == csYin and 对方状态 == csYang:
    result = cfInsulated
  else:
    result = cfNegative

proc 总资源评估*(容器: 声调容器): int =
  result = 0
  for u in 容器.声调表:
    result += u.权值

# ============================================================================
# 运行演示
# ============================================================================
when isMainModule:
  echo "========================================="
  echo "满全法 - 100声调容器注册器"
  echo "========================================="
  echo ""

  let 声调 = 初始化声调容器()

  echo "总声调数: " & $声调.总量
  echo ""

  echo "--- 第1-4：基础四声（纯反射层）---"
  for i in 1..4:
    let u = 声调.按地址(i)
    echo "  地址=" & $u.地址 & " " & u.名称 & " 状态=" & $u.容器状态 &
         " 反馈=" & $u.反馈类型 & " 感知=" & $u.感知位 &
         " 权值=" & $u.权值 & " 相位=" & $u.相位 & " 笔画序=" & $u.笔画序

  echo ""
  echo "--- 第5-10：轻声/入声（纯反射·绝缘态）---"
  for i in 5..10:
    let u = 声调.按地址(i)
    echo "  地址=" & $u.地址 & " " & u.名称 & " 状态=" & $u.容器状态 &
         " 反馈=" & $u.反馈类型 & " 权值=" & $u.权值

  echo ""
  echo "--- 第11-40：阴阳变调（观察层·带阴阳反馈）---"
  for i in 11..40:
    let u = 声调.按地址(i)
    if i <= 18:  # 只展示前几个
      echo "  地址=" & $u.地址 & " " & u.名称 & " 状态=" & $u.容器状态 &
           " 反馈=" & $u.反馈类型 & " 权值=" & $u.权值

  echo ""
  echo "--- 第41-70：情境调（观察层·碰撞材质决定）---"
  for i in 41..70:
    let u = 声调.按地址(i)
    if i <= 48:
      echo "  地址=" & $u.地址 & " " & u.名称 & " 状态=" & $u.容器状态 &
           " 反馈=" & $u.反馈类型 & " 权值=" & $u.权值 & " 相位=" & $u.相位

  echo ""
  echo "--- 第71-100：反射调（自感知层·知道自己在发音）---"
  for i in 71..100:
    let u = 声调.按地址(i)
    if i <= 78:
      echo "  地址=" & $u.地址 & " " & u.名称 & " 状态=" & $u.容器状态 &
           " 反馈=" & $u.反馈类型 & " 权值=" & $u.权值 & " 感知=" & $u.感知位

  echo ""
  echo "--- 按感知层级统计 ---"
  let 纯反射 = 声调.按感知层级(plReactive)
  let 观察层 = 声调.按感知层级(plObserving)
  let 自感知 = 声调.按感知层级(plSelfAware)
  echo "  纯反射声调数: " & $纯反射.len & " (地址 1-10)"
  echo "  观察声调数:   " & $观察层.len & " (地址 11-70)"
  echo "  自感知声调数: " & $自感知.len & " (地址 71-100)"

  echo ""
  echo "--- 总资源评估（全100声调的阴阳合计）---"
  echo "  总权值: " & $声调.总资源评估()

  echo ""
  echo "--- 碰撞测试 ---"
  let 反馈1 = 声调.碰撞(1, csYin)   # 阴平（平）碰撞对方接收态
  let 反馈2 = 声调.碰撞(15, csYin) # 变调（阳）碰撞对方接收态
  let 反馈3 = 声调.碰撞(6, csYang) # 轻声（阴）碰撞对方发出态
  echo "  地址1(平) 碰 Yin → " & $反馈1
  echo "  地址15(阳)碰 Yin → " & $反馈2
  echo "  地址6(阴) 碰 Yang→ " & $反馈3
  echo ""
  echo "=== 声调容器注册器就绪 ==="
  echo "=== 声调 = 容器碰撞姿态，不是声音高低 ==="
