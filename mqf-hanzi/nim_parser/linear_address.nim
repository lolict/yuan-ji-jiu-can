## 满全法 - 单值线性选址
##
## 三维几何位置只用一个数值表示。不写坐标。
## 起点对齐 + 终点对齐（纵向）+ 高度对齐（楼梯）
## 终点用尽 → 纵向进位；纵向用尽 → 高度进位
## 高度用尽 → 齐（符号用完的结束态）
##
## 呼唤 = @数值。数值自带算法，不需要写坐标。

import math
import tables

# ===================================================================
# 1. 主轴配置
# ===================================================================

type
  主轴* = object
    起点*: int                # 起始对齐值
    终点*: int                # 终止对齐值（纵向）
    宽度*: int                = 10    # 每层长度符号数
    高度*: int                = 10    # 每层纵向符号数
    层宽*: int                = 100   # 每层尺寸(10×10扇区)

  扇区* = object
    序号*: int
    层号*: int
    横向*: int                 # 层内横向扇区
    纵向*: int                 # 层内纵向扇区
    高度*: int                 # 当前层在第几阶楼梯
    对齐态*: string            # 起点/纵向/高度/齐

  地址对象* = object
    地址*: int
    标识*: string              # 注册地址的命名空间
    扇区*: 扇区               # 算法自动推算的位置
    活性*: bool

# ===================================================================
# 2. 单值→几何位置（纯算法，不存储坐标）
# ===================================================================

proc 选址*(数值: int, 主轴: 主轴): 扇区 =
  ## 从一个数值自动推算出在三维空间的位置。
  ## 数值自带几何意义，不需要外部坐标输入。
  let 总宽 = 主轴.宽度
  let 总高 = 主轴.高度
  let 层面积 = 总宽 * 总高

  let 层号 = 数值 div 层面积
  let 层内 = 数值 mod 层面积
  let 横向 = 层内 mod 总宽
  let 纵向 = 层内 div 总宽
  let 高度 = 层号
  let 对齐态 = if 横向 < 总宽 - 1: "起点对齐"
               elif 纵向 < 总高 - 1: "纵向进位"
               elif 高度 > 0: "高度对齐"
               else: "齐"

  result = 扇区(
    序号: 数值,
    层号: 层号,
    横向: 横向,
    纵向: 纵向,
    高度: 高度,
    对齐态: 对齐态
  )

# ===================================================================
# 3. 进位算法（自动纵向、自动高度）
# ===================================================================

proc 起点用尽*(s: 扇区, 主轴: 主轴): bool =
  ## 起点对齐的符号用完 → 自动进位到纵向关系
  result = s.横向 >= 主轴.宽度 - 1

proc 终点用尽*(s: 扇区, 主轴: 主轴): bool =
  ## 纵向符号用完 → 自动进位到高度
  result = s.纵向 >= 主轴.高度 - 1 and 起点用尽(s, 主轴)

proc 高度用尽*(s: 扇区): bool =
  ## 高度也用完 → 齐（结束态）
  result = s.对齐态 == "齐"

proc 纵向进位*(当前: int, 主轴: 主轴): int =
  ## 横向/终点符号用尽，自动纵向进位
  let s = 选址(当前, 主轴)
  if 起点用尽(s, 主轴) and not 终点用尽(s, 主轴):
    result = 当前 + 1   # 纵向向前一步
  else:
    result = 当前

proc 高度进位*(当前: int, 主轴: 主轴): int =
  ## 纵向也用尽，自动上升一层（搭楼梯）
  let s = 选址(当前, 主轴)
  if 终点用尽(s, 主轴):
    result = 当前 + 1   # 高度上升
  else:
    result = 当前

# ===================================================================
# 4. 寄存器——地址自带算法，呼唤只用数值
# ===================================================================

type
  寄存器* = object
    主轴*: 主轴
    对象表*: seq[地址对象]
    下一地址*: int
    门牌索引*: Table[string, int]

proc 新寄存器*(宽度: int = 10, 高度: int = 10): 寄存器 =
  var r: 寄存器
  r.主轴 = 主轴(起点: 0, 终点: 0, 宽度: 宽度, 高度: 高度, 层宽: 宽度 * 高度)
  r.下一地址 = 0
  r.门牌索引 = initTable[string, int]()
  result = r

proc 登记*(r: var 寄存器, 标识: string): int =
  ## 登记一个新对象，返回唯一地址数值
  let 门牌 = r.下一地址
  let sector = 选址(门牌, r.主轴)
  let obj = 地址对象(地址: 门牌, 标识: 标识, 扇区: sector, 活性: true)
  r.对象表.add(obj)
  r.门牌索引[标识] = 门牌
  r.下一地址 += 1
  result = 门牌

proc at*(r: var 寄存器, 地址: int): string =
  ## @地址：呼唤=对齐+算法自动展开
  if 地址 < 0 or 地址 >= r.对象表.len:
    return "越界"
  let s = 选址(地址, r.主轴)
  let obj = r.对象表[地址]
  if not obj.活性: return "失活"
  r.对象表[地址].扇区 = s
  result = "@" & $地址 & "_" & s.对齐态

# ===================================================================
# 5. 对齐对齐——数值序列的位置推算表
# ===================================================================

proc 对齐*(r: 寄存器, 数值: int): string =
  let s = 选址(数值, r.主轴)
  result = "@" & $数值 & " -> (" & $s.横向 & "," & $s.纵向 & "," & $s.高度 & ") " & s.对齐态

proc 对齐开始*(r: 寄存器): int =
  ## 重新开始一个新的起点
  result = r.下一地址

proc 对齐结尾*(r: 寄存器, 数值: int): int =
  ## 标记当前段结束，自动进位
  let s = 选址(数值, r.主轴)
  if 起点用尽(s, r.主轴):
    result = 数值 + 1
  else:
    result = 数值

