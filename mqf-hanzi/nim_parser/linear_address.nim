## 满全法 - 单值线性选址
##
## 接口只有两个：对齐开始、对齐结尾。
## 算法自带：终点用尽→纵向进位；纵向用尽→高度进位；高度用尽→回到起点。
## 不写坐标。不写三个数值。一个数值=三维位置。
## 每次调用只需要地址。地址自带算法。算法只声明一次，全部地址共享。

import tables
import sequtils
import strutils

# ===================================================================
# 共享算法规则（只声明一次，全部地址共享）
# ===================================================================

type
  对齐阶段* = enum
    asStart,      # 起点对齐
    asEnd,        # 终点对齐（纵向即将进位）
    asLongitude,  # 纵向关系（层级进位中）
    asCarry       # 高度楼梯（爬高·下一层）

  地址* = int                     # 一个数值 = 三维几何位置

  共享算法* = object
    起点对齐*: int                 # 默认开始
    终点对齐*: int                 # 纵向结束
    纵向进位*: int                 # 横向用完=纵向
    高度楼梯*: int                 # 纵向用完=爬高
    齐*: int                       # 全部用完=回到起点
    命名空间*: string              # 共享注册域名称
    进制*: int                    # 地址的进制基底

# ===================================================================
# 算法的单一声明（所有地址共享·不重复写）
# ===================================================================

let 默认算法* = 共享算法(
  起点对齐: 0,                    # 起点·起点对齐   → 默认共享开始
  终点对齐: 9,                    # 横向用尽        → 自动纵向关系
  纵向进位: 10,                   # 纵向开始        → 进位到层级
  高度楼梯: 99,                   # 纵向用尽        → 爬高一层
  齐:        100,                 # 高也用尽        → 全部用完,回起点
  命名空间: "满全法单值地址空间",
  进制:      10
)

# ===================================================================
# 选址算法：一个数值→它在哪个对齐阶段，不需要坐标
# ===================================================================

proc 对齐开始*(地址: 地址): int =
  ## 默认共享的起点——新的开始
  result = 默认算法.起点对齐

proc 对齐结尾*(地址: 地址): int =
  ## 终点对齐：这层的对齐态用完了
  result = 默认算法.终点对齐

proc 进位到纵向*(地址: 地址): int =
  ## 起点用尽→自动进位到纵向关系
  result = 地址 + 默认算法.纵向进位

proc 进位到高度*(地址: 地址): int =
  ## 纵向用尽→自动高度楼梯（爬高一层）
  result = 地址 + 默认算法.高度楼梯

proc 齐了*(地址: 地址): bool =
  ## 高度也用尽→回到新的起点
  let 当前阶段 = 地址 mod 默认算法.齐
  result = 当前阶段 == 默认算法.高度楼梯

proc 阶段*(地址: 地址, 算法: 共享算法): 对齐阶段 =
  let r = 地址 mod 算法.齐
  if r < 算法.终点对齐:
    result = asStart
  elif r == 算法.终点对齐:
    result = asEnd
  elif r < 算法.高度楼梯:
    result = asLongitude
  else:
    result = asCarry

# ===================================================================
# 地址注册：地址自带算法·不需要单独写坐标
# ===================================================================

type
  地址对象* = object
    地址*: 地址                    # 唯一数值 = 三维位置
    标识*: string                  # 注册在这个地址上的名称
    依赖*: seq[地址]               # 外包给谁（不重新发明）

  注册表* = object
    算法*: 共享算法                 # 全部地址共享的算法
    对象*: seq[地址对象]
    名称索引*: Table[string, 地址]

proc 新注册表*(算法: 共享算法 = 默认算法): 注册表 =
  var r: 注册表
  r.算法 = 算法
  r.名称索引 = initTable[string, 地址]()
  result = r

proc 登记*(r: var 注册表, 标识: string, 依赖: seq[地址] = @[]): 地址 =
  ## 登记一个新对象，返回唯一地址
  ## 地址自带算法，不需要写坐标
  let 门牌 = r.对象.len
  let obj = 地址对象(地址: 门牌, 标识: 标识, 依赖: 依赖)
  r.对象.add(obj)
  r.名称索引[标识] = 门牌
  result = 门牌

# ===================================================================
# 呼唤（@地址 = 调用，不写坐标）
# ===================================================================

proc at*(r: var 注册表, 地址: 地址): string =
  ## 呼唤=对齐整个地址，不需要写坐标
  if 地址 < 0 or 地址 >= r.对象.len:
    return "越界"
  let s = 阶段(地址, r.算法)
  let 阶段名 = case s
    of asStart:     "起点对齐"
    of asEnd:       "终点对齐"
    of asLongitude: "纵向进位"
    of asCarry:     "高度楼梯"
  var 结果 = "@" & $地址 & "_" & 阶段名 & " " & r.对象[地址].标识
  if 齐了(地址):
    结果 &= " (齐→回起点)"
  if r.对象[地址].依赖.len > 0:
    结果 &= " 外包→" & r.对象[地址].依赖.mapIt("@" & $it).join(",")
  result = 结果

# ===================================================================
# 演示
# ===================================================================

when isMainModule:
  var r = 新注册表()

  echo "════════════════════════════════════════"
  echo "  单值线性选址·共享算法·不用坐标"
  echo "════════════════════════════════════════"
  echo ""
  echo "共享算法规则:"
  echo "  起点对齐:" & $默认算法.起点对齐
  echo "  终点对齐:" & $默认算法.终点对齐
  echo "  纵向进位:" & $默认算法.纵向进位
  echo "  高度楼梯:" & $默认算法.高度楼梯
  echo "  齐:      " & $默认算法.齐
  echo "  命名空间:" & 默认算法.命名空间
  echo ""

  # 登记120个对象（地址自带算法·不写坐标）
  var 门牌列表: seq[地址] = @[]
  for i in 0..<120:
    let dep: seq[地址] = if i > 0 and i mod 5 == 0: @[i - 5] else: @[]
    门牌列表.add(r.登记("obj" & $i, dep))

  echo "══ @地址呼唤 ══"
  for addr in [0, 5, 9, 10, 50, 99, 100, 101, 119]:
    echo "  " & r.at(addr)

  echo ""
  echo "══ 对齐开始/结尾 ══"
  echo "  对齐开始 = " & $对齐开始(0)
  echo "  对齐结尾 = " & $对齐结尾(0)

  echo ""
  echo "══ 进位链（起点→纵向→高度→齐→回起点）══"
  echo "  addr 0  : " & r.at(0)
  echo "  addr 9  : " & r.at(9)
  echo "  addr 99 : " & r.at(99)
  echo "  addr 100: " & r.at(100)
  echo "  addr 199: " & r.at(199)
  echo "  addr 200: " & r.at(200)

  echo ""
  echo "一次调用·@地址·算法即位置·齐则回起点"
  echo "════════════════════════════════════════"
