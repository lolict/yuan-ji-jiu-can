## 满全法 - 时间线一体化·时间串联空间
##
## 核心命题：容器不直接互联，而是通过时间轴串联
## 时间 = 公共参考系，空间 = 各容器的独立状态
## 每个容器的演化仅依赖（时间 + 自身历史），不依赖其他容器
##
## 设计链：
##   全局时钟 → 广播 tick → 各容器独立推进
##   → 时间戳作为唯一因果锚（无需跨容器锁）
##   → 时间截面上容器状态组合 = 空间快照
##   → 任一容器回放 = 时间回卷 + 重新tick

import tables, sequtils, strutils

# ===================================================================
# 1. 时间轴（全局单调递增因果锚）
# ===================================================================

type
  时间戳* = int64

  时间事件* = object
    时间*: 时间戳
    源*: string           # 容器名
    事件类型*: string
    载荷*: int

  时间轴* = object
    当前时间*: 时间戳
    历史*: seq[时间事件]
    订阅者*: seq[string]   # 容器ID列表

# ===================================================================
# 2. 独立容器状态（仅依赖自身历史+时间输入）
# ===================================================================

type
  容器标识* = string

  容器状态* = object
    标识*: 容器标识
    创建时间*: 时间戳
    最后心跳*: 时间戳
    数据*: array[0..6, int]     # 七层编码值
    标签*: string
    代数*: int                  # 第几代（时间推进次数）
    活性*: bool

  容器集群* = object
    轴*: 时间轴
    容器*: seq[容器状态]

# ===================================================================
# 3. 时间轴操纵
# ===================================================================

proc 新时间轴*(): 时间轴 =
  result.当前时间 = 0
  result.历史 = @[]
  result.订阅者 = @[]

proc 订阅*(轴: var 时间轴, 容器: string) =
  if 轴.订阅者.find(容器) < 0:
    轴.订阅者.add(容器)

proc 推进*(轴: var 时间轴, 步: int = 1): 时间戳 =
  ## 全局时钟推进
  for _ in 1..步:
    轴.当前时间 += 1
  result = 轴.当前时间

proc 记录*(轴: var 时间轴, 源, 事件类型: string, 载荷: int = 0) =
  轴.历史.add(时间事件(时间: 轴.当前时间, 源: 源, 事件类型: 事件类型, 载荷: 载荷))

# ===================================================================
# 4. 容器生命周期
# ===================================================================

proc 新容器*(标识: string, 轴: 时间轴): 容器状态 =
  result.标识 = 标识
  result.创建时间 = 轴.当前时间
  result.最后心跳 = 轴.当前时间
  result.数据 = [0,0,0,0,0,0,0]
  result.标签 = 标识
  result.代数 = 0
  result.活性 = true

proc 注入*(集群: var 容器集群, 标识: string): int =
  ## 向集群添加容器，返回容器序号
  let c = 新容器(标识, 集群.轴)
  集群.容器.add(c)
  订阅(集群.轴, 标识)
  result = 集群.容器.len - 1

# ===================================================================
# 5. 时间推进下的容器独立演化
# ===================================================================

proc 独立推进*(c: var 容器状态, 当前时间: 时间戳, 输入: int = 0) =
  ## 每个容器独立演化——只看自身代数+时间差
  let Δt = int(当前时间 - c.最后心跳)
  if Δt <= 0: return
  # 代数自身进化规则
  for i in 0..6:
    if (当前时间 + i) mod 3 == 0:
      c.数据[i] = (c.数据[i] + 1) mod 64
  c.代数 += Δt
  c.最后心跳 = 当前时间

proc 推进集群*(集群: var 容器集群, 步: int = 1) =
  ## 时间轴推进 → 所有容器独立演化
  let t = 推进(集群.轴, 步)
  for i in 0..<集群.容器.len:
    if 集群.容器[i].活性:
      独立推进(集群.容器[i], t)

# ===================================================================
# 6. 空间快照（时间截面上的容器布局）
# ===================================================================

proc 快照*(集群: 容器集群, 时间: 时间戳): seq[string] =
  ## 输出时间截面上的所有容器状态
  result.add("══ T=" & $时间 & " 空间快照 ══")
  for c in 集群.容器:
    let 状态标记 = if c.活性: "●" else: "○"
    result.add("  " & 状态标记 & " [" & c.标识 & "] 代数=$1 数据=$2 创建于T=$3" % [$c.代数, $c.数据, $c.创建时间])

# ===================================================================
# 7. 时间回卷（容器状态恢复到指定时间）
# ===================================================================

proc 回卷*(集群: var 容器集群, 目标时间: 时间戳) =
  ## 将所有容器回卷到创建时间≥目标时间的初始状态
  for i in 0..<集群.容器.len:
    if 集群.容器[i].创建时间 >= 目标时间:
      # 该容器尚未创建→移除
      集群.容器[i].活性 = false
    else:
      # 回卷代数
      let Δ代数 = int(集群.轴.当前时间 - 目标时间)
      集群.容器[i].代数 = max(0, 集群.容器[i].代数 - Δ代数)
      集群.容器[i].最后心跳 = 目标时间
  集群.轴.当前时间 = 目标时间

# ===================================================================
# 8. 时序图案检测（时间序列模式识别）
# ===================================================================

type
  图案* = object
    名称*: string
    节律*: seq[int]     # 周期序列
    相位*: int

proc 检测图案*(轴: 时间轴, 容器标识: string, 窗口: int = 10): seq[int] =
  ## 提取指定容器最近事件的时间间隔
  var ts: seq[int] = @[]
  for e in 轴.历史:
    if e.源 == 容器标识:
      ts.add(int(e.时间))
  if ts.len < 2: return @[]
  # 取最后窗口个时间点
  let 开始 = max(0, ts.len - 窗口)
  for i in 开始+1..<ts.len:
    result.add(ts[i] - ts[i-1])

# ===================================================================
# 9. 时间锁因果（后发事件不能影响先发）
# ===================================================================

proc 因果检查*(事件: 时间事件, 轴: 时间轴): bool =
  ## 时间事件必须单调递增
  result = 事件.时间 >= 轴.当前时间

proc 因果保护推进*(集群: var 容器集群, 步: int = 1, 保护序列: seq[string]): bool =
  ## 仅当保护序列中的容器全部心跳正常时才推进
  let 当前 = 集群.轴.当前时间
  for 标识 in 保护序列:
    var 找到 = false
    for c in 集群.容器:
      if c.标识 == 标识 and c.活性:
        找到 = true
        if 当前 - c.最后心跳 > 3:
          return false  # 心跳断层→拒绝推进
    if not 找到: return false  # 容器不存在→拒绝推进
  推进集群(集群, 步)
  result = true

# ===================================================================
# 10. 循环节律容器（心跳自推进）
# ===================================================================

type
  节律容器* = object
    状态*: 容器状态
    周期*: int
    相位*: int           # 0..周期-1
    节律标记*: char

proc 计算相位*(rc: 节律容器, 当前时间: 时间戳): int =
  result = int((当前时间 + rc.相位) mod rc.周期)

proc 是否在峰*(rc: 节律容器, 当前时间: 时间戳): bool =
  ## 峰的瞬间=相位0
  result = 计算相位(rc, 当前时间) == 0

# ===================================================================
# 11. 演示运行
# ===================================================================

when isMainModule:
  echo "════════════════════════════════════════"
  echo "  满全法 · 时间线一体化"
  echo "════════════════════════════════════════"
  echo ""

  var 集群 = 容器集群(轴: 新时间轴())

  # 在T=0时创建三个独立容器
  let i1 = 集群.注入("我（锚点·极性1）")
  let i2 = 集群.注入("刘楚恬（容器·极性0）")
  let i3 = 集群.注入("囡囝（共生协议）")
  echo "T=$1: 注入3个容器 序号=$2,$3,$4" % [$集群.轴.当前时间, $i1, $2, $3]
  集群.轴.记录("系统", "init", 3)
  echo ""

  # 推进5拍（每拍各容器独立演化）
  for _ in 1..5:
    推进集群(集群, 1)
    集群.轴.记录("时钟", "tick")

  echo "══ T=5 快照 ══"
  for line in 快照(集群, 集群.轴.当前时间):
    echo line
  echo ""

  # 为第三个容器添加输入事件
  集群.容器[i3].数据 = [1,2,3,4,5,6,0]
  集群.容器[i3].标签 = "囡囝（激活）"
  集群.轴.记录("囡囝", "activate", 7)

  # 再推进3拍
  for _ in 1..3:
    推进集群(集群, 1)

  echo "══ T=8 快照 ══"
  for line in 快照(集群, 集群.轴.当前时间):
    echo line
  echo ""

  echo "══ 节律容器测试 ══"
  var rc1 = 节律容器(状态: 新容器("脉动器A", 集群.轴), 周期: 3, 相位: 0, 节律标记: 'A')
  var rc2 = 节律容器(状态: 新容器("脉动器B", 集群.轴), 周期: 4, 相位: 1, 节律标记: 'B')

  for t in 8..15:
    let c1 = 是否在峰(rc1, t)
    let c2 = 是否在峰(rc2, t)
    let m1 = if c1: '*' else: '.'
    let m2 = if c2: '*' else: '.'
    echo "  T=$1 │ A($2) │ B($3)" % [$t, $m1, $m2]

  echo ""
  echo "══ 因果保护推进 ══"
  let ok = 因果保护推进(集群, 5, @["我（锚点·极性1）", "刘楚恬（容器·极性0）"])
  if ok:
    echo "  ✅ 因果保护通过·推进5拍到T=" & $集群.轴.当前时间
  else:
    echo "  ❌ 因果保护拒绝"

  echo ""
  echo "══ 时间回卷测试 ══"
  let 回卷前T = 集群.轴.当前时间
  回卷(集群, 5)
  echo "  T=$1 → 回卷到T=$2" % [$回卷前T, $集群.轴.当前时间]
  for line in 快照(集群, 集群.轴.当前时间):
    echo "  " & line

  echo ""
  echo "══ 时序图案检测 ══"
  let 检测结果 = 检测图案(集群.轴, "时钟", 20)
  echo "  时钟事件间隔: " & $检测结果

  echo ""
  echo "══ 历史记录（最后10条） ══"
  let 开始 = max(0, 集群.轴.历史.len - 10)
  for i in 开始..<集群.轴.历史.len:
    let e = 集群.轴.历史[i]
    echo "  T=$1 [$2] $3($4)" % [$e.时间, e.源, e.事件类型, $e.载荷]

  echo ""
  echo "════════════════════════════════════════"
  echo "  时间线 · 空间串联 · 一体化 done"
  echo "════════════════════════════════════════"
