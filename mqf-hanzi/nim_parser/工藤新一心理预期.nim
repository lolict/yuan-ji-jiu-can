# ============ 心理预期结构 ============
type
  心理预期* = ref object
    声母*: string
    韵母*: string
    声调*: int
    颜色*: string
    数字*: int        # 阿拉伯数字映射
    字节码*: byte     # 最终编码（目标：1字节）
    压缩率*: float    # 节省了多少

# ============ 编码计算 ============
## 把 声母(5bit) + 韵母(4bit) + 声调(2bit) 压缩到 1字节
## 总组合数 = 23声母 × 16韵母 × 4声调 = 1472 种
## 用 11bit 可以表示 (2048 > 1472)
## 但我们要压缩到 1字节 = 8bit，所以需要巧妙的映射

proc 编码*(声母idx: int, 韵母idx: int, 声调idx: int): byte =
  ## 声母 0-22 用 5bit
  ## 韵母 0-15 用 4bit
  ## 声调 0-3 用 2bit
  ## 共 11bit，需要压缩
  ## 策略：线性组合 mod 256
  let 线性码 = 声母idx * 64 + 韵母idx * 4 + 声调idx
  return byte(线性码 mod 256)

proc 解码*(码: byte): tuple[声母, 韵母, 声调: int] =
  let 线性码 = int(码)
  let 声调 = 线性码 mod 4
  let 韵母 = (线性码 div 4) mod 16
  let 声母 = (线性码 div 64)
  return (声母, 韵母, 声调)

# ============ 心理预期工厂 ============
proc 创建预期*(声母: string, 韵母: string, 声调: int, 颜色: string, 数字: int): 心理预期 =
  new(result)
  result.声母 = 声母
  result.韵母 = 韵母
  result.声调 = 声调
  result.颜色 = 颜色
  result.数字 = 数字
  
  # 找到对应索引
  var 声idx = -1
  for i, s in 声母表:
    if s == 声母: 声idx = i
  
  var 韵idx = -1
  for i, y in 基础韵母:
    if y == 韵母: 韵idx = i
  
  var 调idx = 声调 - 1
  if 调idx < 0 or 调idx > 3: 调idx = 0
  
  result.字节码 = 编码(声idx, 韵idx, 调idx)
  result.压缩率 = 10.0 / 1.0

# ============ 颜色选映射 ============
## 根据线性码选颜色（均匀分布在颜色表上）
proc 码到颜色*(码: byte): string =
  let idx = int(码) mod 颜色数
  return 颜色表[idx]

# ============ 打印 ============
proc 打印预期*(exp: 心理预期) =
  echo "  " & exp.声母 & "+" & exp.韵母 & "+" & $exp.声调 & "声 → 颜色:" & exp.颜色 & " 数字:" & $exp.数字 & " 字节码:0x" & toHex2(exp.字节码) & " 压缩率:" & $exp.压缩率 & "x"

