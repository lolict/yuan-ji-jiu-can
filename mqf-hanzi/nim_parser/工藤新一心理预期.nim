## 满全法 - 工藤新一心理预期完整映射
## 以感知为底层逻辑：声母 + 韵母 + 声调 + 颜色 + 数字
## 目标：最省内存，一个符号=一个字节，不依赖外部映射表
##
## 心理预期就是：工藤新一他想要什么？
## 他想要：一个字节就能代表"妈"这个音的全部信息
## 声母m + 韵母a + 声调1 + 颜色妃 → 压缩到1字节
## 这就是清官编码的逻辑

proc toHex2(b: byte): string =
  let hexChars = "0123456789ABCDEF"
  let hi = int(b) shr 4
  let lo = int(b) and 0x0F
  return $hexChars[hi] & $hexChars[lo]

