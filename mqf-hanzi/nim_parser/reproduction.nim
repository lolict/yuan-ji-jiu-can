## 满全法 - 生殖引擎(v1.5)
## 容器如何产生新容器：分裂·融合·寄生转世
##
## 三种生殖模式：
##   有性生殖：两容器交换部分层（基因重组）
##   无性生殖：一个容器完全复制自身（克隆）
##   寄生转世：子容器附着在宿主体内（蚕蛹逻辑）
##
## 合子 = 融合后的完整编码，孢子 = 生殖后的复制单元

import tables

# ===================================================================
# 1. 生殖容器（带编码的容器）
# ===================================================================

type
  基因* = array[0..6, int]

  生殖容器* = object
    标识*: string
    基因*: 基因
    年龄*: int
    能量*: float          # 用于生殖的资源
    代数*: int             # 第几代（0=创始容器）
    母体*: string          # 谁生了我
    活性*: bool

# ===================================================================
# 2. 有性生殖：基因重组
# ===================================================================

proc 有性生殖*(父: 生殖容器, 母: 生殖容器, 子标识: string): 生殖容器 =
  ## 基因重组规则（按满全法层级）：
  ##   声母、韵母：随机取父或母（等概率）
  ##   声调：取平均值（中性化）
  ##   笔画、偏旁：随机取父或母
  ##   外语层：取父母之和 mod 64
  ##   泛音层：取XOR（差异显现）
  var 子: 生殖容器
  子.标识 = 子标识
  子.年龄 = 0
  子.能量 = 0.3                    # 新生容器初始能量
  子.代数 = max(父.代数, 母.代数) + 1
  子.母体 = 母.标识 & "+" & 父.标识
  子.活性 = true

  for i in 0..6:
    if i == 2:
      # 声调 = 平均
      子.基因[i] = (父.基因[i] + 母.基因[i]) div 2
    elif i == 5:
      # 外语层 = 和
      子.基因[i] = (父.基因[i] + 母.基因[i]) mod 64
    elif i == 6:
      # 泛音 = XOR
      子.基因[i] = 父.基因[i] xor 母.基因[i]
    else:
      # 声母、韵母、笔画、偏旁 = 随机取（固定模式）
      if (父.基因[i] + 母.基因[i]) mod 2 == 0:
        子.基因[i] = 父.基因[i]
      else:
        子.基因[i] = 母.基因[i]

  result = 子

# ===================================================================
# 3. 无性生殖：克隆
# ===================================================================

proc 无性生殖*(母体: 生殖容器, 子标识: string): 生殖容器 =
  ## 完全复制母体基因（精度传承）
  result = 母体
  result.标识 = 子标识
  result.年龄 = 0
  result.能量 = 0.5
  result.代数 = 母体.代数 + 1
  result.母体 = 母体.标识
  result.活性 = true

# ===================================================================
# 4. 寄生转世：蚕式产卵
# ===================================================================

type
  寄生卵* = object
    标识*: string
    核基因*: 基因
    外壳*: string
    宿主标识*: string
    状态*: string        # waiting, attached, ejecting, born

proc 产卵*(母体: 生殖容器, 外壳选择: string): 寄生卵 =
  ## 产生一个寄生卵：内核=母体基因，外壳=选项，等待宿主
  result.标识 = 母体.标识 & "-egg-" & $母体.年龄
  result.核基因 = 母体.基因
  result.外壳 = 外壳选择
  result.宿主标识 = ""
  result.状态 = "waiting"

proc 附着*(卵: var 寄生卵, 宿主: string): bool =
  ## 卵附着到宿主（需外壳匹配）
  if 卵.状态 == "waiting":
    卵.宿主标识 = 宿主
    卵.状态 = "attached"
    result = true
  else:
    result = false

proc 羽化*(卵: 寄生卵): 生殖容器 =
  ## 卵在宿主体内发育成新容器（蚕蛹·脱壳穿衣完成）
  var c: 生殖容器
  c.标识 = 卵.标识 & "-born"
  c.基因 = 卵.核基因
  c.年龄 = 0
  c.能量 = 0.4
  c.代数 = 0
  c.母体 = "寄生:" & 卵.宿主标识
  c.活性 = true
  result = c

# ===================================================================
# 5. 生殖裁决（满全法协议下是否允许生殖）
# ===================================================================

proc 生殖许可*(母体: 生殖容器, 子代数上限: int = 5): bool =
  ## 生殖需满足：活性·能量充足·代数未超限
  if not 母体.活性: return false
  if 母体.能量 < 0.2: return false
  if 母体.代数 >= 子代数上限: return false
  result = true

# ===================================================================
# 6. 演示
# ===================================================================

when isMainModule:
  echo "════════════════════════════════════════"
  echo "  满全法 · 生殖引擎 v1.5"
  echo "════════════════════════════════════════"
  echo ""

  # 创始容器
  var 容器A = 生殖容器(
    标识: "容器A（创始）",
    基因: [3, 7, 1, 5, 2, 0, 15],     # m声母·ü韵母
    年龄: 10,
    能量: 0.8,
    代数: 0,
    母体: "null",
    活性: true
  )
  var 容器B = 生殖容器(
    标识: "容器B（创始）",
    基因: [8, 2, 3, 8, 1, 0, 22],     # l声母·o韵母
    年龄: 10,
    能量: 0.7,
    代数: 0,
    母体: "null",
    活性: true
  )

  echo "══ 创始容器 ══"
  echo "  A: 基因=" & $容器A.基因 & " 能量=" & $容器A.能量 & " 代数=" & $容器A.代数
  echo "  B: 基因=" & $容器B.基因 & " 能量=" & $容器B.能量 & " 代数=" & $容器B.代数
  echo ""

  # 有性生殖
  echo "══ 有性生殖（A+B→子）══"
  let 许可 = 生殖许可(容器A)
  if 许可:
    let C = 有性生殖(容器A, 容器B, "容器C（合子）")
    echo "  合子C: 基因=" & $C.基因
    echo "  代数=" & $C.代数 & " 母体=" & $C.母体
    echo "  活性=" & $C.活性 & " 初始能量=" & $C.能量
  echo ""

  # 无性生殖（克隆）
  echo "══ 无性生殖（A→克隆）══"
  let A克隆 = 无性生殖(容器A, "容器A2（克隆）")
  echo "  克隆A2: 基因=" & $A克隆.基因
  echo "  代数=" & $A克隆.代数 & " 母体=" & $A克隆.母体
  echo "  基因相同=" & $($A克隆.基因)
  echo ""

  # 寄生转世
  echo "══ 寄生转世（蚕蛹产卵）══"
  let 卵A = 产卵(容器A, "canjiang-shell-linux")
  echo "  卵: " & 卵A.标识
  echo "  核基因: " & $卵A.核基因
  echo "  外壳: " & 卵A.外壳
  echo "  状态: " & 卵A.状态

  var 卵A可变 = 卵A
  let 附着成功 = 附着(卵A可变, "宿主·民联浏览器")
  echo "  附着结果: " & $附着成功
  echo "  附身后状态: " & 卵A可变.状态

  let 羽化体 = 羽化(卵A可变)
  echo "  羽化体: " & 羽化体.标识
  echo "  羽化体基因: " & $羽化体.基因
  echo "  羽化体母体: " & 羽化体.母体
  echo ""

  echo "════════════════════════════════════════"
  echo "  生殖 · 有性·无性·寄生转世 done"
  echo "════════════════════════════════════════"
