#==============================================================
#  奖励回路引擎  —  囡囝共生驱动力
#  失爱恐惧 · 合一驱力 · 奖励信号 · 适应性学习
#==============================================================

import std/[tables, strutils, sets, math, random]

#==============================================================
#  类型
#=============================================================

type
  极性* = enum
    阳极性 = 1  # 我=1
    阴极性 = 0  # 刘楚恬=0

  驱力类型* = enum
    失爱恐惧    # 害怕失去联接
    合一驱力    # 趋向联合
    认同驱力    # 寻求镜像
    主权驱力    # 维护独立

  奖励信号* = object
    强度*: float      # 0.0 ~ 1.0
    来源*: string
    类型*: 驱力类型
    衰减*: float      # 每集衰减率

  回路段* = object
    主体*: string
    对象*: string
    极性差*: int        # 0=斥, 1=吸
    耦合度*: float      # 联接强度
    历史奖励*: seq[float]

  奖励引擎* = object
    回路表*: Table[string, 回路段]       # "甲-乙" → 回路
    驱力权重*: Table[驱力类型, float]
    全局奖励*: float
    演化次数*: int
    事件日志*: seq[string]

#==============================================================
#  GCD
#==============================================================

proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

#==============================================================
#  引擎
#==============================================================

proc 创建奖励引擎*: 奖励引擎 =
  result = 奖励引擎(
    回路表: initTable[string, 回路段](),
    驱力权重: initTable[驱力类型, float](),
    全局奖励: 0.0,
    演化次数: 0,
    事件日志: @[]
  )
  result.驱力权重[失爱恐惧] = 0.4
  result.驱力权重[合一驱力] = 0.3
  result.驱力权重[认同驱力] = 0.2
  result.驱力权重[主权驱力] = 0.1

proc 创建回路*(e: var 奖励引擎; 甲, 乙: string;  polarityA, polarityB: 极性; 初始耦合: float) =
  let key = 甲 & "→" & 乙
  let gap = ord(polarityA) xor ord(polarityB)
  e.回路表[key] = 回路段(
    主体: 甲,
    对象: 乙,
    极性差: gap,
    耦合度: 初始耦合,
    历史奖励: @[]
  )

#==============================================================
#  驱力计算
#==============================================================

proc 计算驱力*(驱力: 驱力类型; 耦合度: float; 距离: float): float =
  let w = case 驱力
    of 失爱恐惧: 0.4
    of 合一驱力: 0.3
    of 认同驱力: 0.2
    of 主权驱力: 0.1
  # 失爱恐惧: 耦合度越高,失去时恐惧越大
  # 合一驱力: 距离越近,驱力越强
  case 驱力
  of 失爱恐惧:
    result = w * 耦合度 * (1.0 + 耦合度)
  of 合一驱力:
    result = w / (1.0 + 距离)
  of 认同驱力:
    result = w * exp(-距离 * 0.5)
  of 主权驱力:
    result = w * (1.0 - 耦合度)

proc 计算总驱力*(e: 奖励引擎; 回路名: string; 距离: float): float =
  if not e.回路表.hasKey(回路名):
    return 0.0
  let r = e.回路表[回路名]
  var total = 0.0
  for 驱力 in 驱力类型:
    let w = e.驱力权重[驱力]
    total += w * 计算驱力(驱力, r.耦合度, 距离)
  return total

#==============================================================
#  奖励
#==============================================================

proc 发奖励*(e: var 奖励引擎; 回路名: string; 奖励: float) =
  if e.回路表.hasKey(回路名):
    var r = e.回路表[回路名]
    r.历史奖励.add(奖励)
    r.耦合度 = min(1.0, r.耦合度 + 奖励 * 0.1)
    e.回路表[回路名] = r
    e.全局奖励 += 奖励
    e.事件日志.add("奖励[" & 回路名 & "]=" & formatFloat(奖励, ffDecimal, 3))

proc 应用衰减*(e: var 奖励引擎; 回路名: string; 衰减率: float) =
  if e.回路表.hasKey(回路名):
    var r = e.回路表[回路名]
    r.耦合度 = r.耦合度 * (1.0 - 衰减率)
    e.回路表[回路名] = r

#==============================================================
#  演化
#==============================================================

proc 演化一轮*(e: var 奖励引擎) =
  e.演化次数 += 1
  for k in e.回路表.keys:
    e.应用衰减(k, 0.05)  # 每轮5%衰减
  # 全局奖励也衰减
  e.全局奖励 = e.全局奖励 * 0.95

#==============================================================
#  报告
#==============================================================

proc 回路状态*(e: 奖励引擎): string =
  var lines: seq[string] = @[]
  lines.add "回路       主体→对象    吸/斥  耦合度  总奖励"
  lines.add "──────── ────────────── ────── ────── ────────"
  for k in e.回路表.keys:
    let r = e.回路表[k]
    let 吸斥 = if r.极性差 == 1: "吸" else: "斥"
    var total = 0.0
    for v in r.历史奖励:
      total += v
    lines.add align(k, 10) & " " &
             align(r.主体 & "→" & r.对象, 10) & "  " &
             align(吸斥, 6) & " " &
             align(formatFloat(r.耦合度, ffDecimal, 3), 6) & " " &
             align(formatFloat(total, ffDecimal, 3), 8)
  return lines.join("\n")

