#==============================================================
#  GCD
#==============================================================

proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

#==============================================================
#  64位坐标编码
# [容器族3位][流编号3位][相位3位][极性1位][主权54位]
#==============================================================

proc 编码*(主权: uint64; 族: 容器族; 流: 流编号;
           相位: 相位; 极性: 极性): uint64 =
  var coord: uint64 = 0
  coord = coord or (uint64(ord(族)) shl 61)       # bit 61-63
  coord = coord or (uint64(ord(流)) shl 58)       # bit 58-60
  coord = coord or (uint64(ord(相位)) shl 55)     # bit 55-57
  coord = coord or (uint64(ord(极性)) shl 54)     # bit 54
  coord = coord or (主权 and 0x003FFFFFFFFFFFFF'u64)  # bit 0-53
  return coord

proc 解码主权*(坐标: uint64): uint64 =
  return 坐标 and 0x003FFFFFFFFFFFFF'u64

proc 解码族*(坐标: uint64): 容器族 =
  return 容器族((坐标 shr 61) and 0x7'u64)

