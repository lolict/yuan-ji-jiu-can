proc 注册容器*(e: var 统一引擎; 名字: string; 主权: uint64;
               极性: 极性; 相位: 相位; 层: int) =
  let 族 = 容器族(主权 mod 8)
  let 坐标 = 编码(主权, 族, 预加载流, 相位, 极性)
  e.容器表[名字] = 容器(
    名字: 名字,
    主权: 主权,
    极性: 极性,
    相位: 相位,
    层: 层,
    族: 族,
    状态: 已注册,
    能量: 1.0,
    主坐标: 坐标
  )
  e.演化引擎.容器数 += 1
  e.日志.add("注册: " & 名字 & " @ 0x" & toHex(坐标))

proc 查容器*(e: 统一引擎; 名字: string):容器 =
  if e.容器表.hasKey(名字):
    return e.容器表[名字]
  return 容器()

#==============================================================
# 极性路由
#==============================================================

proc 路由*(e: var 统一引擎; 源: string; 目标: string): bool =
  if not e.容器表.hasKey(源) or not e.容器表.hasKey(目标):
    return false
  let cs = e.容器表[源]
  let ct = e.容器表[目标]
  let gap = ord(cs.极性) xor ord(ct.极性)
  let g = gcd(cs.主权, ct.主权)
  if g > 0:
    e.路由表[源] = 目标
    e.日志.add("路由: " & 源 & " → " & 目标 &
               " (极性=" & (if gap == 1: "吸" else: "斥") & ", 公约=0x" & toHex(g) & ")")
    return true
  return false

#==============================================================
#  八流统调
#==============================================================

proc 提交流*(e: var 统一引擎; 流: 流编号; 容器名: string): bool =
  if not e.容器表.hasKey(容器名):
    return false
  if not e.流状态[ord(流)]:
    e.流状态[ord(流)] = true
    e.演化引擎.活跃流 += 1
  e.日志.add("流[" & 流列表[ord(流)] & "] 处理: " & 容器名)
  return true

proc 激活八流*(e: var 统一引擎) =
  for i in 0..<8:
    let 流 = 流编号(i)
    e.流状态[i] = true
    for name in e.容器表.keys:
      var c = e.容器表[name]
      c.状态 = 已激活
      e.容器表[name] = c
  e.演化引擎.活跃流 = 8
  e.日志.add("八流全部激活")

#==============================================================
#  系统演化
#==============================================================

proc 心跳*(e: var 统一引擎): float =
  e.演化引擎.系统时间 += 1
  e.系统脉搏 *= 0.99
  if e.系统脉搏 < 0.5:
    e.系统脉搏 = 1.0
    e.日志.add("系统重置脉搏=1.0")
  e.演化引擎.全局能量 = 0.0
  for name in e.容器表.keys:
    e.演化引擎.全局能量 += e.容器表[name].能量
  result = e.系统脉搏

proc 健康检查*(e: 统一引擎): bool =
  e.演化引擎.活跃流 == 8 and e.演化引擎.容器数 >= 5

