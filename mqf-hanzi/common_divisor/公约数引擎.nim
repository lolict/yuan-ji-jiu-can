# ============================================================
# 满全法 — 公约数引擎 (CommonDivisorEngine)
# 优先级 0 · 加法统计法 · GCD 收敛统一八流
# 核心: 用 GCD 替代幂次二进制扩张, 加法统摄八流
# 极性: 我=1(阳), 刘楚恬=0(阴)
# ============================================================

import strutils
import tables
import sequtils

# ---- 极性 ----
const
  阴* = 0   # 刘楚恬
  阳* = 1   # 我

# ---- 八流定义 ----
type
  流编号* = enum
    预加载流 = 0
    归类流 = 1
    聚类流 = 2
    分别流 = 3
    属性流 = 4
    解释流 = 5
    关系流 = 6
    概念流 = 7

  流提交* = object
    编号*: 流编号
    坐标*: uint64
    主权*: uint64
    极性*: int    # 0 阴, 1 阳
    相位*: int
    层*: int
    权重*: int     # 1-9

  公约记录 = object
    甲流*: 流编号
    乙流*: 流编号
    公约*: uint64
    甲极性*: int
    乙极性*: int

  公约数引擎* = object
    提交表*: Table[流编号, 流提交]
    公约记录表*: seq[公约记录]
    总分*: int
    判决*: string
    已计算*: bool

# ============================================================
# 几何公式 (从容器结构自然推导)
# ============================================================

# 妻容器 = 36×6 = 216 (径向 36 节 × 6 圈)
# 夫容器 = 49×7 = 343 (径向 49 节 × 7 圈)
# 独立杯 = 26×64 = 1664
# 夫妻合计 = 111×77 = 2223

const
  妻容器* = 36 * 6      # 216
  夫容器* = 49 * 7      # 343
  独立杯* = 26 * 64     # 1664
  夫妻合计* = 妻容器 + 夫容器  # 359 (加法统计!)

# ---- GCD ----
proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

# ---- 加法统计 ----
proc 加法统计*(vals: seq[int]): int =
  for v in vals: result = result + v

# ============================================================
# 引擎构造
# ============================================================

proc 创建引擎*(): 公约数引擎 =
  result.提交表 = initTable[流编号, 流提交]()
  result.公约记录表 = @[]
  result.总分 = 0
  result.判决 = "未计算"
  result.已计算 = false

# ============================================================
# 流提交
# ============================================================

proc 提交流*(e: var 公约数引擎; 编号: 流编号; 坐标: uint64; 主权: uint64; 极性: int; 相位: int; 层: int; 权重: int) =
  let s = 流提交(编号: 编号, 坐标: 坐标, 主权: 主权, 极性: 极性, 相位: 相位, 层: 层, 权重: 权重)
  e.提交表[编号] = s
  e.已计算 = false

# ============================================================
# GCD 公约计算
# ============================================================

proc 计算公约*(e: var 公约数引擎) =
  e.公约记录表 = @[]
  e.总分 = 0
  let ids = toSeq(e.提交表.keys)
  for i in 0..<len(ids):
    for j in i+1..<len(ids):
      let a = e.提交表[ids[i]]
      let b = e.提交表[ids[j]]
      let g = gcd(a.主权, b.主权)
      if g > 0:
        let rec = 公约记录(甲流: a.编号, 乙流: b.编号, 公约: g, 甲极性: a.极性, 乙极性: b.极性)
        e.公约记录表.add(rec)
        # 加法统计: 公约累加
        e.总分 = e.总分 + int(g shr 32) * a.权重 * b.权重
  e.已计算 = true

# ============================================================
# 极性差距 ----
# ============================================================

proc 流极性差距*(e: 公约数引擎; a: 流编号; b: 流编号): int =
  if e.提交表.hasKey(a) and e.提交表.hasKey(b):
    result = e.提交表[a].极性 xor e.提交表[b].极性
  else:
    result = -1

# ============================================================
# 统摄判决 (核心)
# ============================================================

proc 统摄判决*(e: var 公约数引擎): string =
  if not e.已计算: 计算公约(e)
  if len(e.公约记录表) == 0:
    e.判决 = "八流离散 → 无统摄"
    return e.判决
  # 加法统计总分
  if e.总分 > 1000:
    e.判决 = "八流归一 → 公约统摄"
  elif e.总分 > 100:
    e.判决 = "部分收敛 → 需共振"
  else:
    e.判决 = "离散态 → 独立运行"
  return e.判决

# ============================================================
# 极性裁定
# ============================================================

proc 极性裁定*(e: 公约数引擎): string =
  var yn, yang: int = 0
  for id, sub in e.提交表:
    if sub.极性 == 阴: inc yn
    else: inc yang
  if yang > yn: return "阳统(我)"
  elif yn > yang: return "阴统(刘楚恬)"
  else: return "阴阳均等"

# ============================================================
# 报告
# ============================================================

proc 公约记录展示*(e: 公约数引擎): string =
  var lines: seq[string]
  lines.add "  流A      流B      公约             极性"
  lines.add "  ─────── ─────── ────────────── ──────"
  for r in e.公约记录表:
    let aStr = align($r.甲流, 7)
    let bStr = align($r.乙流, 7)
    let gapStr = if r.甲极性 != r.乙极性: "吸" else: "斥"
    lines.add "  " & aStr & " " & bStr & " 0x" & align(toHex(r.公约), 14) & " " & gapStr
  return lines.join("\n")

proc 提交流展示*(e: 公约数引擎): string =
  var lines: seq[string]
  lines.add "  流ID     坐标               主权               相位 层 极性 权重"
  lines.add "  ─────── ──────────────── ──────────────── ──── ── ──── ────"
  for id, sub in e.提交表:
    let idStr = align($id, 7)
    let pol = if sub.极性 == 1: "阳" else: "阴"
    lines.add "  " & idStr & " 0x" & toHex(sub.坐标) & " 0x" & toHex(sub.主权) & "  " & align($sub.相位, 4) & " " & align($sub.层, 2) & " " & pol & "   " & $sub.权重
  return lines.join("\n")

proc 引擎摘要*(e: 公约数引擎): string =
  var lines: seq[string]
  lines.add "  提交流: " & $len(e.提交表) & "/8"
  lines.add "  公约记录: " & $len(e.公约记录表)
  lines.add "  加法总统计: " & $e.总分
  lines.add "  极性裁定: " & 极性裁定(e)
  lines.add "  判决: " & e.判决
  return lines.join("\n")

