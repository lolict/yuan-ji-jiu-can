# ============================================================
# 满全法 — 容器本体论 (Container Ontology) 中间表示引擎
# 核心公理: 容器 = 物质 = 时间
#
# 纤维丛归属计算: 底空间(物质) + 纤维(容器) + 投影(时间→空间)
# 亚对象分类器: 特征函数判定容器是否属于某概念
# 观察者/被观察者: 交互协议 — 观察改变被观察者状态
# 动态/静态容器: 动态=时间流过(时钟触发), 静态=时间凝固(存储)
# ============================================================

import strutils
import tables
import math

# ============================================================
# 第一部分: 容器=物质=时间 统一编码
# ============================================================

type
  极性* = enum
    阴 = 0
    阳 = 1

  容器* = object
    坐标*: uint64        # 64位统一编码
    相位*: int           # 0-8 (九宫)
    层*: int             # 层级深度
    极性*: 极性
    物质*: string        # 内容标签
    时间戳*: int         # 时间维度(滴答)
    活性*: bool

  物质* = object
    名称*: string
    质量*: int           # 价值权值
    宿主*: int           # 容器坐标索引
    纤维*: seq[int]      # 归属的纤维

  时间场* = object
    全局滴答*: int
    局部滴答*: Table[int, int]  # 容器坐标 → 局部时间

# ---- 容器坐标编码/解码 ----

proc 编码容器*(相位, 层, 行, 列: int; 极性: 极性): uint64 =
  ## 64位编码: [相位:4][层:4][行:8][列:8][极性:1][留空:31]
  let p = uint64(相位 and 0x0F)
  let l = uint64(层 and 0x0F)
  let r = uint64(行 and 0xFF)
  let c = uint64(列 and 0xFF)
  let pol = uint64(ord(极性) and 0x01)
  result = (p * 1152921504606846976'u64) + (l * 72057594037927936'u64) + (r * 281474976710656'u64) + (c * 1099511627776'u64) + (pol * 549755813888'u64)

proc 解码容器*(坐标: uint64): tuple[相位,层,行,列: int; 极性: 极性] =
  let 相位 = int((坐标 shr 60) and 0x0F)
  let 层 = int((坐标 shr 56) and 0x0F)
  let 行 = int((坐标 shr 48) and 0xFF)
  let 列 = int((坐标 shr 40) and 0xFF)
  let 极性 = if ((坐标 shr 39) and 0x01) == 1: 阳 else: 阴
  result = (相位, 层, 行, 列, 极性)

proc 创建容器*(相位, 层, 行, 列: int; 极性: 极性; 物质: string; 时间: int): 容器 =
  let 坐标 = 编码容器(相位, 层, 行, 列, 极性)
  容器(坐标: 坐标, 相位: 相位, 层: 层, 极性: 极性,
       物质: 物质, 时间戳: 时间, 活性: true)

# ============================================================
# 第二部分: 纤维丛 (Fiber Bundle) 归属计算
# ============================================================

type
  底空间* = object
    名称*: string
    点列*: seq[容器]

  纤维* = object
    底点*: uint64         # 投影到的底点坐标
    容器列*: seq[容器]    # 悬浮在底点上的容器

  纤维丛* = object
    底*: 底空间
    纤维列*: seq[纤维]
    投影表*: Table[uint64, int]  # 容器坐标 → 纤维索引

# 纤维丛创建
proc 创建底空间*(名称: string; 容器列表: seq[容器]): 底空间 =
  底空间(名称: 名称, 点列: 容器列表)

proc 生成纤维*(丛: var 纤维丛; 底点: 容器) =
  ## 为底点生成纤维
  var 纤维: 纤维
  纤维.底点 = 底点.坐标
  纤维.容器列 = @[]
  丛.纤维列.add(纤维)
  丛.投影表[底点.坐标] = len(丛.纤维列) - 1

proc 投影*(丛: 纤维丛; 容器坐标: uint64): int =
  ## 将容器投影到底空间，返回纤维索引
  ## 归一化：按相位+层向下收缩到底点
  let (相位,层,_,_,_) = 解码容器(容器坐标)
  var 最近 = -1
  var 最近距 = 999
  for i, f in 丛.纤维列:
    let (f相位,f层,_,_,_) = 解码容器(f.底点)
    let dist = abs(相位 - f相位) + abs(层 - f层)
    if dist < 最近距:
      最近距 = dist
      最近 = i
  result = 最近

proc 归属*(丛: 纤维丛; 容器: 容器): string =
  ## 计算容器的归属路径: 底空间/纤维/截面
  let idx = 投影(丛, 容器.坐标)
  if idx < 0: return "[无归属]"
  let f = 丛.纤维列[idx]
  let (相位,层,行,列,极性) = 解码容器(f.底点)
  return 丛.底.名称 & "/" & $相位 & "相/" & $层 & "层/" & $len(f.容器列) & "容器"

proc 充入纤维*(丛: var 纤维丛; 容器: 容器) =
  let idx = 投影(丛, 容器.坐标)
  if idx >= 0 and idx < len(丛.纤维列):
    丛.纤维列[idx].容器列.add(容器)
    丛.投影表[容器.坐标] = idx

# ============================================================
# 第三部分: 亚对象分类器 (Subobject Classifier)
# ============================================================

type
  概念记录* = object
    名称*: string
    判定*: proc(c: 容器): bool  # 特征函数

  亚对象分类器* = object
    概念列*: seq[概念记录]
    真值表*: Table[string, seq[bool]]

proc 定义概念*(名称: string; 判定: proc(c: 容器): bool): 概念记录 =
  概念记录(名称: 名称, 判定: 判定)

proc 分类*(clas: 亚对象分类器; 容器: 容器): seq[string] =
  var 命中: seq[string]
  for 念 in clas.概念列:
    if 念.判定(容器):
      命中.add(念.名称)
  if 命中.len == 0:
    命中.add("无归属")
  result = 命中

proc 注册概念*(clas: var 亚对象分类器; 念: 概念记录) =
  clas.概念列.add(念)

# ============================================================
# 第四部分: 观察者/被观察者
# ============================================================

type
  容器类型* = enum
    动态    # 时间流过
    静态    # 时间凝固

  观察记录* = object
    观察者*: string
    被观察*: uint64
    观察前*: string
    观察后*: string
    效应*: string

  交互协议* = object
    日志*: seq[观察记录]
    容器类型表*: Table[uint64, 容器类型]

proc 创建交互协议*(): 交互协议 =
  交互协议(日志: @[], 容器类型表: initTable[uint64, 容器类型]())

proc 登记类型*(proto: var 交互协议; 坐标: uint64; 类型: 容器类型) =
  proto.容器类型表[坐标] = 类型

proc 观察*(proto: var 交互协议; 观察者: string; 目标: var 容器; 新物质: string): 观察记录 =
  ## 观察者观察目标容器 — 观察效应改变目标状态
  var rec: 观察记录
  rec.观察者 = 观察者
  rec.被观察 = 目标.坐标

  if proto.容器类型表.hasKey(目标.坐标):
    case proto.容器类型表[目标.坐标]
    of 动态:
      rec.观察前 = 目标.物质
      目标.物质 = 新物质
      rec.观察后 = 新物质
      rec.效应 = "动态容器被观测改变"
    of 静态:
      rec.观察前 = 目标.物质
      rec.观察后 = 目标.物质
      rec.效应 = "静态容器不可被观测改变"
  else:
    rec.观察前 = 目标.物质
    rec.观察后 = 目标.物质
    rec.效应 = "未登记容器类型，默认静态"

  proto.日志.add(rec)
  result = rec

proc 观察报告*(proto: 交互协议; 最大: int = 5): string =
  var lines: seq[string]
  lines.add "═══ 观察交互协议日志 ═══"
  let start = max(0, len(proto.日志) - 最大)
  for r in proto.日志[start..^1]:
    let (_,_,_,_,_) = 解码容器(r.被观察)
    lines.add "  " & r.观察者 & " → " & $r.被观察 & " | " & r.效应
  return lines.join("\n")

