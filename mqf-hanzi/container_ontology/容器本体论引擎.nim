  echo "─────────────────────────────────"

  var 容器列表: seq[容器]
  容器列表.add(创建容器(0, 0, 0, 0, 阳, "天元", 0))
  容器列表.add(创建容器(1, 1, 2, 3, 阴, "水元", 1))
  容器列表.add(创建容器(2, 1, 5, 1, 阳, "火元", 2))
  容器列表.add(创建容器(4, 2, 7, 7, 阴, "山元", 3))
  容器列表.add(创建容器(5, 2, 3, 4, 阳, "泽元", 4))
  容器列表.add(创建容器(8, 3, 1, 1, 阴, "人元", 5))

  for c in 容器列表:
    let (相位,层,行,列,极性) = 解码容器(c.坐标)
    let polStr = if 极性 == 阳: "阳" else: "阴"
    echo "  容器: " & c.物质 & " | 坐标=" & $c.坐标 & " | 相位=" & $相位 & " 层=" & $层 & " 行=" & $行 & " 列=" & $列 & " | " & polStr

  echo ""

  echo "【第二部分】纤维丛归属计算"
  echo "─────────────────────────────────"

  var 丛: 纤维丛
  丛.底 = 创建底空间("满全法底空间", @[])
  丛.纤维列 = @[]
  丛.投影表 = initTable[uint64, int]()

  # 用2个0层容器作为底点
  for c in 容器列表:
    if c.层 == 0 or c.层 == 1:
      生成纤维(丛, c)

  # 把所有容器投影到纤维
  for c in 容器列表:
    充入纤维(丛, c)

  echo "  底空间: " & 丛.底.名称
  echo "  纤维数: " & $len(丛.纤维列)
  for i, f in 丛.纤维列:
    let (相位,层,_,_,_) = 解码容器(f.底点)
    echo "  纤维" & $i & ": 底点=相" & $相位 & "层" & $层 & " → " & $len(f.容器列) & "个悬浮容器"

  echo ""
  echo "  归属路径:"
  for c in 容器列表:
    echo "    " & c.物质 & " → " & 归属(丛, c)

  echo ""

  echo "【第三部分】亚对象分类器"
  echo "─────────────────────────────────"

  var 分类器: 亚对象分类器
  分类器.概念列 = @[]
  分类器.真值表 = initTable[string, seq[bool]]()

  # 定义概念: 天级以上(层≤1)
  proc 天级以上判定(c: 容器): bool = c.层 <= 1
  注册概念(分类器, 定义概念("天级", 天级以上判定))

  # 定义概念: 阳类容器
  proc 阳类判定(c: 容器): bool = c.极性 == 阳
  注册概念(分类器, 定义概念("阳", 阳类判定))

  # 定义概念: 人元(相位8)
  proc 人元判定(c: 容器): bool = c.相位 == 8
  注册概念(分类器, 定义概念("人元", 人元判定))

  # 定义概念: 物质长度≥3
  proc 复杂物质判定(c: 容器): bool = c.物质.len >= 3
  注册概念(分类器, 定义概念("复杂物质", 复杂物质判定))

  echo "  注册概念: 天级, 阳, 人元, 复杂物质"
  echo ""
  echo "  分类结果:"
  for c in 容器列表:
    let 命中 = 分类(分类器, c)
    echo "    " & c.物质 & " ← [" & 命中.join(", ") & "]"

  echo ""

  echo "【第四部分】观察者/被观察者"
  echo "─────────────────────────────────"

  var 协议 = 创建交互协议()

  # 将容器分为动态和静态
  for c in 容器列表:
    if c.层 <= 1:
      登记类型(协议, c.坐标, 动态)
    else:
      登记类型(协议, c.坐标, 静态)

  echo "  动态容器(时间流过): 天级"
  echo "  静态容器(时间凝固): 层级≥2"
  echo ""

  # 观察场景
  var c0 = 容器列表[0]  # 天元 — 动态
  var 效应 = 观察(协议, "观察者甲", c0, "观测后的天元")
  echo "  观察: " & 效应.观察者 & "观" & $效应.被观察 & " → " & 效应.效应

  var c3 = 容器列表[3]  # 山元 — 静态
  效应 = 观察(协议, "观察者乙", c3, "不可改变的山元")
  echo "  观察: " & 效应.观察者 & "观" & $效应.被观察 & " → " & 效应.效应

  echo ""
  echo 观察报告(协议, 5)

  echo ""
  echo "═══════════════════════════════════════════"
  echo "容器本体论引擎演示完毕"
  echo "容器=物质=时间，纤维丛归属，亚对象分类，观察者效应"
  echo "═══════════════════════════════════════════"
