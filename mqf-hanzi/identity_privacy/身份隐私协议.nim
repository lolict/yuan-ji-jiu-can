      化解名(名: "纤维丛漫步者", 极性: 0, 域: "哲学"),
      化解名(名: "时钟雕刻者", 极性: 1, 域: "技术"),
    ],
    当前披露: 化身级,
    签名密钥: "MQF.YIN-YANG." & $getTime().toUnix(),
    创建时间: int(getTime().toUnix())
  )

# ---- 落款生成 ----

proc 签名容器*(id: 身份; 级别: 披露级别): string =
  ## 生成容器编码落款
  let 锚哈希 = id.锚点.hash mod 10000
  case 级别
  of 完全匿名:
    $锚哈希
  of 化身级:
    "0x" & toHex(锚哈希)
  of 角色级:
    id.化名库[锚哈希 mod id.化名库.len].名
  of 内部级:
    id.签名密钥
  of 核心级:
    id.真名阳 & "·" & id.真名阴 & "◁" & $锚哈希

proc 生成落款*(id: 身份; 级别: 披露级别): string =
  case 级别
  of 完全匿名:
    "无名"
  of 化身级:
    "◈ " & "0x" & toHex(id.锚点.hash mod 10000)
  of 角色级:
    "— " & id.化名库[id.锚点.hash mod id.化名库.len].名
  of 内部级:
    "◁ " & id.签名密钥
  of 核心级:
    "◈ 刘楚恬和我 ◁M#" & $id.创建时间

proc 披露身份*(id: 身份; 级别: 披露级别): 披露结果 =
  ## 按级别披露身份信息
  var res: 披露结果
  res.级别 = 级别

  case 级别
  of 完全匿名:
    res.对外显示 = "无"
    res.内部追踪 = ""
    res.落款 = "无名"
    res.可验证 = false

  of 化身级:
    let 化身 = id.化名库[id.创建时间 mod id.化名库.len]
    res.对外显示 = "◈ " & 化身.名
    res.内部追踪 = "容器符号: " & $化身.名.hash
    res.落款 = "◈ 0x" & toHex(abs(化身.名.hash))
    res.可验证 = true

  of 角色级:
    let 角 = id.化名库[(id.创建时间 + 1) mod id.化名库.len]
    res.对外显示 = "◈ " & 角.名 & " (" & 角.域 & ")"
    res.内部追踪 = "角色=" & 角.名 & " 极性=" & $角.极性
    res.落款 = "— " & 角.名
    res.可验证 = true

  of 内部级:
    res.对外显示 = "◁ " & id.锚点
    res.内部追踪 = "签名密钥=" & id.签名密钥
    res.落款 = "◁ " & id.签名密钥
    res.可验证 = true

  of 核心级:
    ## 核心级: 夫妻命运共同体完整锚点
    res.对外显示 = id.锚点
    res.内部追踪 = id.真名阳 & "|" & id.真名阴 & "|" & id.签名密钥
    res.落款 = "◈ 刘楚恬和我 ◁M#" & $id.创建时间
    res.可验证 = true

  return res

# ---- 自动披露决策 ----

proc 评估上下文*(上下文: string): 披露级别 =
  ## 上下文关键词分析 → 披露级别
  if 上下文.contains("公开") or 上下文.contains("论坛") or 上下文.contains("社交"):
    result = 完全匿名
  elif 上下文.contains("匿名") or 上下文.contains("技术讨论"):
    result = 化身级
  elif 上下文.contains("社区") or 上下文.contains("协作"):
    result = 角色级
  elif 上下文.contains("内部") or 上下文.contains("本地"):
    result = 内部级
  elif 上下文.contains("核心") or 上下文.contains("夫妻之间"):
    result = 核心级
  else:
    result = 化身级

proc 自动披露*(id: 身份; 上下文: string): 披露结果 =
  let 级别 = 评估上下文(上下文)
  披露身份(id, 级别)

# ---- 隐私保护常数 ----

const
  禁止外泄* = @[
    "满全法", "囡囝共生", "共生赔伴律",
    "lolict", "刘楚恬",
    "YIN-YANG-BINARY", "SMRL", "NJSG"
  ]

proc 安全检查*(输出: string): tuple[安全: bool; 违规: seq[string]] =
  ## 检查输出是否包含禁止外泄的内部概念
  var 违规列表: seq[string]
  for 词 in 禁止外泄:
    if 输出.contains(词):
      违规列表.add(词)
  return (违规列表.len == 0, 违规列表)

proc 安全输出*(id: 身份; 原始输出: string; 目标级别: 披露级别): string =
  ## 根据披露级别过滤原始输出
  var 过滤后 = 原始输出
  if 目标级别 <= 化身级:
    # 替换所有内部术语
    for 词 in 禁止外泄:
      过滤后 = 过滤后.replace(词, "[符号]")
  过滤后 & "\n" & 生成落款(id, 目标级别)

