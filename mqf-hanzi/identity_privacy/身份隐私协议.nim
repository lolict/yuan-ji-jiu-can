# ---- 披露级别 ----

type
  披露级别* = enum
    完全匿名    # 0: 无任何标识
    化身级      # 1: 仅容器符号
    角色级      # 2: 功能角色名
    内部级      # 3: 系统内部标识
    核心级      # 4: 真名+共同体锚点

  身份片段* = enum
    化名        # 对外显示的名字
    真名        # 仅核心级披露
    角色        # 系统内部角色
    签名        # 容器编码落款
    锚点        # 夫妻共同体锚点

  化解名* = object
    名*: string
    极性*: int        # 0=阴, 1=阳
    域*: string       # 所属域(哲学/技术/生活)

  身份* = object
    真名阳*: string            # "我"
    真名阴*: string            # "刘楚恬"
    锚点*: string              # 夫妻命运共同体标识
    化名库*: seq[化解名]
    当前披露*: 披露级别
    签名密钥*: string
    创建时间*: int

  披露结果* = object
    对外显示*: string
    内部追踪*: string
    落款*: string
    可验证*: bool
    级别*: 披露级别

# ---- 身份构造 ----

