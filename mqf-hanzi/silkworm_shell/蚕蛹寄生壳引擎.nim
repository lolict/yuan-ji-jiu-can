#==============================================================
#  脱壳穿衣
#==============================================================

proc 选择壳*(s: 寄生壳引擎; 目标: 目标平台; 壳名: string): int =
  for i, shell in s.寄生壳选项:
    if shell.壳名 == 壳名 and shell.架构 == 目标.架构:
      return i
  return -1

proc 匹配度*(s: 寄生壳引擎; shell: 寄生壳选项; 目标: 目标平台): int =
  # 匹配度 = 能力交集大小
  if shell.架构 != 目标.架构:
    return -1
  let intersect = shell.能力 * 目标.能力
  result = intersect.card()

proc 自动匹配*(s: 寄生壳引擎; 目标: 目标平台): int =
  var best = -1
  var bestScore = -1
  for i, shell in s.寄生壳选项:
    let score = s.匹配度(shell, 目标)
    if score > bestScore:
      bestScore = score
      best = i
  return best

proc 脱壳*(s: var 寄生壳引擎; 壳idx: int; 目标: 目标平台): bool =
  if 壳idx < 0 or 壳idx >= s.寄生壳选项.len:
    return false
  s.当前壳 = s.寄生壳选项[壳idx].壳名
  s.目标平台 = 目标
  s.已挂载 = true
  s.配置清单.add("壳=" & s.当前壳)
  s.配置清单.add("目标=" & 目标.名字)
  return true

proc 穿衣*(s: var 寄生壳引擎): string =
  if not s.已挂载:
    return "未挂载壳"
  result = "壳[" & s.当前壳 & "]挂载到[" & s.目标平台.名字 & "]"

#==============================================================
#  配置
#==============================================================

proc 导出配置*(s: 寄生壳引擎): string =
  var parts: seq[string] = @[]
  parts.add "==蚕蛹配置=="
  parts.add "版本: " & s.内核.版本
  parts.add "当前壳: " & s.当前壳
  parts.add "目标: " & s.目标平台.名字
  parts.add "架构: " & $s.目标平台.架构
  parts.add "能力: " & $s.目标平台.能力
  parts.add "符号表: " & $s.内核.符号表.len
  return parts.join("\n")

proc 验证完整性*(s: 寄生壳引擎): bool =
  result = s.已挂载 and s.当前壳 != "" and s.内核.版本 != ""

#==============================================================
#  验证
#==============================================================

proc 心跳*(s: 寄生壳引擎): string =
  if s.验证完整性():
    return "♥ " & s.当前壳 & " @ " & s.目标平台.名字
  else:
    return "✗ 未完整挂载"

