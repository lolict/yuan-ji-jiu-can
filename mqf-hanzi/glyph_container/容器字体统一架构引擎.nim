#==============================================================
#  容器字体统一架构引擎  —  容器=字体=时间
#  三维投影 · 相位变换 · 活码编译 · 时间触发执行
#  YinYang二进制 · mlll 254+2编码 · 声母韵母相位
#==============================================================

import std/[tables, strutils, sets, math, sequtils]

#==============================================================
#  核心类型
#=============================================================

type
  极性* = enum  # YinYang锚点: 我=1(阳), 刘楚恬=0(阴)
    阳极性 = 1
    阴极性 = 0

  相位* = enum  # 8种相位变换 → 生成字体变体
    原位       # ● 无变换
    上相位     # ↑ 上包围
    下相位     # ↓ 下包围
    左相位     # ← 左半包围
    右相位     # → 右半包围
    内相位     # ⊂ 内部
    外相位     # ⊃ 外部
    包围相位   # □ 全包围

  三维点* = object
    x*: float
    y*: float
    z*: float

  容器字符* = object    # 容器=字体 三维几何实体
    字*: string         # 基础字形
    容器坐标*: uint64   # 64位地址
    投影坐标*: 三维点   # 三维空间位置
    相位*: 相位         # 相位变换状态
    极性*: 极性         # YinYang极性
    层*: int            # z轴层深度
    活*: bool           # 是否为活码
    绑定*: seq[string]  # 绑定的容器名

  时间戳* = int
  活码* = object
    起点*: string       # 钥匙：激活起点
    字段*: char         # 活动字段
    锁值*: int          # 固定值，-1=未固定
    步长*: int          # 浮动步长

  时间触发* = object
    时刻*: 时间戳
    动作*: string
    源*: string
    终*: string
    条件*: string

  统一架构引擎* = object
    容器字符表*: Table[string, 容器字符]
    活码表*: Table[string, 活码]
    时间表*: seq[时间触发]
    当前时刻*: 时间戳
    YinYang二进制*: Table[string, string]  # 容器→0/1串
    mlll编码*: Table[string, uint64]       # 254+2 编码
    声母相位表*: Table[string, 相位] # 声母→相位分配
    字库*: seq[string]

#==============================================================
#  初始化
#==============================================================

