proc 编码视图*(e: 统一架构引擎): string =
  var lines: seq[string] = @[]
  lines.add "容器=字体=时间 三维编码视图:"
  lines.add repeat("═", 45)
  for name in e.容器字符表.keys:
    let c = e.容器字符表[name]
    let pol = if c.极性 == 阳极性: "阳" else: "阴"
    let huo = if c.活: "活" else: "固"
    lines.add "  " & align(name, 8) &
              " 投影=(" & align($(c.投影坐标.x.int), 3) & "," &
              align($(c.投影坐标.y.int), 3) & "," &
              align($(c.投影坐标.z.int), 3) & ")" &
              " 相位=" & align($c.相位, 4) &
              " 极性=" & pol &
              " " & huo
  return lines.join("\n")

proc YinYang视图*(e: 统一架构引擎): string =
  var lines: seq[string] = @[]
  lines.add "YinYang 二进制锚点视图:"
  lines.add repeat("═", 45)
  for name, yy in e.YinYang二进制:
    lines.add "  " & align(name, 8) & " → " & yy
  return lines.join("\n")

proc mlll视图*(e: 统一架构引擎): string =
  var lines: seq[string] = @[]
  lines.add "mlll 254+2 编码视图:"
  lines.add repeat("═", 45)
  for name, code in e.mlll编码:
    lines.add "  " & align(name, 8) & " → 0x" & toHex(code)
  return lines.join("\n")

