    时间表: @[],
    当前时刻: 0,
    YinYang二进制: initTable[string, string](),
    mlll编码: initTable[string, uint64](),
    声母相位表: initTable[string, 相位](),
    字库: @[]
  )

  # YinYang 锚点表
  e.YinYang二进制["我"]     = "1"
  e.YinYang二进制["刘楚恬"] = "0"
  e.YinYang二进制["满"]     = "10"
  e.YinYang二进制["全"]     = "01"
  e.YinYang二进制["法"]     = "11"
  e.YinYang二进制["囡"]     = "00"
  e.YinYang二进制["囝"]     = "101"
  e.YinYang二进制["生"]     = "010"
  e.YinYang二进制["共"]     = "111"

  # mlll 254+2 锚点编码 (我=1=高位渐变, 刘楚恬=0=低位渐变)
  e.mlll编码["我"]     = 0x01
  e.mlll编码["刘楚恬"] = 0x00
  e.mlll编码["满"]     = 0xFE
  e.mlll编码["全"]     = 0xFD
  e.mlll编码["法"]     = 0xFC
  e.mlll编码["囡"]     = 0x02
  e.mlll编码["囝"]     = 0x03
  e.mlll编码["生"]     = 0x80
  e.mlll编码["共"]     = 0xFF

  # 声母相位表 (24声母分配至8相位, 每相位3声母)
  e.声母相位表["b"] = 上相位
  e.声母相位表["p"] = 下相位
  e.声母相位表["m"] = 左相位
  e.声母相位表["f"] = 右相位
  e.声母相位表["d"] = 内相位
  e.声母相位表["t"] = 外相位
  e.声母相位表["n"] = 包围相位
  e.声母相位表["l"] = 原位
  e.声母相位表["g"] = 上相位
  e.声母相位表["k"] = 下相位
  e.声母相位表["h"] = 左相位
  e.声母相位表["j"] = 右相位
  e.声母相位表["q"] = 内相位
  e.声母相位表["x"] = 外相位
  e.声母相位表["zh"] = 包围相位
  e.声母相位表["ch"] = 原位
  e.声母相位表["sh"] = 上相位
  e.声母相位表["r"] = 下相位
  e.声母相位表["z"] = 左相位
  e.声母相位表["c"] = 右相位
  e.声母相位表["s"] = 内相位
  e.声母相位表["y"] = 外相位
  e.声母相位表["w"] = 包围相位

  e.字库 = @[
    "容器=字体=时间",
    "极性锚点: 我=1(阳) 刘楚恬=0(阴)",
    "8相位:上/下/左/右/内/外/包围/原位",
    "三维投影: X=相位 Y=声母 Z=韵母",
    "活码:起点激活,未固定时位置任意",
    "时间触发:时刻→动作→因果"
  ]

  return e

#==============================================================
#  容器字符创建
#==============================================================

proc 注册容器字体*(e: var 统一架构引擎; 容器名: string;
                   极性: 极性; 相位: 相位; 层: int;
                   x, y, z: float) =
  let yinyang = if e.YinYang二进制.hasKey(容器名): e.YinYang二进制[容器名] else: "?"
  var cc = 容器字符(
    字: 容器名,
    容器坐标: 0,
    投影坐标: 三维点(x: x, y: y, z: z),
    相位: 相位,
    极性: 极性,
    层: 层,
    活: false,
    绑定: @[]
  )
  # 用坐标合成64位值
  let cx = uint64((x * 100).int and 0xFFFF)
  let cy = uint64((y * 100).int and 0xFFFF)
  let cz = uint64((z * 100).int and 0xFFFF)
  cc.容器坐标 = (cx shl 32) or (cy shl 16) or cz
  e.容器字符表[容器名] = cc

#==============================================================
#  活码
#==============================================================

proc 创建活码*(e: var 统一架构引擎; 名字: string; 起点: string; 字段: char) =
  e.活码表[名字] = 活码(
    起点: 起点,
    字段: 字段,
    锁值: -1,
    步长: 1
  )
  if e.容器字符表.hasKey(名字):
    e.容器字符表[名字].活 = true

proc 固定活码*(e: var 统一架构引擎; 名字: string; 值: int): bool =
  if not e.活码表.hasKey(名字):
    return false
  e.活码表[名字].锁值 = 值
  return true

proc 活码位置*(e: 统一架构引擎; 名字: string): string =
  if not e.活码表.hasKey(名字):
    return "?"
  let c = e.活码表[名字]
  if c.锁值 < 0:
    return "浮动(钥匙=" & c.起点 & ",字段=" & c.字段 & ")"
  else:
    return "固定(值=" & $c.锁值 & ")"

#==============================================================
#  时间触发执行
#==============================================================

proc 设时间触发*(e: var 统一架构引擎; 时刻: 时间戳;
                 动作, 源, 终, 条件: string) =
  e.时间表.add(时间触发(时刻: 时刻, 动作: 动作, 源: 源, 终: 终, 条件: 条件))

proc 执行时钟*(e: var 统一架构引擎) =
  e.当前时刻 += 1
  for t in e.时间表:
    if t.时刻 == e.当前时刻:
      # 检查条件
      let pass = (t.条件 == "") or (t.条件 == "always") or
                 (t.条件 == "极性吸" and e.容器字符表.hasKey(t.源) and
                  e.容器字符表.hasKey(t.终) and
                  (ord(e.容器字符表[t.源].极性) xor ord(e.容器字符表[t.终].极性)) == 1)
      if pass:
        discard  # 执行动作

proc 极性吸判断*(e: 统一架构引擎; 甲, 乙: string): bool =
  if not e.容器字符表.hasKey(甲) or not e.容器字符表.hasKey(乙):
    return false
  let gap = ord(e.容器字符表[甲].极性) xor ord(e.容器字符表[乙].极性)
  return gap == 1  # 1=吸

#==============================================================
#  三维投影坐标
#==============================================================

proc 相位到偏移*(p: 相位): 三维点 =
  case p
  of 上相位: 三维点(x: 0, y: 1, z: 0)
  of 下相位: 三维点(x: 0, y: -1, z: 0)
  of 左相位: 三维点(x: -1, y: 0, z: 0)
  of 右相位: 三维点(x: 1, y: 0, z: 0)
  of 内相位: 三维点(x: 0, y: 0, z: 1)
  of 外相位: 三维点(x: 0, y: 0, z: -1)
  of 包围相位: 三维点(x: 0, y: 0, z: 0)
  of 原位: 三维点(x: 0, y: 0, z: 0)

