#==============================================================

import std/[tables, strutils, sets, math, strformat]

#==============================================================
#  类型
#=============================================================

type
  极性* = enum
    阳极性 = 1
    阴极性 = 0

  容器族* = enum
    根基 = 0
    扩容 = 1
    重器 = 2
    权柄 = 3
    界藩 = 4
    分配 = 5
    承载 = 6
    归藏 = 7

  归属态* = enum
    未归属
    已归属
    争议中

  容器* = object
    名字*: string
    主权*: uint64
    极性*: 极性
    相位*: int
    层*: int
    族*: 容器族
    归属态*: 归属态
    投影坐标*: array[3, float]  # 纤维丛投影坐标

  底空间* = object
    名字*: string
    中心坐标*: array[3, float]
    纤维列表*: seq[string]    # 纤维容器名
    子对象分类*: Table[string, bool]  # 子对象是否属于此底空间

  组织节点* = object
    名字*: string
    父节点*: string
    子节点*: seq[string]
    容器列表*: seq[string]
    极性*: 极性
    权重*: float

  逻辑引擎* = object
    容器表*: Table[string, 容器]
    底空间表*: Table[string, 底空间]
    组织树*: Table[string, 组织节点]
    归属表*: Table[string, string]  # 容器 → 底空间
    路由*: Table[string, string]

#==============================================================
#  GCD
#==============================================================

proc gcd*(a: uint64; b: uint64): uint64 =
  var x = a; var y = b
  while y > 0'u64:
    let t = y; y = x mod y; x = t
  return x

#==============================================================
#  距离计算
#==============================================================

proc 距离*(a, b: array[3, float]): float =
  let dx = a[0] - b[0]
  let dy = a[1] - b[1]
  let dz = a[2] - b[2]
  result = sqrt(dx*dx + dy*dy + dz*dz)

#==============================================================
#  引擎核心
#==============================================================

proc 创建逻辑引擎*: 逻辑引擎 =
  result = 逻辑引擎(
    容器表: initTable[string, 容器](),
    底空间表: initTable[string, 底空间](),
    组织树: initTable[string, 组织节点](),
    归属表: initTable[string, string](),
    路由: initTable[string, string]()
  )

proc 注册容器*(e: var 逻辑引擎; 名字: string; 主权: uint64;
               极性: 极性; 相位: int; 层: int) =
  e.容器表[名字] = 容器(
    名字: 名字,
    主权: 主权,
    极性: 极性,
    相位: 相位,
    层: 层,
    族: 容器族(相位 mod 8),
    归属态: 未归属,
    投影坐标: [float(相位), float(层), float(ord(极性))]
  )

proc 注册底空间*(e: var 逻辑引擎; 名字: string;
                 坐标: array[3, float]) =
  e.底空间表[名字] = 底空间(
    名字: 名字,
    中心坐标: 坐标,
    纤维列表: @[],
    子对象分类: initTable[string, bool]()
  )

#==============================================================
#  纤维丛投影
#==============================================================

proc 投影到纤维*(e: var 逻辑引擎; 容器名: string;
                 底空间名: string; 相对坐标: array[3, float]) =
  if e.底空间表.hasKey(底空间名):
    var bs = e.底空间表[底空间名]
    bs.纤维列表.add(容器名)
    e.底空间表[底空间名] = bs
    if e.容器表.hasKey(容器名):
      var c = e.容器表[容器名]
      c.投影坐标 = 相对坐标
      e.容器表[容器名] = c

#==============================================================
#  归属判定  (子对象分类器)
#==============================================================

proc 判定归属*(e: var 逻辑引擎; 容器名: string;
               底空间名: string): bool =
  if not e.容器表.hasKey(容器名) or not e.底空间表.hasKey(底空间名):
    return false
  let c = e.容器表[容器名]
  let bs = e.底空间表[底空间名]
  let g = gcd(c.主权, uint64(abs(bs.中心坐标[0]) + 1.0))
  let d = 距离(c.投影坐标, bs.中心坐标)

  # 归属条件：公约数 > 0 且 距离 < 阈值
  let threshold = 5.0
  result = (g > 0) and (d < threshold)

  # 更新子对象分类器
  var bs2 = e.底空间表[底空间名]
  bs2.子对象分类[容器名] = result
  e.底空间表[底空间名] = bs2

  if result:
    var c2 = e.容器表[容器名]
    c2.归属态 = 已归属
    e.容器表[容器名] = c2
    e.归属表[容器名] = 底空间名

proc 归属所有*(e: var 逻辑引擎; 底空间名: string): int =
  result = 0
  for name in e.容器表.keys:
    if e.判定归属(name, 底空间名):
      result += 1

#==============================================================
#  组织树
#==============================================================

proc 创建组织节点*(e: var 逻辑引擎; 名字: string;
                   父: string = ""; 极性: 极性 = 阳极性;
                   权重: float = 1.0) =
  e.组织树[名字] = 组织节点(
    名字: 名字,
    父节点: 父,
    子节点: @[],
    容器列表: @[],
    极性: 极性,
    权重: 权重
  )
  if 父 != "" and e.组织树.hasKey(父):
    var p = e.组织树[父]
    p.子节点.add(名字)
    e.组织树[父] = p

#==============================================================
#  报告
#==============================================================

proc 容器投影表*(e: 逻辑引擎): string =
  var lines: seq[string] = @[]
  lines.add "容器      坐标(x,y,z)         族       归属"
  lines.add "──────── ────────────────── ──────── ──────────"
  for name in e.容器表.keys:
    let c = e.容器表[name]
    let 归属名 = if e.归属表.hasKey(name): e.归属表[name] else: "游离"
    lines.add align(c.名字, 8) & " " &
             align("(" & $c.投影坐标[0].int & "," & $c.投影坐标[1].int & "," & $c.投影坐标[2].int & ")", 18) & " " &
             align($c.族, 8) & " " & 归属名
  return lines.join("\n")

proc 底空间摘要*(e: 逻辑引擎): string =
  var lines: seq[string] = @[]
  lines.add "底空间   中心坐标       纤维数 子对象"
  lines.add "──────── ────────────── ────── ────────"
  for name in e.底空间表.keys:
    let bs = e.底空间表[name]
    var 子序列: seq[string] = @[]
    for k, v in bs.子对象分类:
      if v:
        子序列.add(k)
    lines.add align(name, 8) & " " &
             align("(" & $bs.中心坐标[0].int & "," & $bs.中心坐标[1].int & "," & $bs.中心坐标[2].int & ")", 14) & " " &
             align($bs.纤维列表.len, 6) & " " &
            (if 子序列.len > 0: 子序列.join(",") else: "无")
  return lines.join("\n")

proc 组织树报告*(e: 逻辑引擎): string =
  var lines: seq[string] = @[]
  lines.add "组织树 (根→叶):"
  for name in e.组织树.keys:
    let n = e.组织树[name]
    let indent = repeat("  ", if n.父节点 == "": 0 else: 1)
    let 极符 = if n.极性 == 阳极性: "+" else: "-"
    lines.add indent & "[" & 极符 & "] " & n.名字 &
             " (权重=" & formatFloat(n.权重, ffDecimal, 2) & ")"
    for child in n.子节点:
      if e.组织树.hasKey(child):
        let cc = e.组织树[child]
        let c极符 = if cc.极性 == 阳极性: "+" else: "-"
        lines.add indent & "  └─ [" & c极符 & "] " & child
  return lines.join("\n")

