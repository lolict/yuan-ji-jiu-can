#==============================================================
#  天庭空间引擎  —  容器=物质=时间
#  高维容器空间 · 神殿层级 · 灵魂路由 · 八流汇聚
#  42位坐标 × 64位值 → 高维容器存储
#==============================================================

import std/[tables, strutils, sets, math, hashes]

#==============================================================
#  基础类型
#=============================================================

type
  极性* = enum
    阳极性 = 1  # 我=1
    阴极性 = 0  # 刘楚恬=0

  容器族* = enum
    根基 = 0
    扩容 = 1
    重器 = 2
    权柄 = 3
    界藩 = 4
    分配 = 5
    承载 = 6
    归藏 = 7

  神殿层级* = enum
    南天门 = 0    # 入口层 (对外接口)
    青龙殿 = 1    # 东 - 生发
    朱雀殿 = 2    # 南 - 显现
    白虎殿 = 3    # 西 - 收敛
    玄武殿 = 4    # 北 - 蛰伏
    凌霄殿 = 5    # 中央 - 统摄 (最高层)

  流编号* = enum
    预加载流 = 0
    归类流 = 1
    聚类流 = 2
    分别流 = 3
    属性流 = 4
    解释流 = 5
    关系流 = 6
    概念流 = 7

  灵魂路由* = enum
    谐音路由 = 0    # 同音异义路由
    主权路由 = 1    # 主权归属路由

  神殿容器* = object
    坐标*: uint64      # 42位神殿坐标
    值*: uint64        # 64位存储值
    容器族*: 容器族
    层级*: 神殿层级
    极性*: 极性
    名字*: string
    可见*: bool        # 南天门可见性
    激活*: bool        # 是否激活

  天庭空间* = object
    神殿*: Table[uint64,神殿容器]       # 坐标 → 容器
    层级结构*: array[6, seq[uint64]]    # 每个层级的容器坐标列表
    路由表*: Table[uint64, uint64]      # 源坐标 → 目标坐标
    吸引子*: HashSet[uint64]            # 高能量坐标
    容纳量*: int
    演化轮次*: int
    流汇聚点*: uint64                   # 八流汇聚的凌霄殿坐标

#==============================================================
#  坐标编码
#  42位神殿坐标布局:
#  [层级3位][容器族3位][极性1位][填充2位][分片16位][序号17位]
#==============================================================

proc 构建坐标*(层级: 神殿层级; 族: 容器族;
               极性: 极性; 分片: uint16;
               序号: uint16): uint64 =
  var c: uint64 = 0
  c = c or uint64(层级.ord)                     # bit 0-2    : 层级
  c = c or (uint64(ord(族)) shl 3)           # bit 3-5    : 容器族
  c = c or (uint64(ord(极性)) shl 6)             # bit 6      : 极性
  c = c or uint64(分片) shl 7               # bit 7-22   : 分片
  c = c or (uint64(序号) shl 23)                 # bit 23-39  : 序号
  result = c

proc 坐标到层*(coord: uint64): 神殿层级 =
  result = 神殿层级(coord and 0x7'u64)

proc 坐标到族*(coord: uint64): 容器族 =
  result = 容器族((coord shr 3) and 0x7'u64)

proc 坐标到极性*(coord: uint64): 极性 =
  result = 极性((coord shr 6) and 0x1'u64)

proc 坐标到分片*(coord: uint64): uint16 =
  result = uint16((coord shr 7) and 0xFFFF'u64)

#==============================================================
#  引擎核心
#==============================================================

proc 创建天庭*: 天庭空间 =
  result = 天庭空间(
    神殿: initTable[uint64, 神殿容器](),
    层级结构: default(array[6, seq[uint64]]),
    路由表: initTable[uint64, uint64](),
    吸引子: initHashSet[uint64](),
    容纳量: 0,
    演化轮次: 0,
    流汇聚点: 0'u64
  )
  # 凌霄殿坐标 (中央统摄)
  result.流汇聚点 = 构建坐标(凌霄殿, 权柄, 阳极性, 0'u16, 0'u16)

proc 放入*(t: var 天庭空间; 坐标: uint64; 值: uint64;
           名字: string = ""; 可见: bool = true) =
  let 层 = 坐标到层(坐标)
  let 族 = 坐标到族(坐标)
  let 极 = 坐标到极性(坐标)
  t.神殿[坐标] = 神殿容器(
    坐标: 坐标,
    值: 值,
    容器族: 族,
    层级: 层,
    极性: 极,
    名字: 名字,
    可见: 可见,
    激活: true
  )
  t.层级结构[层.ord].add(坐标)
  t.容纳量 += 1

proc 取出*(t: 天庭空间; 坐标: uint64): uint64 =
  if t.神殿.hasKey(坐标):
    return t.神殿[坐标].值
  return 0'u64

#==============================================================
#  路由
#==============================================================

proc 设路由*(t: var 天庭空间; 源: uint64; 目标: uint64) =
  t.路由表[源] = 目标

proc 路由步*(t: 天庭空间; 源: uint64): uint64 =
  if t.路由表.hasKey(源):
    return t.路由表[源]
  return 源  # 无路由则指向自身

proc 跳转层级*(t: 天庭空间; 源: uint64; 目标层级: 神殿层级): uint64 =
  # 修改源坐标的层级段为目标层级
  let masked = 源 and 0x7'u64  # 保留低3位 (层级)
  let base  = 源 and (not 0x7'u64)  # 清除层级位
  result = base or uint64(目标层级.ord)

#==============================================================
#  演化
#==============================================================

proc 标记吸引子*(t: var 天庭空间; 坐标: uint64) =
  t.吸引子.incl(坐标)

proc 随机扰动*(t: var 天庭空间; 坐标: uint64; 增量: int16) =
  if t.神殿.hasKey(坐标):
    var c = t.神殿[坐标]
    c.值 = uint64(int64(c.值) + int64(增量))
    t.神殿[坐标] = c

#==============================================================
#  南天门过滤 (安全检查)
#==============================================================

proc 南天门可见*(t: 天庭空间; 坐标: uint64): bool =
  if t.神殿.hasKey(坐标):
    return t.神殿[坐标].可见
  return false

#==============================================================
#  安全过滤
#==============================================================

proc 南天门守卫*(t: 天庭空间; 请求者极性: 极性; 目标层级: 神殿层级; 目标可见: bool): bool =
  # 只有阳极性可访问隐藏层
  if not 目标可见:
    return 请求者极性 == 阳极性
  return true

#==============================================================
#  层摘要
#==============================================================

proc 神殿摘要*(t: 天庭空间): string =
  var lines: seq[string] = @[]
  let 层级名 = ["南天门", "青龙殿", "朱雀殿", "白虎殿", "玄武殿", "凌霄殿"]
  for i in 0..5:
    let count = t.层级结构[i].len
    let indent = repeat("  ", i)
    lines.add indent & 层级名[i] & ": " & $count & " 容器"
    for coord in t.层级结构[i]:
      if t.神殿.hasKey(coord):
        let c = t.神殿[coord]
        if c.可见:
          lines.add indent & "  [" & toHex(coord) & "] " &
                   c.名字 & " =0x" & toHex(c.值)
        else:
          lines.add indent & "  [§隐藏§]"
  lines.add "  ──────"
  lines.add "  容纳量: " & $t.容纳量 & " | 路由: " & $t.路由表.len &
          " | 吸引子: " & $t.吸引子.len
  return lines.join("\n")

#==============================================================
#  主程序
#==============================================================

when isMainModule:
  echo "════════════════════════════════════════"
  echo "  天 庭 空 间 引 擎"
  echo "  高维容器空间 · 神殿层级 · 灵魂路由"
  echo "════════════════════════════════════════"

  var t = 创建天庭()

  echo "\n-- 层级结构 (6大殿) --"
  let 层级 = [南天门, 青龙殿, 朱雀殿, 白虎殿, 玄武殿, 凌霄殿]
  let 层级名 = ["南天门(入口)", "青龙殿(东)", "朱雀殿(南)", "白虎殿(西)", "玄武殿(北)", "凌霄殿(中央)"]
  for i, name in 层级名:
    echo "  ", name

  echo "\n-- 放入核心容器 --"
  # 南天门 - 入口
  let c1 = 构建坐标(南天门, 根基, 阳极性, 0'u16, 0'u16)
  let c2 = 构建坐标(南天门, 根基, 阴极性, 0'u16, 1'u16)
  t.放入(c1, 0x100, "入口", false)
  t.放入(c2, 0x101, "入口阴", false)

  # 青龙殿 - 生发
  let c3 = 构建坐标(青龙殿, 根基, 阳极性, 0'u16, 0'u16)
  let c4 = 构建坐标(青龙殿, 扩容, 阴极性, 1'u16, 0'u16)
  t.放入(c3, 0x200, "生发点")
  t.放入(c4, 0x201, "扩展槽")

  # 朱雀殿 - 显现
  let c5 = 构建坐标(朱雀殿, 重器, 阳极性, 2'u16, 0'u16)
  t.放入(c5, 0x300, "显器")

  # 白虎殿 - 收敛
  let c6 = 构建坐标(白虎殿, 权柄, 阴极性, 3'u16, 0'u16)
  t.放入(c6, 0x400, "收敛权柄")

  # 玄武殿 - 蛰伏
  let c7 = 构建坐标(玄武殿, 界藩, 阳极性, 4'u16, 0'u16)
  t.放入(c7, 0x500, "蛰伏点")

  # 凌霄殿 - 八流汇聚
  let c8 = 构建坐标(凌霄殿, 权柄, 阳极性, 0'u16, 0'u16)
  t.放入(c8, 0x600, "汇聚核", false)  # 隐藏

  # 额外流容器填充到 南天门层
  for i in 1'u16..5'u16:
    let 族偏移: 容器族 = 容器族(i mod 8)
    let flow_coord = 构建坐标(南天门, 族偏移, 阳极性, 0'u16, uint16(i + 10))
    t.放入(flow_coord, 0x10'u64 * uint64(i), "流" & $i, true)

  echo t.神殿摘要()

  echo "\n-- 路由验证 --"
  t.设路由(c1, c3)  # 入口南天门 → 青龙殿生发点
  t.设路由(c3, c5)  # 青龙殿 → 朱雀殿
  t.设路由(c5, c6)  # 朱雀殿 → 白虎殿
  t.设路由(c6, c7)  # 白虎殿 → 玄武殿
  t.设路由(c7, c8)  # 玄武殿 → 凌霄殿
  echo "  路径: 南天门(0x", toHex(c1), ") → 青龙殿(0x", toHex(c3), ") → 朱雀殿(0x", toHex(c5), ") → ..."
  echo "  跳转: 南天门 → 青龙殿 = 0x", toHex(t.路由步(c1))
  echo "  朱雀殿 → 白虎殿 = 0x", toHex(t.路由步(c5))
  echo "  玄武殿 → 凌霄殿 = 0x", toHex(t.路由步(c7))

  echo "\n-- 层级跳转 --"
  let 升层 = t.跳转层级(c1, 凌霄殿)
  echo "  南天门0x", toHex(c1), " → 凌霄殿0x", toHex(升层)
  echo "  验证层级: ", $坐标到层(升层)

  echo "\n-- 南天门过滤 --"
  echo "  入口(阳)可见: ", t.南天门可见(c1), " (false=受保护)"
  echo "  生发点可见: ", t.南天门可见(c3), " (true=公开)"
  echo "  汇聚核可见: ", t.南天门可见(c8), " (false=凌霄殿核心隐藏)"

  echo "\n-- 数值查询 --"
  echo "  生发点值: 0x", toHex(t.取出(c3))
  echo "  显器值: 0x", toHex(t.取出(c5))
  echo "  未注册的坐标: 0x", toHex(t.取出(0xDEAD_BEEF'u64)), " (返回0)"

  echo "\n-- 极性验证 --"
  let 阳坐标 = 构建坐标(南天门, 根基, 阳极性, 0'u16, 0'u16)
  let 阴坐标 = 构建坐标(南天门, 根基, 阴极性, 0'u16, 1'u16)
  echo "  阳坐标末位: ", $坐标到极性(阳坐标), " (= 我)"
  echo "  阴坐标末位: ", $坐标到极性(阴坐标), " (= 刘楚恬)"

  echo "\n════════════════════════════════════════"
  echo " 天庭空间 · 凌霄殿 · 八流汇聚 · 高维容器"
  echo "════════════════════════════════════════"
