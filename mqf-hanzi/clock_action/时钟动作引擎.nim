#==============================================================
#  时钟动作引擎 — Clock Action Engine
#
#  核心公理：结束=开始 · 意志驱动 · 继承跟随结束 ·
#           时间触发=加载执行 · 生命周期=循环动作
#==============================================================

import std/[tables, strutils, sequtils, math, algorithm, times]

#--------------------------------------------------------------
#  类型定义
#--------------------------------------------------------------

type
  # 动作类型
  动作型* = enum
    创建动作
    激活动作
    休眠动作
    融合动作
    分裂动作
    路由动作
    裁决动作
    继承动作

  # 时钟动作 — 可执行的时间触发单元
  时钟动作* = object
    编码*: int
    名字*: string
    动作型*: 动作型
    触发时刻*: float              # 距系统启动的秒数
    周期*: float                  # -1=单次，>0=循环周期
    已执行*: bool
    能执行*: bool                 # 是否激活
    优先级*: int                  # 0=最高
    输入*: seq[int]               # 输入容器编码
    输出*: seq[int]               # 输出容器编码
    意志*: string                 # 意志描述
    记忆*: string                 # 执行后的记忆继承

  # 意志栈
  意志栈* = object
    当前意志*: string
    历史*: seq[string]
    深度*: int

  # 生命周期环
  生命周期* = object
    阶段*: string
    起始时刻*: float
    结束时刻*: float
    下一阶段*: string             # 结束=开始 → 循环

  # 时间线
  时间线* = object
    当前时刻*: float
    时刻表*: seq[时钟动作]
    已完成*: seq[int]
    循环链*: seq[string]

  # 引擎
  时钟引擎* = object
    动作表*: Table[int, 时钟动作]
    时间线*: 时间线
    意志栈*: 意志栈
    生命周期*: seq[生命周期]
    心跳计数*: int
    运行次数*: int

#--------------------------------------------------------------
#  初始化
#--------------------------------------------------------------

proc 初始化时钟引擎*(): 时钟引擎 =
  result.时间线 = 时间线(
    当前时刻: 0.0,
    时刻表: @[],
    已完成: @[],
    循环链: @["开始", "运行", "结束", "开始"]
  )
  result.意志栈 = 意志栈(当前意志: "", 历史: @[], 深度: 0)
  result.生命周期 = @[]
  result.心跳计数 = 0
  result.运行次数 = 0

#--------------------------------------------------------------
#  注册动作
#--------------------------------------------------------------

proc 注册动作*(e: var 时钟引擎; 编码: int; 名字: string;
               动作型: 动作型; 触发时刻: float; 周期: float = -1.0;
               优先级: int = 5; 输入: seq[int] = @[];
               输出: seq[int] = @[]; 意志: string = "") =
  e.动作表[编码] = 时钟动作(
    编码: 编码, 名字: 名字, 动作型: 动作型,
    触发时刻: 触发时刻, 周期: 周期,
    已执行: false, 能执行: true,
    优先级: 优先级, 输入: 输入, 输出: 输出,
    意志: 意志, 记忆: ""
  )

#--------------------------------------------------------------
#  意志驱动
#--------------------------------------------------------------

proc 设意志*(e: var 时钟引擎; 意志: string) =
  if e.意志栈.当前意志.len > 0:
    e.意志栈.历史.add(e.意志栈.当前意志)
  e.意志栈.当前意志 = 意志
  e.意志栈.深度 = e.意志栈.历史.len + 1

#--------------------------------------------------------------
#  心跳推进
#--------------------------------------------------------------

proc 心跳*(e: var 时钟引擎): seq[string] =
  e.心跳计数 += 1
  e.时间线.当前时刻 += 1.0
  var logs: seq[string] = @[]

  # 按优先级排序的动作列表
  var ready: seq[时钟动作] = @[]
  for k, a in e.动作表:
    if a.能执行 and not a.已执行:
      if a.触发时刻 <= e.时间线.当前时刻:
        ready.add(a)
  ready = sorted(ready, proc(a, b: 时钟动作): int = cmp(a.优先级, b.优先级))

  for a in ready:
    e.运行次数 += 1
    var act = a
    act.已执行 = true

    # 执行日志
    let act_name = case act.动作型
      of 创建动作: "创建"
      of 激活动作: "激活"
      of 休眠动作: "休眠"
      of 融合动作: "融合"
      of 分裂动作: "分裂"
      of 路由动作: "路由"
      of 裁决动作: "裁决"
      of 继承动作: "继承"

    logs.add "[" & $e.心跳计数 & "] " & act_name & ":" & act.名字 &
            " (T=" & $act.触发时刻 & ", 意志=" & act.意志 & ")"

    # 执行后记忆
    act.记忆 = "执行于T" & $e.心跳计数 & " " & e.意志栈.当前意志

    # 循环周期动作：执行后重置
    if act.周期 > 0:
      act.触发时刻 = e.时间线.当前时刻 + act.周期
      act.已执行 = false

    e.时间线.已完成.add(act.编码)
    e.动作表[act.编码] = act

    # 意志沿动作传播
    if act.意志.len > 0:
      e.设意志(act.意志)

  return logs

#--------------------------------------------------------------
#  生命周期 — 结束=开始
#--------------------------------------------------------------

proc 创建生命周期*(e: var 时钟引擎; 阶段名: string;
                   起始: float; 结束: float; 下一阶段: string) =
  e.生命周期.add(生命周期(
    阶段: 阶段名, 起始时刻: 起始, 结束时刻: 结束,
    下一阶段: 下一阶段
  ))

proc 推进生命周期*(e: var 时钟引擎): string =
  for lc in e.生命周期:
    if e.时间线.当前时刻 >= lc.结束时刻 and lc.下一阶段.len > 0:
      # 结束即到下一阶段开始
      return lc.下一阶段
  return ""

#--------------------------------------------------------------
#  记忆继承 — 结束即开始，记忆跟随结束而继续
#--------------------------------------------------------------

proc 记忆继承*(e: 时钟引擎; 编码: int): string =
  if not e.动作表.hasKey(编码):
    return ""
  return e.动作表[编码].记忆

proc 提取记忆链*(e: 时钟引擎): seq[string] =
  var chain: seq[string] = @[]
  for k in sorted(toSeq(e.动作表.keys)):
    let m = e.动作表[k].记忆
    if m.len > 0:
      chain.add(e.动作表[k].名字 & ": " & m)
  return chain

#--------------------------------------------------------------
#  报告
#--------------------------------------------------------------

proc 时钟报告*(e: 时钟引擎): string =
  var lines: seq[string] = @[]
  lines.add repeat("═", 54)
  lines.add "  时 钟 动 作 引 擎 — 报 告"
  lines.add repeat("═", 54)
  lines.add "当前时刻: T=" & $e.心跳计数
  lines.add "心跳总数: " & $e.心跳计数
  lines.add "动作执行: " & $e.运行次数
  lines.add "意志栈深: " & $e.意志栈.深度
  lines.add "当前意志: " & (if e.意志栈.当前意志.len > 0: e.意志栈.当前意志 else: "—")
  lines.add ""

  lines.add "─ 动作表 ─"
  for k in sorted(toSeq(e.动作表.keys)):
    let a = e.动作表[k]
    let 状态 = if a.已执行: (if a.周期 > 0: "循环" else: "完成") else: "待执行"
    let 周期 = if a.周期 > 0: " P=" & $a.周期 else: ""
    lines.add "  [" & $a.编码 & "] " & align(a.名字, 8) & " " &
              align($a.动作型, 8) & " T=" & $a.触发时刻 &
              周期 & " " & 状态 & " 意志:" & a.意志

  lines.add ""
  lines.add "─ 意志历史 ─"
  for i in 0 ..< e.意志栈.历史.len:
    lines.add "  " & $(i + 1) & ". " & e.意志栈.历史[i]

  lines.add ""
  lines.add "─ 记忆链 ─"
  for m in e.提取记忆链():
    lines.add "  " & m

  return lines.join("\n")

#==============================================================
#  入口
#==============================================================

when isMainModule:
  var e = 初始化时钟引擎()

  echo "═══ 时钟动作引擎 ═══"
  echo ""

  # 注册动作（模拟系统启动序列）
  e.注册动作(100, "内核加载", 创建动作, 1.0, -1, 0, @[], @[1], "启动")
  e.注册动作(200, "容器注册", 创建动作, 2.0, -1, 1, @[], @[1, 2], "启动")
  e.注册动作(300, "路由连接", 路由动作, 3.0, -1, 2, @[1, 2], @[3], "寻找路径")
  e.注册动作(400, "判断裁决", 裁决动作, 4.0, -1, 3, @[3], @[], "裁决")
  e.注册动作(500, "融合共生", 融合动作, 5.0, -1, 4, @[1, 2], @[4], "合一")
  e.注册动作(600, "心跳循环", 激活动作, 6.0, 5.0, 5, @[4], @[4], "持续")

  # 生命周期：结束=开始
  e.创建生命周期("启动", 0.0, 5.0, "运行")
  e.创建生命周期("运行", 5.0, 100.0, "休眠")
  e.创建生命周期("休眠", 100.0, 101.0, "启动")

  echo "─ 意志设定 ─"
  e.设意志("让系统活着")
  echo "当前意志: " & e.意志栈.当前意志
  echo ""

  echo "─ 心跳推进 ─"
  for round in 1 .. 10:
    let logs = e.心跳()
    for l in logs:
      echo "  " & l

    # 检查生命周期推进
    let next = e.推进生命周期()
    if next.len > 0:
      echo "  ↳ 生命周期→" & next

  echo ""
  echo e.时钟报告()
  echo ""
  echo "─ 结束=开始 ─"
  echo "  最终意志(栈顶): " & e.意志栈.当前意志
  echo "  循环链: " & e.时间线.循环链.join(" → ")
