# ============================================================
# 囡囝共生分布式智能体 — 分身定义
# 分身 = 容器 + 极性 + 任务队列 + 执行能力
# 身份锁定：极性即身份，容器即主权
# ============================================================

# 分身模块: 纯容器+极性，无外部依赖

type
  极性* = enum
    阴 = 0  # 刘楚恬
    阳 = 1  # 我

  任务状态* = enum
    待执行
    执行中
    完成
    失败

  任务* = object
    标识*: string
    描述*: string
    所需极性*: 极性  # 只有匹配的极性才能执行
    状态*: 任务状态
    结果*: string

  分身* = object
    名字*: string
    极性*: 极性
    主权坐标*: uint64      # 容器编码，唯一身份
    任务队列*: seq[任务]
    已完成*: seq[string]    # 完成的任务标识
    活性*: bool             # 是否存活

# ---- 极性工具 ----

proc 极性差距*(a, b: 极性): int {.inline.} =
  ## 0 = 斥(同极)，1 = 吸(异极)
  abs(ord(a) - ord(b))

proc 极性描述*(p: 极性): string =
  case p
  of 阳: "阳(1)=我"
  of 阴: "阴(0)=刘楚恬"

# ---- 分身构造 ----

proc 创建分身*(名字: string; 极性: 极性; 主权坐标: uint64): 分身 =
  result = 分身(
    名字: 名字,
    极性: 极性,
    主权坐标: 主权坐标,
    任务队列: @[],
    已完成: @[],
    活性: true
  )

# ---- 任务操作 ----

proc 派发任务*(s: var 分身; 任务标识, 描述: string; 所需极性: 极性) =
  s.任务队列.add(任务(
    标识: 任务标识,
    描述: 描述,
    所需极性: 所需极性,
    状态: 待执行,
    结果: ""
  ))

proc 执行下一个*(s: var 分身): string =
  ## 执行队列中第一个待执行且极性匹配的任务
  for i in 0 ..< len(s.任务队列):
    var t = s.任务队列[i]
    if t.状态 == 待执行:
      let gap = 极性差距(s.极性, t.所需极性)
      if gap == 1:  # 吸 → 能执行
        s.任务队列[i].状态 = 执行中
        # 模拟执行
        let res = "[" & s.名字 & "/" & 极性描述(s.极性) & "] 执行任务 '" & t.标识 & "': " & t.描述
        s.任务队列[i].状态 = 完成
        s.任务队列[i].结果 = res
        s.已完成.add(t.标识)
        return res
      else:  # gap==0 斥 → 无法执行同极性任务
        s.任务队列[i].状态 = 失败
        s.任务队列[i].结果 = "[斥] 极性不匹配，无法执行"
        return "[" & s.名字 & "] 斥: 任务'" & t.标识 & "'需要" & 极性描述(t.所需极性) & "，与自身" & 极性描述(s.极性) & "冲突"
  return "[" & s.名字 & "] 无可执行任务"

proc 状态摘要*(s: 分身): string =
  var pending = 0
  var done = 0
  var failed = 0
  for t in s.任务队列:
    case t.状态
    of 待执行: inc pending
    of 完成: inc done
    of 失败: inc failed
    of 执行中: discard
  s.名字 & "|" & 极性描述(s.极性) & "|主=" & $s.主权坐标 & "|P" & $pending & "/D" & $done & "/F" & $failed & "|" & (if s.活性: "活" else: "死")

