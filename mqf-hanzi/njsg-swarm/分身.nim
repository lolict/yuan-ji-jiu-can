when isMainModule:
  echo "=== 分身单元测试 ==="
  var s = 创建分身("震甲", 阳, 0x01020304)
  echo "创建: ", 状态摘要(s)
  派发任务(s, "T1", "扫描命名空间", 阴)  # 阴任务给阳分身 → 吸，能执行
