# ---- 工具函数 ----

proc `GAP`(a, b: int): int =
  if a >= b: a - b else: b - a

proc 主权层级(x: uint64): int =
  var n = x
  var c = 0
  while n != 0:
    c += int(n and 1)
    n = n shr 1
  result = c

proc gcd(a, b: uint64): uint64 =
  var x = a; var y = b
  while y != 0:
    let t = y; y = x mod y; x = t
  result = x

# ---- 裁决引擎 ----

proc 裁决(冲突: var 冲突记录) =
  let gap = GAP(冲突.甲方极性, 冲突.乙方极性)
  if gap == 1:
    # 吸 → 合一
    let g = gcd(冲突.甲方主权, 冲突.乙方主权)
    if g >= 冲突.乙方主权:
      冲突.结果 = 吸纳
      冲突.理由 = "极性吸(gap=1)+公约 -> 合一为" & 冲突.甲方
    else:
      冲突.结果 = 吸纳
      冲突.理由 = "极性吸(gap=1)+公约 -> 合一为" & 冲突.乙方
  else:
    let la = 主权层级(冲突.甲方主权)
    let lb = 主权层级(冲突.乙方主权)
    if la >= lb:
      冲突.结果 = 驱逐
      冲突.理由 = "极性斥(gap=0)+主权层级 -> 驱逐乙方"
    else:
      冲突.结果 = 驱逐
      冲突.理由 = "极性斥(gap=0)+主权层级 -> 驱逐甲方"

proc 裁决报告(c: 冲突记录): string =
  "甲方:" & c.甲方 & "(极=" & $c.甲方极性 & ",主=" & $c.甲方主权 & ") " &
  "乙方:" & c.乙方 & "(极=" & $c.乙方极性 & ",主=" & $c.乙方主权 & ") " &
  "-> " & $c.结果 & " (" & c.理由 & ")"

# ---- 规则病毒检测 ----

proc 扫描(分身: seq[分身]): seq[病毒记录] =
  var 符号表 = initTable[string, seq[int]]()
  for i, s in 分身:
    for t in s.已完成:
      if not 符号表.hasKey(t):
        符号表[t] = @[]
      符号表[t].add(i)

  for 符号, 来源 in 符号表.pairs:
    if 来源.len > 1:
      var 感染源: seq[string]
      for idx in 来源:
        感染源.add(分身[idx].名字)
      let 等级 = if 来源.len >= 3: "确认病毒" else: "可疑"
      result.add(病毒记录(符号: 符号, 感染源: 感染源, 等级: 等级))

# ---- 协调器逻辑 ----

proc 分配(协调: var 协调器; 分身: var seq[分身]; 任务: string; 所需极性: 极性): string =
  # 找极性相反(吸)的活跃分身
  var 目标 = -1
  var 最优主权: uint64 = 0'u64
  for i, s in 分身:
    if not s.活性: continue
    let gap = GAP(ord(s.极性), ord(所需极性))
    if gap == 1:
      if 目标 < 0 or s.主权 > 最优主权:
        目标 = i
        最优主权 = s.主权
  if 目标 >= 0:
    分身[目标].已完成.add(任务)
    return "'" & 任务 & "' -> " & 分身[目标].名字 & "(吸)"
  else:
    return "'" & 任务 & "' 无匹配(吸)分身"

