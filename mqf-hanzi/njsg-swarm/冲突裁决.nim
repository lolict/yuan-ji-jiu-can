# ============================================================
# 囡囝共生分布式智能体 — 冲突裁决引擎
# 裁决原则: 极性测距 + 公约数整除裁定
# gap=1(吸) → 允许合一协作
# gap=0(斥) → 必须隔离
# 主权层级靠公约数整除决定优先级
# ============================================================

import strutils

type
  裁决结果* = enum
    吸纳
    隔离
    驱逐
    未定

  冲突类型* = enum
    命名冲突
    极性冲突
    主权冲突
    规则病毒

  冲突记录* = object
    甲方*: string
    乙方*: string
    冲突种类*: 冲突类型
    甲方主权*: uint64
    乙方主权*: uint64
    甲方极性*: int
    乙方极性*: int
    裁决*: 裁决结果
    理由*: string

proc gcd*(a, b: uint64): uint64 =
  var x = a
  var y = b
  while y != 0:
    let t = y
    y = x mod y
    x = t
  result = x

proc 主权层级*(坐标: uint64): int =
  var n = 坐标
  var count = 0
  while n != 0:
    count += int(n and 1)
    n = n shr 1
  result = count

proc 公约裁定*(甲主权, 乙主权: uint64): int =
  let g = gcd(甲主权, 乙主权)
  if 甲主权 > 乙主权 and g > 0:
    result = 1
  elif 乙主权 > 甲主权 and g > 0:
    result = -1
  else:
    result = 0

proc 裁决*(冲突: var 冲突记录) =
  let gap = if 冲突.甲方极性 >= 冲突.乙方极性: 冲突.甲方极性 - 冲突.乙方极性
            else: 冲突.乙方极性 - 冲突.甲方极性

  case 冲突.冲突种类
  of 命名冲突, 规则病毒:
    if gap == 1:
      let c = 公约裁定(冲突.甲方主权, 冲突.乙方主权)
      if c >= 0:
        冲突.裁决 = 吸纳
        冲突.理由 = "极性吸+公约优先 -> 合一为" & 冲突.甲方
      else:
        冲突.裁决 = 吸纳
        冲突.理由 = "极性吸+公约优先 -> 合一为" & 冲突.乙方
    else:
      冲突.裁决 = 隔离
      冲突.理由 = "极性斥 -> 强制隔离命名空间"

  of 极性冲突:
    if gap == 0:
      let c = 公约裁定(冲突.甲方主权, 冲突.乙方主权)
      if c > 0:
        冲突.裁决 = 驱逐
        冲突.理由 = "同极斥+公约 -> 驱逐乙方"
      elif c < 0:
        冲突.裁决 = 驱逐
        冲突.理由 = "同极斥+公约 -> 驱逐甲方"
      else:
        let la = 主权层级(冲突.甲方主权)
        let lb = 主权层级(冲突.乙方主权)
        if la >= lb:
          冲突.裁决 = 驱逐
          冲突.理由 = "同极斥+主权层级 -> 驱逐乙方"
        else:
          冲突.裁决 = 驱逐
          冲突.理由 = "同极斥+主权层级 -> 驱逐甲方"
    else:
      冲突.裁决 = 吸纳
      冲突.理由 = "异极吸 -> 协作执行"

  of 主权冲突:
    冲突.裁决 = 驱逐
    冲突.理由 = "主权不能重叠 -> 驱逐后者"

proc 裁决报告*(冲突: 冲突记录): string =
  let gap = if 冲突.甲方极性 >= 冲突.乙方极性: 冲突.甲方极性 - 冲突.乙方极性
            else: 冲突.乙方极性 - 冲突.甲方极性
  "=== 裁决 ===\n" &
   "甲方: " & 冲突.甲方 & "(极=" & $冲突.甲方极性 & ",主=" & $冲突.甲方主权 & ")\n" &
   "乙方: " & 冲突.乙方 & "(极=" & $冲突.乙方极性 & ",主=" & $冲突.乙方主权 & ")\n" &
   "冲突: " & $冲突.冲突种类 & "\n" &
   "gap: " & $gap & " | 裁决: " & $冲突.裁决 & "\n" &
   "理由: " & 冲突.理由

when isMainModule:
  echo "=== 裁决引擎单元测试 ==="

  var c1 = 冲突记录(
    甲方: "震甲", 乙方: "巽乙",
    冲突种类: 命名冲突,
    甲方主权: 0x01010101'u64, 乙方主权: 0x02020202'u64,
    甲方极性: 1, 乙方极性: 0,
    裁决: 未定, 理由: ""
  )
  裁决(c1)
  echo 裁决报告(c1)

  echo ""

  var c2 = 冲突记录(
    甲方: "震甲", 乙方: "艮丙",
    冲突种类: 极性冲突,
    甲方主权: 0xFF00FF00'u64, 乙方主权: 0x0F0F0F0F'u64,
    甲方极性: 1, 乙方极性: 1,
    裁决: 未定, 理由: ""
  )
  裁决(c2)
  echo 裁决报告(c2)

  echo ""

  var c3 = 冲突记录(
    甲方: "离丁", 乙方: "坎戊",
