    甲方主权: 0x11111111'u64, 乙方主权: 0xFFFFFFFF'u64,
    甲方极性: 0, 乙方极性: 1,
    裁决: 未定, 理由: ""
  )
  裁决(c3)
  echo 裁决报告(c3)
