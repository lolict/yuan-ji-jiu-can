#==============================================================
#  拼音符号编码器  —  满全法七层编码体系
#  24进制声母 · 24进制韵母 · 60进制声调
#  上下·左右·内外·半包围相位变换压缩单字形
#==============================================================

import std/[tables, strutils, math, sequtils]

#==============================================================
#  常量：声母表 (24个基础)
#==============================================================

const
  声母表*: array[24, string] = [
    "b", "p", "m", "f",     # 唇音
    "d", "t", "n", "l",     # 舌音
    "g", "k", "h",          # 腭音
    "j", "q", "x",          # 齿音
    "zh", "ch", "sh", "r",  # 翘舌
    "z", "c", "s",          # 平舌
    "y", "w", "∅"           # 半元音/零声母
  ]

  # 30-60 进制韵母表 (基础24，大小写扩展至48)
  韵母表*: array[24, string] = [
    "a", "o", "e", "i", "u", "ü",
    "ai", "ei", "ao", "ou",
    "an", "en", "ang", "eng", "ong",
    "ia", "ie", "iao", "iou", "ian", "in", "iang", "ing", "iong"
  ]

  # 声调 (4声 + 轻声 = 5种基础调值)
  声调表*: array[5, string] = [
    "ˉ",  # 阴平 55
    "ˊ",  # 阳平 35
    "ˇ",  # 上声 214
    "ˋ",  # 去声 51
    "˙"   # 轻声
  ]

#==============================================================
#  映射表创建
#==============================================================

proc 建声母映射*: Table[string, int] =
  for i, s in 声母表:
    result[s] = i

proc 建韵母映射*: Table[string, int] =
  for i, y in 韵母表:
    result[y] = i

let
  声母到序号 = 建声母映射()
  韵母到序号 = 建韵母映射()

#==============================================================
#  类型
#==============================================================

type
  极性* = enum
    阳极性 = 1
    阴极性 = 0

  相位* = enum
    原位
    上相位    # 上包围
    下相位    # 下包围
    左相位    # 左半包围
    右相位    # 右半包围
    内相位    # 内部
    外相位    # 外部
    包围相位  # 全包围

  拼音码* = object
    声母序*: int       # 0-23 (24进制)
    韵母序*: int       # 0-23 (24进制)
    声调序*: int       # 0-4  (5种)
    相位*: 相位
    极性*: 极性
    坐标*: uint64      # 合并坐标

  符号引擎* = object
    容器表*: Table[string, 拼音码]
    音节库*: Table[string, seq[string]]  # 声母+韵母 → [汉字...]
    注册清单*: seq[string]
    相位变换表*: Table[相位, 相位]

#==============================================================
#  相位变换表 (位置指示)
#==============================================================

const 相位字符*: array[相位, string] = [
  "∘",  # 原位 (无变换)
  "↑",  # 上相位
  "↓",  # 下相位
  "←",  # 左相位
  "→",  # 右相位
  "⊂",  # 内相位
  "⊃",  # 外相位
  "□"   # 包围相位
]

#==============================================================
#  编码核心：三部分坐标合并
#==============================================================
#  64位布局:
#  [极性1位][相位3位][声调6位][韵母6位][声母6位]
#  = 22位编码空间, 可容纳 24×24×5 = 2880 音节
#==============================================================

proc 拼音到坐标*(声母序, 韵母序, 声调序: int; 相位: 相位 = 原位; 极性: 极性 = 阳极性): uint64 =
  var coord: uint64 = 0
  coord = coord or uint64(ord(极性))          # bit 0      : 极性
  coord = coord or (uint64(ord(相位)) shl 1)   # bit 1-3    : 相位
  coord = coord or (uint64(声调序) shl 4)      # bit 4-9    : 声调(0-63)
  coord = coord or (uint64(韵母序) shl 10)     # bit 10-15  : 韵母(0-63)
  coord = coord or (uint64(声母序) shl 16)     # bit 16-21  : 声母(0-63)
  result = coord

#==============================================================
#  解码
#==============================================================

proc 坐标到拼音*(coord: uint64): tuple[声母序, 韵母序, 声调序: int; 相位: 相位; 极性: 极性] =
  let 极性值 = int(coord and 0x1'u64)
  let 相位值 = int((coord shr 1) and 0x7'u64)
  let 声调值 = int((coord shr 4) and 0x3F'u64)
  let 韵母值 = int((coord shr 10) and 0x3F'u64)
  let 声母值 = int((coord shr 16) and 0x3F'u64)
  result = (
    声母序: 声母值,
    韵母序: 韵母值,
    声调序: 声调值,
    相位: 相位(相位值),
    极性: 极性(极性值)
  )

#==============================================================
#  引擎
#==============================================================

proc 创建符号引擎*: 符号引擎 =
  result = 符号引擎(
    容器表: initTable[string, 拼音码](),
    音节库: initTable[string, seq[string]](),
    注册清单: @[],
    相位变换表: initTable[相位, 相位]()
  )
  # 预设音节库
  result.音节库["b_a"] = @["八", "把", "爸", "吧", "巴"]
  result.音节库["m_a"] = @["马", "妈", "吗", "码", "麻"]
  result.音节库["w_o"] = @["我", "握", "窝", "卧", "沃"]
  result.音节库["l_i"] = @["力", "立", "里", "理", "利"]
  result.音节库["li_u"] = @["六", "流", "留", "柳", "刘"]
  result.音节库["ch_u"] = @["出", "初", "楚", "除", "处"]
  result.音节库["t_ian"] = @["天", "田", "甜", "添", "填"]
  result.音节库["m_an"] = @["满", "曼", "慢", "漫", "蛮"]
  result.音节库["q_üan"] = @["全", "权", "泉", "拳", "劝"]
  result.音节库["f_a"] = @["法", "发", "罚", "乏", "伐"]
  result.音节库["n_ü"] = @["女", "钕", "恧", "衄", "絮"]
  result.音节库["sh_en"] = @["身", "深", "神", "审", "甚"]
  result.音节库["g_an"] = @["感", "干", "敢", "赶", "肝"]
  result.音节库["x_ing"] = @["行", "形", "性", "星", "兴"]
  result.音节库["zh_i"] = @["之", "知", "直", "只", "止"]

proc 注册拼音*(e: var 符号引擎; 名字: string; 声母序, 韵母序, 声调序: int;
                极性值: 极性 = 阳极性; 相位值: 相位 = 原位): uint64 =
  let coord = 拼音到坐标(声母序, 韵母序, 声调序, 相位值, 极性值)
  e.容器表[名字] = 拼音码(
    声母序: 声母序,
    韵母序: 韵母序,
    声调序: 声调序,
    相位: 相位值,
    极性: 极性值,
    坐标: coord
  )
  e.注册清单.add(名字)
  result = coord

#==============================================================
#  符号化输出 (压缩表示)
#==============================================================

proc 符号化*(e: 符号引擎; 名字: string): string =
  if not e.容器表.hasKey(名字):
    return "?"
  let code = e.容器表[名字]
  let 声母str = 声母表[code.声母序]
  let 韵母str = 韵母表[code.韵母序]
  let 声调str = if code.声调序 < 5: 声调表[code.声调序] else: "?"
  let 相位str = 相位字符[code.相位]
  let 极性符 = if code.极性 == 阳极性: "+" else: "-"
  # 压缩表示: 声母+韵母+声调+相位+极性
  result = 声母str & 韵母str & 声调str & 相位str & 极性符

proc 解码报告*(e: 符号引擎; 名字: string): string =
  if not e.容器表.hasKey(名字):
    return "不存在: " & 名字
  let code = e.容器表[名字]
  var lines: seq[string] = @[]
  lines.add "  ┌─ 拼音码: " & 名字
  lines.add "  │ 声母[" & $code.声母序 & "]: " & 声母表[code.声母序]
  lines.add "  │ 韵母[" & $code.韵母序 & "]: " & 韵母表[code.韵母序]
  lines.add "  │ 声调[" & $code.声调序 & "]: " & (if code.声调序 < 5: 声调表[code.声调序] else: "?")
  lines.add "  │ 相位: " & $code.相位 & " " & 相位字符[code.相位]
  lines.add "  │ 极性: " & (if code.极性 == 阳极性: "阳(+)" else: "阴(-)")
  lines.add "  │ 坐标: 0x" & toHex(code.坐标)
  let 音节键 = 声母表[code.声母序] & "_" & 韵母表[code.韵母序]
  if e.音节库.hasKey(音节键):
    lines.add "  │ 同音字: " & e.音节库[音节键].join(", ")
  lines.add "  └─ 符号: " & e.符号化(名字)
  return lines.join("\n")

#==============================================================
#  主程序
#==============================================================

when isMainModule:
  echo "════════════════════════════════════════"
  echo "  拼 音 符 号 编 码 器"
  echo "  24进制声母 · 24进制韵母 · 5种声调"
  echo "  相位变换 · 极性编码 · 单字形压缩"
  echo "════════════════════════════════════════"

  var e = 创建符号引擎()

  echo "\n-- 编码表 --"
  echo "  声母: ", 声母表.len, " 个 (24进制)"
  echo "  韵母: ", 韵母表.len, " 个 (24进制,可扩展大小写至48)"
  echo "  声调: ", 声调表.len, " 种 (5基础: 阴平/阳平/上声/去声/轻声)"
  echo "  相位: ", 相位.high.ord + 1, " 种 (上/下/左/右/内/外/包围)"
  echo "  地址空间: ", 24 * 24 * 5, " 音节 (6位一组, 共22位)"

  echo "\n-- 注册满全法核心音节 --"
  let c1 = e.注册拼音("满", 声母到序号["m"], 韵母到序号["an"], 0, 阳极性, 原位)
  let c2 = e.注册拼音("全", 声母到序号["q"], 19, 1, 阴极性, 原位)
  let c3 = e.注册拼音("法", 声母到序号["f"], 韵母到序号["a"], 3, 阳极性, 原位)
  let c4 = e.注册拼音("囡", 声母到序号["n"], 韵母到序号["an"], 1, 阴极性, 包围相位)
  let c5 = e.注册拼音("囝", 声母到序号["j"], 韵母到序号["ian"], 0, 阳极性, 上相位)

  for name in e.注册清单:
    echo e.解码报告(name)

  echo "\n-- 坐标空间验证 --"
  echo "  满 坐标: 0x", toHex(c1)
  echo "  全 坐标: 0x", toHex(c2)
  echo "  法 坐标: 0x", toHex(c3)
  echo "  囡 坐标: 0x", toHex(c4)
  echo "  囝 坐标: 0x", toHex(c5)

  echo "\n-- 编码/解码往返 --"
  let decoded = 坐标到拼音(c1)
  echo "  满 解码: 声母=", 声母表[decoded.声母序],
       " 韵母=", 韵母表[decoded.韵母序],
       " 声调=", 声调表[decoded.声调序],
       " 相位=", $decoded.相位,
       " 极性=", $decoded.极性

  echo "\n-- 极性分配验证 --"
  echo "  我 (阳=1): ", toHex(拼音到坐标(声母到序号["w"], 韵母到序号["o"], 3, 原位, 阳极性)),
       " 末位 = 1"
  echo "  刘楚恬首字 (阴=0): ", toHex(拼音到坐标(声母到序号["l"], 韵母到序号["iou"], 0, 原位, 阴极性)),
       " 末位 = 0"

  echo "\n════════════════════════════════════════"
  echo " 拼音编码 · 相位变换 · 极性坐标"
  echo "════════════════════════════════════════"
