// ────────────────────────────────────────────────────────────
// 4. 残差计算 — 旧对象与新对象对比, 产生镜像差异
// ────────────────────────────────────────────────────────────

/// 残差 — 两个符号对比后的差异
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct 残差 {
    /// 全局序号差异
    pub 序号差: u32,
    /// 偏移差异 (定点)
    pub 偏移差: i32,
    /// 家族是否相同
    pub 同族: bool,
    /// 范畴是否相同
    pub 同范畴: bool,
    /// 成本评估: 0=最低成本, 越大越昂贵
    pub 成本: u32,
}

/// 层级创造力引擎 — 通过残差自生长新关系
pub struct 层级创造力;

impl 层级创造力 {
    /// 计算两个符号之间的残差
    ///
    /// 残差 = 旧对象与新对象的镜像差异
    /// 用于判断: 哪个符号成本更低, 哪个应该被淘汰
    pub fn 计算残差(旧全局序号: u32, 新全局序号: u32) -> Option<残差> {
        let 旧家族 = 一维时间线::家族码(旧全局序号);
        let 新家族 = 一维时间线::家族码(新全局序号);
        let 旧位置 = 一维时间线::时间线位置(旧全局序号);
        let 新位置 = 一维时间线::时间线位置(新全局序号);

        // 获取偏移
        let 旧偏移 = Self::取偏移(旧家族, 旧位置)?;
        let 新偏移 = Self::取偏移(新家族, 新位置)?;

        // 获取范畴
        let 旧范畴 = 解释::取范畴(旧家族, 旧位置);
        let 新范畴 = 解释::取范畴(新家族, 新位置);

        // 成本 = 字节数 (单字节=1, 多字节=2+)
        let 旧成本 = Self::计算成本(旧家族, 旧位置);
        let 新成本 = Self::计算成本(新家族, 新位置);

        Some(残差 {
            序号差: 旧全局序号.abs_diff(新全局序号),
            偏移差: 旧偏移 as i32 - 新偏移 as i32,
            同族: 旧家族 == 新家族,
            同范畴: 旧范畴 == 新范畴,
            成本: 旧成本 + 新成本,
        })
    }

    /// 成本筛选 — 成本高的淘汰, 成本低的保留
    ///
    /// 返回: true = 保留(低成本), false = 淘汰(高成本)
    pub fn 成本筛选(残差: &残差) -> bool {
        // 成本阈值: 单字节=1, 双字节=2, 允许一个单字节+一个双字节=3
        // 同族双部首=4 → 淘汰
        残差.成本 <= 3
    }

    /// 自生长 — 通过残差发现新关系
    ///
    /// 比较两个符号, 如果残差小(相似度高)且成本低 → 建立近义词关系
    /// 如果残差大(差异大)且跨族 → 建立范畴流
    /// 如果同族差异极大 → 反义词
    pub fn 自生长(旧全局序号: u32, 新全局序号: u32) -> Option<&'static str> {
        let r = Self::计算残差(旧全局序号, 新全局序号)?;

        if !Self::成本筛选(&r) {
            return Some("高成本-淘汰");
        }

        if r.同族 && r.偏移差.abs() < 1500 {
            // 同族 + 偏移接近 (相邻) → 近义词
            Some("近义词-保留")
        } else if !r.同族 && r.偏移差.abs() > 3000 {
            // 跨族 + 偏移差异大 → 范畴流
            Some("范畴流-发现")
        } else if r.同族 && r.偏移差.abs() > 5000 {
            // 同族 + 偏移差异极大 → 反义词
            Some("反义词-对立")
        } else {
            Some("中性-观察")
        }
    }

    /// 获取符号的偏移值
    fn 取偏移(家族码: u8, 时间线位置: u16) -> Option<i32> {
        // 偏移 = (时间线位置 + 1) × 1000 (基础偏移)
        // 不同家族可能有不同的偏移率
        let base = (时间线位置 as i32 + 1) * 1000;
        match 家族码 {
            0 => Some(base),           // 声母: 标准偏移
            1 => Some(base + 500),     // 韵母: 略高
            2 => Some(base),           // 声调: 标准
            3 => Some(base * 2),       // 部首: 双倍
            4 => Some(base),           // 结构: 标准
            5 => Some(base + 200),     // 几何: 略高
            6 => Some(base + 300),     // 颜色: 略高
            7 => Some(base + 400),     // 相位: 略高
            8 => Some(base),           // 笔画: 标准
            9 => Some(base + 100),     // 五笔: 略高
            10 => Some(base + 600),    // 音乐: 较高
            _ => None,
        }
    }

    /// 计算符号成本 (字节数)
    pub fn 计算成本(家族码: u8, 时间线位置: u16) -> u32 {
        // 低成本 = 单字节可表示
        // 高成本 = 需要多字节
        match 家族码 {
            0 => 1,  // 声母: 单字母 (b, p, m, f...)
            1 => {   // 韵母: 部分单字母, 部分双字母
                let p = 时间线位置 as u32;
                if p <= 5 { 1 } else if p <= 16 { 2 } else { 2 }
            }
            2 => 1,  // 声调: 数字 1-8
            3 => 2,  // 部首: 汉字, 多字节
            4 => 2,  // 结构: 汉字
            5 => 1,  // 几何: 单字
            6 => 1,  // 颜色: 单字
            7 => 1,  // 相位: 单字
            8 => 1,  // 笔画: 单字
            9 => 1,  // 五笔: 单字母
            10 => 2, // 音乐: 唱名
            _ => 4,
        }
    }
}

