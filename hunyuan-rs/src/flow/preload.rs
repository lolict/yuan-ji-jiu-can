// 核心原则:
//   1. 全局唯一 — 跨家族无重码, 每个符号在万物之中有且仅有一个
//   2. 命名空间 — 前缀即层级, 声母::b ≠ 部首::一 ≠ 五笔::王
//   3. 一维串联 — 所有集装箱可拆散排在一条时间线上, 每位置唯一
//   4. 层级可感 — 每个符号携带完整层级记忆, 永不迷失
//
// 层级结构:
//   家族(11) > 组(若干) > 身份(具体) > 状态(逻辑/渲染)
//
//   家族: 声母(24) · 韵母(39) · 声调(8) · 部首(25) · 结构(8) ·
//         几何(4) · 颜色(7) · 相位(5) · 笔画(8) · 五笔(25) · 音乐(12)
//
//   层级路径示例: 声母 > 双唇音(组) > b(身份) > 逻辑(状态)
//
// 全局唯一公式:
//   全局序号 = 家族偏移 + 时间线位置
//   家族偏移 = 家族码 × 家族跨距 (跨距 = 2048 > 最大家族人数)
//
// 命名空间格式: "家族名::身份名"
//   例: "声母::b" · "韵母::a" · "部首::一" · "五笔::王"
//
// ══════════════════════════════════════════════════════════════════

