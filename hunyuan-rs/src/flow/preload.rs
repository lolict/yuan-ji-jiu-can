/// 替身演员 — 用低成本符号替代高成本符号
pub mod 替身演员 {
    use super::*;

    /// 演员候选 — 评估一个符号能否扮演另一个符号
    #[derive(Clone, Copy, Debug, PartialEq)]
    pub struct 演员候选 {
        pub 替身全局序号: u32,
        pub 替身成本: u32,
        pub 外形匹配度: u32,  // 0-100
        pub 范畴匹配: bool,
        pub 综合评分: u32,    // 越高越好
    }

    /// 导演选角 — 为高成本符号寻找最佳替身
    ///
    /// 从预加载符号库中搜索:
    ///   1. 成本必须低于目标
    ///   2. 外形相似度高
    ///   3. 范畴匹配
    pub fn 寻找替身(目标全局序号: u32) -> Option<演员候选> {
        let 目标家族 = 一维时间线::家族码(目标全局序号);
        let 目标位置 = 一维时间线::时间线位置(目标全局序号);
        let 目标成本 = 层级创造力::计算成本(目标家族, 目标位置);
        let 目标外形 = 外形::取外形(目标家族, 目标位置);
        let 目标范畴 = 解释::取范畴(目标家族, 目标位置);

        // 只考虑低成本符号作为替身 (成本 <= 2)
        if 目标成本 <= 1 {
            return None; // 已经是最低成本, 无需替身
        }

        let mut 最佳候选: Option<演员候选> = None;

        // 遍历所有低成本家族
        let 低成本家族: [(u8, u16); 8] = [
            (0, 24),  // 声母 24
            (2, 8),   // 声调 8
            (5, 4),   // 几何 4
            (6, 7),   // 颜色 7
            (7, 5),   // 相位 5
            (8, 8),   // 笔画 8
            (9, 25),  // 五笔 25
            (1, 6),   // 韵母单字节部分 (a o e i u v)
        ];

        for (家族, 数量) in &低成本家族 {
            for pos in 0..*数量 {
                let 替身成本 = 层级创造力::计算成本(*家族, pos as u16);
                if 替身成本 >= 目标成本 {
                    continue; // 成本不够低
                }

                let 替身外形 = 外形::取外形(*家族, pos as u16);
                let 替身范畴 = 解释::取范畴(*家族, pos as u16);

                // 计算外形匹配度 (简单字符串相似度)
                let 外形匹配度 = 计算外形相似度(目标外形, 替身外形);
                let 范畴匹配 = 目标范畴 == 替身范畴;

                // 综合评分 = 外形匹配度 + 范畴匹配加分 + 成本优势加分
                let 成本优势 = (目标成本 - 替身成本) * 20;
                let 范畴加分 = if 范畴匹配 { 30 } else { 0 };
                let 综合评分 = 外形匹配度 + 范畴加分 + 成本优势;

                let 替身序号 = 一维时间线::全局序号(*家族, pos as u16);

                if 最佳候选.map_or(true, |ref best| 综合评分 > best.综合评分) {
                    最佳候选 = Some(演员候选 {
                        替身全局序号: 替身序号,
                        替身成本,
                        外形匹配度,
                        范畴匹配,
                        综合评分,
                    });
                }
            }
        }

        最佳候选
    }

    /// 计算外形相似度 (0-100)
    fn 计算外形相似度(外形1: &str, 外形2: &str) -> u32 {
        // 简单匹配: 包含相同关键词
        let mut 匹配数 = 0u32;

        // 关键词重叠检测
        let 关键词列表 = ["双唇", "舌尖", "舌根", "舌面", "口", "鼻", "擦", "塞",
            "横", "竖", "撇", "点", "圆", "扁", "光", "声", "波"];
        for 键词 in &关键词列表 {
            if 外形1.contains(键词) && 外形2.contains(键词) {
                匹配数 += 1;
            }
        }

        // 长度相近加分
        let len_diff = (外形1.len() as i32 - 外形2.len() as i32).abs() as u32;
        let 长度加分 = if len_diff < 4 { 10 } else { 0 };

        // 完全相同 = 100
        if 外形1 == 外形2 {
            return 100;
        }

        // 基础分 + 匹配加分 + 长度加分
        let 基础分 = 10u32;
        let 匹配加分 = 匹配数 * 5;
        (基础分 + 匹配加分 + 长度加分).min(99) // 最高99, 100留给完全相同
    }

    /// 阴阳关联法 — 通过关联寻找思路
    ///
    /// 返回与目标符号有关联的其他符号
    pub fn 阴阳关联(目标全局序号: u32, 关联数量: usize) -> Vec<u32> {
        let 目标家族 = 一维时间线::家族码(目标全局序号);
        let 目标位置 = 一维时间线::时间线位置(目标全局序号);

        let mut 关联列表: Vec<(u32, u32)> = Vec::new(); // (全局序号, 关联度)

        let all = 一维时间线::全部序号();
        for (g, _, _) in &all {
            if *g == 目标全局序号 {
                continue;
            }

            let 候选家族 = 一维时间线::家族码(*g);
            let 候选位置 = 一维时间线::时间线位置(*g);

            // 计算关联度
            let mut 关联度 = 0u32;

            // 同族加分
            if 候选家族 == 目标家族 {
                关联度 += 20;
            }

            // 位置接近加分
            let pos_diff = (目标位置 as i32 - 候选位置 as i32).abs() as u32;
            if pos_diff <= 2 {
                关联度 += 15;
            }

            // 外形相似加分
            let 目标外形 = 外形::取外形(目标家族, 目标位置);
            let 候选外形 = 外形::取外形(候选家族, 候选位置);
            if 目标外形 == 候选外形 {
                关联度 += 25;
            }

            // 范畴相同加分
            let 目标范畴 = 解释::取范畴(目标家族, 目标位置);
            let 候选范畴 = 解释::取范畴(候选家族, 候选位置);
            if 目标范畴 == 候选范畴 {
                关联度 += 30;
            }

            if 关联度 > 20 {
                关联列表.push((*g, 关联度));
            }
        }

        // 按关联度排序
        关联列表.sort_by(|a, b| b.1.cmp(&a.1));
        关联列表.iter().take(关联数量).map(|(g, _)| *g).collect()
    }
}

/// 因果观察者 — 搜索外部资源并纳入体系
pub mod 因果观察者 {
    use super::*;

    /// 观察结果
    #[derive(Clone, Debug, PartialEq)]
    pub struct 观察结果 {
        pub 观察对象: u32,          // 全局序号
        pub 是否归属: bool,         // 是否属于我们的预加载体系
        pub 已知范畴: bool,         // 是否已知
        pub 可解释: bool,           // 能否被我们解释
        pub 可纳入: bool,           // 能否纳入我们的状态空间
        pub 建议替身: Option<u32>,  // 建议的替身演员
    }

    /// 观察一个符号 — 判断它是否可被我们使用
    pub fn 观察(目标全局序号: u32) -> 观察结果 {
        let 家族 = 一维时间线::家族码(目标全局序号);
        let 位置 = 一维时间线::时间线位置(目标全局序号);

        // 是否属于我们的预加载体系
        let 是否归属 = 家族 <= 10;

        // 是否已知 (有定义的外形和范畴)
        let 已知范畴 = 是否归属;

        // 能否被解释 (有发音定义)
        let 可解释 = 是否归属 && 发音::取发音(家族, 位置) != "未知家族";

        // 能否纳入状态空间
        let 可纳入 = 可解释;

        // 建议替身 (如果是高成本符号)
        let 建议替身 = if 是否归属 {
            let 成本 = 层级创造力::计算成本(家族, 位置);
            if 成本 > 1 {
                // 寻找替身
                if let Some(候选) = 替身演员::寻找替身(目标全局序号) {
                    Some(候选.替身全局序号)
                } else {
                    None
                }
            } else {
                None
            }
        } else {
            None
        };

        观察结果 {
            观察对象: 目标全局序号,
            是否归属,
            已知范畴,
            可解释,
            可纳入,
            建议替身,
        }
    }

    /// 搜索并审判 — 从外部搜索资源, 判断能否扮演我们的角色
    pub fn 搜索审判(预期角色全局序号: u32) -> Vec<替身演员::演员候选> {
        let mut 候选列表: Vec<替身演员::演员候选> = Vec::new();

        // 搜索所有低成本符号
        let 低成本家族: [(u8, u16); 8] = [
            (0, 24), (2, 8), (5, 4), (6, 7),
            (7, 5), (8, 8), (9, 25), (1, 6),
        ];

        for (家族, 数量) in &低成本家族 {
            for pos in 0..*数量 {
                let 候选序号 = 一维时间线::全局序号(*家族, pos as u16);
                if let Some(候选) = 替身演员::寻找替身(预期角色全局序号) {
                    候选列表.push(候选);
                }
            }
        }

        // 去重并按评分排序
        候选列表.sort_by(|a, b| b.综合评分.cmp(&a.综合评分));
        候选列表.dedup_by(|a, b| a.替身全局序号 == b.替身全局序号);
        候选列表
    }
}

