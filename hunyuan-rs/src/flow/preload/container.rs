    /// 血缘祖先 (向后兼容 stats.rs)
    pub fn call_relational_parents(&self, n: u8) -> Vec<u8> {
        if n == 0 { return vec![0]; }
        let mut result = Vec::new();
        for p in 1..n {
            if n % p == 0 { result.push(p); }
        }
        result
    }

