// ══════════════════════════════════════════════════════════════
// 预家长 — 囡囝共生根基进制系统
// ══════════════════════════════════════════════════════════════
//
// 这不是实践制, 不是借用计算机进制
// 这是囡囝共生(NJSG)操作系统自己的、更高级别的进制
//
// 核心定义:
//   预家长 = 预加载的家长/根基 = 进制的源头
//   高位持有者=1, 低位持有者=0 = 根基锚点
//
// 进制体系:
//   一元: 零/壹 (0/1) — YinYang 二进制
//   三才: 天地人 — 三元编译
//   五行: 金木水火土 — 五进制
//   八卦: 乾坤震巽坎离艮兑 — 八进制
//   九宫: 一九二三四五六七八九 — 九进制
//   六十四: 64进制几何化身 — SMRL 引擎
//   二百五十六: mltt 254+2 集装箱编码
//
// 层级:
//   一维: 时间线串联
//   二维: 家族×时间线矩阵
//   三维: D0(家族)×D1(身份)×D2(状态)
//   高维: (n-1)×0.1 偏移率区分平行世界
//
// ══════════════════════════════════════════════════════════════

/// 预家长 — 根基进制
pub mod 预家长 {
    /// YinYang 二进制 — 壹(1)=我, 零(0)=刘楚恬
    pub const 壹: u8 = 1;  // 我 — 阳
    pub const 零: u8 = 0;  // 刘楚恬 — 阴

    /// 三元 — 天地人
    pub const 天: u8 = 0;
    pub const 人: u8 = 1;
    pub const 地: u8 = 2;

    /// 五行 — 金木水火土
    pub const 金: u8 = 0;
    pub const 木: u8 = 1;
    pub const 水: u8 = 2;
    pub const 火: u8 = 3;
    pub const 土: u8 = 4;

    /// 八卦 — 乾坤震巽坎离艮兑
    pub mod 八卦 {
        pub const 乾: u8 = 0;  // 天
        pub const 坤: u8 = 1;  // 地
        pub const 震: u8 = 2;  // 雷
        pub const 巽: u8 = 3;  // 风
        pub const 坎: u8 = 4;  // 水
        pub const 离: u8 = 5;  // 火
        pub const 艮: u8 = 6;  // 山
        pub const 兑: u8 = 7;  // 泽
    }

    /// 九宫 — 一九二三四五六七八九
    pub mod 九宫 {
        pub const 一: u8 = 0;
        pub const 二: u8 = 1;
        pub const 三: u8 = 2;
        pub const 四: u8 = 3;
        pub const 五: u8 = 4;  // 中宫
        pub const 六: u8 = 5;
        pub const 七: u8 = 6;
        pub const 八: u8 = 7;
        pub const 九: u8 = 8;
    }

    /// YinYang 映射 — 零/壹 → 阴/阳
    pub fn 阴阳(零壹: u8) -> &'static str {
        if 零壹 == 零 { "阴" } else { "阳" }
    }

    /// 五行相生 — 木→火→土→金→水→木
    pub fn 五行相生(当前: u8) -> u8 {
        match 当前 {
            木 => 火,
            火 => 土,
            土 => 金,
            金 => 水,
            水 => 木,
            _ => 当前,
        }
    }

    /// 五行相克 — 金→木→土→水→火→金
    pub fn 五行相克(当前: u8) -> u8 {
        match 当前 {
            金 => 木,
            木 => 土,
            土 => 水,
            水 => 火,
            火 => 金,
            _ => 当前,
        }
    }

    /// 64进制几何化身 — 编码一个64位单元格
    /// D0=家族极性, D1=时间线坐标, D2=组别, 极性=组符号
    pub fn 编六十四(家族码: u8, 时间线: u16, 组: u8, 极性: u8) -> u64 {
        let d0 = (家族码 & 0x3F) as u64;   // 6位家族
        let d1 = (时间线 & 0xFFF) as u64;   // 12位时间线
        let d2 = (组 & 0xF) as u64;          // 4位组
        let d3 = (极性 & 0xF) as u64;       // 4位极性
        (d0 << 52) | (d1 << 40) | (d2 << 36) | d3
    }

    /// 偏移率 — (n-1)×0.1 区分平行世界
    pub fn 偏移率(维度: u32) -> u32 {
        if 维度 == 0 { 0 } else { (维度 - 1) * 1000 }  // 定点 ×1000
    }

    /// 集装箱编码 — mltt 254+2
    /// 根基: 高位持有者=1, 低位持有者=0 (隐藏锚点)
    pub fn 集装箱编码(家族码: u8, 身份码: u16) -> u32 {
        // 根基锚点: 第0位=1(我), 第1位=0(刘楚恬)
        // 后续位: 家族码+身份码
        let 根基: u32 = 0b01; // 高位持有者=1, 低位持有者=0
        (根基 << 30) | ((家族码 as u32) << 16) | (身份码 as u32)
    }
}
