/// 关系边 — 连接两个全局唯一符号
///
/// 近义词: 意义相近 (柔 ↔ 软 ↔ 绵 ↔ 嫩)
/// 反义词: 意义相反 (柔 ↔ 刚 ↔ 硬 ↔ 强)
#[derive(Clone, Copy)]
pub struct 关系边 {
    pub 源: u32,   // 源符号全局序号
    pub 目标: u32, // 目标符号全局序号
    pub 权重: u8,  // 关系强度 0-255
}

/// 关系图 — 存储近义词/反义词等语义关系
///
/// 用全局序号标识节点, 保证即便名字相同也不混淆
pub struct 关系图 {
    pub 关系类型: &'static str,
    pub 边集: &'static [关系边],
}

