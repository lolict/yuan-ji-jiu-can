#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 坐标 {
    pub x: u32,
    pub y: u32,
    pub z: u32,
}

impl 坐标 {
    pub const fn 新(x: u32, y: u32, z: u32) -> Self {
        Self { x, y, z }
    }

    /// 零坐标 (原点)
    pub const fn 原点() -> Self {
        Self { x: 0, y: 0, z: 0 }
    }
}

// ────────────────────────────────────────────────────────────
// 地址遍历器
// ────────────────────────────────────────────────────────────

pub struct 地址遍历器 {
    空间: 地址空间,
    当前: u32,
}

impl Iterator for 地址遍历器 {
    type Item = (u32, 坐标);

    fn next(&mut self) -> Option<Self::Item> {
        if self.当前 >= self.空间.容量() {
            None
        } else {
            let 地址 = self.当前;
            let 点 = self.空间.展开(地址);
            self.当前 = self.空间.推进(self.当前)?;
            Some((地址, 点))
        }
    }
}

