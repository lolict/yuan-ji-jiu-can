/// 范畴 — 远程呼唤的生效范围
///
/// "只要在范畴里面, 就当它已经被调用了"
/// 不需要把调用粘在一起, 距离很远也当它已经生效
/// 只需要用声明的方式证明它生效
pub struct 范畴 {
    pub 名称: String,
    pub 空间: 地址空间,
    pub 槽位: Vec<Option<地址槽>>,
    pub 子范畴: Vec<范畴>,
}

impl 范畴 {
    pub fn 新(名称: &str, 空间: 地址空间) -> Self {
        let 容量 = 空间.容量() as usize;
        Self {
            名称: 名称.to_string(),
            空间,
            槽位: vec![None; 容量],
            子范畴: Vec::new(),
        }
    }

    /// 绑定: 将对象固定到地址上
    pub fn 绑定(&mut self, 地址: u32, 名称: &str, 值: 槽值) -> Result<(), 呼唤错误> {
        if 地址 as usize >= self.槽位.len() {
            return Err(呼唤错误::地址越界(地址));
        }
        self.槽位[地址 as usize] = Some(地址槽 {
            地址,
            名称: 名称.to_string(),
            值,
            惰性: false,
        });
        Ok(())
    }

    /// @呼唤 — 通过地址找到绑定的数值
    ///
    /// 只讲数值不讲名称, 机器层面效率不低
    /// 因为 @地址 直接当数组索引, O(1)
    pub fn 呼唤(&self, 地址: u32) -> Result<槽值, 呼唤错误> {
        match self.槽位.get(地址 as usize) {
            Some(Some(槽)) => Ok(槽.值.clone()),
            Some(None) => Err(呼唤错误::空槽(地址)),
            None => Err(呼唤错误::地址越界(地址)),
        }
    }

    /// 召唤 — 远程呼唤
    ///
    /// 在当前范畴中查找指定名称的绑定
    /// 找到即视为调用, 不需要显式传参
    /// "只要声明好了, 名称就写在数值上"
    pub fn 召唤(&self, 名称: &str) -> Result<槽值, 呼唤错误> {
        // 先在当前范畴查找
        for 槽 in self.槽位.iter().flatten() {
            if 槽.名称 == 名称 {
                return Ok(槽.值.clone());
            }
        }
        // 再在子范畴查找 (函子提升)
        for 子 in &self.子范畴 {
            if let Ok(值) = 子.召唤(名称) {
                return Ok(值);
            }
        }
        Err(呼唤错误::未声明(名称.to_string()))
    }

    /// @[条件] — 选址投影
    ///
    /// 按条件筛选地址子集, 返回满足条件的所有槽
    pub fn 选址(&self, 条件: impl Fn(&地址槽) -> bool) -> Vec<&地址槽> {
        self.槽位
            .iter()
            .filter_map(|槽| 槽.as_ref())
            .filter(|槽| 条件(槽))
            .collect()
    }

    /// 添加子范畴
    pub fn 添加子范畴(&mut self, 子: 范畴) {
        self.子范畴.push(子);
    }
}

// ────────────────────────────────────────────────────────────
// 错误类型
// ────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq)]
pub enum 呼唤错误 {
    地址越界(u32),
    空槽(u32),
    未声明(String),
}

impl core::fmt::Display for 呼唤错误 {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            呼唤错误::地址越界(地址) => write!(f, "地址越界: {}", 地址),
            呼唤错误::空槽(地址) => write!(f, "空槽 @{}", 地址),
            呼唤错误::未声明(名称) => write!(f, "未声明: {}", 名称),
        }
    }
}

// ────────────────────────────────────────────────────────────
// 希尔伯特空间 — 填表编程的数学基础
// ────────────────────────────────────────────────────────────

/// 希尔伯特基向量 — 每个地址对应一个基 |@地址⟩
///
/// 在填表中:
///   行 = 状态向量 |r⟩ = Σ c_i |@i⟩
///   列 = 线性算子
///   单元格 = ⟨@i|O|r_j⟩
#[derive(Debug, Clone)]
pub struct 希尔伯特表 {
    pub 空间: 地址空间,
    pub 基: Vec<u32>,           // 基向量地址列表
    pub 算子: Vec<线性算子>,    // 列算子
}

/// 线性算子 — 可用地址选择来定义
#[derive(Debug, Clone)]
pub struct 线性算子 {
    pub 名称: String,
    pub 映射: Vec<(u32, f64)>, // (基地址, 系数)
}

impl 希尔伯特表 {
    pub fn 新(空间: 地址空间) -> Self {
        let 基: Vec<u32> = (0..空间.容量()).collect();
        Self {
            空间,
            基,
            算子: Vec::new(),
        }
    }

    /// 添加算子 — 用地址选择定义列
    pub fn 添加算子(&mut self, 名称: &str, 映射: Vec<(u32, f64)>) {
        self.算子.push(线性算子 {
            名称: 名称.to_string(),
            映射,
        });
    }

    /// 投影到子空间 — P_条件 = Σ |@addr⟩⟨@addr|
    pub fn 投影(&self, 条件: impl Fn(u32) -> bool) -> Vec<u32> {
        self.基.iter().copied().filter(|&addr| 条件(addr)).collect()
    }

    /// 内积 — ⟨@a|@b⟩ = δ_{a,b} (离散正交基)
    pub fn 内积(&self, a: u32, b: u32) -> f64 {
        if a == b { 1. } else { 0. }
    }

    /// 线性组合 — |r⟩ = Σ c_i |@i⟩
    pub fn 线性组合(&self, 系数: &[(u32, f64)]) -> Vec<f64> {
        let mut 结果 = vec![0.0; self.基.len()];
        for (addr, c)  in 系数 {
            if (*addr as usize) < 结果.len() {
                结果[*addr as usize] += c;
            }
        }
        结果
    }
}

// ────────────────────────────────────────────────────────────
// 惰性求值器 — 按需计算, 默认不缓存
// ────────────────────────────────────────────────────────────

/// 惰性符号 — 懒惰的获取符号法
///
/// "不是直接调用已经准备好的符号, 而是通过计算获取某个计算时产生的符号"
///
/// 内存规则:
///   默认不缓存, 按需算
///   作用域结束回收
///   显式缓存用 记
pub struct 懒符号 {
    pub thunk: Box<dyn Fn() -> 槽值>,
    pub 已求值: bool,
    pub 缓存: Option<槽值>,
}

impl 懒符号 {
    pub fn 新(thunk: Box<dyn Fn() -> 槽值>) -> Self {
        Self {
            thunk,
            已求值: false,
            缓存: None,
        }
    }

    /// 求值 — 首次调用时计算, 之后可选缓存
    pub fn 求值(&mut self) -> 槽值 {
        if !self.已求值 {
            let 结果 = (self.thunk)();
            self.缓存 = Some(结果.clone());
            self.已求值 = true;
            结果
        } else {
            self.缓存.clone().unwrap_or(槽值::空)
        }
    }

    /// 清除缓存 (弱缓存策略)
    pub fn 清除(&mut self) {
        self.已求值 = false;
        self.缓存 = None;
    }
}

// ────────────────────────────────────────────────────────────
// 选址呼唤 REPL — 交互式入口
// ────────────────────────────────────────────────────────────

/// 选址呼唤编程的交互式会话
pub struct 呼唤会话 {
    pub 根范畴: 范畴,
}

impl 呼唤会话 {
    pub fn 新() -> Self {
        Self {
            根范畴: 范畴::新("根", 地址空间::默认十进制()),
        }
    }

    pub fn 执行(&self, 输入: &str) -> Result<String, 呼唤错误> {
         let 输入 = 输入.trim();
        
        // @地址 呼唤
        if 输入.starts_with('@') {
            let 地址_str = &输入[1..];
            if let Ok(地址) = 地址_str.parse::<u32>() {
                match self.根范畴.呼唤(地址) {
                    Ok(值) => Ok(format!("@{} = {:?}", 地址, 值)),
                    Err(e) => Err(e),
                }
            } else {
                // 按名称召唤
                match self.根范畴.召唤(地址_str) {
                    Ok(值) => Ok(format!("召唤 {} = {:?}", 地址_str, 值)),
                    Err(e) => Err(e),
                }
            }
        } else {
            Ok(format!("未知指令: {}", 输入))
        }
    }
}

