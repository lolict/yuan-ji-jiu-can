# 容器节点
# ============================================================
type
  YunmuNode* = object
    yunmu*: string
    codes*: seq[int]
    symbols*: seq[string]

  RongQi120* = object
    name*: string
    symbol_to_idx*: Table[string, int]
    nodes*: seq[YunmuNode]

func new_rongqi120*(name: string): RongQi120 =
  result.name = name
  result.symbol_to_idx = initTable[string, int]()
  for i, sym in SYMBOLS120:
    result.symbol_to_idx[sym] = i

func symbol_value*(r: RongQi120, sym: string): int =
  if r.symbol_to_idx.hasKey(sym): return r.symbol_to_idx[sym]
  return -1

func is_equivalent*(a: string, b: string): bool =
  let r = new_rongqi120("tmp")
  let va = r.symbol_value(a)
  let vb = r.symbol_value(b)
  if va >= 0 and vb >= 0: return va == vb
  return a == b

proc add_yunmu*(r: var RongQi120, name: string) =
  var node: YunmuNode
  node.yunmu = name
  if YUNMU_CODES.hasKey(name):
    node.codes = YUNMU_CODES[name]
    for idx in node.codes:
      if idx < SYMBOLS120.len:
        node.symbols.add(SYMBOLS120[idx])
  r.nodes.add(node)

func primary_code*(node: YunmuNode): int =
  if node.codes.len > 0: return node.codes[0]
  return -1

func is_yunmu_equiv*(a: YunmuNode, b: YunmuNode): bool =
  for ca in a.codes:
    for cb in b.codes:
      if ca == cb: return true
  return false

# ============================================================
# 去重验证：确保 120 个符号全部唯一
# ============================================================
proc verify_unique*(): tuple[total: int, unique: int, duplicates: seq[string]] =
  var seen = initTable[string, int]()
  var dups: seq[string] = @[]
  for i, sym in SYMBOLS120:
    if seen.hasKey(sym):
      dups.add(sym & " at #" & $i & " (first at #" & $seen[sym] & ")")
    else:
      seen[sym] = i
  return (SYMBOLS120.len, seen.len, dups)

# ============================================================
# 大小写配对验证：确认每个小写都有大写对应
# ============================================================
proc verify_case_pairs*(): seq[string] =
  var issues: seq[string] = @[]
  for i in 0..<SYMBOLS120.len:
    let sym = SYMBOLS120[i]
    # 每隔2个为一对：偶数=小写，奇数=大写
    if i mod 2 == 0:
      let partner = SYMBOLS120[i + 1]
      # 简单 ASCII 检查：大写 = toUpper(小写)
      # 仅对 ASCII 有效；IPA/修饰符无 ASCII 大小写关系，跳过
      if sym[0].ord < 128 and partner[0].ord < 128:
        let expected_upper = sym[0].toUpperAscii
        if partner != expected_upper:
          issues.add("#" & $i & " " & sym & " -> " & partner & " (expected " & $expected_upper & ")")
  return issues

