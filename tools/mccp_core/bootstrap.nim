proc compute_checksum*(text: string): string =
  result = getMD5(text)

proc read_rules*(ctx: var MCCPContext): int =
  if not dirExists(ctx.rules_dir):
    ctx.families = @[]
    return 0

  var total = 0
  for kind, path in walkDir(ctx.rules_dir):
    if kind == pcFile and path.endsWith(".mccp"):
      let content = readFile(path)
      var fam = RuleFamily(
        source: path,
        rules: @[],
        checksum: compute_checksum(content)
      )
      for line in content.splitLines():
        let stripped = strip(line)
        if stripped.len == 0 or stripped[0] == '#':
          continue
        let parts = stripped.split("->")
        if parts.len >= 2:
          let left = parts[0].split(":")
          let right = parts[1].split(":")
          if left.len >= 2 and right.len >= 2:
            let rule = FCCPRule(
              name: "auto_" & $total,
              source: path,
              glyph: left[0].strip(),
              polarity: 0,
              pattern: left[1].strip(),
              action: right[0].strip(),
              action_target: right[1].strip()
            )
            fam.rules.add(rule)
            total += 1

      ctx.families.add(fam)

  result = total

proc register_glyph*(ctx: var MCCPContext; name: string; pol: int8 = 0; layer: int = 1) =
  var entry = GlyphEntry(
    name: name,
    polarity: pol,
    cluster_id: -1,
    offset_layer: layer
  )
  var yy_bits = ""
  for c in name:
    yy_bits.add(if int(c) mod 2 == 0: '0' else: '1')
  entry.yinyang = yy_bits
  ctx.glyphs.add((name: name, entry: entry))
  ctx.glyph_names.add(name)

proc validate_rules*(ctx: MCCPContext): seq[string] =
  var errs: seq[string] = @[]
  var seen_glyphs: seq[string] = @[]

  for fam in ctx.families:
    if fam.checksum.len != 32:
      errs.add("规则文件 " & fam.source & " checksum 异常")
    for rule in fam.rules:
      if seen_glyphs.contains(rule.glyph):
        errs.add("重复符号定义: " & rule.glyph & " in " & fam.source)
      seen_glyphs.add(rule.glyph)

  result = errs

proc generate_nim*(ctx: MCCPContext; module_name: string): string =
  var res_str = "# Auto-generated by MCCP Self-Bootstrap" & "\n"
  res_str &= "# Module: " & module_name & "\n"
  res_str &= "# Rules applied: " & $ctx.families.len & " families\n\n"
  res_str &= "const glyph_registry* = [\n"
  for pair in ctx.glyphs:
    let name = pair.name
    let entry = pair.entry
    res_str &= "  (\"" & name & "\", " & $entry.polarity & ", " & $entry.offset_layer & "),\n"
  res_str &= "]\n\n"
  for fam in ctx.families:
    for rule in fam.rules:
      res_str &= "proc " & rule.glyph & "*(): string =\n"
      res_str &= "  ## Source: " & rule.source & "\n"
      res_str &= "  ## Pattern: " & rule.pattern & "\n"
      res_str &= "  result = \"" & rule.action & "\"\n\n"
  result = res_str

proc generate_json*(ctx: MCCPContext): string =
  var json_str = "{\n"
  json_str &= "  \"mccp\": \"self-bootstrap\",\n"
  json_str &= "  \"glyphs\": {\n"
  var first_entry = true
  for pair in ctx.glyphs:
    let name = pair.name
    let e = pair.entry
    if not first_entry: json_str &= ",\n"
    first_entry = false
    json_str &= "    \"" & name & "\": {"
    json_str &= "\"yinyang\": \"" & e.yinyang & "\", "
    json_str &= "\"polarity\": " & $e.polarity & ", "
    json_str &= "\"layer\": " & $e.offset_layer
    json_str &= "}"
  json_str &= "\n  },\n"
  json_str &= "  \"rules\": [\n"
  for fam in ctx.families:
    for rule in fam.rules:
      json_str &= "    {\"glyph\": \"" & rule.glyph & "\", "
      json_str &= "\"action\": \"" & rule.action & "\", "
      json_str &= "\"target\": \"" & rule.action_target & "\"},\n"
  json_str &= "  ]\n"
  json_str &= "}\n"
  result = json_str

proc self_verify*(ctx: MCCPContext): tuple[ok: bool; hash1: string; hash2: string] =
  let nim_code = ctx.generate_nim("mccp_self")
  let json_code = ctx.generate_json()
  let h1 = compute_checksum(nim_code)
  let h2 = compute_checksum(json_code)
  let ok = nim_code.len > 100 and json_code.len > 100
  result = (ok, h1, h2)

proc new_mccp*(rules_dir: string; output_dir: string): MCCPContext =
  MCCPContext(
    rules_dir: rules_dir,
    output_dir: output_dir,
    families: @[],
    glyphs: @[],
    glyph_names: @[],
    units: @[],
    phase: bpRead,
    self_hash: ""
  )
