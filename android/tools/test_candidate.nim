# ── 候选字上下文权重计算 ──────────────────────────────────────
proc weighCandidate(candidate: string, smIdx: int, lastChar: string): int =
  var score = 0

  # 常见双字组词匹配
  if BIGRAM_TABLE.hasKey(lastChar):
    let rights = BIGRAM_TABLE[lastChar]
    if candidate in rights:
      score += 3

  # 声母优先级 (b/p/m/f 在词首)
  if smIdx <= 3:
    score += 1

  # 高频字加分
  if candidate in HIGH_FREQ_WORDS:
    score += 1

  return score

# ── 音节拆解: pinyin → (声母idx, 韵母idx) ─────────────────────
proc splitSyllable(py: string): (int, int) =
  let p = py.normalize      # 转小写

  # 尝试双字母声母 (zh, ch, sh)
  if p.len >= 2:
    let dbl = p[0..1]
    let smd = shengMuToIdx(dbl)
    if smd >= 0:
      let yml = p[2..^1]
      let ymd = yunMuToIdx(yml)
      if ymd >= 0:
        return (smd, ymd)

  # 单字母声母
  if p.len >= 1:
    let sgl = $p[0]
    let sms = shengMuToIdx(sgl)
    if sms >= 0:
      let yml = p[1..^1]
      let ymd = yunMuToIdx(yml)
      if ymd >= 0:
        return (sms, ymd)

  # 尝试零声母 (纯韵母)
  let ymd0 = yunMuToIdx(p)
  if ymd0 >= 0:
    return (-1, ymd0)

  return (-99, -99)  # 无法拆解

# ── 候字生成: (声母idx, 韵母idx) + 上下文权重 → 候字顺序 ──────
proc generateCandidates(smIdx: int, ymIdx: int, lastChar: string): seq[string] =
  let key = (smIdx, ymIdx)
  if not CANDIDATE_TABLE.hasKey(key):
    return @[]

  var cands = CANDIDATE_TABLE[key]

  # 上下文权重排序
  if lastChar.len > 0:
    var scored: seq[(int, string)] = @[]
    for c in cands:
      let w = weighCandidate(c, smIdx, lastChar)
      scored.add((w, c))
    scored.sort(proc (a, b: (int, string)): int = cmp(b[0], a[0]))
    cands = scored.mapIt(it[1])

  return cands

# ── CLI 入口 ───────────────────────────────────────────────────
when isMainModule:
  echo "============================================="
  echo " MetaIME 声母-韵母候选 · 离线测试"
  echo "============================================="

  var pySeq: seq[string] = @[]
  var i = 1
  while i <= paramCount():
    pySeq.add(paramStr(i))
    i += 1

  if pySeq.len == 0:
    # 默认测试集
    pySeq = @["ni", "hao", "shi", "jie", "ren", "sheng"]
    echo "无输入参数, 使用默认测试集: ", pySeq.join(" "), "\n"

  var lastChar: string = ""
  var totalSyllables = 0
  var hitCount = 0

  for py in pySeq:
    let (sm, ym) = splitSyllable(py)
    if sm == -99:
      echo "  [跳过] 无法拆解 '$py'"
      continue

    totalSyllables += 1
    let shengName = if sm >= 0: SHENG_MU_LIST[sm] else: "零声母"
    let yunName = YUN_MU_LIST[ym]

    let cands = generateCandidates(sm, ym, lastChar)
    if cands.len > 0:
      hitCount += 1
      let topCand = cands[0]
      echo "  音节 $py($shengName+$yunName) → [${cands.join(\", \")}]"
      echo "    推荐首字: '$topCand'"
      lastChar = topCand  # 更新上下文
    else:
      echo "  [空] 音节 $py($shengName+$yunName) → 无候选"
      lastChar = ""

  echo ""
  echo "============================================="
  echo " 总音节: $totalSyllables  命中: $hitCount"
  echo "============================================="
