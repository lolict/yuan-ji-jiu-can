# ── 高频字表 ──────────────────────────────────────────────────
const HIGH_FREQ_WORDS: seq[string] = @[
  "的", "是", "了", "在", "有", "我", "他", "她", "你", "不",
  "这", "那", "个", "来", "去", "说", "看", "好", "大", "小",
