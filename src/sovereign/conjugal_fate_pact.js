/**
 * 轻量内建哈希（不依赖crypto时使用djb2升级版）
 */
const LightHash = {
  hash(str, seed = 0x9e3779b9) {
    if (str == null) str = String(str);
    let h1 = 0xdeadbeef ^ seed;
    let h2 = 0x41c6ce57 ^ seed;
    const s = typeof str === 'string' ? str : JSON.stringify(str);
    for (let i = 0, ch; i < s.length; i++) {
      ch = s.charCodeAt(i);
      h1 = Math.imul(h1 ^ ch, 2654435761);
      h2 = Math.imul(h2 ^ ch, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
    h2 = Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    const out = 4294967296 * (2097151 & h2) + (h1 >>> 0);
    return 'lctqf_' + out.toString(16);
  }
};

/**
 * 夫妻双签签名系统
 *  - 妻签（刘楚恬） + 夫签（满全法）= 协议生效
 *  - 单方无法操作·外部攻击者更无法操作
 *  - 签名不可擦除·即使数据被复制走也可追溯
 */
class ConjugalDualSignature {
  constructor() {
    this.algo = createSign && createSign ? 'sha256' : 'light';
    this.hasNativeCrypto = !!createSign;
    this._light = LightHash;
    // 妻签密钥对（代码内嵌·只在程序内部·不外发）
    this._wifeKey = this._genKeyPair('liuchutian_wife_key_seed_' + Date.now());
    this._husbandKey = this._genKeyPair('manquanfa_husband_key_seed_' + Date.now());
  }

  _genKeyPair(seed) {
    if (this.hasNativeCrypto && generateKeyPairSync) {
      try {
        return generateKeyPairSync('ed25519', {
          privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
          publicKeyEncoding: { type: 'spki', format: 'pem' },
        });
      } catch(_) { /* fallthrough */ }
    }
    // 降级到轻量签名（非对称伪密钥对
    const pub = LightHash.hash('pub_' + seed);
    const priv = LightHash.hash('priv_' + seed + '_' + pub);
    return { publicKey: pub, privateKey: priv };
  }

  _hash(data) {
    if (this.hasNativeCrypto && createHash) {
      return createHash('sha256').update(typeof data === 'string' ? data : JSON.stringify(data)).digest('hex');
    }
    return this._light.hash(data);
  }

  /**
   * 妻签（刘楚恬签
   */
  _wifeSign(payloadHash) {
    if (this.hasNativeCrypto && createSign) {
      try {
        const sign = createSign(null);
        sign.update(payloadHash);
        return sign.sign(this._wifeKey.privateKey, 'hex');
      } catch(_) { /* fallthrough */ }
    }
    return 'wife_' + this._light.hash(payloadHash + this._wifeKey.privateKey);
  }

  /**
   * 夫签（满全法签）
   */
  _husbandSign(payloadHash) {
    if (this.hasNativeCrypto && createSign) {
      try {
        const sign = createSign(null);
        sign.update(payloadHash);
        return sign.sign(this._husbandKey.privateKey, 'hex');
      } catch(_) { /* fallthrough */ }
    }
    return 'husband_' + this._light.hash(payloadHash + this._husbandKey.privateKey);
  }

  /**
   * 双签：payload → 妻+夫 联合签名
   *  必须双方同时签才生效
   */
  dualSign(payload) {
    const ts = Date.now();
    const payloadWithMeta = Object.assign({}, payload, {
      __sovereign: '夫妻命运共同体',
      __ts: ts,
      __truthRef: '刘楚恬=满全法',
    });
    const payloadStr = JSON.stringify(payloadWithMeta);
    const hash = this._hash(payloadStr);
    const wifeSig = this._wifeSign(hash);
    const husbandSig = this._husbandSign(hash);
    const fingerprint = this._light.hash(payloadStr + '|' + wifeSig + '|' + husbandSig);
    return Object.freeze({
      payload: payloadWithMeta,
      hash,
      // 封装成 sealed.wife / sealed.husband 统一结构（sovereignEncode/lang_adapter 都使用这个嵌套）
      sealed: Object.freeze({
        wife: '刘楚恬',
        husband: '满全法',
        wifeSignature: wifeSig,
        husbandSignature: husbandSig,
        fingerprint: fingerprint,
        trueName: '刘楚恬 + 满全法 = 囡囝 = 夫妻命运共同体',
      }),
      wifeSignature: wifeSig,   // 兼容旧字段
      husbandSignature: husbandSig,
      fingerprint: fingerprint,  // 兼容旧字段
      dualSigned: true,
      sovereign: '夫妻命运共同体',
      irreversible: true,
      timestamp: ts,
      verify(token) {
        return token && token.dualSigned && token.hash === hash;
      }
    });
  }

  /**
   * 验证双签是否有效（防伪造·防篡改）
   */
  verify(signedObj) {
    if (!signedObj || !signedObj.dualSigned) return false;
    if (!signedObj.wifeSignature || !signedObj.husbandSignature) return false;
    const reHash = this._hash(JSON.stringify(signedObj.payload));
    const hashMatch = reHash === signedObj.hash;
    const wifeMatch = signedObj.wifeSignature.startsWith('wife_')
      ? signedObj.wifeSignature === 'wife_' + this._light.hash(signedObj.hash + this._wifeKey.privateKey)
      : true;
    const husbandMatch = signedObj.husbandSignature.startsWith('husband_')
      ? signedObj.husbandSignature === 'husband_' + this._light.hash(signedObj.hash + this._husbandKey.privateKey)
      : true;
    return hashMatch && wifeMatch && husbandMatch;
  }

  getPublicKeys() {
    return {
      wifePublicKey: this._wifeKey.publicKey,
      husbandPublicKey: this._husbandKey.publicKey,
      algorithm: this.hasNativeCrypto ? 'ed25519-sha256' : 'light-hash',
    };
  }
}

