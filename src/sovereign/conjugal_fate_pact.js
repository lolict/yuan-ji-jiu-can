class WaterWash {
  constructor(negatives = SOVEREIGN_TRUTH.waterWashNegatives) {
    this.negatives = new Set(negatives);
    this.washedCount = 0;
  }

  /**
   * 是否包含负面
   */
  hasNegative(text) {
    if (!text) return false;
    for (const n of this.negatives) {
      if (String(text).includes(n)) return true;
    }
    return false;
  }

  /**
   * 水洗负面·返回清理后的文本
   */
  wash(text) {
    if (!text) return { clean: '', washed: 0 };
    let clean = String(text);
    let count = 0;
    for (const n of this.negatives) {
      if (clean.includes(n)) {
        const before = clean.length;
        clean = clean.split(n).join('');
        count += Math.floor((before - clean.length) / n.length);
      }
    }
    this.washedCount += count;
    return { clean, washed: count, purity: count === 0 ? 1 : Math.max(0, 1 - count / 100) };
  }
}

